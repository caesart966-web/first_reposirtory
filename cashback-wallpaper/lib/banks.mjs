// Названия банков — по-русски и одинаково, как их ни подписал скрин
// («Тинькофф», «T-Bank», «Т‑Банк» → «Т-Банк»). Неизвестный банк остаётся
// как написан.
import { normalize } from './categories.mjs';

const BANKS = [
  ['Т-Банк', [/^т ?банк/, /^t ?bank/, /тинькофф/, /tinkoff/]],
  ['Сбер', [/^сбер/, /^sber/]],
  ['Альфа-Банк', [/^альфа/, /^alfa/]],
  ['ВТБ', [/^втб/, /^vtb/]],
  ['Яндекс Банк', [/^яндекс/, /^yandex/]],
  ['Озон Банк', [/^озон/, /^ozon/]],
  ['Газпромбанк', [/газпром/, /^гпб/]],
  ['Райффайзенбанк', [/^райф/, /raiff/]],
  ['Совкомбанк', [/совком/, /халва/]],
  ['МТС Банк', [/^мтс/, /^mts/]],
  ['Почта Банк', [/^почта/]],
  ['ПСБ', [/^псб/, /промсвязь/]],
  ['Росбанк', [/^росбанк/]],
  ['Уралсиб', [/уралсиб/]],
  ['ОТП Банк', [/^отп/, /^otp/]],
  ['Банк ДОМ.РФ', [/дом рф/]],
  ['WB Банк', [/^wb/, /вайлдберриз/, /wildberries/]],
  ['Россельхозбанк', [/россельхоз/, /^рсхб/]],
  ['Ренессанс Банк', [/ренессанс/]],
  ['Хоум Банк', [/^хоум/, /home ?credit/]],
];

export function resolveBank(raw) {
  const n = normalize(raw);
  for (const [name, res] of BANKS) if (res.some((re) => re.test(n))) return name;
  return String(raw).trim();
}
