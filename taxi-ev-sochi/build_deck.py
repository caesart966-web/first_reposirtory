def slide_tree(prs):
    s = base_slide(
        prs, 'Логика анализа: дерево решения',
        'Ответ распадается на три условия — выгодно, выполнимо, устойчиво; '
        'масштаб ограничивает второе',
        'анализ рабочей группы')

    X0, W0 = LEFT, 1.85            # главный вопрос
    X1, W1 = 2.62, 2.35            # уровень 1 — условия
    X2, W2 = 5.42, 4.15            # уровень 2 — проверяемые гипотезы
    X3, W3 = 9.95, 3.02            # вывод по факту
    Y0, BH, STEP = 1.56, 0.46, 0.52

    for x, w, lbl in ((X1, W1, 'Условие'), (X2, W2, 'Что проверяли'),
                      (X3, W3, 'Вывод по факту')):
        textbox(s, x, 1.30, w, 0.20, [lbl], size=10, bold=True, italic=True,
                color=GRAY)

    def cy(i):
        return Y0 + i * STEP + BH / 2

    root_c = cy(4)
    box(s, X0, root_c - 0.70, W0, 1.40,
        ['Стоит ли таксопарку в Сочи (200 авто) покупать электромобили?'],
        fill=AQUA, size=12, bold=True, line_spacing=1.1)
    connect_tree(s, X0 + W0, root_c, X1, [cy(1), cy(4), cy(7)])

    for b, (head, descr, verdict, hfill, hcolor, kids) in enumerate(TREE):
        top = Y0 + (b * 3) * STEP
        h = 2 * STEP + BH
        sh = box(s, X1, top, W1, h, [], fill=hfill, size=10)
        fill_tf(sh.text_frame,
                [[(head, {'size': 11.5, 'bold': True, 'color': hcolor})],
                 [(descr, {'size': 10})],
                 [(verdict, {'size': 10, 'bold': True, 'color': hcolor})]],
                align=PP_ALIGN.CENTER, line_spacing=1.0, space_after=4)
        box(s, X1 - 0.09, top, 0.06, h, [], fill=hcolor, radius=0.0,
            shape=MSO_SHAPE.RECTANGLE)
        connect_tree(s, X1 + W1, cy(b * 3 + 1), X2, [cy(b * 3 + k) for k in range(3)])
        for k, (q, ans, ac) in enumerate(kids):
            i = b * 3 + k
            box(s, X2, Y0 + i * STEP, W2, BH, [q], fill=LIGHT, size=10,
                align=PP_ALIGN.LEFT, pad=0.10, line_spacing=0.95)
            line(s, X2 + W2, cy(i), X3, cy(i), color=GRAY_LT, arrow=True)
            box(s, X3, Y0 + i * STEP, W3, BH, [ans], fill=None, size=10,
                bold=True, color=ac, align=PP_ALIGN.LEFT, pad=0.04,
                line_spacing=0.95)
    return s


