def style_run(run, size=12, bold=False, color=INK, italic=False):
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    run.font.color.rgb = color
    run.font.name = FONT
    run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)
    run._element.rPr.rFonts.set(qn('w:cs'), FONT)


def para(doc, text=None, size=12, bold=False, color=INK, space_before=0,
         space_after=8, spacing=1.35, align=WD_ALIGN_PARAGRAPH.LEFT,
         italic=False, keep_with_next=False):
    p = doc.add_paragraph()
    p.alignment = align
    pf = p.paragraph_format
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    pf.line_spacing = spacing
    pf.keep_with_next = keep_with_next
    if text:
        # **жирный** внутри абзаца
        for i, chunk in enumerate(re.split(r'\*\*(.+?)\*\*', text, flags=re.S)):
            if not chunk:
                continue
            r = p.add_run(chunk)
            style_run(r, size, bold or i % 2 == 1, color, italic)
    return p


def hrule(doc, color="E2E0DA", size=8):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(4)
    p.paragraph_format.space_after = Pt(10)
    pbdr = OxmlElement('w:pBdr')
    bottom = OxmlElement('w:bottom')
    bottom.set(qn('w:val'), 'single')
    bottom.set(qn('w:sz'), str(size))
    bottom.set(qn('w:space'), '1')
    bottom.set(qn('w:color'), color)
    pbdr.append(bottom)
    p._p.get_or_add_pPr().append(pbdr)
    return p


def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    sh = OxmlElement('w:shd')
    sh.set(qn('w:val'), 'clear')
    sh.set(qn('w:fill'), hexcolor)
    tcPr.append(sh)


