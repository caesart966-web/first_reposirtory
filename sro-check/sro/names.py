"""Сверка названия компании из файла с названием, которое вернул реестр.

Зачем. Проверка идёт по ИНН, и опечатка в ИНН не вызывает ошибки: реестр
честно находит запись — только про другую организацию. В файле окажется
уверенное «да», и это худший вид неправильного ответа, потому что он выглядит
достоверным. Единственный способ поймать такое — сравнить названия.

Как. Сравнение намеренно снисходительное: «ООО "Мега-Строй"» и
«ОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ "МЕГА СТРОЙ"» — одна компания.
Ругаться нужно только на явное расхождение, поэтому при любых сомнениях
функция отвечает «похоже» и молчит. Ложная тревога на каждой третьей строке
обесценила бы предупреждение целиком.
"""

from __future__ import annotations

import re

# Организационно-правовые формы: они одинаковы у миллионов компаний и для
# сравнения бесполезны. Длинные формы убираем раньше коротких, иначе от
# «общество с ограниченной ответственностью» останутся хвосты.
LEGAL_FORMS = (
    "общество с ограниченной ответственностью",
    "публичное акционерное общество",
    "непубличное акционерное общество",
    "закрытое акционерное общество",
    "открытое акционерное общество",
    "акционерное общество",
    "индивидуальный предприниматель",
    "федеральное государственное бюджетное учреждение",
    "федеральное государственное унитарное предприятие",
    "федеральное государственное бюджетное образовательное учреждение",
    "государственное бюджетное учреждение",
    "государственное унитарное предприятие",
    "муниципальное унитарное предприятие",
    "муниципальное бюджетное учреждение",
    "муниципальное казенное учреждение",
    "санкт-петербургское государственное унитарное предприятие",
    "саморегулируемая организация",
    "ассоциация",
    "союз",
)

# Те же формы сокращениями — отдельными словами.
SHORT_FORMS = {
    "ооо", "оао", "зао", "пао", "ао", "ип", "нао",
    "гуп", "муп", "фгуп", "спбгуп", "мбу", "гбу", "фгбу", "мку", "гку", "фгбоу",
    "сро", "нп", "тсж", "жск", "кфх", "фонд", "учреждение", "предприятие",
}

_QUOTES = "«»\"'“”„‘’`"


def normalize(name: str | None) -> str:
    """Привести название к виду, пригодному для сравнения."""
    if not name:
        return ""
    text = str(name).lower().replace("ё", "е")
    for quote in _QUOTES:
        text = text.replace(quote, " ")
    text = re.sub(r"[^\w\s-]", " ", text, flags=re.UNICODE)
    text = re.sub(r"\s+", " ", text).strip()

    for form in LEGAL_FORMS:
        text = text.replace(form, " ")

    words = [word for word in text.split() if word and word not in SHORT_FORMS]
    return " ".join(words).strip()


def tokens(name: str | None) -> list[str]:
    """Значимые слова названия: короткие обрывки отбрасываем."""
    return [word for word in normalize(name).replace("-", " ").split() if len(word) >= 2]


def _matches(first: str, second: str) -> bool:
    """Слова считаем совпавшими, если одно является началом другого.

    Так переживаются сокращения и обрезанные названия: «мегастрой» и «мега».
    """
    if first == second:
        return True
    shorter, longer = sorted((first, second), key=len)
    return len(shorter) >= 3 and longer.startswith(shorter)


def looks_like_same_company(from_file: str | None, from_registry: str | None) -> bool:
    """Правдоподобно ли, что это одна и та же организация.

    При нехватке данных отвечает True: молчание лучше ложной тревоги.
    """
    left, right = tokens(from_file), tokens(from_registry)
    if not left or not right:
        return True  # сравнивать нечего — поводов для тревоги нет
    return any(_matches(a, b) for a in left for b in right)


def mismatch_note(from_file: str | None, from_registry: str | None) -> str:
    """Текст предупреждения для колонки «Примечание», либо пустая строка."""
    if looks_like_same_company(from_file, from_registry):
        return ""
    return (
        f"ВНИМАНИЕ: в реестре по этому ИНН другая компания — «{str(from_registry).strip()}». "
        "Проверьте ИНН в исходном файле"
    )
