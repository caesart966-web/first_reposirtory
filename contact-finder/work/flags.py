"""Пометка заведомо непригодных номеров.

Два разных основания, и их нельзя смешивать:
  «код не существует» — в российском плане нумерации коды ABC/DEF
      начинаются только на 3, 4, 8 или 9. Всё остальное — брак данных.
  «шаблон-заглушка»  — 1234567 и подобное: так заполняют поле, когда
      настоящего номера нет. «Красивые» номера (993-99-99, 252-52-55)
      сюда не относятся — они настоящие.
Отдельно «код сомнителен»: диапазон валидный, но такого кода в плане
нумерации нет. Это повод проверить, а не выбрасывать.
"""
import re

BAD_FIRST = set('12567')
DOUBT = {'403', '857', '894'}


def _placeholder(sub):
    if len(set(sub)) == 1:                       # 0000000, 1111111
        return True
    asc = ''.join(str((int(sub[0]) + i) % 10) for i in range(7))
    dsc = ''.join(str((int(sub[0]) - i) % 10) for i in range(7))
    return sub in (asc, dsc)                     # 1234567, 7654321


def flag(phone):
    n = re.sub(r'\D', '', phone)
    if len(n) != 11 or n[0] != '7':
        return 'формат неверный'
    code, sub = n[1:4], n[4:]
    if code[0] in BAD_FIRST:
        return 'код не существует'
    if _placeholder(sub):
        return 'шаблон-заглушка'
    if code in DOUBT:
        return 'код сомнителен'
    return ''
