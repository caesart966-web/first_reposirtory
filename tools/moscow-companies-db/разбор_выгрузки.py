"""Разбор официальной выгрузки реестра членов СРО с сайта НОСТРОЙ.

На странице СРО (reestr.nostroy.ru/sro/294 и т.п.) есть кнопка «Выгрузить
реестр членов СРО». Она отдаёт Excel по 500 членов в файле — у крупной СРО
это десяток файлов. Скрипт собирает их в один список, сверяет с реестром
НОПРИЗ и раскладывает на листы, готовые к работе.

ПОЧЕМУ ЭТО НАДЁЖНЕЕ API

У НОСТРОЯ не отвечает ни список СРО, ни выборка членов по ID, а полный
перебор реестра — это 418 тысяч записей и часы ожидания. Кнопка на сайте
отдаёт ровно то, что нужно, и сразу с телефонами.

ЗАПУСК

    python разбор_выгрузки.py --файлы register*.xlsx ^
           --nopriz нопориз_исправленный.xlsx --out эксперстрой.xlsx ^
           --телефон-сро "+7(495) 151-25-21"

Листы на выходе:

    Нет в НОПРИЗ    действующие члены без проектного/изыскательского СРО —
                    это база под обзвон
    Исключённые     те, кто членство прекратил: СРО у них уже нет, а
                    контакты остались
    Общие телефоны  номера, записанные у нескольких компаний сразу
    Все члены       полный список с отметками

ПРО ОБЩИЕ ТЕЛЕФОНЫ

Один номер у десятка компаний — это почти всегда не они сами: либо телефон
самой СРО (укажите его через --телефон-сро, тогда он будет помечен), либо
агента, который их всех и приводил. Для обзвона такой номер бесполезен, а
иногда и вреден, поэтому он вынесен отдельно, а не отброшен молча.
"""

from __future__ import annotations

import argparse
import glob
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from mosstroybase.normalize import extract_phones  # noqa: E402

# Колонки официальной выгрузки: номер столбца -> как назовём у себя.
# Первые две строки файла — шапка в два яруса, данные идут с третьей.
ВЫГРУЗКА = {
    2: "Наименование", 3: "Сокращённое", 4: "Номер в реестре СРО",
    5: "Дата вступления", 6: "Дата госрегистрации", 7: "Дата прекращения",
    8: "Основание прекращения", 9: "ОГРН", 10: "ИНН", 11: "Телефоны",
    12: "Адрес", 13: "Руководитель",
}
СРО_КОЛОНКА = 0          # наименование самой СРО, заполнено не в каждой строке
ПЕРВАЯ_СТРОКА_ДАННЫХ = 2

БАЗОВЫЕ = ["Наименование", "Сокращённое", "ИНН", "Телефоны", "Руководитель",
           "Адрес", "Дата вступления", "Номер в реестре СРО", "ОГРН", "СРО"]
НОПРИЗ = ["В НОПРИЗ", "Проектирование: дата вступления", "Проектирование: СРО",
          "Изыскания: дата вступления", "Изыскания: СРО"]
ТЕЛЕФОНЫ = ["Свой телефон", "Телефон общий с", "Пометка по телефону"]
ИСКЛЮЧЕНИЕ = ["Дата прекращения", "Основание прекращения"]

ШИРИНА = {"Наименование": 52, "Сокращённое": 26, "ИНН": 14, "Телефоны": 30,
          "Руководитель": 34, "Адрес": 50, "Дата вступления": 15,
          "Номер в реестре СРО": 16, "ОГРН": 16, "СРО": 34,
          "Дата прекращения": 16, "Основание прекращения": 40,
          "В НОПРИЗ": 24, "Телефон общий с": 16, "Пометка по телефону": 34, "Свой телефон": 14}


def норм_инн(value) -> str:
    """Только цифры; ведущий ноль у регионов 01–09 Excel съедает."""
    digits = re.sub(r"\D", "", "" if value is None else str(value))
    if len(digits) == 9:
        return digits.zfill(10)
    if len(digits) == 11:
        return digits.zfill(12)
    return digits


def разобрать_сро(блок: str) -> dict:
    """Карточка СРО из первой колонки выгрузки: имя, номер, телефон.

    Там лежит не просто название, а вся карточка одной строкой через «;» —
    включая собственный телефон СРО. Его и достаём: именно он чаще всего
    оказывается «общим» у десятков компаний, и спрашивать его у человека
    незачем.
    """
    части = [ч.strip() for ч in re.split(r"[;\n]", блок or "") if ч.strip()]
    номер = next((m.group(0) for ч in части
                  if (m := re.search(r"СРО-[СПИ]-\d+-\d+", ч))), "")
    # Второй строкой идёт сокращённое наименование. Искать в нём слово «СРО»
    # нельзя: у «Ассоциации «Архитектурное наследие» его нет, и такое правило
    # подхватывало регистрационный номер вместо названия.
    имя = next((ч for ч in части[1:]
                if ":" not in ч and not re.fullmatch(r"СРО-[СПИ]-\d+-\d+", ч)),
               части[0] if части else "")
    телефон = next((ч.split(":", 1)[1] for ч in части
                    if ч.lower().startswith("телефон")), "")
    return {"имя": имя or (части[0] if части else ""), "номер": номер,
            "телефон": телефон.strip()}


def читать_выгрузку(пути: list[Path]) -> list[tuple[dict, list[dict]]]:
    """Члены из файлов выгрузки, сгруппированные по СРО.

    Каждый член занимает несколько строк: главную с ИНН и строки-продолжения
    с проверками и страховками. Берём только главные.

    Группировка по СРО обязательна: сайт называет файлы одинаково
    (register1500.xlsx у каждой СРО), поэтому в одной папке они неминуемо
    перемешиваются, а склеить членов разных СРО в один список — тихо
    испортить результат.
    """
    from openpyxl import load_workbook

    по_сро: dict[str, dict[str, dict]] = {}
    for путь in пути:
        ws = load_workbook(путь, read_only=True).active
        текущая = ""
        добавлено = 0
        for номер, строка in enumerate(ws.iter_rows(values_only=True)):
            if номер < ПЕРВАЯ_СТРОКА_ДАННЫХ:
                continue
            блок = строка[СРО_КОЛОНКА]
            if блок and str(блок).strip():
                текущая = str(блок).strip()
            инн = норм_инн(строка[10])
            if len(инн) not in (10, 12):
                continue
            запись = {имя: ("" if строка[к] is None else str(строка[к]).strip())
                      for к, имя in ВЫГРУЗКА.items()}
            запись["ИНН"] = инн
            if по_сро.setdefault(текущая, {}).setdefault(инн, запись) is запись:
                добавлено += 1
        сро = разобрать_сро(текущая)
        print(f"[выгрузка] {путь.name}: +{добавлено} членов "
              f"({сро['имя'] or 'СРО не определена'})", flush=True)

    результат = []
    for блок, члены in по_сро.items():
        сро = разобрать_сро(блок)
        подпись = " ".join(x for x in (сро["имя"], сро["номер"]) if x)
        for запись in члены.values():
            запись["СРО"] = подпись
        результат.append((сро, list(члены.values())))
    return результат


def читать_нопориз(путь: Path) -> tuple[dict, dict]:
    """ИНН -> (дата, СРО) отдельно по проектированию и изысканиям.

    Берётся самое раннее действующее членство каждого вида; исключённые
    не учитываются.
    """
    from openpyxl import load_workbook

    ws = load_workbook(путь, read_only=True).active
    строки = ws.iter_rows(values_only=True)
    шапка = [str(c) if c is not None else "" for c in next(строки)]
    поле = {имя: шапка.index(имя) for имя in
            ("ИНН", "СРО", "Вид деятельности", "Дата вступления", "Бывший член")
            if имя in шапка}

    проект: dict[str, tuple] = {}
    изыск: dict[str, tuple] = {}
    for прочитано, строка in enumerate(строки, 1):
        if прочитано % 25000 == 0:
            print(f"[нопориз] прочитано {прочитано} строк", flush=True)
        if str(строка[поле["Бывший член"]] or "").strip() == "да":
            continue
        инн = норм_инн(строка[поле["ИНН"]])
        дата = str(строка[поле["Дата вступления"]] or "").strip()
        if not инн or not дата:
            continue
        вид = str(строка[поле["Вид деятельности"]] or "")
        имя = str(строка[поле["СРО"]] or "")
        ключ = tuple(reversed(дата.split(".")))          # для сравнения «раньше»
        for слово, склад in (("проектирование", проект), ("изыскания", изыск)):
            if слово in вид and (инн not in склад or ключ < склад[инн][0]):
                склад[инн] = (ключ, дата, имя)
    return проект, изыск


def пометить_нопориз(члены: list[dict], проект: dict, изыск: dict) -> None:
    for запись in члены:
        инн = запись["ИНН"]
        п, и = проект.get(инн), изыск.get(инн)
        запись["Проектирование: дата вступления"] = п[1] if п else ""
        запись["Проектирование: СРО"] = п[2] if п else ""
        запись["Изыскания: дата вступления"] = и[1] if и else ""
        запись["Изыскания: СРО"] = и[2] if и else ""
        запись["В НОПРИЗ"] = ("проектирование и изыскания" if п and и else
                              "проектирование" if п else
                              "изыскания" if и else "нет")


def пометить_телефоны(члены: list[dict], телефоны_сро: str | None) -> list[dict]:
    """Отмечает номера, записанные сразу у нескольких компаний.

    Возвращает сводку по таким номерам. Номер самой СРО помечается отдельно:
    его компании указывают не потому, что связаны друг с другом.

    Главное здесь — колонка «Свой телефон». У «ЦСО» собственный номер СРО
    записан у 2048 членов из 2055: формально телефон есть у всех, а звонить
    некуда. Такие компании должны уходить в Checko наравне с теми, у кого
    поле телефона пустое, иначе база под обзвон наполовину мёртвая.
    """
    сро_норм = set(extract_phones(телефоны_сро or ""))
    владельцы: dict[str, list[dict]] = defaultdict(list)
    for запись in члены:
        запись["_номера"] = extract_phones(запись.get("Телефоны", ""))
        for номер in запись["_номера"]:
            владельцы[номер].append(запись)

    for запись in члены:
        номера = запись["_номера"]
        общие = [len(владельцы[н]) for н in номера if len(владельцы[н]) > 1]
        максимум = max(общие, default=1)
        свои = [н for н in номера if н not in сро_норм]
        запись["Телефон общий с"] = "" if максимум < 2 else f"{максимум} компаниями"
        запись["Свой телефон"] = "да" if свои else "нет"
        пометки = []
        if номера and not свои:
            пометки.append("только телефон СРО")
        elif any(н in сро_норм for н in номера):
            пометки.append("среди номеров есть телефон СРО")
        if максимум >= 10 and свои:
            пометки.append("похоже на агента")
        запись["Пометка по телефону"] = "; ".join(пометки)

    сводка = []
    for номер, компании in sorted(владельцы.items(), key=lambda kv: -len(kv[1])):
        if len(компании) < 2:
            continue
        сводка.append({
            "Телефон": номер,
            "Компаний": str(len(компании)),
            "Чей это номер": ("самой СРО" if номер in сро_норм else
                              "похоже на агента" if len(компании) >= 10 else ""),
            "Компании": "; ".join(к["Сокращённое"] or к["Наименование"]
                                  for к in компании[:20]),
            "ИНН": "; ".join(к["ИНН"] for к in компании[:20]),
        })
    for запись in члены:
        запись.pop("_номера", None)
    return сводка


def записать(путь: Path, листы: list[tuple[str, list[str], list[dict]]]) -> None:
    from openpyxl import Workbook

    wb = Workbook()
    первый = True
    for имя, колонки, строки in листы:
        ws = wb.active if первый else wb.create_sheet()
        ws.title = имя[:31]
        первый = False
        ws.append(колонки)
        for строка in строки:
            ws.append([строка.get(к, "") for к in колонки])
        for номер, к in enumerate(колонки):
            ws.column_dimensions[chr(65 + номер) if номер < 26 else
                                 "A" + chr(65 + номер - 26)].width = ШИРИНА.get(к, 22)
        ws.freeze_panes = "A2"
    wb.save(путь)


СВОД_КОЛОНКИ = ["СРО", "Рег. номер", "Телефон СРО", "Всего членов", "Действующих",
                "Под обзвон (не в НОПРИЗ)", "Без своего телефона", "Исключённых",
                "Исключённых не в НОПРИЗ"]


def свести(путь: Path, все_члены: list[dict], сводка_по_сро: list[dict],
           колонки_лидов: list[str], колонки_исключённых: list[str],
           телефоны_сро: str = "", сверять: bool = True) -> None:
    """Один файл по всем СРО сразу: и вся информация, и список под Checko.

    Общие телефоны здесь считаются заново, по объединённому списку: агент,
    который водит компании сразу в несколько СРО, виден только так — внутри
    одной СРО его номер может встретиться всего пару раз.
    """
    действующие = [з for з in все_члены if not з["Дата прекращения"]]
    исключённые = [з for з in все_члены if з["Дата прекращения"]]
    лиды = ([з for з in действующие if з["В НОПРИЗ"] == "нет"] if сверять
            else действующие)
    # Телефоны всех трёх СРО сразу: иначе номер одной из них выглядит агентским
    общие = пометить_телефоны(все_члены, телефоны_сро)
    для_checko = [з for з in лиды if з["Свой телефон"] == "нет"]

    колонки_обзвона = колонки_лидов

    записать(путь, [
        ("Сводка по СРО", СВОД_КОЛОНКИ, сводка_по_сро),
        ("Под обзвон" if сверять else "Действующие", колонки_обзвона, лиды),
        ("Для Checko", колонки_лидов, для_checko),
        ("Исключённые", колонки_исключённых, исключённые),
        ("Общие телефоны",
         ["Телефон", "Компаний", "Чей это номер", "Компании", "ИНН"], общие),
        ("Все члены", колонки_исключённых, все_члены),
    ])
    print()
    print(f"[свод] всего членов по всем СРО: {len(все_члены)}")
    print(f"[свод]   под обзвон:             {len(лиды)}")
    print(f"[свод]   со своим телефоном:     {len(лиды) - len(для_checko)}")
    print(f"[свод]   без своего телефона:    {len(для_checko)}  <- в Checko")
    print(f"[свод]   исключённых:            {len(исключённые)}")
    print(f"[свод] номеров у нескольких фирм: {len(общие)}")
    print(f"[свод] готово: {путь}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Разбор выгрузки реестра членов СРО с сайта НОСТРОЙ")
    parser.add_argument("--файлы", nargs="+", required=True,
                        help="файлы выгрузки, можно маской register*.xlsx")
    parser.add_argument("--nopriz", default=None,
                        help="выгрузка реестра НОПРИЗ; без неё сверка не делается")
    parser.add_argument("--out", default="члены_сро.xlsx",
                        help="куда сохранить (по файлу на каждую найденную СРО)")
    parser.add_argument("--свод", default=None,
                        help="дополнительно собрать все СРО в один файл с листами")
    parser.add_argument("--телефон-сро", default=None,
                        help="телефон самой СРО; по умолчанию берётся из карточки "
                             "в самой выгрузке")
    args = parser.parse_args(argv)

    пути = [Path(p) for шаблон in args.файлы for p in sorted(glob.glob(шаблон))]
    пути = [p for p in пути if p.exists()]
    if not пути:
        print("Файлы выгрузки не найдены.", file=sys.stderr)
        return 1

    группы = читать_выгрузку(пути)
    if not группы:
        print("В файлах не нашлось ни одной записи с ИНН.", file=sys.stderr)
        return 1
    if len(группы) > 1:
        print(f"[разбор] в файлах {len(группы)} разных СРО — сохраню каждую "
              "в свой файл")

    # Сверка с НОПРИЗ необязательна: для сбора телефонов она не нужна, а
    # выгрузка НОПРИЗ была неполной — тащить её ошибку в новые списки незачем.
    проект = изыск = {}
    сверять = bool(args.nopriz)
    if сверять:
        нопориз = Path(args.nopriz)
        if not нопориз.exists():
            print(f"Файл {нопориз} не найден.", file=sys.stderr)
            return 1
        проект, изыск = читать_нопориз(нопориз)
    else:
        print("[разбор] без сверки с НОПРИЗ — только действующие и телефоны")

    колонки_лидов = БАЗОВЫЕ + ТЕЛЕФОНЫ + (НОПРИЗ if сверять else [])
    колонки_исключённых = (БАЗОВЫЕ + ИСКЛЮЧЕНИЕ + ТЕЛЕФОНЫ +
                           (НОПРИЗ if сверять else []))
    out = Path(args.out)

    все_члены: list[dict] = []
    сводка_по_сро: list[dict] = []

    for сро, члены in группы:
        телефон_сро = args.телефон_сро or сро["телефон"]
        print()
        print(f"[разбор] СРО: {сро['имя']} {сро['номер']}")
        if телефон_сро:
            источник = "задан" if args.телефон_сро else "взят из карточки СРО"
            print(f"[разбор] телефон СРО: {телефон_сро} ({источник})")
        print(f"[разбор] уникальных членов: {len(члены)}")

        if сверять:
            пометить_нопориз(члены, проект, изыск)
        сводка_телефонов = пометить_телефоны(члены, телефон_сро)

        исключённые = [з for з in члены if з["Дата прекращения"]]
        действующие = [з for з in члены if not з["Дата прекращения"]]
        лиды = ([з for з in действующие if з["В НОПРИЗ"] == "нет"] if сверять
                else действующие)

        путь = out if len(группы) == 1 else out.with_name(
            f"{out.stem}_{сро['номер'] or len(члены)}{out.suffix}")
        записать(путь, [
            ("Нет в НОПРИЗ" if сверять else "Действующие", колонки_лидов, лиды),
            ("Исключённые", колонки_исключённых, исключённые),
            ("Общие телефоны",
             ["Телефон", "Компаний", "Чей это номер", "Компании", "ИНН"],
             сводка_телефонов),
            ("Все члены", колонки_исключённых, члены),
        ])

