# Первые цифры настоящих российских кодов: 3xx/4xx/8xx — города, 9xx — мобильные
_КОДЫ = "3489"

# Города, где у номера трёхзначный код и семь цифр, и код один на весь город:
# «212-27-95» у компании с адресом в Перми — это +7 (342) 212-27-95. Москвы
# здесь нет нарочно: там два кода, 495 и 499, и угадывать нельзя.
# Третье — начало ИНН того же региона: компания, переехавшая из Перми
# в Петербург, оставляет в реестре старые пермские номера, и по новому
# адресу они стали бы петербургскими
КОДЫ_ГОРОДОВ = (
    (re.compile(r"\bПермь\b", re.I), "342", "59"),
    (re.compile(r"\bСанкт-Петербург\b", re.I), "812", "78"),
    (re.compile(r"\bЕкатеринбург\b", re.I), "343", "66"),
    (re.compile(r"\bРостов-на-Дону\b", re.I), "863", "61"),
)


def код_города(адрес: str, инн: str | None = None) -> str | None:
    """Код города для номеров без кода. Если дан ИНН — только когда он
    из того же региона, что и адрес."""
    for город, код, регион in КОДЫ_ГОРОДОВ:
        if город.search(адрес or "") and (инн is None or str(инн).startswith(регион)):
            return код
    return None


def _достроить_коды(текст: str) -> str:
    """Коды городов, записанные не скобками, а как есть.

    «/34551/ 6-41-31» — код между косыми чертами: 288 компаний из пермских
    реестров с такими номерами уходили в Checko. А «(3522) 60-07-37,
    60-07-38» — второй номер записан без кода, но он из того же города:
    берёт код предыдущего номера в ячейке. Только код города — у мобильных
    (9xx) общий префикс ничего не значит.
    """
    текст = re.sub(r"/\s*(\d{3,5})\s*/", r"(\1)", текст)
    # «к. 34241, т. 3-19-16» — код и телефон подписаны словами
    текст = re.sub(r"(?i)\bк(?:од)?\.?\s*(\d{3,5})\s*[,;]?\s*т(?:ел)?\.?\s*:?\s*", r"(\1) ", текст)
    части = re.split(r"([,;\n])", текст)
    код = None
    for i, часть in enumerate(части):
        коды = re.findall(r"\((\d{3,5})\)", часть)
        if коды:
            код = коды[-1] if коды[-1][0] != "9" else None
            continue
        if код:
            м = re.fullmatch(r"(\s*(?:[А-Яа-яЁё.]+\s*:?\s*)?)(\d[\d\s\-–—]*\d)(\s*)", часть)
            if м and len(re.sub(r"\D", "", м.group(2))) == 10 - len(код):
                части[i] = f"{м.group(1)}({код}) {м.group(2)}{м.group(3)}"
    return "".join(части)


def номера_ячейки(текст: str, код: str | None = None) -> list[str]:
    """Телефоны из ячейки реестра в виде +7XXXXXXXXXX, без дублей.

    Общий extract_phones из пакета сделан для сайтов: он требует +7 или 8
    впереди, иначе в коде страниц ловятся номера счётчиков. В реестре же это
    поле телефона, и пишут там как попало: «(812) 234-27-21» без кода страны,
    «8 (34271) 2-15-63» с пятизначным кодом района, «+7 (342) 2-155-155».
    Строгий разбор такие номера терял — и компания с живым телефоном уходила
    в Checko, а номер самой СРО «(495) 799-66-07» не узнавался вовсе.

    Ячейка режется на группы цифр; запятая, точка с запятой, слово или «+»
    начинают новый номер. Подряд идущие группы делятся на номера так, чтобы
    номеров вышло больше всего: 10 цифр или 11 с 7/8 впереди. Городской
    номер без кода («212-27-95») достраивается кодом города из адреса
    компании (код_города), а без него пропускается: у «СТРОЙГАРАНТа» так
    записаны номера 80 действующих членов. Полный номер всегда важнее
    достроенного — иначе екатеринбургский «(343) 215-51-55» у пермской
    компании превратился бы в пермский.
    """
    прогоны: list[list[str]] = [[]]
    for кусок in re.finditer(r"\d+|\D+", _достроить_коды(текст or "")):
        t = кусок.group(0)
        if t[0].isdigit():
            прогоны[-1].append(t)
        elif "+" in t or re.search(r"[^\s\-().–—]", t):
            прогоны.append([])
    найдено: list[str] = []

    def номер(цифры: str) -> tuple[int, str] | None:
        """(вес, номер): полный номер весит 2, достроенный кодом города — 1."""
        if код and len(цифры) == 7 and цифры[0] in "234567":
            return 1, "+7" + код + цифры
        if len(цифры) == 11 and цифры[0] in "78":
            цифры = цифры[1:]
        if len(цифры) != 10 or цифры[0] not in _КОДЫ or len(set(цифры)) == 1:
            return None
        return 2, "+7" + цифры

    for группы in прогоны:
        n = len(группы)
        лучше: list[tuple[int, list[str]]] = [(0, [])] * (n + 1)
        for i in range(n - 1, -1, -1):
            вариант = лучше[i + 1]                     # группу пропустить
            for j in range(i + 1, n + 1):
                цифры = "".join(группы[i:j])
                if len(цифры) > 11:
                    break
                if (н := номер(цифры)) and н[0] + лучше[j][0] > вариант[0]:
                    вариант = (н[0] + лучше[j][0], [н[1]] + лучше[j][1])
            лучше[i] = вариант
        for н in лучше[0][1]:
            if н not in найдено:
                найдено.append(н)
    return найдено

# Колонки официальной выгрузки ищутся по шапке, а не по номеру. У НОПРИЗа
# после даты госрегистрации стоит «Статус (члена СРО)», и всё правее съезжает
# на одну колонку: по номерам из выгрузки НОСТРОЯ ИНН читался бы из колонки
# ОГРН, то есть не читался бы вовсе. Берётся первая подходящая колонка —
# у НОПРИЗа в самом конце есть ещё одни «Контактные телефоны», страховой
# компании.
ШАПКА = (
    ("Наименование", lambda x: x.startswith("полное наименование")),
    ("Сокращённое", lambda x: x.startswith("сокращенное наименование")),
    ("Номер в реестре СРО", lambda x: x.startswith("регистрационный номер")),
    ("Дата вступления", lambda x: x.startswith("дата регистрации в реестре")),
    ("Дата госрегистрации", lambda x: x.startswith("дата государственной регистрации")),
    ("Статус", lambda x: x.startswith("статус") and "прав" not in x),
    ("Дата прекращения", lambda x: x.startswith("дата прекращения")),
    ("Основание прекращения", lambda x: x.startswith("основание прекращения")),
    ("ОГРН", lambda x: x.startswith("огрн")),
    ("ИНН", lambda x: x == "инн"),
    ("Телефоны", lambda x: x.startswith("контактные телефоны")),
    ("Адрес", lambda x: x.startswith("адрес места нахождения")),
    ("Руководитель", lambda x: x.startswith("фамилия, имя, отчество лица")),
    ("ФИО ИП", lambda x: x.startswith("фамилия, имя, отчество") and "для ип" in x),
    ("Адрес ИП", lambda x: x.startswith("адрес места фактического")),
)
ПОЛЯ = [имя for имя, _ in ШАПКА if имя not in ("ФИО ИП", "Адрес ИП")]
СРО_КОЛОНКА = 0          # наименование самой СРО, заполнено не в каждой строке

БАЗОВЫЕ = ["Наименование", "Сокращённое", "ИНН", "Телефоны", "Руководитель",
           "Адрес", "Дата вступления", "Номер в реестре СРО", "ОГРН", "СРО"]
НОПРИЗ = ["В НОПРИЗ", "Проектирование: дата вступления", "Проектирование: СРО",
          "Изыскания: дата вступления", "Изыскания: СРО"]
ТЕЛЕФОНЫ = ["Свой телефон", "Телефон общий с", "Пометка по телефону"]
ИСКЛЮЧЕНИЕ = ["Дата прекращения", "Основание прекращения"]

ШИРИНА = {"Наименование": 52, "Сокращённое": 26, "ИНН": 14, "Телефоны": 30,
          "Руководитель": 34, "Адрес": 50, "Дата вступления": 15,
          "Номер в реестре СРО": 16, "ОГРН": 16, "СРО": 34,
          "Дата прекращения": 16, "Основание прекращения": 40,
          "В НОПРИЗ": 24, "Телефон общий с": 16, "Пометка по телефону": 34, "Свой телефон": 14}


def _норм(текст) -> str:
    return re.sub(r"\s+", " ", str(текст or "")).strip().lower().replace("ё", "е")


def найти_шапку(строки: list[tuple]) -> tuple[int, dict[str, int]] | None:
    """(номер строки шапки, поле -> номер колонки) или None, если это не
    выгрузка реестра СРО."""
    for номер, строка in enumerate(строки[:8]):
        ячейки = [_норм(x) for x in строка]
        if "инн" not in ячейки:
            continue
        колонки: dict[str, int] = {}
        for к, x in enumerate(ячейки):
            for поле, признак in ШАПКА:
                if поле not in колонки and признак(x):
                    колонки[поле] = к
        if {"ИНН", "Наименование"} <= set(колонки):
            return номер, колонки
    return None


def исключён(запись: dict) -> bool:
    """Членство прекращено: есть дата прекращения или так сказано в статусе
    (колонка «Статус» есть только в выгрузке НОПРИЗа)."""
    return bool(запись.get("Дата прекращения")) or bool(
        re.search(r"исключ|прекращ", (запись.get("Статус") or "").lower()))


def _дата_ключ(дата: str) -> tuple:
    m = re.match(r"(\d{1,2})\.(\d{1,2})\.(\d{4})", дата or "")
    return (int(m.group(3)), int(m.group(2)), int(m.group(1))) if m else (0, 0, 0)


def свежее(а: dict, б: dict) -> dict:
    """Одна компания бывает в реестре СРО дважды: исключили, потом приняли
    снова. Берётся последнее членство — действующее, иначе прекращённое
    позже; пустые поля дополняются из другой записи. Раньше оставалась
    первая запись, и вернувшаяся компания числилась исключённой."""
    def ключ(з: dict) -> tuple:
        return (not исключён(з), _дата_ключ(з.get("Дата прекращения")),
                _дата_ключ(з.get("Дата вступления")))
    новое, старое = (б, а) if ключ(б) > ключ(а) else (а, б)
    for поле in ("Телефоны", "Адрес", "Руководитель", "Сокращённое", "ОГРН"):
        if пусто(новое.get(поле)) and not пусто(старое.get(поле)):
            новое[поле] = старое[поле]
    # Телефоны — из обеих записей: в новой бывает только номер бухгалтерии,
    # а живой номер директора остался в старой
    if not пусто(старое.get("Телефоны")) and старое["Телефоны"] != новое["Телефоны"]:
        новое["Телефоны"] = f"{новое['Телефоны']}; {старое['Телефоны']}"
    return новое


def пусто(значение) -> bool:
    """Пустая ячейка или заглушка: «Сведения отсутствуют», «-», «нет»."""
    return not re.sub(r"сведения\s+отсутствуют|отсутствует|нет\b|[-–—\s.]", "",
                      str(значение or ""), flags=re.I)


def норм_инн(value) -> str:
    """Только цифры; ведущий ноль у регионов 01–09 Excel съедает."""
    digits = re.sub(r"\D", "", "" if value is None else str(value))
    if len(digits) == 9:
        return digits.zfill(10)
    if len(digits) == 11:
        return digits.zfill(12)
    return digits


def разобрать_сро(блок: str) -> dict:
    """Карточка СРО из первой колонки выгрузки: имя, номер, телефон.

    Там лежит не просто название, а вся карточка одной строкой через «;» —
    включая собственный телефон СРО. Его и достаём: именно он чаще всего
    оказывается «общим» у десятков компаний, и спрашивать его у человека
    незачем.
    """
    части = [ч.strip() for ч in re.split(r"[;\n]", блок or "") if ч.strip()]
    номер = next((m.group(0) for ч in части
                  if (m := re.search(r"СРО-[СПИ]-\d+-\d+", ч))), "")
    # Второй строкой идёт сокращённое наименование. Искать в нём слово «СРО»
    # нельзя: у «Ассоциации «Архитектурное наследие» его нет, и такое правило
    # подхватывало регистрационный номер вместо названия.
    имя = next((ч for ч in части[1:]
                if ":" not in ч and not re.fullmatch(r"СРО-[СПИ]-\d+-\d+", ч)),
               части[0] if части else "")
    телефон = next((ч.split(":", 1)[1] for ч in части
                    if ч.lower().startswith("телефон")), "")
    адрес = next((ч.split(":", 1)[1] for ч in части
                  if ч.lower().startswith("адрес местонахождения")), "")
    return {"имя": имя or (части[0] if части else ""), "номер": номер,
            "телефон": телефон.strip(), "адрес": адрес.strip()}


def читать_выгрузку(пути: list[Path]) -> list[tuple[dict, list[dict]]]:
    """Члены из файлов выгрузки, сгруппированные по СРО.

    Каждый член занимает несколько строк: главную с ИНН и строки-продолжения
    с проверками и страховками. Берём только главные.

    Группировка по СРО обязательна: сайт называет файлы одинаково
    (register1500.xlsx у каждой СРО), поэтому в одной папке они неминуемо
    перемешиваются, а склеить членов разных СРО в один список — тихо
    испортить результат.
    """
    from openpyxl import load_workbook

    по_сро: dict[str, dict[str, dict]] = {}
    for путь in пути:
        wb = load_workbook(путь, read_only=True)
        строки = list(wb.active.iter_rows(values_only=True))
        wb.close()
        шапка = найти_шапку(строки)
        if шапка is None:
            # Например, файл с результатом прошлого разбора, сохранённый
            # в ту же папку: прочитать его как выгрузку — значит задвоить всех
            print(f"[выгрузка] {путь.name}: это не выгрузка реестра СРО "
                  "(нет шапки с ИНН) — пропускаю", file=sys.stderr, flush=True)
            continue
        i_шапки, колонки = шапка
        текущая = ""
        добавлено = повторов = 0
        for строка in строки[i_шапки + 1:]:
            if not строка:
                continue
            блок = строка[СРО_КОЛОНКА]
            if блок and str(блок).strip():
                текущая = str(блок).strip()

            def взять(поле: str) -> str:
                к = колонки.get(поле)
                if к is None or к >= len(строка) or строка[к] is None:
                    return ""
                return str(строка[к]).strip()

            инн = норм_инн(взять("ИНН"))
            if len(инн) not in (10, 12):
                continue
            запись = {поле: взять(поле) for поле in ПОЛЯ}
            запись["ИНН"] = инн
            # У ИП руководителя нет — есть он сам и его адрес
            запись["Руководитель"] = запись["Руководитель"] or взять("ФИО ИП")
            запись["Адрес"] = запись["Адрес"] or взять("Адрес ИП")
            члены_сро = по_сро.setdefault(текущая, {})
            if инн in члены_сро:
                члены_сро[инн] = свежее(члены_сро[инн], запись)
                повторов += 1
            else:
                члены_сро[инн] = запись
                добавлено += 1
        сро = разобрать_сро(текущая)
        print(f"[выгрузка] {путь.name}: +{добавлено} членов "
              f"({сро['имя'] or 'СРО не определена'})"
              + (f", повторное членство у {повторов} — взято последнее" if повторов else ""),
              flush=True)

    результат = []
    for блок, члены in по_сро.items():
        сро = разобрать_сро(блок)
        подпись = " ".join(x for x in (сро["имя"], сро["номер"]) if x)
        for запись in члены.values():
            запись["СРО"] = подпись
        результат.append((сро, list(члены.values())))
    return результат


def читать_нопориз(путь: Path) -> tuple[dict, dict]:
    """ИНН -> (дата, СРО) отдельно по проектированию и изысканиям.

    Берётся самое раннее действующее членство каждого вида; исключённые
    не учитываются.
    """
    from openpyxl import load_workbook

    ws = load_workbook(путь, read_only=True).active
    строки = ws.iter_rows(values_only=True)
    шапка = [str(c) if c is not None else "" for c in next(строки)]
    поле = {имя: шапка.index(имя) for имя in
            ("ИНН", "СРО", "Вид деятельности", "Дата вступления", "Бывший член")
            if имя in шапка}

    проект: dict[str, tuple] = {}
    изыск: dict[str, tuple] = {}
    for прочитано, строка in enumerate(строки, 1):
        if прочитано % 25000 == 0:
            print(f"[нопориз] прочитано {прочитано} строк", flush=True)
        if str(строка[поле["Бывший член"]] or "").strip() == "да":
            continue
        инн = норм_инн(строка[поле["ИНН"]])
        дата = str(строка[поле["Дата вступления"]] or "").strip()
        if not инн or not дата:
            continue
        вид = str(строка[поле["Вид деятельности"]] or "")
        имя = str(строка[поле["СРО"]] or "")
        ключ = tuple(reversed(дата.split(".")))          # для сравнения «раньше»
        for слово, склад in (("проектирование", проект), ("изыскания", изыск)):
            if слово in вид and (инн not in склад or ключ < склад[инн][0]):
                склад[инн] = (ключ, дата, имя)
    return проект, изыск


def пометить_нопориз(члены: list[dict], проект: dict, изыск: dict) -> None:
    for запись in члены:
        инн = запись["ИНН"]
        п, и = проект.get(инн), изыск.get(инн)
        запись["Проектирование: дата вступления"] = п[1] if п else ""
        запись["Проектирование: СРО"] = п[2] if п else ""
        запись["Изыскания: дата вступления"] = и[1] if и else ""
        запись["Изыскания: СРО"] = и[2] if и else ""
        запись["В НОПРИЗ"] = ("проектирование и изыскания" if п and и else
                              "проектирование" if п else
                              "изыскания" if и else "нет")


def пометить_телефоны(члены: list[dict], телефоны_сро: str | set | None) -> list[dict]:
    """Отмечает номера, записанные сразу у нескольких компаний.

    Возвращает сводку по таким номерам. Номер самой СРО помечается отдельно:
    его компании указывают не потому, что связаны друг с другом.

    Главное здесь — колонка «Свой телефон». У «ЦСО» собственный номер СРО
    записан у 2048 членов из 2055: формально телефон есть у всех, а звонить
    некуда. Такие компании должны уходить в Checko наравне с теми, у кого
    поле телефона пустое, иначе база под обзвон наполовину мёртвая.
    """
    сро_норм = (set(телефоны_сро) if isinstance(телефоны_сро, set)
                else set(номера_ячейки(телефоны_сро or "")))
    владельцы: dict[str, list[dict]] = defaultdict(list)
    for запись in члены:
        запись["_номера"] = номера_ячейки(
            запись.get("Телефоны", ""),
            код_города(запись.get("Адрес", ""), запись.get("ИНН", "")))
        for номер in запись["_номера"]:
            владельцы[номер].append(запись)

    for запись in члены:
        номера = запись["_номера"]
        общие = [len(владельцы[н]) for н in номера if len(владельцы[н]) > 1]
        максимум = max(общие, default=1)
        свои = [н for н in номера if н not in сро_норм]
        запись["Телефон общий с"] = "" if максимум < 2 else f"{максимум} компаниями"
        запись["Свой телефон"] = "да" if свои else "нет"
        пометки = []
        if номера and not свои:
            пометки.append("только телефон СРО")
        elif any(н in сро_норм for н in номера):
            пометки.append("среди номеров есть телефон СРО")
        if максимум >= 10 and свои:
            пометки.append("похоже на агента")
        запись["Пометка по телефону"] = "; ".join(пометки)

    сводка = []
    for номер, компании in sorted(владельцы.items(), key=lambda kv: -len(kv[1])):
        if len(компании) < 2:
            continue
        сводка.append({
            "Телефон": номер,
            "Компаний": str(len(компании)),
            "Чей это номер": ("самой СРО" if номер in сро_норм else
                              "похоже на агента" if len(компании) >= 10 else ""),
            "Компании": "; ".join(к["Сокращённое"] or к["Наименование"]
                                  for к in компании[:20]),
            "ИНН": "; ".join(к["ИНН"] for к in компании[:20]),
        })
    for запись in члены:
        запись.pop("_номера", None)
    return сводка


def записать(путь: Path, листы: list[tuple[str, list[str], list[dict]]]) -> None:
    from openpyxl import Workbook

    wb = Workbook()
    первый = True
    for имя, колонки, строки in листы:
        ws = wb.active if первый else wb.create_sheet()
        ws.title = имя[:31]
        первый = False
        ws.append(колонки)
        for строка in строки:
            ws.append([строка.get(к, "") for к in колонки])
        for номер, к in enumerate(колонки):
            ws.column_dimensions[chr(65 + номер) if номер < 26 else
                                 "A" + chr(65 + номер - 26)].width = ШИРИНА.get(к, 22)
        ws.freeze_panes = "A2"
    wb.save(путь)


def очередь_checko(члены: list[dict], все: list[dict] | None = None) -> list[dict]:
    """Кого пробивать через Checko и в каком порядке.

    Одна строка на компанию: она бывает в двух СРО сразу (строительной
    и проектной), а платить за неё дважды незачем. Если свой телефон нашёлся
    хотя бы в одном реестре — в Checko она не идёт вовсе.

    Порядок — это порядок трат лимита (~100 в сутки): сначала действующие
    члены (они наверняка живы), потом исключённые, недавние первыми. Чем
    старше исключение, тем вероятнее, что компании уже нет: в Ростове из
    пробитых закрытыми оказались 43 %.
    """
    с_телефоном = {з["ИНН"] for з in (все or члены) if з.get("Свой телефон") == "да"}
    лучшая: dict[str, dict] = {}
    for з in члены:
        if з["ИНН"] in с_телефоном:
            continue
        было = лучшая.get(з["ИНН"])
        if было is None or (not исключён(з), _дата_ключ(з.get("Дата прекращения"))) > (
                not исключён(было), _дата_ключ(было.get("Дата прекращения"))):
            лучшая[з["ИНН"]] = з
    return sorted(лучшая.values(),
                  key=lambda з: (исключён(з), tuple(-x for x in _дата_ключ(з.get("Дата прекращения")))))


# Тот же вид, что у ростовского и питерского файлов для Checko: по нему
# работают checko_контакты.py и сборка списка на прозвон
КОЛОНКИ_CHECKO = ["Наименование", "ИНН", "СРО", "Статус", "Дата вступления",
                  "Дата прекращения", "Телефоны", "Руководитель", "Адрес"]


def записать_для_checko(путь: Path, очередь: list[dict]) -> None:
    from openpyxl import Workbook

    wb = Workbook()
    ws = wb.active
    ws.title = "Компании"
    ws.append(КОЛОНКИ_CHECKO)
    for з in очередь:
        строка = dict(з, Статус="исключён" if исключён(з) else "действующий")
        ws.append([строка.get(к, "") for к in КОЛОНКИ_CHECKO])
    for номер, к in enumerate(КОЛОНКИ_CHECKO):
        ws.column_dimensions[chr(65 + номер)].width = ШИРИНА.get(к, 16)
    ws.freeze_panes = "A2"
    wb.save(путь)


СВОД_КОЛОНКИ = ["СРО", "Рег. номер", "Телефон СРО", "Всего членов", "Действующих",
                "Под обзвон (не в НОПРИЗ)", "Без своего телефона", "Исключённых",
                "Исключённых не в НОПРИЗ"]


def свести(путь: Path, все_члены: list[dict], сводка_по_сро: list[dict],
           колонки_лидов: list[str], колонки_исключённых: list[str],
           телефоны_сро: str | set = "", сверять: bool = True,
           с_исключёнными: bool = False) -> list[dict]:
    """Один файл по всем СРО сразу: и вся информация, и список под Checko.

    Общие телефоны здесь считаются заново, по объединённому списку: агент,
    который водит компании сразу в несколько СРО, виден только так — внутри
    одной СРО его номер может встретиться всего пару раз.
    """
    действующие = [з for з in все_члены if not исключён(з)]
    исключённые = [з for з in все_члены if исключён(з)]
    лиды = ([з for з in действующие if з["В НОПРИЗ"] == "нет"] if сверять
            else действующие)
    # Телефоны всех трёх СРО сразу: иначе номер одной из них выглядит агентским
    общие = пометить_телефоны(все_члены, телефоны_сро)
    для_checko = очередь_checko(все_члены if с_исключёнными else лиды, все_члены)

    колонки_обзвона = колонки_лидов

    записать(путь, [
        ("Сводка по СРО", СВОД_КОЛОНКИ, сводка_по_сро),
        ("Под обзвон" if сверять else "Действующие", колонки_обзвона, лиды),
        ("Для Checko", колонки_лидов, для_checko),
        ("Исключённые", колонки_исключённых, исключённые),
        ("Общие телефоны",
         ["Телефон", "Компаний", "Чей это номер", "Компании", "ИНН"], общие),
        ("Все члены", колонки_исключённых, все_члены),
    ])
    print()
    print(f"[свод] всего членов по всем СРО: {len(все_члены)}")
    print(f"[свод]   под обзвон:             {len(лиды)}")
    if с_исключёнными:
        в_checko_действующих = sum(1 for з in для_checko if not исключён(з))
        print(f"[свод]   без своего телефона:    {в_checko_действующих}")
        print(f"[свод]   в Checko всего:         {len(для_checko)} — сначала "
              f"{в_checko_действующих} действующих, затем исключённые, "
              "недавние первыми")
    else:
        print(f"[свод]   со своим телефоном:     {len(лиды) - len(для_checko)}")
        print(f"[свод]   без своего телефона:    {len(для_checko)}  <- в Checko")
    print(f"[свод]   исключённых:            {len(исключённые)}")
    print(f"[свод] номеров у нескольких фирм: {len(общие)}")
    print(f"[свод] готово: {путь}")
    return для_checko


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Разбор выгрузки реестра членов СРО с сайта НОСТРОЙ")
    parser.add_argument("--файлы", nargs="+", required=True,
                        help="файлы выгрузки, можно маской register*.xlsx")
    parser.add_argument("--nopriz", default=None,
                        help="выгрузка реестра НОПРИЗ; без неё сверка не делается")
    parser.add_argument("--out", default="члены_сро.xlsx",
                        help="куда сохранить (по файлу на каждую найденную СРО)")
    parser.add_argument("--свод", default=None,
                        help="дополнительно собрать все СРО в один файл с листами")
    parser.add_argument("--телефон-сро", default=None,
                        help="телефон самой СРО; по умолчанию берётся из карточки "
                             "в самой выгрузке")
    parser.add_argument("--для-checko", default=None,
                        help="отдельный файл под checko_контакты.py: все, у кого нет "
                             "своего телефона, — действующие и исключённые")
    parser.add_argument("--без-исключённых", action="store_true",
                        help="в файл для Checko — только действующих членов")
    args = parser.parse_args(argv)

    пути = [Path(p) for шаблон in args.файлы for p in sorted(glob.glob(шаблон))]
    пути = [p for p in пути if p.exists()]
    if not пути:
        print("Файлы выгрузки не найдены.", file=sys.stderr)
        return 1

    группы = читать_выгрузку(пути)
    if not группы:
        print("В файлах не нашлось ни одной записи с ИНН.", file=sys.stderr)
        return 1
    if len(группы) > 1:
        print(f"[разбор] в файлах {len(группы)} разных СРО — сохраню каждую "
              "в свой файл")

    # Сверка с НОПРИЗ необязательна: для сбора телефонов она не нужна, а
    # выгрузка НОПРИЗ была неполной — тащить её ошибку в новые списки незачем.
    проект = изыск = {}
    сверять = bool(args.nopriz)
    if сверять:
        нопориз = Path(args.nopriz)
        if not нопориз.exists():
            print(f"Файл {нопориз} не найден.", file=sys.stderr)
            return 1
        проект, изыск = читать_нопориз(нопориз)
    else:
        print("[разбор] без сверки с НОПРИЗ — только действующие и телефоны")

    колонки_лидов = БАЗОВЫЕ + ТЕЛЕФОНЫ + (НОПРИЗ if сверять else [])
    колонки_исключённых = (БАЗОВЫЕ + ИСКЛЮЧЕНИЕ + ТЕЛЕФОНЫ +
                           (НОПРИЗ if сверять else []))
    out = Path(args.out)

    все_члены: list[dict] = []
    сводка_по_сро: list[dict] = []
    номера_всех_сро: set[str] = set()

    for сро, члены in группы:
        телефон_сро = args.телефон_сро or сро["телефон"]
        print()
        print(f"[разбор] СРО: {сро['имя']} {сро['номер']}")
        if телефон_сро:
            источник = "задан" if args.телефон_сро else "взят из карточки СРО"
            print(f"[разбор] телефон СРО: {телефон_сро} ({источник})")
        print(f"[разбор] уникальных членов: {len(члены)}")

        if сверять:
            пометить_нопориз(члены, проект, изыск)
        номера_сро = set(номера_ячейки(телефон_сро, код_города(сро["адрес"])))
        номера_всех_сро |= номера_сро
        сводка_телефонов = пометить_телефоны(члены, номера_сро)

        исключённые = [з for з in члены if исключён(з)]
        действующие = [з for з in члены if not исключён(з)]
        лиды = ([з for з in действующие if з["В НОПРИЗ"] == "нет"] if сверять
                else действующие)

        путь = out if len(группы) == 1 else out.with_name(
            f"{out.stem}_{сро['номер'] or len(члены)}{out.suffix}")
        записать(путь, [
            ("Нет в НОПРИЗ" if сверять else "Действующие", колонки_лидов, лиды),
            ("Исключённые", колонки_исключённых, исключённые),
            ("Общие телефоны",
             ["Телефон", "Компаний", "Чей это номер", "Компании", "ИНН"],
             сводка_телефонов),
            ("Все члены", колонки_исключённых, члены),
        ])

        без_телефона = sum(1 for з in лиды if з["Свой телефон"] == "нет")
        исключённые_без_нопориз = (sum(1 for з in исключённые
                                       if з["В НОПРИЗ"] == "нет") if сверять else 0)
        print(f"[разбор] действующих членов:        {len(действующие)}")
        if сверять:
            print(f"[разбор]   из них НЕ в НОПРИЗ:      {len(лиды)}  <- база под обзвон")
        print(f"[разбор]   без своего телефона:     {без_телефона}")
        print(f"[разбор] исключённых:               {len(исключённые)}")
        if сверять:
            print(f"[разбор]   из них НЕ в НОПРИЗ:      {исключённые_без_нопориз}")
        print(f"[разбор] номеров у нескольких фирм: {len(сводка_телефонов)}")
        print(f"[разбор] готово: {путь}")

        все_члены.extend(члены)
        сводка_по_сро.append({
            "СРО": сро["имя"], "Рег. номер": сро["номер"],
            "Телефон СРО": телефон_сро,
            "Всего членов": str(len(члены)),
            "Действующих": str(len(действующие)),
            "Под обзвон (не в НОПРИЗ)": str(len(лиды)),
            "Без своего телефона": str(без_телефона),
            "Исключённых": str(len(исключённые)),
            "Исключённых не в НОПРИЗ": str(исключённые_без_нопориз),
        })

    с_исключёнными = bool(args.для_checko) and not args.без_исключённых
    телефоны_всех_сро = номера_всех_сро
    очередь: list[dict] = []
    if args.свод:
        очередь = свести(Path(args.свод), все_члены, сводка_по_сро,
                         колонки_лидов, колонки_исключённых, телефоны_всех_сро,
                         сверять, с_исключёнными)
    elif args.для_checko:
        # Свой ли телефон — по всем СРО сразу, как и в своде
        пометить_телефоны(все_члены, телефоны_всех_сро)
        кандидаты = (все_члены if с_исключёнными else
                     [з for з in все_члены if not исключён(з)
                      and (not сверять or з.get("В НОПРИЗ") == "нет")])
        очередь = очередь_checko(кандидаты, все_члены)
    if args.для_checko:
        записать_для_checko(Path(args.для_checko), очередь)
        действующих = sum(1 for з in очередь if not исключён(з))
        print(f"[checko] файл для Checko: {args.для_checko} — {len(очередь)} компаний "
              f"(действующих {действующих}, исключённых {len(очередь) - действующих}); "
              f"при ~100 запросах в сутки это {-(-len(очередь) // 100)} дн. на одном ключе")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
