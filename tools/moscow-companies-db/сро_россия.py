def субъект(город, инн) -> tuple[str, str]:
    """(субъект РФ, откуда взят): по городу из реестра, иначе по коду региона в ИНН."""
    н = _норм(город)
    if н in ГОРОДА:
        return СУБЪЕКТЫ[ГОРОДА[н]], "город"
    if re.search(r"област|обл\b|край|республик|округ|югра", н):
        # самая длинная примета: «ямало-ненецкий» важнее «ненецкий», «алтайский» — «алтай»
        кандидаты = [(len(п), код) for код, приметы in ПРИМЕТЫ.items() for п in приметы if п in н]
        if кандидаты:
            return СУБЪЕКТЫ[max(кандидаты)[1]], "город"
    for слово in н.split():
        if слово in ГОРОДА:
            return СУБЪЕКТЫ[ГОРОДА[слово]], "город"
    код = re.sub(r"\D", "", str(инн or ""))[:2]
    if код in СУБЪЕКТЫ:
        return СУБЪЕКТЫ[код], "ИНН"
    return "не определён", "нет"


def вид(рег_номер: str) -> str:
    """С / П / И по рег. номеру: «СРО-С-…», «СРО-П-…», «СРО-И-…», «02-С-2009»."""
    м = re.search(r"(?:^|-)([СПИCПI])-", str(рег_номер or "").upper())
    return {"C": "С", "I": "И"}.get(м.group(1), м.group(1)) if м else "?"


