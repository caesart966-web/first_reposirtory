def _норм(текст) -> str:
    т = str(текст or "").lower().replace("ё", "е").replace("—", " ").replace("–", " ")
    т = re.sub(r"(?<![а-я])г\.\s*", " ", т)
    т = re.sub(r"(?<![а-я])город\s+", " ", т)
    return " ".join(т.replace(",", " ").split())


def _города() -> dict[str, str]:
    out = {}
    for часть in _ГОРОДА.replace("\n", " ").split(";"):
        код, *_ = часть.split()
        текст = часть.strip()[len(код):]
        # «нижний новгород», «набережные челны», «новый уренгой»… — составные
        for составное in ("нижний новгород", "набережные челны", "великий новгород", "новый уренгой",
                          "нижний тагил", "старый оскол"):
            if составное in текст:
                out[составное] = код
                текст = текст.replace(составное, " ")
        for г in текст.split():
            out.setdefault(г, код)
    return out


