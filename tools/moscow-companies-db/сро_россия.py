def _годы(x: dict) -> list:
    вступ = [x.get(f"вступило_{г}", 0) for г in ГОДЫ]
    искл = [x.get(f"исключено_{г}", 0) for г in ГОДЫ]
    return [*вступ, sum(вступ), *искл, sum(искл), x.get("без_даты_искл", 0)]


