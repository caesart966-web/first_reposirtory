def прочитать(путь: Path) -> list[dict]:
    d = json.loads(Path(путь).read_text(encoding="utf-8"))
    out = []
    for x in d["сро"]:
        к = x.get("карточка") or {}
        x = dict(x, вид=вид(x["рег_номер"]))
        x["регион"], x["регион_откуда"] = субъект(к.get("город"), x.get("инн"))
        x["город_в_реестре"] = к.get("город")
        out.append(x)
    return out


