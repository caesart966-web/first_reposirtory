def _падеж_отчества(о: str) -> tuple[str, str] | None:
    """(пол, падеж) по окончанию отчества; падеж: им, род_вин (м.), вин (ж.), род (ж.), дат, твор, пред."""
    о = о.lower()
    if о.endswith(("оглы", "кызы")):
        return ("м" if о.endswith("оглы") else "ж"), "им"
    for конец, падеж in (("ич", "им"), ("ича", "род_вин"), ("ичу", "дат"), ("ичем", "твор"), ("иче", "пред")):
        if о.endswith(конец):
            return "м", падеж
    for конец, падеж in (("а", "им"), ("у", "вин"), ("ы", "род"), ("ой", "твор"), ("е", "дат")):
        if re.search(r"(?:вн|чн)" + конец + "$", о):
            return "ж", падеж
    return None


def _имя_м(и: str, падеж: str) -> str:
    if и in _ИМЯ_ОСОБЫЕ:
        return _ИМЯ_ОСОБЫЕ[и]
    замены = {"род_вин": (("ия", "ий"), ("ея", "ей"), ("ая", "ай"), ("ря", "рь"), ("ля", "ль"), ("а", "")),
              "дат": (("ию", "ий"), ("ею", "ей"), ("аю", "ай"), ("рю", "рь"), ("лю", "ль"), ("у", "")),
              "твор": (("ием", "ий"), ("еем", "ей"), ("аем", "ай"), ("рем", "рь"), ("лем", "ль"), ("ом", "")),
              "пред": (("ии", "ий"), ("е", ""))}.get(падеж, ())
    for было, стало in замены:
        if и.endswith(было):
            и = и[: len(и) - len(было)] + стало
            break
    return _ИМЯ_ОСОБЫЕ.get(и, и)


def _имя_ж(и: str, падеж: str) -> str:
    if и in _ИМЯ_ОСОБЫЕ:
        return _ИМЯ_ОСОБЫЕ[и]
    замены = {"вин": (("ию", "ия"), ("ью", "ья"), ("ю", "я"), ("у", "а")),
              "род": (("ии", "ия"), ("ьи", "ья"), ("ги", "га"), ("ки", "ка"), ("хи", "ха"), ("жи", "жа"),
                      ("ши", "ша"), ("чи", "ча"), ("щи", "ща"), ("ы", "а"), ("и", "я")),
              "дат": (("ии", "ия"), ("ье", "ья"), ("е", "а")),
              "твор": (("ией", "ия"), ("ьей", "ья"), ("ей", "я"), ("ой", "а"))}.get(падеж, ())
    for было, стало in замены:
        if и.endswith(было):
            return и[: len(и) - len(было)] + стало
    return и


def _фамилия_м(ф: str, падеж: str) -> str:
    части = ф.split("-")
    return "-".join(_фамилия_м1(ч, падеж) for ч in части)


def _фамилия_м1(ф: str, падеж: str) -> str:
    н = ф.lower()
    if падеж == "род_вин":
        for было, стало in (("ского", "ский"), ("цкого", "цкий"), ("ского", "ский"), ("ого", "ой"),
                            ("его", "ий"), ("ова", "ов"), ("ева", "ев"), ("ёва", "ёв"), ("ина", "ин"),
                            ("ына", "ын")):
            if н.endswith(было):
                return ф[: len(ф) - len(было)] + стало
        if н.endswith(("ля", "ря")) and len(н) > 3:          # Коваля → Коваль
            return ф[:-1] + "ь"
        if н.endswith("я") and len(н) > 3 and н[-2] in _ГЛАСНЫЕ:   # Гайдая → Гайдай
            return ф[:-1] + "й"
        if н.endswith("а") and len(н) > 3 and н[-2] not in _ГЛАСНЫЕ:  # Мельника → Мельник
            return ф[:-1]
        return ф
    if падеж == "дат":
        for было, стало in (("скому", "ский"), ("цкому", "цкий"), ("ому", "ой"), ("ову", "ов"),
                            ("еву", "ев"), ("ину", "ин"), ("ыну", "ын")):
            if н.endswith(было):
                return ф[: len(ф) - len(было)] + стало
        if н.endswith("у") and len(н) > 3 and н[-2] not in _ГЛАСНЫЕ:
            return ф[:-1]
        return ф
    if падеж == "твор":
        for было, стало in (("ским", "ский"), ("цким", "цкий"), ("овым", "ов"), ("евым", "ев"),
                            ("иным", "ин"), ("ыным", "ын")):
            if н.endswith(было):
                return ф[: len(ф) - len(было)] + стало
        if н.endswith("ом") and len(н) > 4 and н[-3] not in _ГЛАСНЫЕ:
            return ф[:-2]
        return ф
    if падеж == "пред":
        for было, стало in (("ском", "ский"), ("цком", "цкий"), ("ове", "ов"), ("еве", "ев"), ("ине", "ин")):
            if н.endswith(было):
                return ф[: len(ф) - len(было)] + стало
        return ф
    return ф


def _фамилия_ж(ф: str, падеж: str) -> str:
    return "-".join(_фамилия_ж1(ч, падеж) for ч in ф.split("-"))


def _фамилия_ж1(ф: str, падеж: str) -> str:
    н = ф.lower()
    if падеж == "вин":
        for было, стало in (("скую", "ская"), ("цкую", "цкая"), ("ову", "ова"), ("еву", "ева"),
                            ("ёву", "ёва"), ("ину", "ина"), ("ыну", "ына"), ("ую", "ая")):
            if н.endswith(было):
                return ф[: len(ф) - len(было)] + стало
        return ф
    if падеж in ("род", "дат", "твор"):
        for было, стало in (("ской", "ская"), ("цкой", "цкая"), ("овой", "ова"), ("евой", "ева"),
                            ("ёвой", "ёва"), ("иной", "ина"), ("ыной", "ына")):
            if н.endswith(было):
                return ф[: len(ф) - len(было)] + стало
        return ф
    return ф


def именительный(ф: str, и: str, о: str) -> str:
    """«Иванова Ивана Ивановича» → «Иванов Иван Иванович» (падеж и пол — по отчеству)."""
    пп = _падеж_отчества(о)
    if not пп or пп[1] == "им":
        return f"{ф} {и} {о}"
    пол, падеж = пп
    if пол == "м":
        о2 = re.sub(r"(ич)(а|у|ем|е)$", r"\1", о)
        return f"{_фамилия_м(ф, падеж)} {_имя_м(и, падеж)} {о2}"
    о2 = re.sub(r"(н)(у|ы|ой|е)$", r"\1а", о)
    return f"{_фамилия_ж(ф, падеж)} {_имя_ж(и, падеж)} {о2}"


def фамилия_при_инициалах(ф: str, падеж: str | None) -> str:
    """«Иванова» при «И. И.» в косвенном падеже: пол угадывается по окончанию."""
    н = ф.lower()
    if падеж in (None, "им"):
        return ф
    if падеж == "вин":                       # «избрать … Иванова И. И.» / «… Иванову И. И.»
        if н.endswith(("ову", "еву", "ёву", "ину", "ыну", "скую", "цкую")):
            return _фамилия_ж(ф, "вин")
        return _фамилия_м(ф, "род_вин")
    if падеж == "род":
        if н.endswith(("овой", "евой", "иной", "ской", "цкой")):
            return _фамилия_ж(ф, "род")
        return _фамилия_м(ф, "род_вин")
    if падеж == "дат":
        if н.endswith(("овой", "евой", "иной", "ской", "цкой")):
            return _фамилия_ж(ф, "дат")
        return _фамилия_м(ф, "дат")
    if падеж == "твор":
        if н.endswith(("овой", "евой", "иной", "ской", "цкой")):
            return _фамилия_ж(ф, "твор")
        return _фамилия_м(ф, "твор")
    return ф


# ---------------------------------------------------------------- поиск в тексте документа

_СЛОВО = п._СЛОВО
_ОТЧ_ЛЮБОЙ = r"[А-ЯЁа-яё][а-яё]+(?:ич(?:а|у|ем|е)?|(?:вн|ичн)(?:а|у|ы|ой|е)|оглы|кызы)"
_ФИО_ЛЮБОЙ = re.compile(rf"({_СЛОВО})\s+({_СЛОВО})\s+({_ОТЧ_ЛЮБОЙ})(?![а-яё])"
                        rf"|({_СЛОВО})\s+({_ОТЧ_ЛЮБОЙ})\s+({_СЛОВО})(?![а-яё])"
                        rf"|({_СЛОВО})\s+([А-ЯЁ])\.\s*([А-ЯЁ])\.(?![а-яё])"
                        rf"|([А-ЯЁ])\.\s*([А-ЯЁ])\.\s*({_СЛОВО})(?![а-яё])")
_ДОЛЖНОСТЬ = re.compile(r"(?<![а-яё])председател(ь|я|ю|ем|е)\s+(совета|правления|наблюдательного\s+совета|"
                        r"президиума|коллегии|постоянно\s+действующего\s+коллегиального\s+органа)", re.I)
_ИЗБРАТЬ = re.compile(r"(?<![а-яё])(?:пере)?(?:избрать|избрали|избирается|назначить|утвердить)(?![а-яё])", re.I)
_ИЗБРАН = re.compile(r"(?<![а-яё])(?:пере)?избран[аы]?(?![а-яё])", re.I)
_ЗАМ_ПЕРЕД = re.compile(r"(заместител\w*|зам\.|и\.\s*о\.|врио|исполняющ\w*|бывш\w+|почет\w+|почёт\w+|"
                        r"прежн\w+|экс-?)\s*$", re.I)
# между должностью и именем — значит, имя не к ней
_МЕЖДУ_НЕЛЬЗЯ = re.compile(r"член|\n\s*\n|;|заместител|секретар|ревизор|комисси", re.I)
# «председатель правления ТОООИ «Инстрой»» — совет или правление другой организации (но не «…АСРО «…»»)
_ЧУЖАЯ_АББР = re.compile(r"\s*(?![А-ЯЁ]*СРО)[А-ЯЁ]{3,}\s*[«\"„]")
_ПАДЕЖ_ДОЛЖНОСТИ = {"ь": "им", "я": "род", "ю": "дат", "ем": "твор", "е": "пред"}


_НЕ_ФАМИЛИЯ_НАЧАЛО = re.compile(r"(председател|ассоциаци|союз|совет|член|генеральн|директор|президент|"
                                r"саморегулир|организаци|правлени|партнерств|общ|протокол|решени|"
                                r"избра|собрани|секретар|заместител|голосова|кандидат)", re.I)


def _не_фамилия(слово: str) -> bool:
    return слово in п._НЕ_ФАМИЛИЯ or bool(_НЕ_ФАМИЛИЯ_НАЧАЛО.match(слово))


def _та_же_фраза(текст: str) -> str:
    """Конец текста после последней точки (не после инициала «И.»), точки с запятой или пустой строки."""
    границы = list(re.finditer(r"(?<![А-ЯЁ])[.;!?](?=\s)|\n\s*\n", текст))
    return текст[границы[-1].end():] if границы else текст


def _имя_из(м: re.Match, падеж_контекста: str | None) -> tuple[str, str] | None:
    """(имя в именительном, как в тексте) из совпадения _ФИО_ЛЮБОЙ."""
    г = м.groups()
    как = " ".join(м.group(0).split())
    if г[0] or г[3]:
        ф, и, о = (г[0], г[1], г[2]) if г[0] else (г[5], г[3], г[4])
        if _не_фамилия(ф) or _не_фамилия(и):
            return None
        return именительный(ф, и, о[:1].upper() + о[1:]), как
    if г[6]:
        ф, и, о = г[6], г[7], г[8]
    else:
        ф, и, о = г[11], г[9], г[10]
    if _не_фамилия(ф):
        return None
    return f"{фамилия_при_инициалах(ф, падеж_контекста)} {и}. {о}.", как


def найти_в_документе(текст: str) -> tuple[int, str, str, str] | None:
    """(вес, имя, как в тексте, фрагмент) — председатель совета в тексте протокола.

    вес 0 — избрание («избрать Председателем Совета Иванова И. И.», «Председателем Совета
    избран Иванов»), 1 — должность с именем в именительном («Председатель Совета: Иванов»),
    2 — упоминание в косвенном падеже («доклад Председателя Совета Иванова И. И.»)."""
    лучшее = None
    for м in _ДОЛЖНОСТЬ.finditer(текст):
        if _ЗАМ_ПЕРЕД.search(текст[max(0, м.start() - 40):м.start()]):
            continue
        хвост = текст[м.end():м.end() + 60]
        if п._ЧУЖОЙ.match(хвост) or п._АББР.match(хвост) or _ЧУЖАЯ_АББР.match(хвост):
            continue
        окончание = м.group(1).lower()
        # «Будзуляк Богдан Владимирович (председатель Совета Ассоциации) 2. Беляева …» — должность
        # в скобках относится к имени перед скобкой, следующее имя — уже другой человек
        в_скобках = bool(re.match(r"[^()\n]{0,80}\)", хвост)) and \
            bool(re.search(r"\(\s*$", текст[max(0, м.start() - 5):м.start()]))
        перед = текст[max(0, м.start() - 200):м.start()]
        после = текст[м.end():м.end() + 220]
        выбор = []                                   # (вес, расстояние, имя, как)
        # имя после должности: «… Председателем Совета Ассоциации Иванова Ивана Ивановича»
        фраза = _та_же_фраза(перед)
        for ф in ([] if в_скобках else _ФИО_ЛЮБОЙ.finditer(после)):
            между = после[:ф.start()]
            # «избрать Председателем Совета из числа членов Совета Иванова И. И.» — имя к должности
            между_чист = re.sub(r"из\s+числа\s+член\w*(?:\s+совета)?", " ", между, flags=re.I)
            if _МЕЖДУ_НЕЛЬЗЯ.search(между_чист) or п._ЛИШНЕЕ.search(между_чист) or ф.start() > 160:
                break
            # избирают «Председателем Совета» — творительный; «Председатель Совета Орлов» после
            # «избрать председателем собрания Козлова» — не избрание
            творительный = окончание == "ем"
            избрание = творительный and bool(_ИЗБРАТЬ.search(фраза) or _ИЗБРАТЬ.search(между))
            избран = творительный and bool(_ИЗБРАН.search(фраза[-60:]) or _ИЗБРАН.search(между))
            if избрание and not избран:
                падеж = "вин"
            elif избран:
                падеж = "им"
            else:
                падеж = _ПАДЕЖ_ДОЛЖНОСТИ.get(окончание, "им")
            имя = _имя_из(ф, падеж)
            if имя:
                вес = 0 if (избрание or избран) else 1 if падеж == "им" else 2
                выбор.append((вес, ф.start(), *имя))
            break
        # имя перед должностью: «Избрать Иванова И. И. Председателем Совета», «Иванов И. И. избран
        # Председателем Совета», «Иванов Иван Иванович — Председатель Совета»
        последнее = None
        for ф in _ФИО_ЛЮБОЙ.finditer(перед):
            последнее = ф
        if последнее is not None:
            между = перед[последнее.end():]
            рядом = re.fullmatch(r"[\s,:–—-]*(?:(?:был[аи]?\s+)?(?:пере)?избран[аы]?\s+|на\s+должность\s+)?\(?\s*",
                                 между)
            избрание = bool(_ИЗБРАТЬ.search(_та_же_фраза(перед[:последнее.start()])[-80:]))
            избран = bool(_ИЗБРАН.search(между))
            полное = bool(последнее.group(1) or последнее.group(4))
            # связь имени с должностью должна быть видна: творительный при избрании («Избрать
            # Иванова И. И. Председателем»), тире или запятая («Иванов И. И. — Председатель Совета»);
            # иначе «…председателем собрания Козлова К. К. Председатель Совета Орлов» — чужое имя
            if в_скобках:
                связь = True
            elif окончание == "ем":
                связь = избрание or избран
            elif окончание == "ь":
                связь = bool(re.search(r"[–—,-]", между)) or ("\n" in между and полное)
            else:
                связь = bool(re.search(r"[–—,-]", между))
            if рядом and связь:
                падеж = ("вин" if избрание and not избран else "им" if избран
                         else _ПАДЕЖ_ДОЛЖНОСТИ.get(окончание, "им"))
                имя = _имя_из(последнее, падеж)
                if имя:
                    вес = 0 if (избрание or избран) else 1 if падеж == "им" else 2
                    выбор.append((вес, len(между), *имя))
        if not выбор:
            continue
        вес, расстояние, имя, как = min(выбор)
        фрагмент = " ".join(текст[max(0, м.start() - 200):м.end() + 200].split())
        if лучшее is None or (вес, расстояние) < лучшее[0]:
            лучшее = ((вес, расстояние), (вес, имя, как, фрагмент))
    return лучшее[1] if лучшее else None


_МЕСЯЦЫ = {м: i for i, м in enumerate(("января", "февраля", "марта", "апреля", "мая", "июня", "июля",
                                        "августа", "сентября", "октября", "ноября", "декабря"), 1)}


def дата(текст: str) -> tuple[int, int, int] | None:
    """Первая дата в тексте: «25.04.2024», «25 апреля 2024», «“25” апреля 2024 г.»."""
    кандидаты = []
    if (м := re.search(r"(?<!\d)(\d{1,2})\.(\d{1,2})\.(20[0-3]\d)(?!\d)", текст)):
        кандидаты.append((м.start(), (int(м.group(3)), int(м.group(2)), int(м.group(1)))))
    if (м := re.search(r"(?<!\d)(\d{1,2})\W{0,3}\s*(" + "|".join(_МЕСЯЦЫ) + r")\s+(20[0-3]\d)", текст, re.I)):
        кандидаты.append((м.start(), (int(м.group(3)), _МЕСЯЦЫ[м.group(2).lower()], int(м.group(1)))))
    if not кандидаты:
        return None
    д = min(кандидаты)[1]
    return д if 1 <= д[1] <= 12 and 1 <= д[2] <= 31 else None


def _дата_строкой(д: tuple[int, int, int] | None) -> str:
    if not д:
        return ""
    г, м, ч = д
    return f"{ч:02d}.{м:02d}.{г}" if ч else f"{г} г."


def год(*строки: str) -> int:
    годы = [int(г) for с in строки for г in re.findall(r"(?<!\d)(20[0-3]\d)(?!\d)", unquote(с or ""))]
    return max(годы) if годы else 0


# ---------------------------------------------------------------- ссылки на документы

_ДОК_РАСШ = re.compile(r"\.(pdf|docx?)(?:$|[?#])", re.I)
_ДОК_ПОХОЖЕ = re.compile(r"download|getfile|get_file|file\.php|attachment|/upload\w*/.*\?|[?&]file=", re.I)
_НЕ_ТОТ = re.compile(r"дисциплинар|ревизион|контрольн\w*\s+комитет|экспертн|аттестац|счетн|счётн|"
                     r"квалификац|оценк[аи]\s+соответств|бухгалтер|финансов\w*\s+отчет|аудит|смет[аы]|"
                     r"disciplin|revizion|audit", re.I)


def оценка_ссылки(подпись: str, url: str) -> int | None:
    """Чем меньше, тем раньше читать; None — документ не про органы управления."""
    к = f"{подпись} {unquote(url)}".lower().replace("ё", "е")
    if _НЕ_ТОТ.search(к):
        return None
    собрание = re.search(r"собрани|sobrani|(?<![а-яa-z])ос(?![а-яa-z])", к)
    протокол = re.search(r"протокол|protokol|protocol|выписк|vypisk|решени|resheni", к)
    совет = re.search(r"совет|sovet|правлени|pravlen|президиум|prezidium|коллеги", к)
    if собрание and протокол:
        return 0
    if собрание:
        return 1
    if совет and (протокол or re.search(r"состав|sostav|избран|izbran", к)):
        return 2
    if протокол:
        return 3
    if совет:
        return 4
    return None


_СТР_0 = re.compile(r"документ|раскрыти|протокол|собрани|избран|dokument|document|docs|raskryt|protokol|"
                    r"sobrani|izbran", re.I)
_СТР_1 = re.compile(r"совет|правлени|органы|решени|информаци|sovet|pravlen|organy|upravlen|council|board|"
                    r"resheni|info", re.I)


def приоритет_страницы(ключ: str) -> int | None:
    """0 — документы и собрания, 1 — совет и раскрытие, 2 — «о нас»; None — не идём (новости и прочее)."""
    if _СТР_0.search(ключ):
        return 0
    if _СТР_1.search(ключ):
        return 1
    if п._ССЫЛКА.search(ключ):
        return 2
    return None
_ТИПОВЫЕ = ("documents/", "docs/", "dokumenty/", "documenty/", "raskrytie-informacii/",
            "raskrytie-informatsii/", "raskrytie/", "info/", "protokoly/", "protocols/",
            "obshchee-sobranie/", "obshhee-sobranie/", "sobranie/", "obshchie-sobraniya/",
            "about/documents/", "o-nas/dokumenty/", "sovet/", "pravlenie/", "organy-upravleniya/")


def скачать_файл(url: str) -> tuple[str, bytes] | None:
    """(итоговый адрес, содержимое) документа или None."""
    for проверять in (True, False):
        try:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                with п._сессия().get(url, timeout=п.ТАЙМАУТ * 2, verify=проверять, stream=True,
                                     allow_redirects=True) as r:
                    if r.status_code >= 400:
                        return None
                    if int(r.headers.get("content-length") or 0) > РАЗМЕР:
                        return None
                    части, всего = [], 0
                    for кусок in r.iter_content(65536):
                        части.append(кусок)
                        всего += len(кусок)
                        if всего > РАЗМЕР:
                            return None
                    return r.url, b"".join(части)
        except requests.exceptions.SSLError:
            continue
        except requests.RequestException:
            return None
    return None


def _pypdf():
    try:
        import pypdf  # noqa: PLC0415
    except ImportError:
        sys.exit("Нет библиотеки pypdf. Поставьте один раз:  .venv\\Scripts\\pip install pypdf")
    return pypdf


def текст_документа(данные: bytes) -> tuple[str, str]:
    """(текст, вид): вид — pdf, docx, скан (PDF без текста), html, не прочитан."""
    if данные[:5] == b"%PDF-":
        pypdf = _pypdf()
        try:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                чтение = pypdf.PdfReader(io.BytesIO(данные), strict=False)
                листы = []
                for лист in чтение.pages[:ЛИСТОВ]:
                    try:
                        листы.append(лист.extract_text() or "")
                    except Exception:  # noqa: BLE001 — битый лист пропускаем
                        листы.append("")
        except Exception:  # noqa: BLE001
            return "", "не прочитан"
        текст = "\n".join(листы)
        букв = len(re.findall(r"[А-Яа-яЁё]", текст))
        return (текст, "pdf") if букв >= 80 else ("", "скан")
    if данные[:2] == b"PK":
        try:
            with zipfile.ZipFile(io.BytesIO(данные)) as z:
                xml = z.read("word/document.xml").decode("utf-8", "ignore")
        except (KeyError, zipfile.BadZipFile):
            return "", "не прочитан"
        xml = re.sub(r"</w:p>|<w:br/>|<w:tab/>", "\n", xml)
        return re.sub(r"<[^>]+>", "", xml), "docx"
    if данные[:8] == b"\xd0\xcf\x11\xe0\xa1\xb1\x1a\xe1":            # старый Word .doc
        лучший = ""
        for кодировка in ("utf-16le", "cp1251"):
            куски = re.findall(r"[А-Яа-яЁё0-9 .,:;«»\"()\-–—№\r\n]{4,}", данные.decode(кодировка, "ignore"))
            текст = "\n".join(к for к in куски if re.search(r"[А-Яа-яЁё]{3}", к)).replace("\r", "\n")
            if len(текст) > len(лучший):
                лучший = текст
        return (лучший, "doc") if len(re.findall(r"[А-Яа-яЁё]", лучший)) >= 80 else ("", "не прочитан")
    начало = данные[:2000].lower()
    if b"<html" in начало or b"<!doctype" in начало:
        return п.разобрать(данные.decode("utf-8", "ignore"))[0], "html"
    return "", "не прочитан"


# ---------------------------------------------------------------- обход сайта

def обойти(сайт: str, скачать=п.скачать, скачать_файл=скачать_файл) -> dict:
    старт = п.адреса(сайт)
    if not старт:
        return {ИТОГ: "сайта нет"}
    очередь: list[tuple[int, int, str]] = [(1, i, u) for i, u in enumerate(старт)]
    счётчик, видели, открылось = len(старт), set(), 0
    домены = {urlparse(u).netloc.removeprefix("www.") for u in старт}
    документы: dict[str, tuple[int, int, int, str]] = {}   # url → (оценка, -год, порядок, подпись)
    находки = []          # (вес, -дата, порядок, итог)
    типовые = False

    def в_очередь(приоритет: int, url: str) -> None:
        nonlocal счётчик
        if url not in видели and all(u != url for _, _, u in очередь):
            очередь.append((приоритет, счётчик, url))
            счётчик += 1

    def в_документы(url: str, подпись: str) -> None:
        оц = оценка_ссылки(подпись, url)
        if оц is not None and url not in документы:
            документы[url] = (оц, -год(подпись, url), len(документы), " ".join(подпись.split())[:200])

    def записать(нашли, адрес, название, д, порядок, текст) -> None:
        вес, имя, как, фрагмент = нашли
        находки.append((вес, tuple(-x for x in (д or (0, 0, 0))), порядок, {
            "Председатель (документ)": имя, "Как в документе": как, "Документ": адрес,
            "Название документа": название, "Дата документа": _дата_строкой(д),
            "Фрагмент (документ)": фрагмент[:500],
            "Текст для разбора (документ)": f"[{адрес}] " + п.кусок_для_разбора(текст, 2500)}))

    while очередь and len(видели) < СТРАНИЦ:
        if len(видели) >= 12 and sum(1 for x in документы.values() if x[0] <= 1) >= ДОКУМЕНТОВ:
            break
        очередь.sort()
        _, _, url = очередь.pop(0)
        if url in видели:
            continue
        видели.add(url)
        ответ = скачать(url)
        if not ответ:
            continue
        открылось += 1
        итоговый, html = ответ
        домены.add(urlparse(итоговый).netloc.removeprefix("www."))
        if url.endswith(".xml") or html.lstrip().startswith("<?xml"):
            for адрес in re.findall(r"<loc>\s*([^<\s]+)\s*</loc>", html)[:5000]:
                if _ДОК_РАСШ.search(адрес):
                    в_документы(адрес, "")
                elif адрес.endswith(".xml"):
                    в_очередь(0, адрес)
                elif (пр := приоритет_страницы(unquote(адрес))) is not None and пр < 2:
                    в_очередь(пр, адрес)
            continue
        текст, ссылки = п.разобрать(html)
        if (нашли := найти_в_документе(текст)) and нашли[0] == 0:
            # «Председателем Совета избран …» в новости о собрании или в протоколе на странице
            записать(нашли, итоговый, "страница сайта", дата(текст[:3000]), -1, текст)
        if not типовые:
            типовые = True
            корень = f"{urlparse(итоговый).scheme}://{urlparse(итоговый).netloc}/"
            в_очередь(0, корень + "sitemap.xml")
            for путь in _ТИПОВЫЕ:
                в_очередь(2, корень + путь)
        for href, подпись in ссылки:
            if not href or href.startswith(("mailto:", "tel:", "javascript:", "#")):
                continue
            полный = urljoin(итоговый, href).split("#")[0]
            чужой = urlparse(полный).netloc.removeprefix("www.") not in домены
            if _ДОК_РАСШ.search(полный) or (_ДОК_ПОХОЖЕ.search(полный) and оценка_ссылки(подпись, полный) is not None
                                            and not re.search(r"\.(jpe?g|png|gif|zip|rar|xlsx?)$", полный, re.I)):
                # документы бывают на поддоменах и в облаке (disk.yandex — нет: там страница, не файл)
                if not re.search(r"disk\.yandex|drive\.google|cloud\.mail", полный):
                    в_документы(полный, подпись)
                continue
            if чужой or re.search(r"\.(jpe?g|png|gif|zip|rar|xlsx?)$", полный, re.I):
                continue
            if (пр := приоритет_страницы(f"{подпись} {unquote(полный)}")) is not None:
                в_очередь(пр, полный)

    if not открылось:
        return {ИТОГ: "сайт не открылся"}
    прочитано, сканы, куски = 0, [], []
    по_порядку = sorted(документы.items(), key=lambda x: x[1][:3])[:ДОКУМЕНТОВ]
    for номер, (url, (оц, минус_год, _, подпись)) in enumerate(по_порядку):
        # свежее избрание уже есть, а дальше только документы старше — дальше не читаем
        if any(н[0] == 0 for н in находки) and -минус_год and \
                -минус_год < max(-н[1][0] for н in находки if н[0] == 0):
            continue
        ответ = скачать_файл(url)
        if not ответ:
            continue
        итоговый, данные = ответ
        текст, вид = текст_документа(данные)
        if вид == "скан":
            сканы.append(итоговый)
            continue
        if not текст:
            continue
        прочитано += 1
        if (нашли := найти_в_документе(текст)):
            записать(нашли, итоговый, подпись or unquote(Path(urlparse(итоговый).path).name),
                     дата(текст[:3000]) or ((год(подпись, url), 0, 0) if год(подпись, url) else None), номер,
                     текст)
        elif re.search(r"председател", текст, re.I) and len(куски) < 2:
            куски.append(f"[{итоговый}] " + п.кусок_для_разбора(текст, 1500))
    if находки:
        # самое свежее избрание или «Председатель Совета: …» в шапке протокола; упоминания
        # в косвенном падеже — только если другого нет
        находки.sort(key=lambda н: (н[0] > 1, н[1], н[0], н[2]))
        вес, _, _, лучшая = находки[0]
        out = dict(лучшая)
        out[ИТОГ] = ("найдено на странице" if лучшая["Название документа"] == "страница сайта"
                     else "найдено в документе") + ("" if вес == 0 else " (не избрание — проверить)")
        out["Сканы без текста"] = "\n".join(сканы[:5])
        другие = []
        for _, _, _, н in находки[1:]:
            строка = f"{н['Председатель (документ)']} — {н['Дата документа'] or 'без даты'} — {н['Документ']}"
            if строка not in другие:
                другие.append(строка)
        out["Другие находки"] = "\n".join(другие[:6])
        return out
    итог = (f"в документах не найдено (прочитано {прочитано})" if прочитано else
            "только сканы — смотреть глазами" if сканы else
            "ссылок на протоколы не нашлось" if not документы else "документы не скачались")
    if прочитано and сканы:
        итог += f", сканов {len(сканы)}"
    return {ИТОГ: итог, "Сканы без текста": "\n".join(сканы[:5]),
            "Текст для разбора (документ)": " … ".join(куски)[:3000]}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--file", default="председатели_осталось.xlsx")
    ap.add_argument("--потоков", type=int, default=8)
    ap.add_argument("--заново", action="store_true", help="пройти и уже обработанные строки")
    ap.add_argument("--все", action="store_true",
                    help="и те, где председатель уже найден на страницах (колонка «Председатель совета»)")
    a = ap.parse_args(argv)
    _pypdf()                                   # нет библиотеки — сказать сразу, а не через час
    from openpyxl import Workbook, load_workbook
    путь = Path(a.file)
    ws = load_workbook(путь).active
    строки = list(ws.iter_rows(values_only=True))
    шапка = [str(c or "") for c in строки[0]]
    записи = [dict(zip(шапка, ["" if v is None else v for v in r])) for r in строки[1:] if any(r)]
    колонки = шапка + [к for к in НОВЫЕ if к not in шапка]
    нужно = [z for z in записи
             if (a.все or not str(z.get("Председатель совета") or "").strip())
             and (a.заново or not str(z.get(ИТОГ) or "").strip())]
    print(f"СРО в файле: {len(записи)}, обойти: {len(нужно)}", flush=True)
    замок = threading.Lock()
    готово = [0]

    def сохранить():
        wb = Workbook()
        w = wb.active
        w.title = "Председатели"
        w.append(колонки)
        for z in записи:
            w.append([z.get(к, "") for к in колонки])
        try:
            wb.save(путь)
        except PermissionError:
            print(f"Не могу записать {путь}: файл открыт в Excel. Закройте его — сохраню на следующем шаге.",
                  file=sys.stderr)

    def одна(z):
        try:
            итог = обойти(str(z.get("Сайт") or ""))
        except Exception as e:  # noqa: BLE001 — одна СРО не должна ронять весь прогон
            итог = {ИТОГ: f"ошибка: {type(e).__name__}"}
        with замок:
            for к in НОВЫЕ:
                z[к] = итог.get(к, "")
            готово[0] += 1
            print(f"  {готово[0]}/{len(нужно)} {z.get('Рег. номер')}: "
                  f"{итог.get('Председатель (документ)') or итог[ИТОГ]}", flush=True)
            if готово[0] % 10 == 0:
                сохранить()

    начало = time.time()
    with ThreadPoolExecutor(max_workers=a.потоков) as pool:
        list(pool.map(одна, нужно))
    сохранить()
    найдено = sum(1 for z in записи if str(z.get(ИТОГ) or "").startswith("найдено"))
    сканы = sum(1 for z in записи if z.get("Сканы без текста"))
    print(f"Готово за {int(time.time() - начало)} с: найдено в документах у {найдено} из {len(записи)}, "
          f"сканы без текста — у {сканы} → {путь}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
