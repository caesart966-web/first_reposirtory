def приоритет_страницы(ключ: str) -> int | None:
    """0 — документы и собрания, 1 — совет и раскрытие, 2 — «о нас»; None — не идём (новости и прочее)."""
    if _СТР_0.search(ключ):
        return 0
    if _СТР_1.search(ключ):
        return 1
    if п._ССЫЛКА.search(ключ):
        return 2
    return None
