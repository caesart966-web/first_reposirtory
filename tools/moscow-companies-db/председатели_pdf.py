    замены = {"род_вин": (("ия", "ий"), ("ея", "ей"), ("ая", "ай"), ("ря", "рь"), ("ля", "ль"), ("а", "")),
              "дат": (("ию", "ий"), ("ею", "ей"), ("аю", "ай"), ("рю", "рь"), ("лю", "ль"), ("у", "")),
              "твор": (("ием", "ий"), ("еем", "ей"), ("аем", "ай"), ("рем", "рь"), ("лем", "ль"), ("ом", "")),
              "пред": (("ии", "ий"), ("е", ""))}.get(падеж, ())
    for было, стало in замены:
        if и.endswith(было):
            и = и[: len(и) - len(было)] + стало
