def текст_документа(данные: bytes) -> tuple[str, str]:
    """(текст, вид): вид — pdf, docx, скан (PDF без текста), html, не прочитан."""
    if данные[:5] == b"%PDF-":
        pypdf = _pypdf()
        try:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                чтение = pypdf.PdfReader(io.BytesIO(данные), strict=False)
                листы = []
                for лист in чтение.pages[:ЛИСТОВ]:
                    try:
                        листы.append(лист.extract_text() or "")
                    except Exception:  # noqa: BLE001 — битый лист пропускаем
                        листы.append("")
        except Exception:  # noqa: BLE001
            return "", "не прочитан"
        текст = "\n".join(листы)
        букв = len(re.findall(r"[А-Яа-яЁё]", текст))
        return (текст, "pdf") if букв >= 80 else ("", "скан")
    if данные[:2] == b"PK":
        try:
            with zipfile.ZipFile(io.BytesIO(данные)) as z:
                xml = z.read("word/document.xml").decode("utf-8", "ignore")
        except (KeyError, zipfile.BadZipFile):
            return "", "не прочитан"
        xml = re.sub(r"</w:p>|<w:br/>|<w:tab/>", "\n", xml)
        return re.sub(r"<[^>]+>", "", xml), "docx"
    if данные[:8] == b"\xd0\xcf\x11\xe0\xa1\xb1\x1a\xe1":            # старый Word .doc
        лучший = ""
        for кодировка in ("utf-16le", "cp1251"):
            куски = re.findall(r"[А-Яа-яЁё0-9 .,:;«»\"()\-–—№\r\n]{4,}", данные.decode(кодировка, "ignore"))
            текст = "\n".join(к for к in куски if re.search(r"[А-Яа-яЁё]{3}", к)).replace("\r", "\n")
            if len(текст) > len(лучший):
                лучший = текст
        return (лучший, "doc") if len(re.findall(r"[А-Яа-яЁё]", лучший)) >= 80 else ("", "не прочитан")
    начало = данные[:2000].lower()
    if b"<html" in начало or b"<!doctype" in начало:
        return п.разобрать(данные.decode("utf-8", "ignore"))[0], "html"
    return "", "не прочитан"


