_ЯЗЫК_WINDOWS = ('В Windows не установлено распознавание русского текста. В PowerShell от имени '
                 'администратора:  Add-WindowsCapability -Online -Name "Language.OCR~~~ru-RU~0.0.1.0"')


def распознаватель():
    """(функция «картинка → текст», чем распознаём) или (None, почему нельзя).

    На Windows — встроенное распознавание текста (pip install winocr), иначе Tesseract
    (pytesseract и установленная программа с русским языком). Листы PDF рисует pypdfium2."""
    try:
        import pypdfium2  # noqa: F401, PLC0415
    except ImportError:
        return None, "нет pypdfium2:  .venv\\Scripts\\pip install pypdfium2 pillow winocr"
    if sys.platform == "win32":
        try:
            import winocr  # noqa: PLC0415
            from winrt.windows.globalization import Language  # noqa: PLC0415
            from winrt.windows.media.ocr import OcrEngine  # noqa: PLC0415
        except ImportError:
            winocr = None
        if winocr is not None:
            if not OcrEngine.is_language_supported(Language("ru")):
                return None, _ЯЗЫК_WINDOWS

            def windows(картинка) -> str:
                р = winocr.recognize_pil_sync(картинка, "ru")
                строки = [л.get("text", "") for л in (р.get("lines") or []) if isinstance(л, dict)]
                return "\n".join(строки) or str(р.get("text") or "")
            return windows, "распознавание Windows"
    try:
        import pytesseract  # noqa: PLC0415
        pytesseract.get_tesseract_version()
        if "rus" in pytesseract.get_languages():
            return (lambda картинка: pytesseract.image_to_string(картинка, lang="rus")), "Tesseract"
    except Exception:  # noqa: BLE001 — нет программы или языка
        pass
    return None, "нет распознавания текста:  .venv\\Scripts\\pip install pypdfium2 pillow winocr"


def распознать_pdf(путь: Path, распознать, листов: int = ЛИСТОВ_СКАНА) -> str:
    import pypdfium2 as pdfium  # noqa: PLC0415
    pdf = pdfium.PdfDocument(str(путь))
    try:
        части = []
        for i in range(min(len(pdf), листов)):
            картинка = pdf[i].render(scale=2.5).to_pil()     # ~180 точек на дюйм
            части.append(распознать(картинка))
        return "\n".join(части)
    finally:
        pdf.close()


def из_сканов(z: dict, распознать) -> bool:
    """Распознать сохранённые сканы строки и дописать находку. True — председатель найден."""
    файлы = [f for f in str(z.get("Сканы (файлы)") or "").split("\n") if f.strip()]
    адреса = [a for a in str(z.get("Сканы без текста") or "").split("\n") if a.strip()]
    находки = []
    for i, файл in enumerate(файлы):
        if not Path(файл).exists():
            continue
        try:
            текст = распознать_pdf(Path(файл), распознать)
        except Exception as e:  # noqa: BLE001 — битый файл не роняет прогон
            print(f"    не распознался {файл}: {type(e).__name__}", flush=True)
            continue
        адрес = адреса[i] if i < len(адреса) else файл
        if not z.get("Совет возглавляет президент") and (ф := президент_во_главе(текст)):
            z["Совет возглавляет президент"] = f"[{адрес}] {ф}"[:600]
        if not z.get("Президент (по сайту)") and (имя := имя_президента(текст)):
            z["Президент (по сайту)"] = имя
        if (нашли := найти_в_документе(текст)):
            д = дата(текст[:3000])
            находки.append((нашли[0] > 1, tuple(-x for x in (д or (0, 0, 0))), нашли[0], i, нашли, адрес, д, текст))
    if not находки:
        if файлы:
            z[ИТОГ] = f"{z.get(ИТОГ)}; сканы распознаны — не найдено"
        return False
    находки.sort(key=lambda н: н[:4])
    *_, (вес, имя, как, фрагмент), адрес, д, текст = находки[0]
    z.update({"Председатель (документ)": имя, "Как в документе": как, "Документ": адрес,
              "Название документа": "скан (распознан)", "Дата документа": _дата_строкой(д),
              "Фрагмент (документ)": фрагмент[:500],
              "Текст для разбора (документ)": f"[{адрес}] " + п.кусок_для_разбора(текст, 2500),
              ИТОГ: "найдено в скане" + ("" if вес == 0 else " (не избрание — проверить)")})
    return True


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--file", default="председатели_осталось.xlsx")
    ap.add_argument("--потоков", type=int, default=8)
    ap.add_argument("--заново", action="store_true", help="пройти и уже обработанные строки")
    ap.add_argument("--все", action="store_true",
                    help="и те, где председатель уже найден на страницах (колонка «Председатель совета»)")
    ap.add_argument("--без-распознавания", action="store_true", help="сканы не распознавать")
    ap.add_argument("--только-распознать", action="store_true",
                    help="сайты не обходить, только распознать уже скачанные сканы")
    a = ap.parse_args(argv)
    _pypdf()                                   # нет библиотеки — сказать сразу, а не через час
    if not a.без_распознавания and распознаватель()[0] is None:
        print(f"Внимание: {распознаватель()[1]}\nСканы будут сохранены, распознать их можно потом "
              f"(--только-распознать).", flush=True)
    from openpyxl import Workbook, load_workbook
    путь = Path(a.file)
    ws = load_workbook(путь).active
    строки = list(ws.iter_rows(values_only=True))
    шапка = [str(c or "") for c in строки[0]]
    записи = [dict(zip(шапка, ["" if v is None else v for v in r])) for r in строки[1:] if any(r)]
    колонки = шапка + [к for к in НОВЫЕ if к not in шапка]
    нужно = [] if a.только_распознать else [
        z for z in записи
        if (a.все or not str(z.get("Председатель совета") or "").strip())
        and (a.заново or not str(z.get(ИТОГ) or "").strip())]
    папка_сканов = путь.with_name(путь.stem + "_сканы")
    print(f"СРО в файле: {len(записи)}, обойти: {len(нужно)}", flush=True)
    замок = threading.Lock()
    готово = [0]

    def сохранить():
        wb = Workbook()
        w = wb.active
        w.title = "Председатели"
        w.append(колонки)
        for z in записи:
            w.append([z.get(к, "") for к in колонки])
        try:
            wb.save(путь)
        except PermissionError:
            print(f"Не могу записать {путь}: файл открыт в Excel. Закройте его — сохраню на следующем шаге.",
                  file=sys.stderr)

    def одна(z):
        try:
            номер = re.sub(r"[^\w.-]+", "_", str(z.get("Рег. номер") or "без_номера"))
            итог = обойти(str(z.get("Сайт") or ""), папка_сканов=папка_сканов / номер)
        except Exception as e:  # noqa: BLE001 — одна СРО не должна ронять весь прогон
            итог = {ИТОГ: f"ошибка: {type(e).__name__}"}
        with замок:
            for к in НОВЫЕ:
                z[к] = итог.get(к, "")
            готово[0] += 1
            print(f"  {готово[0]}/{len(нужно)} {z.get('Рег. номер')}: "
                  f"{итог.get('Председатель (документ)') or итог[ИТОГ]}", flush=True)
            if готово[0] % 10 == 0:
                сохранить()

    начало = time.time()
    with ThreadPoolExecutor(max_workers=a.потоков) as pool:
        list(pool.map(одна, нужно))
    сохранить()
    # второй этап — сканы, по одному в основном потоке (распознавание Windows не любит потоки)
    со_сканами = [z for z in записи if str(z.get("Сканы (файлы)") or "").strip()
                  and not str(z.get(ИТОГ) or "").startswith("найдено")
                  and "распознаны" not in str(z.get(ИТОГ) or "")]
    if со_сканами and not a.без_распознавания:
        распознать, чем = распознаватель()
        if распознать is None:
            print(f"Сканы есть у {len(со_сканами)} СРО, но распознать их нечем: {чем}\n"
                  f"Поставьте и запустите ещё раз с --только-распознать — сайты заново обходить не придётся.")
        else:
            print(f"Распознаю сканы ({чем}) у {len(со_сканами)} СРО — это небыстро", flush=True)
            for i, z in enumerate(со_сканами, 1):
                нашёл = из_сканов(z, распознать)
                print(f"  {i}/{len(со_сканами)} {z.get('Рег. номер')}: "
                      f"{z.get('Председатель (документ)') if нашёл else 'не найдено'}", flush=True)
                if i % 5 == 0:
                    сохранить()
            сохранить()
    найдено = sum(1 for z in записи if str(z.get(ИТОГ) or "").startswith("найдено"))
    сканы = sum(1 for z in записи if z.get("Сканы без текста"))
    print(f"Готово за {int(time.time() - начало)} с: найдено в документах у {найдено} из {len(записи)}, "
          f"сканы без текста — у {сканы} → {путь}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
