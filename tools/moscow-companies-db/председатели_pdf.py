def скачать_файл(url: str) -> tuple[str, bytes] | None:
    """(итоговый адрес, содержимое) документа или None."""
    for проверять in (True, False):
        try:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                with п._сессия().get(url, timeout=п.ТАЙМАУТ * 2, verify=проверять, stream=True,
                                     allow_redirects=True) as r:
                    if r.status_code >= 400:
                        return None
                    if int(r.headers.get("content-length") or 0) > РАЗМЕР:
                        return None
                    части, всего = [], 0
                    for кусок in r.iter_content(65536):
                        части.append(кусок)
                        всего += len(кусок)
                        if всего > РАЗМЕР:
                            return None
                    return r.url, b"".join(части)
        except requests.exceptions.SSLError:
            continue
        except requests.RequestException:
            return None
    return None


