def _окончание(м: re.Match) -> str:
    """Окончание должности в виде «председател-»: ь, я, ю, ем, е (падеж)."""
    if м.group(1) is not None:
        return м.group(1).lower()
    if м.group(3) is not None:
        return м.group(3).lower()
    return _ПРЕЗИДЕНТ_ОКОНЧАНИЕ[(м.group(2) or "").lower()]


