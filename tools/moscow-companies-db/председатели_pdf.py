def президент_во_главе(текст: str) -> str | None:
    """Фрагмент, где сказано, что совет возглавляет президент, или None."""
    м = _ПРЕЗИДЕНТ_ВО_ГЛАВЕ.search(текст)
    if not м or п._ЧУЖОЙ.match(текст[м.end():м.end() + 60]):
        return None
    return " ".join(текст[max(0, м.start() - 120):м.end() + 120].split())


def имя_президента(текст: str) -> str | None:
    """«Президент Ассоциации Иванов Иван Иванович» / «Президент: Иванов И. И.» → имя (именительный)."""
    for м in _ПРЕЗИДЕНТ_ИМЯ.finditer(текст):
        if re.search(r"вице-?\s*$", текст[max(0, м.start() - 6):м.start()], re.I):
            continue
        ф = п._ФИО.match(текст, м.end())
        if ф and (имя := п._фио(ф)):
            return имя
    return None
_ИЗБРАТЬ = re.compile(r"(?<![а-яё])(?:пере)?(?:избрать|избрали|избирается|назначить|утвердить)(?![а-яё])", re.I)
