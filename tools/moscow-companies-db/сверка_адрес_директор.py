def сверить(запись: dict, ответ: dict | None) -> dict:
    """Строка итоговой таблицы по записи реестра и ответу Checko."""
    строка = {
        "СРО": запись.get("СРО", ""), "Наименование": запись.get("Наименование", ""),
        "ИНН": запись["ИНН"],
        "Член СРО": ("вышел " + запись.get("Дата прекращения", "")).strip()
        if разбор.исключён(запись) else "действует",
        "Адрес в реестре СРО": запись.get("Адрес", ""),
        "Руководитель в реестре СРО": запись.get("Руководитель", ""),
    }
    if ответ is None:
        return строка
    data, проверено = ответ.get("data") or {}, ответ.get("проверено", "")
    строка["Проверено в ЕГРЮЛ"] = проверено
    пометки = []
    if ответ.get("ошибка"):
        строка["Статус в ЕГРЮЛ"] = ответ["ошибка"]
        return строка
    ип = len(запись["ИНН"]) == 12
    строка["Статус в ЕГРЮЛ"] = статус_егрюл(data)

    if ип:
        # Адрес ИП в ЕГРИП закрыт, руководителя у ИП нет — сам предприниматель
        фио = data.get("ФИО")
        if isinstance(фио, dict):
            фио = " ".join(str(фио.get(к) or "") for к in ("Фамилия", "Имя", "Отчество")).strip()
        строка["Адрес по ЕГРЮЛ"] = "у ИП адрес не раскрывается"
        строка["Адрес: итог"] = "не сверяется (ИП)"
        головы = [{"фио": str(фио or ""), "должность": "Индивидуальный предприниматель",
                   "с": "", "недост": False, "управляющая": False}] if фио else []
    else:
        адрес, п = адрес_егрюл(data)
        пометки += п
        строка["Адрес по ЕГРЮЛ"] = адрес
        строка["Адрес: итог"], строка["Адрес: что отличается"] = сравнить_адреса(
            запись.get("Адрес", ""), адрес)
        головы = руководители(data)

    строка["Руководитель по ЕГРЮЛ"] = "; ".join(
        " ".join(x for x in (г["должность"], г["фио"]) if x) for г in головы)
    строка["Руководитель в ЕГРЮЛ с"] = "; ".join(г["с"] for г in головы if г["с"])
    итог, пояснение = сравнить_руководителя(запись.get("Руководитель", ""), головы)
    строка["Руководитель: итог"] = итог + (f" ({пояснение})" if пояснение else "")
    if any(г["недост"] for г in головы):
        пометки.append("ФНС: сведения о руководителе недостоверны")
    if строка["Статус в ЕГРЮЛ"] and not строка["Статус в ЕГРЮЛ"].lower().startswith("действ"):
        пометки.append(строка["Статус в ЕГРЮЛ"])
    строка["Пометки"] = "; ".join(пометки)
    return строка


def _цвет(итог: str) -> str:
    итог = итог.split(" (")[0]
    if итог in ЗЕЛЁНЫЕ:
        return "зелёный"
    if итог in ЖЁЛТЫЕ:
        return "жёлтый"
    if итог in КРАСНЫЕ:
        return "красный"
    return ""


def расхождение(строка: dict) -> bool:
    return any(_цвет(строка.get(к, "")) in ("красный", "жёлтый")
               for к in ("Адрес: итог", "Руководитель: итог")) or bool(строка.get("Пометки"))


