def _дата(значение: Any) -> str:
    m = re.match(r"(\d{4})-(\d{2})-(\d{2})", str(значение or ""))
    return f"{m.group(3)}.{m.group(2)}.{m.group(1)}" if m else str(значение or "")


def руководители(data: dict) -> list[dict]:
    """[{фио, должность, с, недост, управляющая}] — из «Руковод», а если
    компанией управляет другая организация — из «УпрОрг»."""
    итог = []
    головы = data.get("Руковод")
    if isinstance(головы, dict):
        головы = [головы]
    for г in головы if isinstance(головы, list) else []:
        if isinstance(г, dict) and isinstance(г.get("ФИО"), str) and г["ФИО"].strip():
            итог.append({"фио": г["ФИО"].strip(),
                         "должность": str(г.get("НаимДолжн") or "").strip().capitalize(),
                         "с": _дата(г.get("ДатаЗаписи")), "недост": bool(г.get("Недост")),
                         "управляющая": False})
    упр = data.get("УпрОрг")
    if isinstance(упр, dict):
        упр = [упр]
    for у in упр if isinstance(упр, list) else []:
        if isinstance(у, dict):
            имя = str(у.get("НаимСокр") or у.get("НаимПолн") or "").strip()
            if имя:
                итог.append({"фио": имя, "должность": "Управляющая организация",
                             "с": _дата(у.get("ДатаЗаписи")), "недост": bool(у.get("Недост")),
                             "управляющая": True})
    return итог


def адрес_егрюл(data: dict) -> tuple[str, list[str]]:
    """(адрес, пометки ФНС)."""
    юр = data.get("ЮрАдрес")
    if not isinstance(юр, dict):
        return "", []
    пометки = []
    if юр.get("Недост"):
        пометки.append("ФНС: адрес недостоверен")
    if юр.get("МассАдрес"):
        пометки.append("адрес массовой регистрации")
    return str(юр.get("АдресРФ") or "").strip(), пометки


def статус_егрюл(data: dict) -> str:
    с = data.get("Статус")
    if isinstance(с, dict):
        return str(с.get("Наим") or "").strip()
    return str(с or "").strip()


def ужать(data: dict) -> dict:
    return {к: data[к] for к in _ХРАНИТЬ if к in data}


