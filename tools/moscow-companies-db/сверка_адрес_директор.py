class Адрес:
    """Разобранный адрес. Обычный класс, а не dataclass: тесты грузят скрипт
    по пути, мимо sys.modules, и dataclass на этом падает."""

    def __init__(self) -> None:
        self.индекс = self.дом = self.корпус = self.строение = self.литера = ""
        self.города: list = []        # варианты названий: [["пермь"], ...]
        self.улицы: list = []
        self.помещения: tuple = ()
        self.дом_неразборчив = False  # метка дома есть, номер не читается («д.З/П»)


def _цифра(слово: str) -> bool:
    return bool(слово) and слово[0].isdigit()


def _порядковое(слово: str) -> bool:
    """«18-я линия», «2-й Верхний пер.» — часть названия, а не номер дома."""
    return bool(re.fullmatch(r"\d+-?(я|й|е|го|ая|ий|ой|ый)", слово))


def разобрать_адрес(текст: str) -> Адрес:
    t = str(текст or "").lower().replace("ё", "е")
    for шаблон, замена in _ЗАМЕНЫ:
        t = re.sub(шаблон, замена, t)
    сегменты = []
    for кусок in re.split(r"[,;]", t):
        слова = _СЛОВО.findall(кусок)
        начало = 0
        for j in range(1, len(слова) - 1):
            # Сокращённая метка стоит только перед названием — по ней можно
            # резать, даже если запятую пропустили. Полные слова («улица»,
            # «город») бывают и после названия — по ним не режем
            # «ул. Г. Успенского» — после метки улицы «г» это инициал, а не город
            if слова[j] in _РЕЗАТЬ and (слова[j] not in ("к", "д") or _цифра(слова[j + 1])) \
                    and слова[j - 1] not in УЛИЦЫ:
                сегменты.append(слова[начало:j])
                начало = j
        сегменты.append(слова[начало:])
    сегменты = [с for с in сегменты if с]
    а = Адрес()
    помещения = []

    for i, слова in enumerate(сегменты):
        for j, слово in enumerate(слова):
            if not а.индекс and re.fullmatch(r"\d{6}", слово):
                а.индекс = слово
            # Значение метки — следующее слово, а если метка стоит последней
            # в сегменте («ул. Соликамская, д, 313 А») — начало следующего
            хвост = слова[j + 1:] or (сегменты[i + 1] if i + 1 < len(сегменты) else [])
            дальше, после, за_ним = (хвост + ["", "", ""])[:3]
            if not дальше:
                continue
            if слово in ДОМ and not _цифра(дальше) and (слово != "д" or not дальше.isalpha()):
                а.дом_неразборчив = True
            if слово in ДОМ and _цифра(дальше) and not а.дом:
                дом = дальше
                # «д. 19 а» — буква отдельным словом; но не «д. 5 к. 2»
                if re.fullmatch(r"[а-я]", после) and not _цифра(за_ним) and после not in _МЕТКИ:
                    дом += после
                а.дом = дом
            elif слово in КОРПУС and _цифра(дальше) and not а.корпус:
                а.корпус = дальше
            elif слово in СТРОЕНИЕ and _цифра(дальше) and not а.строение:
                а.строение = дальше
            elif слово in ЛИТЕРА and not а.литера:
                а.литера = дальше
            elif слово in ПОМЕЩЕНИЕ:
                помещения.append(re.sub(r"[-№]", "", дальше))      # «10-Н» = «10Н»

        if слова[0] in УЛИЦЫ or (слова[-1] in УЛИЦЫ and len(слова) > 1) \
                or (len(слова) > 1 and set(слова) & _УЛИЦА_ГДЕ_УГОДНО and слова[0] not in _МЕТКИ):
            ключ = [с for с in слова if с not in УЛИЦЫ]
            # «ул. Ленина 5» и «ул. Ленина, 5» — номер дома без «д.»
            хвост = ключ[-1] if ключ else ""
            if _цифра(хвост) and len(ключ) > 1 and not any(с in ДОМ for с in слова):
                if not а.дом:
                    а.дом = хвост
                ключ = ключ[:-1]
            elif not а.дом and i + 1 < len(сегменты) and _цифра(сегменты[i + 1][0]) \
                    and len(сегменты[i + 1]) <= 2 and сегменты[i + 1][0] != а.индекс:
                а.дом = "".join(сегменты[i + 1])
            ключ = [_СОКР.get(с, с) for с in ключ]
            ключ = [с for с in ключ if с and not (с in _МЕТКИ)]
            if ключ:
                а.улицы.append(ключ)
        elif слова[0] in ГОРОДА and len(слова) > 1 and not _цифра(слова[1]) \
                or слова[-1] in ГОРОДА and len(слова) > 1:
            ключ = [с for с in слова if с not in ГОРОДА]
            if ключ:
                а.города.append(ключ)
        elif слова[0] == "д" and len(слова) > 1 and not _цифра(слова[1]):
            а.города.append(слова[1:])            # «д. Ивановка» — деревня, не дом

    if not а.улицы:
        _улица_по_месту(сегменты, а)
    # «ул. Танкистов, стр. 25» — у здания нет дома, только строение
    if not а.дом and а.строение and not а.дом_неразборчив:
        а.дом, а.строение = а.строение, ""
    а.помещения = tuple(sorted(set(помещения)))
    return а


def _улица_по_месту(сегменты: list[list[str]], а: Адрес) -> None:
    """Улица без «ул.» и дом без «д.»: «г. Пермь, Строителей, 24в, 16».
    Так записана каждая седьмая строка реестра. Порядок в адресе
    постоянный — город, улица, дом, — поэтому улица — это сегмент из одних
    слов прямо перед первым номером (индекс не в счёт)."""
    for i, слова in enumerate(сегменты):
        с_номером = (_цифра(слова[0]) and not _порядковое(слова[0])) or \
            (слова[0] in ДОМ and len(слова) > 1 and _цифра(слова[1]))
        if not с_номером or re.fullmatch(r"\d{6}", слова[0]):
            continue
        if i == 0:
            return
        пред = сегменты[i - 1]
        # «К. Маркса», «С. Лазо», «им. Г.А. Угрюмова» — инициалы, а не метки
        # корпуса или села; отсекаем только район, край и сам город
        if _цифра(пред[0]) or set(пред) & _АДМИН or пред[0] in ("г", "город", "гор"):
            return
        ключ = [_СОКР.get(с, с) for с in пред]
        ключ = [с for с in ключ if с]
        if ключ:
            а.улицы.append(ключ)
        if not а.дом and _цифра(слова[0]):
            дом = слова[0]
            # «95, Б» — буква дома отдельным сегментом
            след = сегменты[i + 1] if i + 1 < len(сегменты) else []
            if len(слова) == 1 and len(след) == 1 and re.fullmatch(r"[а-я]", след[0]):
                дом += след[0]
            elif len(слова) == 2 and re.fullmatch(r"[а-я]", слова[1]):
                дом += слова[1]
            а.дом = дом
        return


def _дом_равен(а: str, б: str) -> bool:
    """«95б» и «95» — один дом (буква записана в одном источнике литерой,
    в другом — никак); «95б» и «95в» — разные."""
    ма, мб = re.match(r"(\d+)(.*)", а), re.match(r"(\d+)(.*)", б)
    if not ма or not мб:
        return а == б
    if ма.group(1) != мб.group(1):
        return False
    ха, хб = ма.group(2).strip("/-"), мб.group(2).strip("/-")
    return not (ха and хб and ха != хб)


def _похожи(а: list, б: list) -> bool:
    """Одно и то же название, записанное по-разному: «Тверская-Ямская 1-я»
    и «1-я Тверская-Ямская», «Б. Садовая» и «Большая Садовая», опечатка
    в одну букву."""
    # инициалы не в счёт: «К. Маркса» и «Карла Маркса» — одна улица
    А, Б = {с[:5] for с in а if len(с) > 1}, {с[:5] for с in б if len(с) > 1}
    if not А or not Б:
        А, Б = {с[:5] for с in а}, {с[:5] for с in б}
    if А <= Б or Б <= А:
        return True
    return SequenceMatcher(None, " ".join(sorted(а)), " ".join(sorted(б))).ratio() >= 0.85


def _сравнить_списки(а: list, б: list) -> bool | None:
    """True — есть общее название, False — оба названы и разные,
    None — с одной из сторон не разобрано."""
    if not а or not б:
        return None
    return any(_похожи(x, y) for x in а for y in б)


def сравнить_адреса(реестр: str, егрюл: str) -> tuple[str, str]:
    """(итог, что отличается). Итоги: совпадает / тот же дом, другое
    помещение / совпадает, кроме индекса / другой адрес / сверить вручную."""
    if разбор.пусто(реестр):
        return "не указан в реестре", ""
    if not егрюл:
        return "нет данных", ""
    а, б = разобрать_адрес(реестр), разобрать_адрес(егрюл)
    город = _сравнить_списки(а.города, б.города)
    улица = _сравнить_списки(а.улицы, б.улицы)
    дом = _дом_равен(а.дом, б.дом) if а.дом and б.дом else None
    if улица is None and дом is None:
        if not а.улицы and not а.дом:
            return "сверить вручную", "в реестре адрес без улицы и дома"
        return "сверить вручную", "адрес не разобрался"

    отличия = []
    if город is False:
        отличия.append("город")
    if улица is False:
        отличия.append("улица")
    if дом is False:
        отличия.append(f"дом {а.дом} → {б.дом}")
    for имя, x, y in (("корпус", а.корпус, б.корпус), ("строение", а.строение, б.строение),
                      ("литера", а.литера, б.литера)):
        if x and y and x != y:
            отличия.append(f"{имя} {x} → {y}")
    индекс_другой = bool(а.индекс and б.индекс and а.индекс != б.индекс)
    if отличия:
        if индекс_другой:
            отличия.append(f"индекс {а.индекс} → {б.индекс}")
        return "другой адрес", ", ".join(отличия)
    if улица is None or дом is None:
        return "сверить вручную", "не удалось сравнить " + ("улицу" if улица is None else "дом")
    if индекс_другой:
        return "совпадает, кроме индекса", f"индекс {а.индекс} → {б.индекс}"
    if а.помещения and б.помещения and not set(а.помещения) & set(б.помещения):
        return "тот же дом, другое помещение", (f"{', '.join(а.помещения)} → "
                                                f"{', '.join(б.помещения)}")
    return "совпадает", ""


