_ФОРМЫ = {"ооо", "оао", "зао", "пао", "ао", "нао", "ип", "общество", "с", "ограниченной",
          "ответственностью", "акционерное", "публичное", "непубличное", "закрытое",
          "открытое", "управляющая", "компания", "организация"}


def _слова(текст: str) -> list[str]:
    return re.findall(r"[а-яa-z]+", str(текст or "").lower().replace("ё", "е"))


def сравнить_руководителя(реестр: str, руководители: list[dict]) -> tuple[str, str]:
    """(итог, пояснение). Должность не сравнивается — только человек:
    «Генеральный директор Иванов Иван Иванович» и «ДИРЕКТОР Иванов И.И.»
    — это совпадение."""
    if разбор.пусто(реестр):
        return "не указан в реестре", ""
    if not руководители:
        return "нет данных", ""
    слова = _слова(реестр)
    есть = set(слова)
    почти = None
    for р in руководители:
        фио = _слова(р["фио"])
        if not фио:
            continue
        if р.get("управляющая"):
            значимые = [с for с in фио if с not in _ФОРМЫ]
            if значимые and set(значимые) <= есть:
                return "совпадает", ""
            continue
        if set(фио) <= есть:
            return "совпадает", ""
        фамилия, остальное = фио[0], фио[1:]
        # «Иванов И.И.» или «И.И. Иванов» — фамилия и инициалы рядом с ней
        if фамилия in есть and остальное:
            i = слова.index(фамилия)
            нужно = [с[0] for с in остальное]
            после = слова[i + 1:i + 1 + len(нужно)]
            до = слова[max(0, i - len(нужно)):i]
            if нужно in (после, до):
                return "совпадает", "по инициалам"
        if len(остальное) >= 2 and set(остальное) <= есть:
            почти = "те же имя и отчество, другая фамилия — возможно, сменила фамилию"
    if почти:
        return "сверить вручную", почти
    return "другой руководитель", ""


