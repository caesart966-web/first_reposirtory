def записать(путь: Path, строки: list[dict], сводка: list[list], непроверенные: list[dict],
             примечания: list[str] = ()) -> None:
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill
    from openpyxl.utils import get_column_letter

    wb = Workbook()
    шапка_шрифт = Font(bold=True, color="FFFFFF")
    шапка_фон = PatternFill("solid", fgColor="1F3A5F")

    def лист(имя: str, колонки: list[str], ряды: list[dict]):
        ws = wb.create_sheet()
        ws.title = имя
        ws.append(колонки)
        for c in ws[1]:
            c.font, c.fill = шапка_шрифт, шапка_фон
            c.alignment = Alignment(wrap_text=True, vertical="center")
        for р in ряды:
            ws.append([р.get(к, "") for к in колонки])
        for i, к in enumerate(колонки, 1):
            ws.column_dimensions[get_column_letter(i)].width = ШИРИНА.get(к, 16)
            if к in ("Адрес: итог", "Руководитель: итог"):
                for c in ws.iter_cols(min_col=i, max_col=i, min_row=2):
                    for ячейка in c:
                        цвет = _цвет(str(ячейка.value or ""))
                        if цвет:
                            ячейка.fill = PatternFill("solid", fgColor=ЗАЛИВКА[цвет])
        for ряд in ws.iter_rows(min_row=2):
            for ячейка in ряд:
                ячейка.alignment = Alignment(wrap_text=True, vertical="top")
        ws.freeze_panes = "D2" if "ИНН" in колонки else "A2"
        ws.auto_filter.ref = ws.dimensions
        return ws

    ws = wb.active
    ws.title = "Сводка"
    ws.append([f"Сверка реестра СРО с ЕГРЮЛ — {date.today():%d.%m.%Y}"])
    ws["A1"].font = Font(bold=True, size=13)
    ws.append(["ЕГРЮЛ — по данным Checko на дату в колонке «Проверено в ЕГРЮЛ». Реестр СРО "
               "обновляется, только когда компания сама сообщит об изменениях."])
    ws.append([])
    for i, ряд in enumerate(сводка):
        ws.append(ряд)
        if i == 0:
            for c in ws[ws.max_row]:
                c.font, c.fill = шапка_шрифт, шапка_фон
                c.alignment = Alignment(wrap_text=True, vertical="center")
    if примечания:
        ws.append([])
        for текст in примечания:
            ws.append([текст])
    ws.column_dimensions["A"].width = 46
    for буква in "BCDEFGH":
        ws.column_dimensions[буква].width = 15

    лист("Расхождения", КОЛОНКИ, [с for с in строки if расхождение(с)])
    лист("Все", КОЛОНКИ, строки)
    if непроверенные:
        лист("Не проверены", ["СРО", "Наименование", "ИНН", "Член СРО", "Причина"], непроверенные)
    wb.save(путь)


def свести(строки: list[dict], непроверенные: list[dict]) -> list[list]:
    шапка = ["СРО", "Проверено", "Адрес отличается", "Адрес — уточнить",
             "Руководитель отличается", "Руководитель — уточнить", "Не проверено"]
    по_сро: dict[str, list[int]] = {}
    for с in строки:
        н = по_сро.setdefault(с["СРО"], [0] * 6)
        н[0] += 1
        н[1] += _цвет(с.get("Адрес: итог", "")) == "красный"
        н[2] += _цвет(с.get("Адрес: итог", "")) == "жёлтый"
        н[3] += _цвет(с.get("Руководитель: итог", "")) == "красный"
        н[4] += _цвет(с.get("Руководитель: итог", "")) == "жёлтый"
    for с in непроверенные:
        по_сро.setdefault(с["СРО"], [0] * 6)[5] += 1
    ряды = [шапка] + [[сро] + н for сро, н in sorted(по_сро.items())]
    if len(по_сро) > 1:
        ряды.append(["Всего"] + [sum(н[i] for н in по_сро.values()) for i in range(6)])
    return ряды


