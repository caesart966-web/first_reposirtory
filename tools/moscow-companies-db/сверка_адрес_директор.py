def _читать_лист(строки: list[tuple], имя: str) -> list[dict] | None:
    """Таблица не из официальной выгрузки: ищем шапку с ИНН и колонки
    по смыслу — наименование, адрес, руководитель, СРО. None — шапки нет."""
    for номер, строка in enumerate(строки[:10]):
        ячейки = [разбор._норм(x) for x in строка]
        if not any(x == "инн" or x.startswith("инн ") for x in ячейки):
            continue

        def колонка(*признаки, кроме=()):
            for к, x in enumerate(ячейки):
                if any(п in x for п in признаки) and not any(н in x for н in кроме):
                    return к
            return None

        к = {"ИНН": next(к for к, x in enumerate(ячейки) if x == "инн" or x.startswith("инн ")),
             "ОПФ": next((к for к, x in enumerate(ячейки) if x in ("опф", "организационно-правовая форма")),
                         None),
             "Наименование": колонка("наименован", "название", "организац", "компани",
                                     кроме=("сро",)),
             # юридический адрес важнее фактического, если в таблице есть оба
             "Адрес": next((к for к, x in enumerate(ячейки)
                            if "адрес" in x and ("юрид" in x or "нахожд" in x)),
                           колонка("адрес", кроме=("почт", "электрон", "e-mail", "сайт"))),
             # «Должность руководителя» — не сам руководитель
             "Руководитель": колонка("руковод", "директор", "фио", "фамилия", кроме=("должност",)),
             "Должность": колонка("должност"),
             "СРО": колонка("сро", кроме=("инн", "дата", "номер")),
             "Дата прекращения": колонка("прекращ", "исключ")}
        записи = []
        for с in строки[номер + 1:]:
            def взять(поле):
                i = к.get(поле)
                return str(с[i]).strip() if i is not None and i < len(с) and с[i] is not None else ""
            инн = разбор.норм_инн(взять("ИНН"))
            if len(инн) not in (10, 12):
                continue
            имя_орг = взять("Наименование")
            if взять("ОПФ") and взять("ОПФ") != "ИП" and not имя_орг.startswith(взять("ОПФ")):
                имя_орг = f"{взять('ОПФ')} {имя_орг}"
            руководитель = взять("Руководитель")
            if руководитель and взять("Должность") and len(инн) == 10:
                руководитель = f"{взять('Должность')} {руководитель}"
            записи.append({"ИНН": инн, "Наименование": имя_орг, "Адрес": взять("Адрес"),
                           "Руководитель": руководитель, "СРО": взять("СРО") or имя,
                           "Дата прекращения": взять("Дата прекращения")})
        return записи
    return None


def _читать_любую(путь: Path) -> list[dict]:
    """Каждый лист с шапкой — отдельный список; название СРО — имя листа
    (так заказчик присылает реестры нескольких СРО одним файлом)."""
    from openpyxl import load_workbook
    wb = load_workbook(путь, read_only=True)
    итог = []
    for ws in wb.worksheets:
        записи = _читать_лист(list(ws.iter_rows(values_only=True)),
                              ws.title if len(wb.worksheets) > 1 else путь.stem)
        if записи is None:
            continue
        print(f"[таблица] {путь.name} / {ws.title}: {len(записи)} компаний", flush=True)
        итог += записи
    wb.close()
    if not итог:
        print(f"[таблица] {путь.name}: нет листа с колонкой ИНН — пропускаю", file=sys.stderr)
    return итог


def читать_файлы(пути: list[Path]) -> list[dict]:
    from openpyxl import load_workbook
    официальные, записи = [], []
    for путь in пути:
        wb = load_workbook(путь, read_only=True)
        строки = list(wb.active.iter_rows(max_row=10, values_only=True))
        wb.close()
        if разбор.найти_шапку(строки) is not None:
            официальные.append(путь)
        else:
            записи += _читать_любую(путь)
    for _, члены in разбор.читать_выгрузку(официальные) if официальные else []:
        записи += члены
    return записи


