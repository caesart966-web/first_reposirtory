import importlib.util
import unittest
from pathlib import Path

_spec = importlib.util.spec_from_file_location(
    "сро_доля_регион", Path(__file__).resolve().parent.parent / "сро_доля_регион.py")
д = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(д)

ДА = {"title": "Является членом"}
НЕТ = {"title": "Исключен"}


def член(инн, сро, статус=ДА, регион=None):
    z = {"inn": инн, "sro": {"id": сро}, "member_status": статус}
    if регион:
        z["region_number"] = {"title": регион}
    return z


class Доля(unittest.TestCase):
    def test_посчитать(self):
        сро_с = [{"id": 1, "рег_номер": "СРО-С-001-01012009"}, {"id": 2, "рег_номер": "СРО-С-002-01012009"}]
        сро_пи = [{"id": 1, "рег_номер": "СРО-П-001-01012009"}, {"id": 2, "рег_номер": "СРО-И-001-01012009"}]
        члены_с = [
            член("3900000001", 1, регион="Калининградская область"),
            член("3900000001", 2, регион="Калининградская область"),   # в двух строительных — один раз
            член("3900000002", 1, регион="Калининградская область"),
            член("3900000003", 1),                                     # региона нет — по ИНН (39)
            член("3900000004", 1, статус=НЕТ, регион="Калининградская область"),  # исключён — не считается
            член("7700000001", 2, регион="Москва"),
        ]
        члены_пи = [
            член("3900000001", 1), член("3900000001", 2),               # и в проектной, и в изыскательской
            член("3900000002", 1, статус=НЕТ),                         # исключён из проектной — не состоит
            член("3900000003", 2),
            член("3900000004", 1),
        ]
        итог = д.посчитать(члены_с, члены_пи, сро_с, сро_пи)
        к = итог["регионы"]["Калининградская область"]
        self.assertEqual(к["строительных"], 3)
        self.assertEqual(к["в_проектных"], 1)
        self.assertEqual(к["в_изыскательских"], 2)
        self.assertEqual(к["в_обоих"], 1)
        self.assertEqual(к["доля_в_проектных"], 33.3)
        self.assertEqual(к["доля_в_изыскательских"], 66.7)
        self.assertEqual(итог["регионы"]["г. Москва"]["строительных"], 1)
        self.assertEqual(итог["откуда_регион_записей"], {"реестр": 4, "ИНН": 1})
        self.assertIn("| Калининградская область | 3 | 1 | 33.3 | 2 | 66.7 |", д.таблица_md(итог))

    def test_все_члены_пи_по_регионам(self):
        сро_пи = [{"id": 1, "рег_номер": "СРО-П-001-01012009"}, {"id": 2, "рег_номер": "СРО-И-001-01012009"},
                  {"id": 3, "рег_номер": "СРО-П-002-01012009"}]
        члены_пи = [
            член("3900000001", 1, регион="Калининградская область"),
            член("3900000001", 3, регион="Калининградская область"),   # в двух проектных — один раз
            член("3900000001", 2, регион="Калининградская область"),   # и в изыскательской
            член("3900000002", 2),                                      # региона нет — по ИНН
            член("390000000003", 1, регион="Калининградская область"), # ИП
            член("3900000004", 1, статус=НЕТ, регион="Калининградская область"),  # исключён
        ]
        пи = д.пи_по_регионам(члены_пи, сро_пи)
        к = пи["регионы"]["Калининградская область"]
        self.assertEqual(к["в_проектных_юл"], 1)
        self.assertEqual(к["в_изыскательских_юл"], 2)
        self.assertEqual(к["хотя_бы_в_одной_юл"], 2)
        self.assertEqual(к["в_обоих_юл"], 1)
        self.assertEqual(к["в_проектных_ип"], 1)
        self.assertNotIn("в_изыскательских_ип", к)
        self.assertIn("| Калининградская область | 1 | 2 | 2 | 1 | 0 |", д.таблица_пи_md(пи))


    def test_вступления_по_годам(self):
        сро_пи = [{"id": 1, "рег_номер": "СРО-П-001-01012009"}, {"id": 2, "рег_номер": "СРО-И-001-01012009"},
                  {"id": 3, "рег_номер": "СРО-П-002-01012009"}]

        def вст(инн, сро, дата, статус=ДА):
            z = член(инн, сро, статус)
            z["registry_registration_date"] = дата
            return z
        члены_пи = [
            вст("3900000001", 1, "2023-03-01"),
            вст("3900000001", 3, "2023-09-01"),            # вторая проектная в том же году — одна компания
            вст("3900000002", 1, "2024-05-01", статус=НЕТ),  # потом исключили — вступление всё равно было
            вст("3900000003", 2, "2025-01-15T00:00:00"),
            вст("3900000004", 1, "2026-02-01"),            # текущий год — в среднее не входит
            вст("3900000005", 1, "2019-02-01"),            # раньше периода
            вст("390000000006", 1, "2024-02-01"),          # ИП
            вст("3900000007", 1, None),                    # без даты
        ]
        в = д.вступления_пи_по_регионам(члены_пи, сро_пи)
        к = в["регионы"]["Калининградская область"]
        self.assertEqual((к["проект_юл_2023"], к["проект_юл_2024"], к.get("проект_юл_2025", 0), к["проект_юл_2026"]),
                         (1, 1, 0, 1))
        self.assertEqual(к["проект_юл_в_среднем_за_год"], 0.7)        # (1 + 1 + 0) / 3
        self.assertEqual(к["изыскания_юл_в_среднем_за_год"], 0.3)
        self.assertEqual(к["проект_ип_2024"], 1)
        self.assertEqual(в["полные_годы"], [2023, 2024, 2025])
        self.assertEqual(в["записей_без_даты_вступления"], 1)
        self.assertIn("| Калининградская область | 1 | 1 | 0 | 1 | 0.7 |", д.таблица_вступлений_md(в))



if __name__ == "__main__":
    unittest.main()
