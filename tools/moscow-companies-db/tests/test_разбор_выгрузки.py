"""Тесты разбора официальной выгрузки реестра членов СРО."""

import importlib.util
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
_spec = importlib.util.spec_from_file_location("разбор", ROOT / "разбор_выгрузки.py")
разбор = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(разбор)

КАРТОЧКА = (
    "Ассоциация строителей саморегулируемая организация «Объединение "
    "строительных организаций «ЭкспертСтрой»;\n"
    "Ассоциация СРО «ЭкспертСтрой»;\nСРО-С-265-10042013;\nИНН:7708240612;\n"
    "ОГРН:1127799010668;\nАдрес местонахождения:107078, Москва г;\n"
    "Телефон:+7(495) 151-25-21;\nEmail:infosro@asostroi.ru"
)


class TestКарточкаСРО(unittest.TestCase):
    def test_короткое_имя(self):
        self.assertEqual(разбор.разобрать_сро(КАРТОЧКА)["имя"],
                         "Ассоциация СРО «ЭкспертСтрой»")

    def test_регистрационный_номер(self):
        self.assertEqual(разбор.разобрать_сро(КАРТОЧКА)["номер"], "СРО-С-265-10042013")

    def test_телефон(self):
        # Ради него всё и разбирается: именно телефон СРО чаще всего
        # оказывается «общим» у десятков компаний
        self.assertEqual(разбор.разобрать_сро(КАРТОЧКА)["телефон"], "+7(495) 151-25-21")

    def test_пустая_карточка(self):
        пусто = разбор.разобрать_сро("")
        self.assertEqual((пусто["имя"], пусто["номер"], пусто["телефон"]), ("", "", ""))


