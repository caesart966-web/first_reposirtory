class TestОчередьChecko(unittest.TestCase):
    def _з(self, инн, свой, дата_прекр="", сро="С-082"):
        return {"ИНН": инн, "Свой телефон": свой, "Дата прекращения": дата_прекр,
                "СРО": сро, "Наименование": f"ООО {инн}"}

    def test_порядок_и_повторы(self):
        члены = [self._з("1", "нет", "01.03.2015"), self._з("2", "нет"),
                 self._з("3", "нет", "20.09.2026"), self._з("4", "да"),
                 # «5» в одной СРО без телефона, в другой — с телефоном
                 self._з("5", "нет"), self._з("5", "да", сро="С-129"),
                 # «6» в двух СРО: исключена из одной, действует в другой
                 self._з("6", "нет", "01.01.2020"), self._з("6", "нет", сро="С-129")]
        очередь = разбор.очередь_checko(члены)
        self.assertEqual([з["ИНН"] for з in очередь], ["2", "6", "3", "1"])
        self.assertEqual(очередь[1]["СРО"], "С-129")

    def test_файл_как_ростовский(self):
        with tempfile.TemporaryDirectory() as tmp:
            путь = Path(tmp) / "пермь_для_checko.xlsx"
            разбор.записать_для_checko(путь, [self._з("2", "нет"), self._з("3", "нет", "20.09.2026")])
            строки = list(load_workbook(путь).active.iter_rows(values_only=True))
        self.assertEqual(list(строки[0]), разбор.КОЛОНКИ_CHECKO)
        self.assertEqual([r[3] for r in строки[1:]], ["действующий", "исключён"])


