class TestЧтениеВыгрузки(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.папка = Path(self.tmp.name)

    def tearDown(self):
        self.tmp.cleanup()

    def test_обе_раскладки_читаются_одинаково(self):
        член = {"Полное наименование": "ООО «Кама»", "ИНН": "5902000001",
                "Контактные телефоны": "8 (34271) 2-15-63", "Дата регистрации в реестре СРО": "01.02.2020",
                "Фамилия, имя, отчество лица, осуществляющего функции единоличного "
                "исполнительного органа юридического лица": "Иванов И. И."}
        _выгрузка(self.папка / "н.xlsx", ШАПКА_НОСТРОЙ, [член])
        член_п = dict(член)
        член_п["Контактные телефоны\t"] = член_п.pop("Контактные телефоны")
        _выгрузка(self.папка / "п.xlsx", ШАПКА_НОПРИЗ, [dict(член_п, **{"Статус (члена СРО": "Является членом"})])
        for файл in ("н.xlsx", "п.xlsx"):
            [(сро, члены)] = разбор.читать_выгрузку([self.папка / файл])
            self.assertEqual(сро["номер"], "СРО-С-082-27112009")
            self.assertEqual(len(члены), 1, файл)              # подстрока не член
            з = члены[0]
            self.assertEqual((з["ИНН"], з["Телефоны"], з["Руководитель"], з["Дата вступления"]),
                             ("5902000001", "8 (34271) 2-15-63", "Иванов И. И.", "01.02.2020"), файл)
            self.assertFalse(разбор.исключён(з))

    def test_ип_сам_себе_руководитель(self):
        _выгрузка(self.папка / "ип.xlsx", ШАПКА_НОСТРОЙ, [{
            "Полное наименование": "ИП Петров", "ИНН": "590200000012",
            "Фамилия, имя, отчество (при наличии) для ИП": "Петров Пётр Петрович",
            "Адрес места фактического осуществления деятельности для ИП": "г. Пермь"}])
        [(_, [з])] = разбор.читать_выгрузку([self.папка / "ип.xlsx"])
        self.assertEqual((з["Руководитель"], з["Адрес"]), ("Петров Пётр Петрович", "г. Пермь"))

    def test_вернувшийся_член_не_исключён(self):
        # Исключили в 2019, приняли снова в 2023: в реестре две записи.
        # Раньше оставалась первая, и действующий член считался исключённым
        _выгрузка(self.папка / "в.xlsx", ШАПКА_НОСТРОЙ, [
            {"Полное наименование": "ООО «Вернулись»", "ИНН": "5902000002",
             "Дата регистрации в реестре СРО": "10.10.2015", "Дата прекращения членства": "01.03.2019",
             "Контактные телефоны": "+7 342 211-11-11"},
            {"Полное наименование": "ООО «Вернулись»", "ИНН": "5902000002",
             "Дата регистрации в реестре СРО": "15.06.2023"},
        ])
        [(_, [з])] = разбор.читать_выгрузку([self.папка / "в.xlsx"])
        self.assertFalse(разбор.исключён(з))
        self.assertEqual(з["Дата вступления"], "15.06.2023")
        self.assertEqual(з["Телефоны"], "+7 342 211-11-11")       # дополнен из старой

    def test_чужой_файл_пропускается(self):
        wb = Workbook()
        wb.active.append(["Наименование", "ИНН", "Телефоны"])
        wb.active.append(["ООО «Свод»", "5902000003", ""])
        wb.save(self.папка / "свод.xlsx")
        _выгрузка(self.папка / "н.xlsx", ШАПКА_НОСТРОЙ,
                  [{"Полное наименование": "ООО «Кама»", "ИНН": "5902000001"}])
        группы = разбор.читать_выгрузку([self.папка / "свод.xlsx", self.папка / "н.xlsx"])
        self.assertEqual([len(ч) for _, ч in группы], [1])

    def test_исключён_по_статусу_без_даты(self):
        self.assertTrue(разбор.исключён({"Статус": "Исключен", "Дата прекращения": ""}))
        self.assertFalse(разбор.исключён({"Статус": "Является членом", "Дата прекращения": ""}))


