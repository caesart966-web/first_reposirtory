def _выгрузка(путь, шапка, члены, карточка=КАРТОЧКА_ПЕРМЬ):
    """Файл как с сайта: две строки шапки, карточка СРО, члены с подстроками."""
    wb = Workbook()
    ws = wb.active
    ws.append(["Сведения о СРО", "Сведения о члене саморегулируемой организации"])
    ws.append(шапка)
    ws.append([карточка, " "])
    for n, член in enumerate(члены, 1):
        строка = [None] * len(шапка)
        строка[1] = str(n)
        for поле, значение in член.items():
            строка[шапка.index(поле)] = значение
        ws.append(строка)
        ws.append([None, " "] + [None] * (len(шапка) - 3) + ["подстрока: страховка"])
    wb.save(путь)


