def _член(инн, телефоны, имя=None):
    return {"ИНН": инн, "Телефоны": телефоны,
            "Наименование": имя or f"ООО {инн}", "Сокращённое": ""}


class TestОбщиеТелефоны(unittest.TestCase):
    def test_одиночный_номер_не_помечается(self):
        члены = [_член("1", "+7 495 111-22-33"), _член("2", "+7 495 444-55-66")]
        сводка = разбор.пометить_телефоны(члены, None)
        self.assertEqual(сводка, [])
        self.assertEqual(члены[0]["Телефон общий с"], "")

    def test_общий_номер_считается(self):
        члены = [_член(str(i), "+7 495 111-22-33") for i in range(3)]
        сводка = разбор.пометить_телефоны(члены, None)
        self.assertEqual(len(сводка), 1)
        self.assertEqual(сводка[0]["Компаний"], "3")
        self.assertEqual(члены[0]["Телефон общий с"], "3 компаниями")

    def test_телефон_сро_помечен_отдельно(self):
        # Номер СРО у многих компаний — не признак связи между ними
        члены = [_член(str(i), "+7(495) 151-25-21") for i in range(12)]
        сводка = разбор.пометить_телефоны(члены, "+7(495) 151-25-21")
        self.assertEqual(сводка[0]["Чей это номер"], "самой СРО")
        self.assertEqual(члены[0]["Пометка по телефону"], "телефон самой СРО")

    def test_агент_помечен_от_десяти_компаний(self):
        члены = [_член(str(i), "+7 965 080-01-08") for i in range(10)]
        сводка = разбор.пометить_телефоны(члены, "+7(495) 151-25-21")
        self.assertEqual(сводка[0]["Чей это номер"], "похоже на агента")
        self.assertEqual(члены[0]["Пометка по телефону"], "похоже на агента")

    def test_несколько_номеров_в_ячейке(self):
        # В выгрузке в одной ячейке бывает и номер, и фамилия, и второй номер
        члены = [_член("1", "(495)747-19-48, Пупков Владимир, +7 965 080-01-08"),
                 _член("2", "+7 965 080-01-08")]
        сводка = разбор.пометить_телефоны(члены, None)
        self.assertEqual([с["Телефон"] for с in сводка], ["+79650800108"])

    def test_служебное_поле_убрано(self):
        члены = [_член("1", "+7 495 111-22-33")]
        разбор.пометить_телефоны(члены, None)
        self.assertNotIn("_номера", члены[0])


class TestПометкаНОПРИЗ(unittest.TestCase):
    def test_виды_и_итог(self):
        члены = [_член("1", ""), _член("2", ""), _член("3", "")]
        проект = {"1": (("2021", "03", "15"), "15.03.2021", "СРО-П")}
        изыск = {"1": (("2022", "07", "20"), "20.07.2022", "СРО-И"),
                 "2": (("2020", "01", "01"), "01.01.2020", "СРО-И2")}
        разбор.пометить_нопориз(члены, проект, изыск)
        self.assertEqual(члены[0]["В НОПРИЗ"], "проектирование и изыскания")
        self.assertEqual(члены[0]["Проектирование: дата вступления"], "15.03.2021")
        self.assertEqual(члены[1]["В НОПРИЗ"], "изыскания")
        self.assertEqual(члены[2]["В НОПРИЗ"], "нет")


