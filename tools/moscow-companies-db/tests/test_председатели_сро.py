class TestОбход(unittest.TestCase):
    def test_адреса(self):
        self.assertEqual(пред.адреса("https://np-mooss.ru/;  https://mooss.ru/"),
                         ["https://np-mooss.ru/", "https://mooss.ru/"])
        self.assertEqual(пред.адреса("www.npas.ru"), ["http://www.npas.ru"])
        self.assertEqual(пред.адреса(""), [])

    def test_через_ссылку_органы_управления(self):
        страницы = {
            "http://sro.ru": '<a href="/news">Новости</a><a href="/about/organy">Органы управления</a>'
                             '<a href="https://chuzhoy.ru/sovet">Совет у соседей</a>',
            "http://sro.ru/about/organy": "<p>Председатель Совета — Смирнов Алексей Петрович</p>",
            "https://chuzhoy.ru/sovet": "<p>Председатель Совета — Чужой Чужак Чужакович</p>",
        }
        итог = пред.обойти("sro.ru", скачать=сайт(страницы))
        self.assertEqual(итог["Председатель совета"], "Смирнов Алексей Петрович")
        self.assertEqual(итог["Где найдено"], "http://sro.ru/about/organy")
        self.assertEqual(итог[пред.ИТОГ], "найдено")

    def test_новость_на_главной_не_мешает(self):
        # на главной — новость с председателем, а настоящий — на странице «Совет»
        страницы = {
            "http://sro.ru": '<p>Председатель Совета: Новостной Н. Н. выступил</p><a href="/sovet">Совет</a>',
            "http://sro.ru/sovet": "<p>Председатель Совета — Петров Пётр Петрович</p>",
        }
        итог = пред.обойти("sro.ru", скачать=сайт(страницы))
        self.assertEqual(итог["Председатель совета"], "Петров Пётр Петрович")

    def test_карта_сайта_и_типовые_адреса(self):
        # меню рисует скрипт — ссылок нет; страница находится по карте сайта
        страницы = {
            "http://sro.ru": "<div id='app'></div>",
            "http://sro.ru/sitemap.xml": '<?xml version="1.0"?><urlset><url><loc>http://sro.ru/news/1</loc></url>'
                                         "<url><loc>http://sro.ru/o-nas/pravlenie-assotsiatsii</loc></url></urlset>",
            "http://sro.ru/o-nas/pravlenie-assotsiatsii": "<p>Председатель Правления: Орлов Олег Олегович</p>",
        }
        self.assertEqual(пред.обойти("sro.ru", скачать=сайт(страницы))["Председатель совета"], "Орлов Олег Олегович")
        # карты нет, но есть типовой адрес /sovet/
        страницы = {"http://sro.ru": "<div id='app'></div>",
                    "http://sro.ru/sovet/": "<p>Председатель Совета — Белов Борис Борисович</p>"}
        self.assertEqual(пред.обойти("sro.ru", скачать=сайт(страницы))["Председатель совета"], "Белов Борис Борисович")

    def test_голый_председатель_на_странице_совета(self):
        страницы = {"http://sro.ru": '<a href="/sovet">Совет Ассоциации</a>',
                    "http://sro.ru/sovet": "<h1>Совет Ассоциации</h1><p>Председатель – Громов Глеб Глебович</p>"
                                           "<p>Председатель ревизионной комиссии – Тихонов Т. Т.</p>"}
        self.assertEqual(пред.обойти("sro.ru", скачать=сайт(страницы))["Председатель совета"], "Громов Глеб Глебович")
        # на обычной странице просто «Председатель» не считается
        self.assertIsNone(self.т_страница("<p>Председатель – Громов Глеб Глебович</p>"))

    def т_страница(self, html):
        return пред.найти(пред.разобрать(html)[0])

    def test_текст_для_разбора(self):
        страницы = {"http://sro.ru": '<a href="/sovet">Совет</a>',
                    "http://sro.ru/sovet": "<p>Совет Ассоциации</p><table><tr><td>Председатель</td></tr>"
                                           "<tr><td>Г. Г. Громов, генеральный директор</td></tr></table>"}
        итог = пред.обойти("sro.ru", скачать=сайт(страницы))
        if итог[пред.ИТОГ] != "найдено":
            self.assertEqual(итог["Страница для разбора"], "http://sro.ru/sovet")
            self.assertIn("Председатель", итог["Текст для разбора"])

    def test_не_открылся_и_не_найдено(self):
        self.assertEqual(пред.обойти("dead.ru", скачать=сайт({}))[пред.ИТОГ], "сайт не открылся")
        итог = пред.обойти("sro.ru", скачать=сайт({"http://sro.ru": "<p>Добро пожаловать</p>"}))
        self.assertTrue(итог[пред.ИТОГ].startswith("не найдено"))
        self.assertEqual(пред.обойти("", скачать=сайт({}))[пред.ИТОГ], "сайта нет")


class TestФайл(unittest.TestCase):
    def test_дописывает_и_продолжает(self):
        with tempfile.TemporaryDirectory() as tmp:
            путь = Path(tmp) / "п.xlsx"
            wb = openpyxl.Workbook()
            wb.active.append(пред.ИСХ)
            wb.active.append(["СРО-С-001", "А", "Строительная", "г. Москва", "7700000001", "a.ru"])
            wb.active.append(["СРО-П-002", "Б", "Проектная", "г. Москва", "7700000002", "b.ru"])
            wb.save(путь)
            вызовы = []

            def обойти(сайт):
                вызовы.append(сайт)
                return ({"Председатель совета": "Иванов Иван Иванович", пред.ИТОГ: "найдено"}
                        if сайт == "a.ru" else {пред.ИТОГ: "сайт не открылся"})

            with mock.patch.object(пред, "обойти", обойти), redirect_stdout(io.StringIO()):
                пред.main(["--file", str(путь), "--потоков", "2"])
                пред.main(["--file", str(путь)])                  # второй раз — ничего не обходит
            ws = openpyxl.load_workbook(путь).active
            шапка = [c.value for c in ws[1]]
            строки = [dict(zip(шапка, [c.value for c in r])) for r in ws.iter_rows(min_row=2)]
        self.assertEqual(sorted(вызовы), ["a.ru", "b.ru"])
        self.assertEqual(шапка[:6], пред.ИСХ)
        self.assertEqual(строки[0]["Председатель совета"], "Иванов Иван Иванович")
        self.assertEqual(строки[1][пред.ИТОГ], "сайт не открылся")


