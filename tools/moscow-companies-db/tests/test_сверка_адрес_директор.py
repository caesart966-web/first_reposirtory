def выгрузка(путь: Path, члены: list[tuple]) -> None:
    from openpyxl import Workbook
    wb = Workbook()
    ws = wb.active
    ws.append(["Сведения о СРО", "Сведения о члене саморегулируемой организации"])
    ws.append(ШАПКА_НОСТРОЙ)
    for i, (инн, имя, адрес, рук, прекр) in enumerate(члены):
        ws.append([КАРТОЧКА if i == 0 else None, i + 1, имя, имя, str(i), "01.01.2020",
                   "01.01.2010", прекр, None, "1", инн, "+7 (342) 200-00-00", адрес, рук])
    wb.save(путь)


class TestТаблицаЗаказчика(unittest.TestCase):
    """Реестры нескольких СРО одним файлом: лист — СРО, должность — отдельной колонкой."""

    def test_листы_и_колонки(self):
        from openpyxl import Workbook
        шапка = ["ОПФ", "Сокращенное наименование", "ИНН", "Должность руководителя",
                 "Руководитель", "Юридический адрес"]
        wb = Workbook()
        ws = wb.active
        ws.title = "Сфера проектировщиков"
        ws.append(шапка)
        ws.append(["ООО", "«Аксиома»", "7811514257", "Генеральный директор",
                   "Горильчаный Алексей Владимирович", "193230, г. Санкт-Петербург, ул. Крыленко, д. 3"])
        ws.append(["ИП", "Маковейчук Владимир Валерьевич", "233303203507",
                   "Индивидуальный предприниматель", "Маковейчук Владимир Валерьевич",
                   "344019, г. Ростов-на-Дону"])
        ws2 = wb.create_sheet("ЦОС СФЕРА-А")
        ws2.append(шапка)
        ws2.append(["ООО", "«НИС»", "7810542170", "Генеральный директор", "Ананьев Андрей Юрьевич",
                    "196247, Санкт-Петербург, пр. Ленинский, д. 160"])
        with tempfile.TemporaryDirectory() as tmp:
            путь = Path(tmp) / "реестры.xlsx"
            wb.save(путь)
            записи = св.читать_файлы([путь])
        self.assertEqual([з["СРО"] for з in записи],
                         ["Сфера проектировщиков", "Сфера проектировщиков", "ЦОС СФЕРА-А"])
