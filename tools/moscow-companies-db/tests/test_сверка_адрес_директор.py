def голова(фио, **kw):
    return {"фио": фио, "должность": "Директор", "с": "", "недост": False,
            "управляющая": False, **kw}


class TestРуководитель(unittest.TestCase):
    def итог(self, реестр, *головы):
        return св.сравнить_руководителя(реестр, list(головы))

    def test_должность_не_мешает(self):
        self.assertEqual(self.итог("Генеральный директор Арсеньев Юрий Владимирович",
                                   голова("Арсеньев Юрий Владимирович")), ("совпадает", ""))

    def test_ё_и_регистр(self):
        self.assertEqual(self.итог("ДИРЕКТОР СЕМЁНОВ ПЁТР ИВАНОВИЧ",
                                   голова("Семенов Петр Иванович"))[0], "совпадает")

    def test_инициалы_после_и_до_фамилии(self):
        self.assertEqual(self.итог("Иванов И.И.", голова("Иванов Иван Ильич")),
                         ("совпадает", "по инициалам"))
        self.assertEqual(self.итог("Директор И.И. Иванов", голова("Иванов Иван Ильич"))[0],
                         "совпадает")

    def test_и_о_не_принимается_за_инициалы(self):
        self.assertEqual(self.итог("И.о. директора Петров П.П.", голова("Петров Павел Петрович"))[0],
                         "совпадает")

    def test_другой_человек(self):
        self.assertEqual(self.итог("Директор Арапов Игорь Алексеевич",
                                   голова("Сидоров Олег Петрович")), ("другой руководитель", ""))

    def test_однофамилец_с_другими_инициалами(self):
        self.assertEqual(self.итог("Иванов П.С.", голова("Иванов Иван Ильич"))[0],
                         "другой руководитель")

    def test_опечатка_в_одну_букву(self):
        self.assertEqual(self.итог("Генеральный директор Каганов Виталий Давыдович",
                                   голова("Каганов Виталий Давидович")),
                         ("совпадает", "написание отличается"))

    def test_обрезанное_отчество(self):
        self.assertEqual(self.итог("Директор Портнов Алексей Владимирови",
                                   голова("Портнов Алексей Владимирович"))[0], "совпадает")

    def test_муж_и_жена_не_опечатка(self):
        self.assertEqual(self.итог("Директор Петров Александр Сергеевич",
                                   голова("Петрова Александра Сергеевна"))[0], "другой руководитель")

