"""спб_юрлица.py: торговля и услуги Петербурга с 5–20 сотрудниками."""

import importlib.util
import io
import tempfile
import unittest
import zipfile
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
_spec = importlib.util.spec_from_file_location("спб_юрлица", ROOT / "спб_юрлица.py")
спб = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(спб)
checko = спб.checko


def док(инн, оквэд, регион="78", ссчр=None, кат="1", новый=None, ип=False):
    атр = f' ССЧР="{ссчр}"' if ссчр is not None else ""
    атр += f' ПризНовМСП="{новый}"' if новый else ""
    кто = (f'<ИПВклМСП ИННФЛ="{инн}" ОГРНИП="1"/><ФИОИП Фамилия="Иванова" Имя="Анна"/>' if ип else
           f'<ОргВклМСП НаимОрг="ООО {инн}" НаимОргСокр="ООО «{инн}»" ИННЮЛ="{инн}" ОГРН="1"/>')
    return (f'<Документ ИдДок="{инн}" ДатаСост="10.10.2026" ДатаВклМСП="10.08.2019" ВидСубМСП="1" '
            f'КатСубМСП="{кат}"{атр}>{кто}<СведМН КодРегион="{регион}"/>'
            f'<СвОКВЭД><СвОКВЭДОсн КодОКВЭД="{оквэд}"/><СвОКВЭДДоп КодОКВЭД="47.71"/></СвОКВЭД></Документ>')


def реестр(путь: Path, документы: list[str]) -> None:
    xml = '<?xml version="1.0" encoding="utf-8"?><Файл ИдФайл="x" ВерсФорм="4.07">' + "".join(документы) + "</Файл>"
    with zipfile.ZipFile(путь, "w") as z:
        z.writestr("data-1.xml", xml.encode("utf-8"))


class TestНаправление(unittest.TestCase):
    def test_окведы(self):
        self.assertEqual(спб.направление("96.02"), "Салоны красоты, парикмахерские")
        self.assertEqual(спб.направление("47.71.1"), "Розница: одежда, обувь, текстиль")
        self.assertEqual(спб.направление("85.11"), "Детские сады, частные школы, кружки и курсы")
        self.assertIsNone(спб.направление("85.42"))        # автошколы и проф. обучение — нет
        self.assertIsNone(спб.направление("14.13"))        # пошив — производство
        self.assertIsNone(спб.направление("41.20"))
        self.assertIsNone(спб.направление(""))


class TestКандидаты(unittest.TestCase):
    def _прогнать(self, документы):
        with tempfile.TemporaryDirectory() as tmp:
            tmp = Path(tmp)
            реестр(tmp / "rsmp.zip", документы)
            with redirect_stdout(io.StringIO()) as вывод:
                код = спб.main(["кандидаты", "--rsmp", str(tmp / "rsmp.zip"), "--out", str(tmp / "к.xlsx")])
            self.assertEqual(код, 0)
            _ш, строки = checko.read_rows(tmp / "к.xlsx")
        return {r["ИНН"]: r for r in строки}, вывод.getvalue()

    def test_с_численностью(self):
        r, вывод = self._прогнать([
            док("7801000001", "96.02", ссчр=8),            # подходит
            док("7801000002", "96.02", ссчр=3),            # мало сотрудников
            док("7801000003", "96.02", ссчр=25, кат="2"),  # много
            док("7801000004", "47.75", ссчр=20),           # граница — подходит
            док("7801000005", "25.11", ссчр=10),           # производство (доп. ОКВЭД торговля — не в счёт)
            док("7701000006", "96.02", регион="77", ссчр=10),  # Москва
            док("780100000007", "96.02", ссчр=10, ип=True),     # ИП
        ])
        self.assertEqual(set(r), {"7801000001", "7801000004"})
        self.assertEqual(r["7801000001"]["Сотрудников (реестр МСП)"], "8")
        self.assertEqual(r["7801000001"]["Направление"], "Салоны красоты, парикмахерские")
        self.assertIn("с нужным ОКВЭД: 4, из них с численностью в реестре: 4", вывод)

    def test_без_численности_микро_и_малые(self):
        r, вывод = self._прогнать([
            док("7801000001", "69.20", кат="1"),
            док("7801000002", "69.20", кат="2"),
            док("7801000003", "69.20", кат="3"),           # среднее — больше 100 человек
            док("7801000004", "69.20", новый="1"),         # новая — отчётности ещё нет
        ])
        self.assertEqual(set(r), {"7801000001", "7801000002"})
        self.assertEqual(r["7801000001"]["Сотрудников (реестр МСП)"], "нет в реестре")
        self.assertIn("численности нет", вывод)


def ответ(**поля):
    r = {"Наименование": "ООО", "ИНН": "7801000001", "Направление": "Бухгалтерия и аудит",
         "Статус (Checko)": "Действует", checko.НЕДОСТОВЕРНОСТЬ: "нет", "Сотрудников (СЧР)": "9",
         "Налоги уплачено, ₽": "1200000", "Регион (Checko)": "Санкт-Петербург",
         "ОКВЭД основной (Checko)": "69.20 Деятельность по оказанию услуг в области бухгалтерского учёта",
         "Банкротство": ""}
    r.update(поля)
    return r


class TestИтог(unittest.TestCase):
    def test_разбор(self):
        р = lambda **п: спб.разобрать(ответ(**п), 5, 20)
        self.assertEqual(р(), ("Подходят", ""))
        self.assertEqual(р(**{"Статус (Checko)": ""})[0], "Не проверены")
        self.assertEqual(р(**{"Статус (Checko)": "лимит исчерпан"})[0], "Не проверены")
        self.assertEqual(р(**{checko.НЕДОСТОВЕРНОСТЬ: ""})[0], "Не проверены")
        self.assertIn("недостоверные", р(**{checko.НЕДОСТОВЕРНОСТЬ: "адрес"})[1])
        self.assertIn("статус", р(**{"Статус (Checko)": "Находится в стадии ликвидации"})[1])
        self.assertIn("сотрудников 3", р(**{"Сотрудников (СЧР)": "3"})[1])
        self.assertIn("сотрудников 21", р(**{"Сотрудников (СЧР)": "21"})[1])
        self.assertIn("нет данных о сотрудниках", р(**{"Сотрудников (СЧР)": ""})[1])
        self.assertIn("налогов нет", р(**{"Налоги уплачено, ₽": "0"})[1])
        self.assertIn("регион", р(**{"Регион (Checko)": "Ленинградская область"})[1])
        self.assertIn("ОКВЭД сменился", р(**{"ОКВЭД основной (Checko)": "25.11 Производство"})[1])

    def test_файл(self):
        with tempfile.TemporaryDirectory() as tmp:
            tmp = Path(tmp)
            колонки = list(ответ())
            checko.write_rows(tmp / "к.xlsx", колонки,
                              [ответ(), ответ(ИНН="7801000002", **{"Налоги уплачено, ₽": "0"}),
                               ответ(ИНН="7801000003", **{"Статус (Checko)": ""})])
            with redirect_stdout(io.StringIO()):
                спб.main(["итог", "--file", str(tmp / "к.xlsx"), "--out", str(tmp / "и.xlsx")])
            from openpyxl import load_workbook
            wb = load_workbook(tmp / "и.xlsx")
        self.assertEqual(wb.sheetnames, ["Подходят (1)", "Не подходят (1)", "Не проверены (1)"])
        self.assertEqual([c.value for c in wb["Подходят (1)"][2]][:2], ["ООО", "7801000001"])


if __name__ == "__main__":
    unittest.main()
