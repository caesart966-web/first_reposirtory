"""Какая доля строительных компаний региона состоит в проектных и изыскательских СРО.

Просьба 19.11.2026: для регионов, где нет своих проектных и изыскательских СРО,
посчитать процент строительных компаний, которые всё же состоят в проектной
(и отдельно — в изыскательской) СРО, — понятно, что в СРО другого региона.

Строительная компания региона — действующий член любой строительной СРО
(НОСТРОЙ, «Является членом»), у которого в записи реестра указан этот регион
(поле region_number; если его нет — по коду региона в ИНН). Считается по ИНН,
один раз, даже если компания состоит в двух строительных СРО. «В проектных» —
этот ИНН среди действующих членов хотя бы одной проектной СРО (НОПРИЗ, «-П-»)
любого региона, «в изыскательских» — изыскательской («-И-»).

Списки членов берутся по каждой СРО одним запросом (как в сро_пересечения.py:
у общего списка НОПРИЗ нестабильная сортировка). В репозиторий идут только
числа по регионам; списки с ИНН остаются в кэше.

  python сро_доля_регион.py --нострой russia_2026_11/нострой.json --ноприз russia_2026_11/ноприз.json \\
         --out russia_2026_11/доли_по_регионам.json
"""
from __future__ import annotations

import argparse
import datetime as dt
import importlib.util
import json
import os
import sys
from collections import Counter, defaultdict
from pathlib import Path

_ЗДЕСЬ = Path(__file__).resolve().parent


def _модуль(имя: str):
    spec = importlib.util.spec_from_file_location(имя, _ЗДЕСЬ / f"{имя}.py")
    м = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(м)
    return м


пересечения = _модуль("сро_пересечения")
россия = _модуль("сро_россия")


def регион_члена(z: dict) -> tuple[str, str]:
    """(субъект РФ, откуда): из записи реестра (region_number), иначе по коду в ИНН."""
    блок = z.get("region_number")
    название = (блок.get("title") or блок.get("name")) if isinstance(блок, dict) else None
    if название:
        субъект, откуда = россия.субъект(название, None)
        if откуда != "нет":
            return субъект, "реестр"
    субъект, откуда = россия.субъект(None, z.get("inn"))
    return субъект, ("ИНН" if откуда == "ИНН" else "нет")


def посчитать(члены_с: list[dict], члены_пи: list[dict], сро_с: list[dict], сро_пи: list[dict]) -> dict:
    """Числа по регионам. сро_* — записи сводок (рег_номер, id)."""
    номер_с = {str(x["id"]): x["рег_номер"] for x in сро_с if x.get("id")}
    номер_пи = {str(x["id"]): x["рег_номер"] for x in сро_пи if x.get("id")}
    в_проекте, в_изысканиях = set(), set()
    for z in члены_пи:
        if not пересечения.действует(z) or not пересечения.инн(z):
            continue
        в = пересечения.вид(номер_пи.get(пересечения.сро_id(z), ""))
        if в == "П":
            в_проекте.add(пересечения.инн(z))
        elif в == "И":
            в_изысканиях.add(пересечения.инн(z))
    # ИНН → регион; если у одной компании в двух СРО разные регионы — берётся чаще указанный
    регионы_инн: dict[str, Counter] = defaultdict(Counter)
    откуда = Counter()
    for z in члены_с:
        if not пересечения.действует(z) or not пересечения.инн(z):
            continue
        if пересечения.вид(номер_с.get(пересечения.сро_id(z), "")) != "С":
            continue
        субъект, источник = регион_члена(z)
        регионы_инн[пересечения.инн(z)][субъект] += 1
        откуда[источник] += 1
    итог: dict[str, Counter] = defaultdict(Counter)
    for и, счёт in регионы_инн.items():
        к = итог[счёт.most_common(1)[0][0]]
        к["строительных"] += 1
        к["в_проектных"] += и in в_проекте
        к["в_изыскательских"] += и in в_изысканиях
        к["в_обоих"] += и in в_проекте and и in в_изысканиях
        к["хотя_бы_в_одной"] += и in в_проекте or и in в_изысканиях
    out = {}
    for регион, к in sorted(итог.items()):
        n = к["строительных"]
        out[регион] = dict(к) | {
            "доля_в_проектных": round(100 * к["в_проектных"] / n, 1),
            "доля_в_изыскательских": round(100 * к["в_изыскательских"] / n, 1),
            "доля_хотя_бы_в_одной": round(100 * к["хотя_бы_в_одной"] / n, 1)}
    return {"регионы": out, "строительных_всего": len(регионы_инн),
            "откуда_регион_записей": dict(откуда),
            "инн_в_проектных": len(в_проекте), "инн_в_изыскательских": len(в_изысканиях)}


def пи_по_регионам(члены_пи: list[dict], сро_пи: list[dict]) -> dict:
    """Все действующие члены проектных и изыскательских СРО по регионам самой компании.

    Просьба 20.11.2026: не только строительные компании, а все юрлица региона — сколько из них
    в проектных и изыскательских СРО (любых). Юрлицо — ИНН из 10 цифр, ИП — из 12; по ИНН без
    повторов: компания в двух проектных СРО считается один раз."""
    номер_пи = {str(x["id"]): x["рег_номер"] for x in сро_пи if x.get("id")}
    виды_инн: dict[str, set] = defaultdict(set)
    регионы_инн: dict[str, Counter] = defaultdict(Counter)
    откуда = Counter()
    for z in члены_пи:
        и = пересечения.инн(z)
        if not пересечения.действует(z) or not и:
            continue
        в = пересечения.вид(номер_пи.get(пересечения.сро_id(z), ""))
        if в not in ("П", "И"):
            continue
        виды_инн[и].add(в)
        субъект, источник = регион_члена(z)
        регионы_инн[и][субъект] += 1
        откуда[источник] += 1
    итог: dict[str, Counter] = defaultdict(Counter)
    for и, виды in виды_инн.items():
        к = итог[регионы_инн[и].most_common(1)[0][0]]
        тип = "юл" if len(и) == 10 else "ип" if len(и) == 12 else "другое"
        if "П" in виды:
            к[f"в_проектных_{тип}"] += 1
        if "И" in виды:
            к[f"в_изыскательских_{тип}"] += 1
        к[f"хотя_бы_в_одной_{тип}"] += 1
        if виды == {"П", "И"}:
            к[f"в_обоих_{тип}"] += 1
    return {"регионы": {р: dict(к) for р, к in sorted(итог.items())}, "откуда_регион_записей": dict(откуда)}


def вступления_пи_по_регионам(члены_пи: list[dict], сро_пи: list[dict],
                              годы: tuple[int, ...] = (2023, 2024, 2025, 2026)) -> dict:
    """Сколько компаний региона вступало в проектные и изыскательские СРО — по годам и в среднем за год.

    Просьба 24.11.2026: для регионов без своих проектных и изыскательских СРО — сколько компаний
    оттуда вступает в такие СРО (любого региона) в среднем за год. Вступление — запись члена
    с датой registry_registration_date в этом году, любого нынешнего статуса (потом исключённый тоже
    вступал). За год и вид СРО компания считается один раз по ИНН (вступила в две проектные — одна).
    Среднее — по полным годам (все, кроме последнего: он ещё идёт)."""
    номер_пи = {str(x["id"]): x["рег_номер"] for x in сро_пи if x.get("id")}
    множества: dict[tuple, set] = defaultdict(set)
    без_даты = 0
    for z in члены_пи:
        и = пересечения.инн(z)
        if not и:
            continue
        в = пересечения.вид(номер_пи.get(пересечения.сро_id(z), ""))
        if в not in ("П", "И"):
            continue
        д = пересечения.регион.дата(z.get("registry_registration_date"))
        if not д:
            без_даты += 1
            continue
        if д.year not in годы:
            continue
        субъект, _ = регион_члена(z)
        тип = "юл" if len(и) == 10 else "ип" if len(и) == 12 else "другое"
        множества[(субъект, "проект" if в == "П" else "изыскания", тип, д.year)].add(и)
    итог: dict[str, dict] = defaultdict(dict)
    for (р, в, т, г), инн_ in множества.items():
        итог[р][f"{в}_{т}_{г}"] = len(инн_)
    полные = [г for г in годы if г < max(годы)]
    for к in итог.values():
        for в in ("проект", "изыскания"):
            for т in ("юл", "ип"):
                к[f"{в}_{т}_в_среднем_за_год"] = round(sum(к.get(f"{в}_{т}_{г}", 0) for г in полные) / len(полные), 1)
    return {"регионы": dict(sorted(итог.items())), "годы": list(годы), "полные_годы": полные,
            "записей_без_даты_вступления": без_даты}


def таблица_вступлений_md(вст: dict) -> str:
    годы, полные = вст["годы"], вст["полные_годы"]
    строки = ["| Регион | " + " | ".join(f"В проектные {г}" for г in годы) + " | В среднем за год "
              "| " + " | ".join(f"В изыскательские {г}" for г in годы) + " | В среднем за год |",
              "|---|" + "---:|" * (2 * len(годы) + 2)]
    for р, к in sorted(вст["регионы"].items(), key=lambda x: -x[1].get("проект_юл_в_среднем_за_год", 0)):
        п = " | ".join(str(к.get(f"проект_юл_{г}", 0)) for г in годы)
        и = " | ".join(str(к.get(f"изыскания_юл_{г}", 0)) for г in годы)
        строки.append(f"| {р} | {п} | {к['проект_юл_в_среднем_за_год']} | {и} "
                      f"| {к['изыскания_юл_в_среднем_за_год']} |")
    return "\n".join(строки) + "\n"


def таблица_пи_md(пи: dict) -> str:
    строки = ["| Регион | Юрлиц в проектных СРО | Юрлиц в изыскательских СРО | Юрлиц хотя бы в одной "
              "| ИП в проектных | ИП в изыскательских |", "|---|---:|---:|---:|---:|---:|"]
    for регион, к in sorted(пи["регионы"].items(), key=lambda x: -x[1].get("хотя_бы_в_одной_юл", 0)):
        строки.append(f"| {регион} | {к.get('в_проектных_юл', 0)} | {к.get('в_изыскательских_юл', 0)} "
                      f"| {к.get('хотя_бы_в_одной_юл', 0)} | {к.get('в_проектных_ип', 0)} "
                      f"| {к.get('в_изыскательских_ип', 0)} |")
    return "\n".join(строки) + "\n"


def таблица_md(итог: dict) -> str:
    строки = ["| Регион | Строительных компаний | В проектных СРО | % | В изыскательских СРО | % |",
              "|---|---:|---:|---:|---:|---:|"]
    for регион, к in sorted(итог["регионы"].items(), key=lambda x: -x[1]["строительных"]):
        строки.append(f"| {регион} | {к['строительных']} | {к['в_проектных']} | {к['доля_в_проектных']} "
                      f"| {к['в_изыскательских']} | {к['доля_в_изыскательских']} |")
    return "\n".join(строки) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--нострой", required=True, help="сводка сро_регион.py по НОСТРОЙ (id ↔ рег. номер)")
    ap.add_argument("--ноприз", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--кэш", default=os.path.expanduser("~/.cache/сро_все_члены"))
    ap.add_argument("--потоков", type=int, default=4)
    a = ap.parse_args(argv)
    сро_с = json.loads(Path(a.нострой).read_text(encoding="utf-8"))["сро"]
    сро_пи = json.loads(Path(a.ноприз).read_text(encoding="utf-8"))["сро"]
    члены_с = пересечения.члены_по_сро("нострой", сро_с, Path(a.кэш) / "нострой_по_сро", a.потоков)
    члены_пи = пересечения.члены_по_сро("ноприз", сро_пи, Path(a.кэш) / "ноприз_по_сро", a.потоков)
    итог = посчитать(члены_с, члены_пи, сро_с, сро_пи)
    итог["проектные_изыскательские_по_регионам"] = пи_по_регионам(члены_пи, сро_пи)
    итог["вступления_пи_по_регионам"] = вступления_пи_по_регионам(члены_пи, сро_пи)
    итог.update({"дата_сбора": dt.date.today().isoformat(),
                 "пояснение": "строительные компании региона — действующие члены строительных СРО "
                              "(НОСТРОЙ) с этим регионом в записи реестра (нет — по ИНН), по ИНН без "
                              "повторов; «в_проектных» — ИНН среди действующих членов хотя бы одной "
                              "проектной СРО любого региона, «в_изыскательских» — изыскательской"})
    out = Path(a.out)
    out.write_text(json.dumps(итог, ensure_ascii=False, indent=1), encoding="utf-8")
    out.with_suffix(".md").write_text(
        f"# Доля строительных компаний региона в проектных и изыскательских СРО ({итог['дата_сбора']})\n\n"
        f"{итог['пояснение']}.\n\nРегион взят из реестра у {итог['откуда_регион_записей'].get('реестр', 0)} "
        f"записей, по ИНН — у {итог['откуда_регион_записей'].get('ИНН', 0)}.\n\n" + таблица_md(итог)
        + "\n## Все члены проектных и изыскательских СРО по регионам компании\n\n"
        "Действующие члены, по ИНН без повторов; юрлицо — ИНН из 10 цифр, ИП — из 12. Регион — из записи "
        "реестра НОПРИЗ (нет — по ИНН).\n\n" + таблица_пи_md(итог["проектные_изыскательские_по_регионам"])
        + "\n## Вступления юрлиц региона в проектные и изыскательские СРО по годам\n\n"
        "Запись члена с датой вступления в этом году, любого нынешнего статуса; за год компания — один раз; "
        f"среднее — по полным годам {итог['вступления_пи_по_регионам']['полные_годы']}; последний год — "
        "по день сбора.\n\n" + таблица_вступлений_md(итог["вступления_пи_по_регионам"]),
        encoding="utf-8")
    print(f"строительных компаний: {итог['строительных_всего']}, регионов: {len(итог['регионы'])}, "
          f"регион: {итог['откуда_регион_записей']} → {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
