# -*- coding: utf-8 -*-
"""Сочетания клавиш, не зависящие от раскладки.

Tkinter узнаёт сочетание по СИМВОЛУ, который печатает клавиша. При английской
раскладке Ctrl+C даёт «c» — знакомо; при русской та же клавиша даёт «с»
кириллическую, и сочетание не срабатывает вовсе. Людям приходилось
переключаться на английский, чтобы просто вставить реквизиты в поле.

Здесь только решение «что делать», без самого Tkinter: так его можно
проверить тестом на любой машине, даже там, где графики нет.
"""

#: Коды клавиш Windows. Код — это номер физической кнопки, он одинаков
#: в любой раскладке, поэтому по нему и опознаём сочетание.
CLIPBOARD_KEYS = {
    67: "<<Copy>>",       # C
    86: "<<Paste>>",      # V
    88: "<<Cut>>",        # X
    65: "<<SelectAll>>",  # A
}

#: Латинские буквы тех же клавиш. Если пришла одна из них, раскладка
#: английская и Tkinter сработал сам — вмешиваться нельзя, иначе действие
#: выполнится дважды и текст вставится два раза.
LATIN_KEYS = frozenset("cvxa")


def clipboard_action(keycode: int, keysym: str) -> str | None:
    """Что сделать за Tkinter при нажатом Ctrl.

    Возвращает имя события Tk («<<Paste>>») либо None, если делать нечего:
    клавиша не та или раскладка английская и Tkinter справится сам.
    """
    action = CLIPBOARD_KEYS.get(keycode)
    if action is None:
        return None
    if (keysym or "").lower() in LATIN_KEYS:
        return None
    return action
