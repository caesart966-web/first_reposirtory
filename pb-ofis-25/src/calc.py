"""Расчёты раздела ПБ-25. Все числа, которые попадают в текстовую часть, считаются здесь
и подставляются в разметку как {{имя}}. Запуск отдельно печатает сводку: python3 calc.py"""
import math

R = {}          # значения для подстановки в текст


def f(x, n=2):
    """Число в русской записи: запятая, без лишних нулей не убираем — как в расчётах."""
    s = f'{x:.{n}f}'.replace('.', ',')
    return s


def put(name, value, n=2):
    R[name] = f(value, n) if isinstance(value, float) else value
    return value


# ───────────────────────── 1. Здание ─────────────────────────
# Габариты по наружным граням стен и отметка верха по модели АР (IFC «Администрация рынка №25»)
B_X, B_Y, B_H = 40.53, 30.56, 7.85
V_BLD = B_X * B_Y * B_H
put('b_x', B_X); put('b_y', B_Y); put('b_h', B_H)
put('v_bld', f'{round(V_BLD, -1):,.0f}'.replace(',', ' '))
FLOOR_AREA = B_X * B_Y                       # площадь этажа по наружному контуру
put('floor_area', FLOOR_AREA, 1)

# наружное пожаротушение: СП 8.13130.2020 (с изм. 1), табл. 2 — общественное здание до 2 этажей, 5–25 тыс. м³
Q_OUT = 15
put('q_out', str(Q_OUT))


# ───────────────────────── 2. АУГПТ серверной (СП 485, прил. Д) ─────────────────────────
S_SRV, H_SRV = 40.37, 3.80                   # площадь по экспликации; высота от пола до низа плиты +3,950 (плита 150 мм)
V_SRV = S_SRV * H_SRV                        # потолок «Грильято» открытый, запотолочное пространство — в объёме помещения
RHO0, T0 = 7.28, 293.0                       # плотность паров хладона 227еа при 20 °С и 101,3 кПа
T_MIN = 283.0                                # минимальная температура в помещении +10 °С (кондиционируемая серверная)
K3 = 1.0                                     # высотный коэффициент: площадка ~ 210 м над у.м. (ГП: 205–209 м), принят 1,0
CN = 7.2                                     # нормативная концентрация хладона 227еа, % об.
K1 = 1.05                                    # коэффициент утечек из сосудов
P_ZONE = 0.4                                 # параметр П: неплотности распределены по высоте
F_LEAK = 0.01                                # постоянно открытые проёмы после закрытия клапанов: неплотности двери и проходок, м²
TAU = 10.0                                   # нормативное время подачи хладона, с
N_MOD, M_BAL = 2, 1.0                        # модулей; остаток ГОТВ в модуле по паспорту, кг (подтверждается паспортом изготовителя)
V_TR = 0.0045                                # вместимость трубопроводов, м³ (2 × Ду25 по 4,0 м + Ду20 0,6 м)

rho1 = RHO0 * T0 / T_MIN * K3
delta = F_LEAK / V_SRV
K2 = P_ZONE * delta * TAU * math.sqrt(H_SRV)
Mp = V_SRV * rho1 * (1 + K2) * CN / (100 - CN)
Mtr = V_TR * rho1                            # остаток в трубах — газовая фаза при атмосферном давлении
Mg = K1 * (Mp + Mtr + N_MOD * M_BAL)
M_FILL = 50.0                                # заправка одного модуля, кг
M_TOT = N_MOD * M_FILL
VOL_MOD = 100.0                              # вместимость модуля, л
fill_k = M_FILL / VOL_MOD
# фактическая концентрация при заправке 2×50 кг
M_act = M_TOT / K1 - Mtr - N_MOD * M_BAL
C_act_min = 100 * M_act / (M_act + V_SRV * rho1)                       # при +10 °С
rho25 = RHO0 * T0 / 298.0
V_net = V_SRV - 8.0                                                    # за вычетом оборудования (4 стойки, ИБП, мебель) ~ 8 м³
C_act_max = 100 * M_act / (M_act + V_net * rho25)                      # +25 °С и объём за вычетом оборудования
NOAEL = 9.0
for k, v in dict(v_srv=V_SRV, rho1=rho1, mp=Mp, mg=Mg, m_act=M_act).items():
    put(k, v)
put('h_srv', H_SRV); put('s_srv', S_SRV)
put('f_leak', F_LEAK, 2); put('cn', CN, 1); put('k3', K3, 1); put('v_tr', V_TR, 4); put('m_bal', M_BAL, 1)
put('delta', delta, 6)
put('k2', K2, 5)
put('mtr', Mtr, 3)
put('c_min', C_act_min); put('c_max', C_act_max)
put('m_tot', M_TOT, 0); put('m_fill', M_FILL, 0); put('fill_k', fill_k, 2)

# ── упрощённый гидравлический расчёт линии «модуль — насадок» (на каждый модуль своя линия, один насадок 360°)
RHO_L = 1390.0                               # плотность жидкого хладона 227еа при 20 °С
P0 = 4.2                                     # давление в модуле при 20 °С, МПа (наддув азотом)
V_L = M_FILL / RHO_L * 1000                  # объём жидкости, л
V_G0 = VOL_MOD - V_L                         # газовая подушка, л
P_END = (P0 + 0.1) * (V_G0 / VOL_MOD) ** 1.2 - 0.1   # давление к концу выпуска жидкой фазы (политропа n=1,2)
P_AVG = (P0 + P_END) / 2
T_DIS = 8.0                                  # принятое время выпуска 95 % массы, с
G = 0.95 * M_FILL / T_DIS                    # средний массовый расход на линию, кг/с
D_IN = 0.0266                                # Ду25: труба 33,7×3,5 по ГОСТ 8732
A = math.pi * D_IN ** 2 / 4
w = G / (RHO_L * A)
L_PIPE, L_EQ = 4.0, 2.6                      # длина трубы и эквивалентная длина отводов и тройника, м
LAM = 0.25 / (math.log10(0.1e-3 / (3.7 * D_IN) + 5.74 / (RHO_L * w * D_IN / 2.5e-4) ** 0.9)) ** 2
dP_pipe = LAM * (L_PIPE + L_EQ) / D_IN * RHO_L * w ** 2 / 2 / 1e6
dP_valve = 0.35                              # запорно-пусковое устройство и РВД — по паспорту модуля, МПа
dP_h = RHO_L * 9.81 * 3.3 / 1e6              # подъём от модуля к насадку 3,3 м
P_NOZ = P_AVG - dP_pipe - dP_valve - dP_h
MU = 0.6
F_NOZ = G / (MU * math.sqrt(2 * RHO_L * P_NOZ * 1e6))
N_HOLE = 8
d_hole = math.sqrt(4 * F_NOZ / math.pi / N_HOLE) * 1000
for k, v in dict(p_end=P_END, p_avg=P_AVG, g_line=G, w_pipe=w, dp_pipe=dP_pipe, dp_h=dP_h,
                 p_noz=P_NOZ).items():
    put(k, v)
put('lam', LAM, 3); put('v_l', V_L, 1); put('f_noz', F_NOZ * 1e6, 0); put('d_hole', d_hole, 1)
put('t_dis', T_DIS, 0); put('dp_valve', dP_valve)
put('v_g0', V_G0, 1)

# ── КСИД (СП 485, прил. Ж) и проверка с учётом азота
P_A = 0.1013                                 # МПа
P_PR = 0.0005                                # допустимое избыточное давление для ограждений из сэндвич-панелей и двери, МПа
RHO_AIR = 1.2
KS2, KS3 = 1.2, 1.0                          # коэффициент запаса; коэффициент изменения давления при подаче (хладон)
vel = math.sqrt(7e6 * P_A * (((P_PR + P_A) / P_A) ** 0.2857 - 1) / RHO_AIR)   # скорость истечения, м/с
Fc = KS2 * KS3 * Mp / (0.7 * K1 * rho1 * T_DIS) / vel - 0.0
# проверка: в проём выходит и азот наддува двух модулей (изотермическое расширение до атмосферного)
V_N2 = N_MOD * V_G0 / 1000 * (P0 + 0.1) / 0.1013
Q_gas = (0.95 * M_TOT / rho1 + V_N2) / T_DIS
rho_mix = RHO_AIR * (1 - CN / 100) + rho1 * CN / 100
Fc2 = Q_gas / (0.6 * math.sqrt(2 * P_PR * 1e6 / rho_mix))
F_KSID_ONE = 0.30 * 0.30 * 0.95              # КСИД 300×300, живое сечение 95 %
N_KSID = math.ceil(max(Fc, Fc2) / F_KSID_ONE)
put('vel', vel, 1); put('fc', Fc, 3); put('v_n2', V_N2, 1); put('q_gas', Q_gas); put('fc2', Fc2, 3)
put('n_ksid', str(N_KSID)); put('f_ksid', N_KSID * F_KSID_ONE, 3); put('p_pr', P_PR * 1e3, 1)


# ───────────────────────── 3. Конференц-зал №36 ─────────────────────────
HALL_L, HALL_B, HALL_H = 16.70, 9.51, 3.80
HALL_S = 158.00
HALL_V = HALL_L * HALL_B * HALL_H
HALL_D = math.hypot(HALL_L, HALL_B)
N_HALL = 200
# выходы: Д1 — в северной стене в коридор (перенесена из западной стены, см. задание АР), Д2 — в западной стене у юга
DOOR_B = 1.2
d_doors = math.hypot(7.40, 8.14)             # между ближайшими гранями: Д1 (х 7,40–8,60 по сев. стене), Д2 (у 8,14–9,34 по зап. стене)
F_PERS = 0.125                               # площадь проекции человека в зимней одежде, м²
q_door = 2.5 + 3.75 * DOOR_B                 # интенсивность движения через проём при D ≥ 0,9, м/мин
P_door = q_door * DOOR_B / F_PERS            # пропускная способность выхода, чел/мин
N1, N2 = 100, 100
t_q = max(N1, N2) / P_door
L_MAX = 14.6                                 # от дальнего места 1-го ряда до выхода Д2 по проходу у южной стены
V_FREE = 60.0                                # м/мин до образования скопления (D < 0,05)
t_first = 4.5 / V_FREE                       # первый человек доходит до выхода по поперечному проходу
t_hall = t_first + t_q
t_path = L_MAX / 30.0                        # по проходу в потоке D ≈ 0,3 (v ≈ 30 м/мин)
T_NEED = 2.0                                 # СП 1.13130.2020, табл. 9: зал без колосниковой сцены, до 5 тыс. м³, С0
for k, v in dict(hall_v=HALL_V, hall_d=HALL_D, hall_d2=HALL_D / 2, d_doors=d_doors, q_door=q_door,
                 p_door=P_door, t_q=t_q, t_first=t_first, t_hall=t_hall, t_path=t_path).items():
    put(k, v)
put('hall_v0', HALL_V, 0); put('hall_dens', N_HALL / HALL_S)
put('t_need', T_NEED, 1); put('f_pers', F_PERS, 3)

# рассадка: 14 рядов по ширине зала, боковые проходы по 1,0 м у стен, шаг рядов 0,9 м, место 0,5 м
ROWS = [15] * 12 + [12, 12]
ROWS[7] -= 2; ROWS[8] -= 2                   # колонны по оси 5 (5/Г, 5/В) приходятся на места 2 и 14 в 8-м и 9-м рядах
SEATS = sum(ROWS)
assert SEATS == N_HALL, SEATS
put('seats', str(SEATS))


