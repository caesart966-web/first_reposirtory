def t_cat_calc():
    out = ['@table 9,25,40,14,12,12,10 | C,L,L,C,C,C,C',
           '№ пом. | Помещение, назначение | Пожарная нагрузка: материал – масса, кг × Qнр, МДж/кг | Q, МДж | S, м² | g, МДж/м² | Кат.']
    for fl in (1, 2):
        out.append(f'!! {fl}-й этаж')
        for c in (c for c in CATS if c['fl'] == fl):
            load = '; '.join(f'{mat} – {m} × {f(Q[mat], 1)}' for mat, m in c['load'])
            out.append(f"{c['num']} | {c['name']}: {c['use']} | {load} | {f(c['q'], 0)} | {f(c['s_load'], 0)} | "
                       f"{f(c['g'], 1)} | {c['cat']}")
    out.append('@end')
    return '\n'.join(out)


