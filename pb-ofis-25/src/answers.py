def sheets_text(heads, gch, marks, gnums):
    parts = []
    tch = sorted({marks[h] for h in heads if h in marks})
    if tch:
        parts.append('ТЧ, лист' + ('ы ' if len(tch) > 1 else ' ') + ', '.join(f'{n:02d}' for n in tch))
    for g in gch:
        parts.append(f'графический лист {g} (лист тома {gnums[g]:02d})')
    return '; '.join(parts)


def build(path, marks, gnums):
    missing = [h for it in ITEMS for h in it[3] if h not in marks]
    if missing:
        raise SystemExit('в текстовой части нет разделов: ' + '; '.join(missing))
    d = docx.Document()
    st = d.styles['Normal']; st.font.name = 'Times New Roman'; st.font.size = Pt(12)
    sec = d.sections[0]
    sec.page_width, sec.page_height = Mm(210), Mm(297)
    sec.left_margin, sec.right_margin, sec.top_margin, sec.bottom_margin = Mm(25), Mm(15), Mm(20), Mm(20)

    def par(text, bold=False, size=12, align=None, space=4):
        p = d.add_paragraph()
        r = p.add_run(text); r.bold = bold; r.font.size = Pt(size)
        p.paragraph_format.space_after = Pt(space)
        if align:
            p.alignment = align
        return p
    par('ОТВЕТЫ НА ЗАМЕЧАНИЯ', True, 14, WD_ALIGN_PARAGRAPH.CENTER, 2)
    par('к разделу ОПР-01/24/2026-ПБ-25 «Мероприятия по обеспечению пожарной безопасности», '
        '«Здание администрации рынка №25 (по генплану)»', False, 12, WD_ALIGN_PARAGRAPH.CENTER, 10)
    par('Замечания отработаны в новой редакции раздела (единый том). Ниже по каждому замечанию – что сделано и на '
        'каких листах. Номера листов – по новой редакции тома.', space=10)
    for n, issue, ans, heads, gch in ITEMS:
        par(f'ЗАМЕЧАНИЕ ИНСПЕКТОРА № {n}', True, 12, space=2)
        par('ЗАМЕЧАНИЕ', True, 10, space=0)
        par(issue, space=4)
        par('ОТВЕТ ИСПОЛНИТЕЛЯ', True, 10, space=0)
        par(ans, space=4)
        par('ИЗМЕНЁННЫЕ ЛИСТЫ И ДОКУМЕНТЫ', True, 10, space=0)
        par(sheets_text(heads, gch, marks, gnums), space=12)
    par('ДОПОЛНИТЕЛЬНО ИСПРАВЛЕНО (по результатам проверки раздела)', True, 12, space=4)
    for k, s in enumerate(EXTRA, 1):
        par(f'{k}. {s}', space=4)
    par('Номера замечаний 1, 3, 5, 7, 8, 9 в полученном файле замечаний отсутствуют.', space=4)
    d.save(path)
    return path
