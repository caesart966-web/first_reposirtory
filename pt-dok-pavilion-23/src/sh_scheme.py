def pump_room_sheet(msp, ox, oy, sheet_no, total):
    frame(msp, ox, oy, 'A1', 1, 'Насосная станция пожаротушения (пом. 05). План, разрез 1-1', sheet_no, total)
    K = 25.0
    px, py = 80, 235      # начало плана на листе (лок. X=0,Y=0 — юго-западный угол помещения)
    d = D(msp, ox, oy)
    def Pp(X, Y):
        return (px + X / K, py + Y / K)
    d.title(px + 85, 545, 'План насосной станции пожаротушения (пом. 05)', 3.5, '1:25')
    # стены
    W, H = 4250, 5900
    t = 100
    for (x0, y0, x1, y1) in [(-t, -t, 0, H + t), (W, -t, W + t, H + t), (0, -t, W, 0), (0, H, W, H + t)]:
        a, b = Pp(x0, y0); c, e = Pp(x1, y1)
        d.wall(a, b, c, e, 'ANSI31', 0.25)
    # наружная дверь (предусмотреть в АР)
    a, b = Pp(-t, 300); c, e = Pp(0, 1300)
    d.r(a, b, c, e, 'ПТ_контур', 35); d.hatch([(a, b), (c, b), (c, e), (a, e)], solid=True, color=7)
    d.l(*Pp(0, 300), *Pp(-1000, 300), 'ПТ_контур', 25); d.m.add_arc(d.P(*Pp(0, 300)), 1000 / K, 90, 180, dxfattribs={'layer': 'ПТ_контур'})
    d.t(*Pp(-1100, 800), 'Дверь EI 30 наружу\n(предусмотреть в АР)'.split('\n')[0], 1.8, 'MR')
    d.t(*Pp(-1100, 500), '(предусмотреть в АР)', 1.8, 'MR')
    # оси
    d.t(*Pp(-125, -900), 'ось 1', 2.0, 'TC'); d.t(*Pp(W, -900), 'ось 2', 2.0, 'TC')
    d.t(*Pp(-1300, -125 + 0), 'ось Д', 2.0, 'MR'); d.t(*Pp(-1300, H - 0), 'ось Е', 2.0, 'MR')
    # трубопроводы (план)
    def pp(pts, lay='ПТ_В2', lw=50):
        d.pipe([Pp(*q) for q in pts], lay, lw)
    # вводы — подъём из подвала
    for (X, Y, n) in [(400, 5200, 1), (400, 4400, 2)]:
        d.c(*Pp(X, Y), 159 / 2 / K, 'ПТ_ввод', 50); d.t(*Pp(X - 250, Y), f'Ввод {n} Ду150 (из подвала)', 1.8, 'MR')
        pp([(X, Y), (700, Y)], 'ПТ_ввод', 60)
        d.valve(*Pp(520, Y), 'V_BFLY', 0, 1.0)
    pp([(700, 2200), (700, 5200)], 'ПТ_В2', 70)                 # всасывающий
    pp([(2700, 1800), (2700, 4900)], 'ПТ_В2', 70)               # напорный
    pp([(2700, 1800), (3900, 1800)], 'ПТ_В2', 70)
    for Y, nm in [(4200, 'Н1'), (3000, 'Н2')]:
        pp([(700, Y), (1450, Y)]); pp([(1950, Y), (2700, Y)])
        a, b = Pp(1450, Y - 300); c, e = Pp(1950, Y + 300)
        d.r(a, b, c, e, 'ПТ_оборудование', 35); d.c(*Pp(1700, Y), 230 / K, 'ПТ_оборудование', 35)
        d.t(*Pp(1700, Y + 450), nm, 2.5, 'BC', style='ПТ_Ж')
        d.valve(*Pp(1050, Y), 'V_BFLY', 0, 1.0); d.valve(*Pp(2250, Y), 'V_CHECK', 0, 1.0); d.valve(*Pp(2500, Y), 'V_BFLY', 0, 1.0)
    d.pos(*Pp(1950, 4200), *Pp(2300, 5400), POS['pump'])
    # жокей
    pp([(700, 2300), (1550, 2300)], 'ПТ_В2', 35); pp([(1850, 2300), (2700, 2300)], 'ПТ_В2', 35)
    a, b = Pp(1550, 2150); c, e = Pp(1850, 2450); d.r(a, b, c, e, 'ПТ_оборудование', 35)
    d.t(*Pp(1700, 2550), 'Н3', 2.5, 'BC', style='ПТ_Ж'); d.pos(*Pp(1550, 2150), *Pp(1200, 1600), POS['jockey'])
    d.c(*Pp(2250, 2750), 250 / K, 'ПТ_оборудование', 35); d.t(*Pp(2250, 3050), 'Бак 100 л', 1.8, 'BC')
    pp([(2450, 2750), (2700, 2750)], 'ПТ_В2', 25)
    # обвод, опробование
    pp([(700, 4900), (2700, 4900)], 'ПТ_В2', 60); d.valve(*Pp(1300, 4900), 'V_BFLY', 0, 1.0); d.valve(*Pp(2000, 4900), 'V_CHECK', 0, 1.0)
    d.t(*Pp(1700, 5050), 'Обвод Ду150', 1.8, 'BC')
    pp([(700, 3600), (2700, 3600)], 'ПТ_В2', 35); d.valve(*Pp(2450, 3600), 'V_BFLY', 0, 0.9)
    a, b = Pp(1500, 3520); c, e = Pp(1900, 3680); d.r(a, b, c, e, 'ПТ_арматура'); d.t(*Pp(1700, 3720), 'Линия опробования Ду100', 1.6, 'BC')
    # УУ, отводы ВПВ
    for X, nm in [(2125, 'УУ-1'), (3025, 'УУ-2')]:
        pp([(X, 1800), (X, 1175)], 'ПТ_В2', 60)
        d.c(*Pp(X, 1175), 250 / K, 'ПТ_оборудование', 50); d.t(*Pp(X, 1175), nm, 1.6, 'MC')
        d.t(*Pp(X, 650), 'Ст.В2' + nm[-1] + '-1', 1.8, 'TC')
    d.pos(*Pp(3025, 1175), *Pp(3500, 300), POS['uu'])
    pp([(3625, 1800), (3625, 775)], 'ПТ_В2', 60); d.c(*Pp(3625, 775), 108 / 2 / K, 'ПТ_В2', 50); d.t(*Pp(3800, 775), 'Б (вверх)', 1.6, 'ML')
    pp([(3625, 1800), (3625, 2975)], 'ПТ_В2', 60); d.c(*Pp(3625, 2975), 108 / 2 / K, 'ПТ_В2', 50); d.t(*Pp(3800, 2975), 'А (вниз)', 1.6, 'ML')
    d.valve(*Pp(3625, 1400), 'V_BFLY', 90, 0.9); d.valve(*Pp(3625, 2400), 'V_BFLY', 90, 0.9)
    # пожарная техника — на +2,200
    pp([(0, 1400), (2700, 1400), (2700, 1800)], 'ПТ_В2', 35); d.t(*Pp(900, 1450), 'Ду100 к ГМ-80, ось +2,200', 1.6, 'BL')
    # шкафы на стене
    for (Y0, Y1, nm) in [(3300, 4100, 'ШКП-30 Н1'), (4200, 5000, 'ШКП-30 Н2'), (5100, 5600, 'ШКП-4'), (2300, 3200, 'Шкаф автоматики')]:
        a, b = Pp(W - 300, Y0); c, e = Pp(W, Y1); d.r(a, b, c, e, 'ПТ_оборудование', 35)
        d.t(*Pp(W - 350, (Y0 + Y1) / 2), nm, 1.6, 'MR')
    d.b('DRAIN', *Pp(1200, 1000), 1.0); d.t(*Pp(1200, 700), 'Трап Ду100 (раздел ВК)', 1.6, 'TC')
    # размеры
    d.dimh(*[Pp(x, 0)[0] for x in (0, W)], Pp(0, -600)[1], '4250', ext_from=Pp(0, 0)[1])
    d.dimv(*[Pp(0, y)[1] for y in (0, H)], Pp(W + 700, 0)[0], '5900', ext_from=Pp(W, 0)[0])
    for X in (400, 700, 1700, 2700):
        d.l(*Pp(X, H), *Pp(X, H + 500), 'ПТ_размеры')
    xs = [0, 400, 700, 1700, 2700, W]
    for a1, a2 in zip(xs, xs[1:]):
        d.dimh(Pp(a1, 0)[0], Pp(a2, 0)[0], Pp(0, H + 450)[1], str(a2 - a1))
    # разрез 1-1 (развёртка по линии Н1)
    sx, sy = 330, 300
    d.title(sx + 110, 545, 'Разрез 1-1 (развёртка по линии Н1)', 3.5, '1:25')
    def Ps(X, Z):
        return (sx + X / K, sy + Z * 1000 / K)
    gx0, gx1 = -200, 5400
