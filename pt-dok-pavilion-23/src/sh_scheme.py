"""Лист: схема принципиальная систем В2, В21, В22."""
from ru import plural
import json, os, math
from draw import D
from dxfkit import frame
HERE = os.path.dirname(os.path.abspath(__file__))
SP = json.load(open(os.path.join(HERE, 'spec.json')))
POS = SP['POS']
C = json.load(open(os.path.join(HERE, 'calc_final.json')))
B = json.load(open(os.path.join(HERE, 'bom.json')))

def scheme_sheet(msp, ox, oy, sheet_no, total):
    frame(msp, ox, oy, 'A1', 1, 'Схема принципиальная систем В2, В21, В22', sheet_no, total)
    d = D(msp, ox, oy)
    d.title(420, 570, 'Схема принципиальная систем водяного пожаротушения (В2, В21, В22)')
    # ---- наружная сеть и колодец
    d.pipe([(40, 140), (40, 470)], 'ПТ_ввод', 70)
    d.t(36, 280, 'Сеть В2 внутриплощадочная (раздел НВК)', 2.2, 'BC', rot=90)
    d.c(40, 330, 7, 'ПТ_контур', 35); d.t(47, 339, 'т. 23.1', 2.5, 'BL')
    # стена здания
    d.l(100, 120, 100, 540, 'ПТ_контур', 50, 'ПТ_ШТРИХ'); d.t(97, 125, 'Стена подвала, ось 1 — граница проектирования ПТ', 2.0, 'BL', rot=90)
    # насосная — контур
    d.r(108, 125, 515, 535, 'ПТ_контур', 25, 'ПТ_ШТРИХ'); d.t(112, 529, 'Насосная станция пожаротушения (технический подвал, оси 1–3/Д–Е, отм. −2,200)', 2.5, 'TL')
    # вводы
    ys = {'1': 445, '2': 205}
    for n, y in ys.items():
        d.pipe([(40, 330), (60, 330), (60, y), (190, y)], 'ПТ_ввод', 60)
        d.t(70, y + 2, f'Ввод {n} Ду150', 2.2)
        d.t(70, y - 4.5, 'отм. -1,900', 2.0)
        d.valve(116, y, 'V_BFLY', 0, 1.5); d.pos(116, y + 4, 112, y + 14, POS['bfly150'])
        d.valve(131, y, 'STRAINER', 0, 1.5); d.pos(131, y - 2, 126, y - 14, POS['strainer150'])
        d.valve(149, y, 'V_PRV', 0, 1.5); d.pos(149, y + 5, 152, y + 16, POS['prv150'])
        d.valve(174, y, 'V_CHECK', 0, 1.5); d.pos(174, y - 2, 179, y - 14, POS['chk150'])
    # всасывающий коллектор
    d.pipe([(190, 160), (190, 470)], 'ПТ_В2', 70); d.t(187, 165, 'Всасывающий коллектор Ду200', 2.0, 'BL', rot=90)
    # насосы Н1, Н2
    def pump_line(y, name, pump_pos, sc=1.0, small=False):
        X0, X1 = 190, 400
        d.pipe([(X0, y), (X1, y)], 'ПТ_В2', 50)
        if small:
            d.valve(215, y, 'V_BALL', 0, 1.2); d.b('PUMP', 260, y, 1.2); d.valve(300, y, 'V_CHECK', 0, 1.2); d.valve(330, y, 'V_BALL', 0, 1.2)
            d.pos(215, y + 2, 210, y + 13, POS['ball32']); d.pos(300, y + 2, 305, y + 13, POS['chk32'])
        else:
            d.valve(212, y, 'V_BFLY', 0, 1.4); d.pos(212, y + 4, 206, y + 15, POS['bfly150'])
            d.r(226, y - 2.5, 230, y + 2.5, 'ПТ_арматура'); d.pos(228, y - 2.5, 232, y - 13, POS['comp'])
            d.b('PUMP', 260, y, 1.8)
            d.r(290, y - 2.5, 294, y + 2.5, 'ПТ_арматура')
            d.valve(312, y, 'V_CHECK', 0, 1.4); d.pos(312, y - 2, 318, y - 13, POS['chk150'])
            d.valve(336, y, 'V_BFLY', 0, 1.4)
            d.b('MANOM', 240, y, 1.0); d.b('MANOM', 282, y, 1.0)
        d.t(260, y + (8 if not small else 6), name, 2.5, 'BC', style='ПТ_загл')
        d.pos(260, y - 5.5, 268, y - 18, pump_pos)
    pump_line(395, 'Н1 (раб.)', POS['pump'])
    pump_line(330, 'Н2 (рез.)', POS['pump'])
    pump_line(230, 'Н3 (жокей)', POS['jockey'], small=True)
    # обводная линия
    d.pipe([(190, 450), (400, 450)], 'ПТ_В2', 50)
    d.valve(240, 450, 'V_BFLY', 0, 1.4); d.valve(300, 450, 'V_CHECK', 0, 1.4)
    d.t(270, 455, 'Обводная линия Ду150', 2.2, 'BC')
    # линия опробования насосов (на всас)
    d.pipe([(400, 285), (360, 285), (360, 275), (190, 275)], 'ПТ_В2', 35)
    d.valve(345, 275, 'V_BFLY', 0, 1.2); d.r(280, 272, 294, 278, 'ПТ_арматура'); d.t(287, 275, 'FQ', 1.8, 'MC')
    d.pos(287, 278, 280, 290, POS['flow']); d.t(240, 270, 'Линия опробования насосов Ду100', 2.0, 'TC')
    # напорный коллектор
    d.pipe([(400, 160), (400, 500)], 'ПТ_В2', 70); d.t(404, 165, 'Напорный коллектор Ду200', 2.0, 'BL', rot=90)
    d.b('TANK', 430, 205, 1.6); d.pipe([(400, 200), (427, 200)], 'ПТ_В2', 35); d.pos(433, 210, 445, 222, POS['tank'])
    for i, (blk, p) in enumerate([('PSW', POS['sdu']), ('PSW', POS['sdu']), ('MANOM', POS['ekm']), ('MANOM', POS['ekm'])]):
        y = 345 + i * 12
        d.pipe([(400, y), (410, y)], 'ПТ_В2', 25); d.b(blk, 410, y, 1.2, -90)
        d.t(418, y, ['СДУ-М-1', 'СДУ-М-2', 'ЭКМ-1', 'ЭКМ-2'][i], 2.0, 'ML')
    # патрубки для пожарной техники
    d.pipe([(100, 510), (400, 510), (400, 500)], 'ПТ_В2', 50)
    d.b('GM80', 98, 510, 1.5, 180); d.b('GM80', 98, 504, 1.5, 180); d.pipe([(100, 504), (110, 504), (110, 510)], 'ПТ_В2', 35)
    d.t(60, 516, '2×ГМ-80 на фасаде', 2.2, 'BL'); d.pos(92, 507, 80, 497, POS['gm80'])
    d.valve(200, 510, 'V_CHECK', 0, 1.3); d.valve(230, 510, 'V_BFLY', 0, 1.3)
    d.t(300, 513, 'Подключение передвижной пожарной техники Ду100', 2.0, 'BC')
    # отводы от напорного коллектора
    outs = [(470, 'УУ-1', 'В21'), (430, 'УУ-2', 'В22'), (300, 'ВПВ, кольцо А', 'В2'), (250, 'ВПВ, кольцо Б', 'В2')]
    for y, nm, sysn in outs:
        lay = {'В21': 'ПТ_В21', 'В22': 'ПТ_В22', 'В2': 'ПТ_В2'}[sysn]
        if nm.startswith('УУ'):
            d.pipe([(400, y), (455, y)], 'ПТ_В2', 60)
            d.b('UU', 465, y, 1.6, layer='ПТ_оборудование'); d.t(465, y + 6, nm, 2.5, 'BC', style='ПТ_загл')
            d.pipe([(469, y), (530, y)], lay, 60)
            d.valve(490, y, 'V_BFLY', 0, 1.4)
            d.pos(465, y - 4, 455, y - 14, POS['uu'])
            d.pipe([(465, y - 4), (465, y - 20)], 'ПТ_В2', 25); d.b('DRAIN', 465, y - 22, 1.0); d.t(468, y - 24, 'в приямок', 1.8)
        else:
            d.pipe([(400, y), (530, y)], lay, 60)
            d.valve(440, y, 'V_BFLY', 0, 1.4)
            d.t(470, y + 2, nm + ' Ду100', 2.2, 'BC')
    # ---- справа: секции
    def section_box(y0, y1, name, lay, nspr, spr_txt, elev_main, risers):
        d.r(540, y0, 830, y1, 'ПТ_контур', 25, 'ПТ_ШТРИХ')
        d.t(545, y1 - 3, name, 2.5, 'TL', style='ПТ_загл')
        ym = (y0 + y1) / 2 - 5
        d.pipe([(530, (y0 + y1) / 2 + 20 if False else ym), (545, ym)], lay, 60)
        d.pipe([(545, ym), (810, ym)], lay, 60)
        d.t(560, ym + 2, f'Питающий трубопровод Ду150, ось {elev_main}', 2.0)
        for i, x in enumerate(range(575, 800, 45)):
            d.pipe([(x, ym), (x, ym + 22)], lay.replace('В21', 'В21_расп').replace('В22', 'В22_расп'), 35)
            for k in range(3):
                d.b('SPR_DN' if 'В21' in lay else 'SPR_UP', x, ym + 7 + k * 7, 1.0, layer='ПТ_оросители')
            d.pipe([(x, ym), (x, ym - 15)], lay.replace('В21', 'В21_расп').replace('В22', 'В22_расп'), 35)
            for k in range(2):
                d.b('SPR_DN' if 'В21' in lay else 'SPR_UP', x, ym - 6 - k * 7, 1.0, layer='ПТ_оросители')
        d.t(800, ym + 30, f"{nspr} {plural(nspr, 'ороситель', 'оросителя', 'оросителей')} {spr_txt}", 2.2, 'BR')
        # конец питающего: промывка, опробование, воздухоотводчик
        d.valve(818, ym, 'V_BALL', 90, 1.2); d.t(822, ym - 8, 'узел 8', 1.8)
        d.b('MANOM', 810, ym, 1.0)
        return ym
    y21 = section_box(455, 525, 'Секция 1 — В21: 1 этаж (группа 2)', 'ПТ_В21', B['spr']['DN'], 'СВО0-РНо0,42 (розеткой вниз)', '+2,900', '')
    d.pipe([(530, 470), (535, 470), (535, y21), (545, y21)], 'ПТ_В21', 60)
    y22 = section_box(370, 445, 'Секция 2 — В22: 2 этаж, зоны «второго света» (группы 2 и 5)', 'ПТ_В22', B['spr']['UP'], 'СВО0-РВо0,42 (розеткой вверх)', '+6,850', '')
    d.pipe([(530, 430), (532, 430), (532, y22), (545, y22)], 'ПТ_В22', 60)
    # ВПВ: кольцо
    d.r(540, 150, 830, 360, 'ПТ_контур', 25, 'ПТ_ШТРИХ')
    d.t(545, 357, 'Внутренний противопожарный водопровод — В2 (2 струи × 5,2 л/с)', 2.5, 'TL', style='ПТ_загл')
    d.pipe([(560, 190), (810, 190), (810, 330), (560, 330), (560, 190)], 'ПТ_В2', 60)
    d.t(685, 192, 'Кольцевая сеть Ду100 в техническом подвале, ось −0,450', 2.2, 'BC')
    for x in (600, 680, 760):
        d.valve(x, 330, 'V_BFLY', 0, 1.2); d.valve(x, 190, 'V_BFLY', 0, 1.2)
    d.pipe([(530, 300), (545, 300), (545, 300), (560, 300)], 'ПТ_В2', 60)
    d.pipe([(530, 250), (550, 250), (550, 210), (560, 210)], 'ПТ_В2', 60)
    grp_y = [(215, 'Подвал, отм. −2,200: шкафы ПК-25…ПК-30 (6 шт., 12 ПК), стояки Ду80'),
             (255, '1 этаж, отм. 0,000: шкафы ПК-1…ПК-16 (16 шт., 32 ПК), стояки Ду80'),
             (295, '2 этаж, отм. +3,700: шкафы ПК-17…ПК-24 (8 шт., 16 ПК), стояки Ду80')]
    _dfl = {x['floor']: x['d_mm'] for x in C['diaphragms'] if x['diaphragm']}
    grp_y = [(y, t + (f', диафрагмы d={_dfl[f]} мм' if f in _dfl else '')) for (y, t), f in zip(grp_y, (0, 1, 2))]
    for y, s in grp_y:
        for x in (600, 640, 680, 720, 760):
            d.pipe([(x, 190 if y < 260 else 330), (x, y)], 'ПТ_В2', 35)
            d.b('PK2', x, y, 0.9, layer='ПТ_ПК')
        d.t(575, y + 6, s, 2.0)
    d.t(685, 160, 'Клапаны ПК Ду65 на высоте 1,35 м от пола, рукав 20 м, ствол с насадком 19 мм', 2.0, 'BC')
    # таблица параметров
    rows = [['Расчётный расход АУПТ (табл. 6.1 СП 485, гр. 2)', f"{C['Q_aup']} л/с"], ['Расход ВПВ (2 струи)', f"{C['Q_vpv']} л/с"],
            ['Расход на вводе', f"{C['Q_pump']} л/с ({round(C['Q_pump'] * 3.6)} м³/ч)"], ['Требуемый напор на выходе насосной', f"{C['H_out']} м"],
            ['Давление в точке 23.1: гарантированное / максимальное', f"{C['H_guar'] / 100:.2f} / {C['P_in_max']:.2f} МПа"],
            ['Настройка регуляторов давления на вводах', f"{C['P_prv']:.2f} МПа"], ['Напор насосов Н1/Н2', f"{C['pump']['H']} м"],
            ['Расход по ТУ (согласовано 10.10.2026)', f"{C['Q_tu']:.0f} л/с"],
            ['Продолжительность работы', '60 мин'], ['Объём воды на пожаротушение', f"{C['volume_m3']} м³"]]
    d.table(30, 110, [('Показатель', 120), ('Значение', 55)], rows, h=2.2, row_h=6)
    # приямок с дренажными насосами
    d.r(225, 135, 335, 172, 'ПТ_контур', 35, 'ПТ_ШТРИХ'); d.t(228, 169, 'Приямок насосной', 2.0, 'TL')
    for x, nm in ((250, 'ДН1'), (300, 'ДН2')):
        d.b('PUMP', x, 145, 1.1); d.t(x, 151, nm, 2.0, 'BC')
        d.pipe([(x, 148), (x, 180)], 'ПТ_В2', 25); d.valve(x, 158, 'V_CHECK', 90, 0.9); d.valve(x, 166, 'V_BALL', 90, 0.9)
    d.pipe([(250, 180), (346, 180)], 'ПТ_В2', 35); d.valve(332, 180, 'V_BALL', 0, 0.9)
    d.l(346, 178, 346, 182, 'ПТ_контур', 50)
    d.t(349, 181, 'Точка подключения ВК: Ду50, отм. -1,200', 1.8, 'BL'); d.t(349, 177.5, 'отвод воды — раздел ВК (задание)', 1.8, 'BL')
    d.pos(300, 142, 318, 130, POS['drain_pump'])
    d.mt(240, 110, 'Примечания\n1. Позиции оборудования — по спецификации ПТ.С.\n2. Отметки: ось насосов и коллекторов −1,750, выход УУ −0,600, '
         'питающие В21 +2,900, В22 +6,850, кольцо В2 −0,450, вводы −1,900.\n3. Затворы на вводах, после УУ, на отводе к кольцу ВПВ, '
         'на обводной линии и линии опробования — с контролем положения (сигнал на ППКУП «Сириус», пом. 03).\n'
         '4. Пуск основного насоса — по падению давления в напорном коллекторе (СДУ-М, ЭКМ), от СДУ узлов управления, '
         'от кнопок «Пуск насосов» в шкафах ПК; резервный — при невыходе основного на режим. Алгоритм — лист 14.\n'
         f"5. Напор насосов подобран при {C['H_guar'] / 100:.2f} МПа на вводе 23.1 (ТУ от 08.10.2026) с учётом потерь в регуляторе давления; "
         f"расчётный расход {C['Q_pump']:g} л/с при согласованных {C['Q_tu']:.0f} л/с. При давлении в точке подключения до {C['P_in_max']:.2f} МПа "
         f"регуляторы на вводах держат за собой {C['P_prv']:.2f} МПа.", 2.2, 380)
