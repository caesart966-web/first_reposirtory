# расчёт АУПП (тушение по объёму)
V_ROOM = round(4.25 * 5.9 * 3.365, 1)
VN = 32.0; K1 = 1.2; S_ZAT = 2.4; S_Y = 25.08; K2 = round(1 + 1.33 * S_ZAT / S_Y, 2); K3 = 1.0; K4 = 1.05
N_CALC = V_ROOM * K1 * K2 * K3 * K4 / VN
N_MOD = math.ceil(N_CALC)
POWDER = dict(V=V_ROOM, VN=VN, K1=K1, K2=K2, K3=K3, K4=K4, N_calc=round(N_CALC, 2), N=N_MOD, mass=N_MOD * 8)

