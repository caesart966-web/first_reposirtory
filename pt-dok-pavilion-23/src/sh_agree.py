"""Лист для согласования с ГИП: размещение насосной станции в техническом подвале, основные данные,
вопросы с предложениями проекта и графой для решения. Выдаётся вместе с листами 3 и 10 (build_agree.py).
Координаты подосновы — мм DWG АР, лист — мм бумаги."""
import json, os
from ezdxf import const
from draw import D
from dxfkit import frame
from geom import AX_X, AX_Y

HERE = os.path.dirname(os.path.abspath(__file__))
C = json.load(open(os.path.join(HERE, 'calc_final.json')))
PM = C['pump']
M = json.load(open(os.path.join(HERE, 'model_sized.json')))
LV = M['levels']
SP = json.load(open(os.path.join(HERE, 'spec.json')))
PUMP_ROW = next(r for r in SP['rows'] if isinstance(r, dict) and r.get('pos') == SP['POS']['pump'])

K = 150.0
PX, PY = 120, 296                       # точка 0,0 DWG на листе
# технические коридоры: внутренние грани стен (зоны DWG АР) и наружные грани (стены 300 мм)
CORR1 = [(300, 22300), (97700, 22300), (97700, 27700), (51700, 27700), (51700, 33700), (46300, 33700), (46300, 27700), (300, 27700)]
CORR1_O = [(0, 22000), (98000, 22000), (98000, 28000), (52000, 28000), (52000, 34000), (46000, 34000), (46000, 28000), (0, 28000)]
CORR2 = [(51700, 12300), (97700, 12300), (97700, 17700), (300, 17700), (300, 12300), (46300, 12300), (46300, 6300), (51700, 6300)]
CORR2_O = [(52000, 12000), (98000, 12000), (98000, 18000), (0, 18000), (0, 12000), (46000, 12000), (46000, 6000), (52000, 6000)]
STAIRS = [(46300, 28475, 47425, 31300, 1, '94'), (46300, 8700, 47425, 11525, -1, '95')]
ROOM = (300, 22300, 8300, 27700)        # насосная (до новой перегородки)
XP, DOOR = 8420, (26300, 27300)
Y_IN = (27200, 26400)
PIT_B = (-1900, 22500, -200, 25900)     # вариант Б: приямок с лестницей снаружи (условно)


def n(v, nd=1):
    return f'{v:.{nd}f}'.replace('.', ',')


def kw(v):
    return f'{v:g}'.replace('.', ',')


def agree_sheet(msp, ox, oy, sheet_no=1, total=1):
    frame(msp, ox, oy, 'A1', 1, 'Насосная станция пожаротушения. Решения для согласования', sheet_no, total)
    d = D(msp, ox, oy)

    def P(X, Y):
        return (PX + X / K, PY + Y / K)

    def pl(pts, layer='ПТ_контур', lw=None, close=False, lt=None):
        d.pl([P(*q) for q in pts], layer, lw, close, lt)

    def ln(a, b, layer='ПТ_контур', lw=None, lt=None, color=None):
        d.l(*P(*a), *P(*b), layer, lw, lt, color)

    # ================================================================ СХЕМА РАЗМЕЩЕНИЯ
    d.title(PX + 49000 / K, 580, 'Схема размещения насосной станции в техническом подвале (отм. −2,200)', 3.5, '1:150')
    # контур здания по 1 этажу
    pl([(-125, -125), (98125, -125), (98125, 40125), (-125, 40125)], 'ПТ_контур', 18, True, 'ПТ_ШТРИХ')
    d.t(*P(60000, 40600), 'контур здания по 1 этажу', 1.8, 'BL')
    # оси
    for s, X in AX_X.items():
        ln((X, -1700), (X, 41200), 'ПТ_оси', 13, 'ПТ_ШТРИХПУНКТ')
        cx, cy = P(X, -1700)
        d.c(cx, cy - 3.5, 3.5, 'ПТ_контур', 25); d.t(cx, cy - 3.5, s, 2.5 if len(s) == 1 else 2.2, 'MC')
    for s, Y in AX_Y.items():
        ln((-1200, Y), (99800, Y), 'ПТ_оси', 13, 'ПТ_ШТРИХПУНКТ')
        cx, cy = P(99800, Y)
        d.c(cx + 3.5, cy, 3.5, 'ПТ_контур', 25); d.t(cx + 3.5, cy, s, 2.5, 'MC')
    # стены коридоров — заливкой, внутренний контур — основной линией
    for inner, outer in ((CORR1, CORR1_O), (CORR2, CORR2_O)):
        h = msp.add_hatch(color=8, dxfattribs={'layer': 'ПТ_штриховка'})
        h.paths.add_polyline_path([d.P(*P(*q)) for q in outer], is_closed=True, flags=const.BOUNDARY_PATH_EXTERNAL)
        h.paths.add_polyline_path([d.P(*P(*q)) for q in inner], is_closed=True, flags=const.BOUNDARY_PATH_OUTERMOST)
        h.set_solid_fill(color=8)
        pl(inner, 'ПТ_контур', 35, True); pl(outer, 'ПТ_контур', 35, True)
    d.t(*P(66000, 26300), 'Технический коридор 1', 2.5, 'BC')
    d.t(*P(66000, 15500), 'Технический коридор 2', 2.5, 'BC')
    # лестницы в осях 9–10
    for x0, y0, x1, y1, up, room in STAIRS:
        pl([(x0, y0), (x1, y0), (x1, y1), (x0, y1)], 'ПТ_контур', 25, True)
        for i in range(1, 10):
            yy = y0 + (y1 - y0) * i / 10
            ln((x0, yy), (x1, yy), 'ПТ_контур', 13)
        xm = (x0 + x1) / 2
        ya, yb = (y0 + 200, y1 - 300) if up > 0 else (y1 - 200, y0 + 300)
        ln((xm, ya), (xm, yb), 'ПТ_контур', 18)
        d.b('ARROW', *P(xm, yb), 0.8, rot=90 if up > 0 else 270, layer='ПТ_текст')
        ty = (35900, 35100) if up > 0 else (5000, 4200)
        d.t(*P(47700, ty[0]), 'Лестница — выход', 2.2, 'BL' if up > 0 else 'TL')
        d.t(*P(47700, ty[1]), f'в тамбур-шлюз {room} (1 этаж)', 2.2, 'TL')
    # насосная: выгородка, перегородка с дверью
    rx0, ry0, rx1, ry1 = ROOM
    d.hatch([P(rx0, ry0), P(rx1, ry0), P(rx1, ry1), P(rx0, ry1)], 'ANSI31', 0.6, color=1)
    pl([(rx0, ry0), (rx1, ry0), (rx1, ry1), (rx0, ry1)], 'ПТ_контур', 70, True)
    for ya, yb in ((ry0, DOOR[0]), (DOOR[1], ry1)):
        pl([(rx1, ya), (XP, ya), (XP, yb), (rx1, yb)], 'ПТ_контур', 50, True)
    ln((XP, DOOR[0]), (XP + 1000, DOOR[0]), 'ПТ_контур', 25)
    msp.add_arc(d.P(*P(XP, DOOR[0])), 1000 / K, 0, 90, dxfattribs={'layer': 'ПТ_контур'})
    d.l(*P(4300, 27400), *P(4300, 31000), 'ПТ_выноски')
    d.l(*P(4300, 31000), *P(4300 + 50 * K, 31000), 'ПТ_выноски')
    d.t(*P(4500, 32000), 'Насосная станция пожаротушения', 2.5, 'BL', style='ПТ_загл')
    d.t(*P(4500, 31300), f'8,0×5,4 м, {n((rx1 - rx0) * (ry1 - ry0) / 1e6)} м², лист 10', 2.2, 'BL')
    # вводы
    for Y in Y_IN:
        ln((-7000, Y), (1300, Y), 'ПТ_ввод', 60)
        d.b('ARROW', *P(1300, Y), 0.8, layer='ПТ_ввод')
    d.t(*P(-7300, 28700), 'Вводы 2×Ду150', 2.2, 'BR')
    d.t(*P(-7300, 27800), 'от точки 23.1 (НВК),', 2.2, 'BR')
    d.t(*P(-7300, 26900), 'отм. −1,900', 2.2, 'BR')
    # кольцевая сеть ВПВ, подводки, шкафы ПК подвала, стояки на этажи
    for p in M['pipes']:
        if p['sys'] == 'В2' and max(p['a'][2], p['b'][2]) <= 0.01:
            a, b = p['a'], p['b']
            if abs(a[0] - b[0]) + abs(a[1] - b[1]) > 1:
                ln(a[:2], b[:2], 'ПТ_В2', 35)
    ln((LV['X_HDR'], LV['Y_HDR']), (LV['X_VPV_TAP'], LV['Y_HDR']), 'ПТ_В2', 35)
    for k in M['pk']:
        if k['floor'] == 0:
            d.b('PK2', *P(k['x'], k['y']), 0.5, rot={'S': 0, 'N': 180}[k['face']], layer='ПТ_ПК')
        elif k['ry'] is not None:
            d.b('RISER', *P(k['rx'], k['ry']), 0.55, layer='ПТ_В2')
    for sec, (sx, sy, sz) in M['src'].items():
        d.b('RISER', *P(sx, sy), 0.7, layer='ПТ_В21' if sec == '1' else 'ПТ_В22')
    d.l(*P(2600, 22900), *P(2600, 19400), 'ПТ_выноски')
    d.l(*P(2600, 19400), *P(2600 + 70 * K, 19400), 'ПТ_выноски')
    d.t(*P(2800, 20700), 'Ст.В21-1, Ст.В22-1, перемычка В2, линия к ГМ-80 —', 2.2, 'BL')
    d.t(*P(2800, 19700), 'вверх в пом. 05 (КУИ) 1 этажа', 2.2, 'BL')
    d.t(*P(30000, 23050), 'Кольцо ВПВ Ду100, ▽−0,450', 2.2, 'BL')
    # путь до лестницы — вариант А
    route = [(XP + 400, 26800), (XP + 400, 25000), (46850, 25000), (46850, 28300)]
    for a, b in zip(route, route[1:]):
        ln(a, b, 'ПТ_контур', 35, 'ПТ_ШТРИХ', color=1)
    d.b('ARROW', *P(46850, 28400), 1.0, rot=90, layer='ПТ_контур')
    d.t(*P(14000, 25300), 'А — путь от насосной до лестницы ≈ 40 м', 2.2, 'BL')
    # вариант Б — отдельный выход наружу через приямок у оси 1 (условно)
    pl([(PIT_B[0], PIT_B[1]), (PIT_B[2], PIT_B[1]), (PIT_B[2], PIT_B[3]), (PIT_B[0], PIT_B[3])], 'ПТ_контур', 35, True, 'ПТ_ШТРИХ')
    ln((PIT_B[2], 24000), (300, 24000), 'ПТ_контур', 35, 'ПТ_ШТРИХ')
    cx, cy = P(-5200, 22600)
    d.l(*P(PIT_B[0], 23200), cx + 2.6, cy, 'ПТ_выноски')
    d.c(cx, cy, 2.6, 'ПТ_контур', 25); d.t(cx, cy, 'Б', 2.5, 'MC')
    d.t(cx - 3.5, cy - 4.5, 'выход наружу', 1.8, 'TR'); d.t(cx - 3.5, cy - 7.3, '(приямок, условно)', 1.8, 'TR')

    # ================================================================ ОСНОВНЫЕ ДАННЫЕ
    J, DR = PM['jockey'], PM['drain']
    P_inst = 2 * PM['N'] + J['N'] + 2 * DR['N'] + 0.2
    P_calc = PM['N'] + J['N'] + DR['N'] + 0.2
    rows = [
        ['Расчётный расход: АУПТ + ВПВ', f"{n(C['Q_aup'])} + {n(C['Q_vpv'])} = {n(C['Q_pump'])} л/с ({round(C['Q_pump'] * 3.6)} м³/ч)"],
        ['Выделено по ТУ от 08.10.2026, точка 23.1', f"{n(C['Q_tu'])} л/с, {n(C['H_guar'] / 100, 2)} МПа"],
        ['Требуемый напор на выходе насосной', f"{n(C['H_out'])} м"],
        ['Напор на выходе при нулевой подаче', f"{n(C['P_shut'])} м (при {n(C['H_guar'] / 100, 2)} МПа на вводе)"],
        ['Насосы Н1, Н2 (1 раб. + 1 рез.), in-line', f"{PM['Q_m3h']} м³/ч, {PM['H']} м, {kw(PM['N'])} кВт"],
        ['Жокей-насос Н3, бак мембранный 100 л', f"{kw(J['Q_m3h'])} м³/ч, {J['H']} м, {kw(J['N'])} кВт"],
        ['Дренажные насосы ДН1, ДН2 в приямке', f"{DR['Q_m3h']} м³/ч, {DR['H']} м, {kw(DR['N'])} кВт"],
        ['Узлы управления Ду150', 'УУ-1 — В21 (1 этаж), УУ-2 — В22 (2 этаж)'],
        ['Помещение, оси 1–3/Д–Е', f"8,0×5,4 м, {n((rx1 - rx0) * (ry1 - ry0) / 1e6)} м²"],
        ['Пол / низ перекрытия / низ балок 20К2', '−2,200 / −0,218 / −0,248'],
        ['Высота в свету: до перекрытия / под балками', '1,98 / 1,95 м'],
        ['Электроснабжение', 'I категория надёжности'],
        ['Мощность установленная / расчётная', f"{kw(round(P_inst, 2))} / {kw(round(P_calc, 1))} кВт"],
    ]
    d.t(615, 268, 'Основные данные', 3.5, 'BL', style='ПТ_загл')
    yb = d.table(615, 264, [('Параметр', 104), ('Значение', 108)], rows, h=2.5, row_h=6.2, header_h=7)
    # условные обозначения
    y = yb - 9
    d.t(615, y, 'Условные обозначения', 3.5, 'BL', style='ПТ_загл')
    y -= 7
    leg = [('wall', 'Стены технического подвала (монолит)'), ('room', 'Насосная станция — новая выгородка'),
           ('in', 'Вводы 2×Ду150 от точки 23.1 (раздел НВК)'), ('ring', 'Сеть ВПВ В2 в подвале, шкафы ПК'),
           ('riser', 'Стояки: ВПВ — на этажи, АУПТ — из насосной'), ('route', 'А — путь до лестницы по коридору 1'),
           ('pit', 'Б — отдельный выход наружу (вариант)'), ('bld', 'Контур здания по 1 этажу')]
    for kind, s in leg:
        x0, x1, ym = 617, 637, y + 1.2
        if kind == 'wall':
            hh = msp.add_hatch(color=8, dxfattribs={'layer': 'ПТ_штриховка'})
            hh.paths.add_polyline_path([d.P(x0, ym - 1.5), d.P(x1, ym - 1.5), d.P(x1, ym + 1.5), d.P(x0, ym + 1.5)], is_closed=True)
            hh.set_solid_fill(color=8)
        elif kind == 'room':
            d.hatch([(x0, ym - 2), (x1, ym - 2), (x1, ym + 2), (x0, ym + 2)], 'ANSI31', 0.6, color=1)
            d.r(x0, ym - 2, x1, ym + 2, 'ПТ_контур', 70)
        elif kind == 'in':
            d.l(x0, ym, x1, ym, 'ПТ_ввод', 60)
        elif kind == 'ring':
            d.l(x0, ym, x1 - 6, ym, 'ПТ_В2', 35); d.b('PK2', x1 - 3, ym, 0.5, layer='ПТ_ПК')
        elif kind == 'riser':
            d.b('RISER', x0 + 5, ym, 0.55, layer='ПТ_В2'); d.b('RISER', x0 + 14, ym, 0.7, layer='ПТ_В21')
        elif kind == 'route':
            d.l(x0, ym, x1, ym, 'ПТ_контур', 35, 'ПТ_ШТРИХ', color=1)
        elif kind == 'pit':
            d.r(x0 + 4, ym - 2, x1 - 4, ym + 2, 'ПТ_контур', 35, 'ПТ_ШТРИХ')
        elif kind == 'bld':
            d.l(x0, ym, x1, ym, 'ПТ_контур', 18, 'ПТ_ШТРИХ')
        d.t(642, ym, s, 2.5, 'ML')
        y -= 6.2

    # ================================================================ ВОПРОСЫ НА СОГЛАСОВАНИЕ
    q = [
        ['1', 'Место насосной',
         'Западный конец технического коридора 1, оси 1–3/Д–Е, у места ввода водопровода; рядом пом. 05 1 этажа, через которое '
         'проходят стояки. Конец коридора отделяется противопожарной перегородкой 1-го типа с дверью EI 30. Если в этой части '
         'коридора проходят сети других разделов, их надо вывести за перегородку.',
         'АР, все'],
        ['2', 'Выход из насосной',
         'Из насосной в подвале нужен выход наружу или на лестничную клетку с выходом наружу. Ближайшая лестница — в осях 9–10, '
         'выход в тамбур-шлюз 94; от двери насосной до неё по коридору 1 около 40 м.\n'
         'А — выход в коридор 1 оставить, если раздел ПБ это обоснует.\n'
         'Б — отдельный выход наружу через стену по оси 1: проём в монолитной стене и приямок с лестницей снаружи.',
         'АР, КР, ПБ, ГП'],
        ['3', 'Вводы и ТУ',
         f"Два ввода Ду150 через стену по оси 1 на отм. −1,900 от точки 23.1. Расход {n(C['Q_pump'])} л/с больше выделенных "
         f"{n(C['Q_tu'])} л/с на {n(C['over_tu'])} л/с — по п. 4.1 ТУ нужна корректировка ТУ. Нужно максимальное давление в точке 23.1 "
         '(п. 4.5 ТУ): по нему проверяется давление у пожарных кранов. Привязку, материал вводов и узел прохода через стену даёт НВК.',
         'НВК, заказчик'],
        ['4', 'Стояки на этажи',
         'Ст.В21-1, Ст.В22-1, перемычка кольца ВПВ и линия к патрубкам ГМ-80 поднимаются из насосной в пом. 05 (КУИ); затворы '
         'после узлов управления — в пом. 05 на отм. +1,000, пом. 05 защищается оросителями. Отверстия в перекрытии — по заданию.',
         'АР, КР'],
        ['5', 'Высота и монтаж',
         'В свету 1,98 м, под балками 20К2 — 1,95 м. Насосы вертикальные in-line на основаниях 150 мм, высота агрегата с основанием '
         f"около 1,45 м. Оборудование заносится по коридору 1 от лестницы в осях 9–10; масса насоса — около {PUMP_ROW['mass']} кг "
         f"(поз. {PUMP_ROW['pos']}, уточняется по выбранной марке). Если по лестнице не пронести, нужен монтажный проём в перекрытии "
         'над насосной.',
         'АР, КР'],
        ['6', 'Приямок и дренаж',
         'Приямок 1000×1000×800 у перегородки, пол с уклоном 0,01 к приямку, два погружных насоса. Выпуск Ду50 в сеть К2 через '
         'стену по оси 1 — решение НВК. Основания под насосы h=150 мм.',
         'КР, НВК'],
        ['7', 'Питание, климат, сигналы',
         f"I категория, два ввода от ППУ, расчётная мощность {kw(round(P_calc, 1))} кВт. Температура в насосной не ниже +5 °С, "
         'вентиляция. Сигналы насосной и аварийного уровня в приямке — на ППКУП «Сириус» в пом. 03 по RS-485. Телефон связи '
         'с пожарным постом.',
         'ЭМ, ОВ, ПБ43, СС'],
    ]
    d.t(30, 268, 'Вопросы на согласование', 3.5, 'BL', style='ПТ_загл')
    yq = d.table(30, 264, [('№', 9), ('Вопрос', 40), ('Предложение проекта', 341), ('Раздел', 33), ('Решение ГИП', 147)],
                 q, h=3.5, row_h=9, header_h=9, cw=0.68)
    # состав пакета и подпись
    y = yq - 10
    d.mt(30, y, 'Состав пакета: настоящий лист; лист 3 «Схема принципиальная систем В2, В21, В22»; лист 10 «Насосная станция '
               'пожаротушения. План, разрезы 1-1, 2-2» — из комплекта ОПР-01/24/2024-ДП1-ПТ. Отметки по КР и КМ стадии Р, '
               'расход и напор — по ТУ от 08.10.2026 и гидравлическому расчёту (ПТ.РР).', 2.5, 565)
    y -= 18
    d.t(30, y, 'Согласовано: ГИП  _______________________  /  _______________________  /    «____» ______________ 2026 г.', 3.5, 'BL')
    return yq
