def bb(poly):
    xs=[p[0] for p in poly]; ys=[p[1] for p in poly]
    return [min(xs),min(ys),max(xs),max(ys)]

def pip(x,y,poly):
    c=False; n=len(poly)
    for i in range(n):
        x1,y1=poly[i]; x2,y2=poly[(i+1)%n]
        if (y1>y)!=(y2>y) and x < (x2-x1)*(y-y1)/(y2-y1)+x1: c=not c
    return c

