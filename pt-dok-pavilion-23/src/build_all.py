def build():
    t0 = time.time()
    doc = make_doc(); setup_dimstyle(doc); msp = doc.modelspace()
    for no, name, fmt, k in SHEETS:
        ox, oy = origin(no, fmt, k)
        if no == 1:
            sh_general.general1(msp, ox, oy, no, TOTAL, [(s[0], s[1], s[2]) for s in SHEETS])
        elif no == 2:
            sh_general.general2(msp, ox, oy, no, TOTAL)
        elif no == 3:
            sh_scheme.scheme_sheet(msp, ox, oy, no, TOTAL)
        elif no in (4, 5, 6):
            fl = {4: 0, 5: 1, 6: 2}[no]
            leg = {0: LEG_B, 1: LEG_F1, 2: LEG_F2}[fl]
            notes = {0: NOTES_B, 1: NOTES_F1, 2: NOTES_F2}[fl]
            head = {0: 'План технического подвала на отм. −2,200', 1: 'План 1 этажа на отм. 0,000', 2: 'План 2 этажа на отм. +3,700'}[fl]
            S = plan_sheet(doc, msp, ox, oy, fl, no, TOTAL, name, notes, leg, head=head)
            {0: extras_basement, 1: extras_f1, 2: extras_f2}[fl](msp, S)
        elif no == 7:
            iso_sheet(doc, msp, ox, oy, 'A0', 100, lambda p: p['sec'] == 1, name, 'Схема системы В21 (секция 1)', no, TOTAL,
                      ['Отметки даны по осям трубопроводов. Розетки оросителей — на отм. +3,250, распределительные трубопроводы — +3,360.',
                       'Диаметры распределительных трубопроводов указаны у участков. Оросители СВО0-РНо0,42 — розеткой вниз.',
                       'План — лист 5. Диктующая площадь — тамбур 35, гидравлический расчёт — ПТ.РР.'],
                      place=(30, 300), elev_pts=[(2000, 23000, -0.6, '−0,600 выход УУ-1'), (12000, 24600, 2.9, '+2,900'), (60000, 15400, 2.9, '+2,900')])
        elif no == 8:
            iso_sheet(doc, msp, ox, oy, 'A0', 100, lambda p: p['sec'] == 2, name, 'Схема системы В22 (секция 2)', no, TOTAL,
                      [f'Отметки даны по осям трубопроводов. Распределительные трубопроводы — параллельно скату покрытия, на отм. от {Z2_LO} до {Z2_HI}.',
                       'Оросители СВО0-РВо0,42 — розеткой вверх.',
                       'План — лист 6. Диктующая площадь — кладовая 27, гидравлический расчёт — ПТ.РР.'],
                      place=(30, 260), elev_pts=[(3200, 23000, -0.6, '−0,600 выход УУ-2'), (12000, 27500, 6.85, '+6,850'), (60000, 12500, 6.85, '+6,850')])
        elif no == 9:
            iso_sheet(doc, msp, ox, oy, 'A0', 100, lambda p: p['sys'] == 'В2', name, 'Схема системы В2', no, TOTAL,
                      ['Схема выполнена без соблюдения масштаба по вертикали.',
                       'Кольцевая сеть — Ду100 на отм. -0,450, стояки и подводки к шкафам — Ду80, клапаны ПК — Ду65 (узел 7).',
                       'Клапаны ПК: подвал — отм. -0,850, 1 этаж — +1,350, 2 этаж — +5,050. ' + sh_details.DIA_TEXT,
                       'Планы — листы 4-6.'],
                      place=(30, 280), zs=3.0, pk_marks=True,
                      elev_pts=[(12000, M['levels']['Y_RING1'], -0.45, '−0,450'), (60000, M['levels']['Y_RING2'], -0.45, '−0,450')])
        elif no == 10:
            sh_pump.pump_room_sheet(msp, ox, oy, no, TOTAL)
        elif no == 11:
            sh_details.details1(msp, ox, oy, no, TOTAL)
        elif no == 12:
            sh_details.details2(msp, ox, oy, no, TOTAL)
        elif no == 13:
            sh_auto.powder_sheet(msp, ox, oy, no, TOTAL)
        elif no == 14:
            sh_auto.automation_sheet(msp, ox, oy, no, TOTAL)
        elif no == 15:
            sh_auto.electric_sheet(msp, ox, oy, no, TOTAL)
        print(f'лист {no} готов', round(time.time() - t0, 1), flush=True)
    dxf_path = os.path.join(OUT, f'{SHIFR.replace("/", "_")}.dxf')
    clean_dxf(doc)
    doc.saveas(dxf_path)
    print('DXF', dxf_path, round(time.time() - t0, 1), flush=True)
    if '--nopdf' in sys.argv:
        return
    only = [int(a) for a in sys.argv[1:] if a.isdigit()]
    pdfs = []
    for no, name, fmt, k in SHEETS:
        p = os.path.join(OUT, f'pdf_{no:02d}.pdf')
        if not only or no in only:
            ox, oy = origin(no, fmt, k)
            sheet_pdf(doc, ox, oy, fmt, k, p)
            print('PDF', no, round(time.time() - t0, 1), flush=True)
        pdfs.append(p)
    album = fitz.open()
    for p in pdfs:
        if os.path.exists(p):
            album.insert_pdf(fitz.open(p))
    album_path = os.path.join(OUT, f'{SHIFR.replace("/", "_")}_графическая_часть.pdf')
    album.save(album_path)
    clean_pdf(album_path, f'{SHIFR}. Графическая часть')
    print('альбом готов', round(time.time() - t0, 1))

if __name__ == '__main__':
    build()
