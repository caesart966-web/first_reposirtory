def extras_basement(msp, S):
    for y, n in ((27425, 1), (26625, 2)):
        msp.add_line(S.p(-4700, y), S.p(275, y), dxfattribs={'layer': 'ПТ_ввод', 'color': 5, 'lineweight': 60})
        ins(msp, 'RISER', *S.p(275, y), KP, layer='ПТ_ввод')
        txt(msp, *S.p(-3300, y + 150), f'Ввод {n} Ду150 от В2-7, ▽−1,900', 1.8, KP)
    for x in (7000, 28000, 49000, 70000, 91000):
        for y in (25200, 14800):
            ins(msp, 'V_BFLY', *S.p(x, y), KP, layer='ПТ_арматура')
    txt(msp, *S.p(1500, 24000), 'подъём в пом. 05 (А)', 1.8, KP)
    txt(msp, *S.p(4900, 15200), 'Б — из пом. 05', 1.8, KP)

