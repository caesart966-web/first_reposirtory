def extras_basement(msp, S):
    LV = M['levels']
    # насосная: перегородка с дверью, приямок, вводы
    for ya, yb in ((22300, 26300), (27300, 27700)):
        msp.add_lwpolyline([S.p(8300, ya), S.p(8420, ya), S.p(8420, yb), S.p(8300, yb)], close=True, dxfattribs={'layer': 'ПТ_контур', 'lineweight': 50})
    msp.add_arc(S.p(8420, 26300), 1000, 0, 90, dxfattribs={'layer': 'ПТ_контур'})
    msp.add_lwpolyline([S.p(7100, 22500), S.p(8100, 22500), S.p(8100, 23500), S.p(7100, 23500)], close=True, dxfattribs={'layer': 'ПТ_контур', 'lineweight': 35})
    mtxt(msp, *S.p(4300, 27300), 'Насосная станция\\Pпожаротушения\\P(лист 10)', 2.2, 40, KP, attach=1)
    txt(msp, *S.p(7600, 23700), 'приямок', 1.6, KP, align='BC')
    for (x, s) in ((LV['X_SRC'], 'УУ-1'), (LV['X_SRC2'], 'УУ-2')):
        msp.add_circle(S.p(x, LV['Y_SRC']), 280, dxfattribs={'layer': 'ПТ_оборудование'})
        txt(msp, *S.p(x, LV['Y_SRC'] + 400), s, 1.6, KP, align='BC')
    for y, n in ((27200, 1), (26400, 2)):
        msp.add_line(S.p(-4700, y), S.p(1300, y), dxfattribs={'layer': 'ПТ_ввод', 'color': 5, 'lineweight': 60})
        txt(msp, *S.p(-4600, y + 150), f'Ввод {n} Ду150 от ввода 23.1, ▽−1,900', 1.8, KP)
    for x in (7000, 28000, 49000, 70000, 91000):
        for y in (LV['Y_RING1'], LV['Y_RING2']):
            ins(msp, 'V_BFLY', *S.p(x, y), KP, layer='ПТ_арматура')
    txt(msp, *S.p(LV['X_R0'] - 200, LV['Y_RING1'] - 400), 'В2 в пом. 05', 1.8, KP, align='TR')
    txt(msp, *S.p(4900, LV['Y_RING2'] + 250), 'В2 из пом. 05', 1.8, KP)

