def sprinkler(d, x, y, sc, up=False):
    """ороситель (вид сбоку): штуцер, дужки, розетка; (x,y) — точка присоединения к бобышке"""
    s = -1 if not up else 1
    d.r(x - 3 * sc, y, x + 3 * sc, y + s * 6 * sc, 'ПТ_оборудование', 35)            # штуцер R1/2
    d.pl([(x - 4 * sc, y + s * 6 * sc), (x - 3 * sc, y + s * 16 * sc), (x + 3 * sc, y + s * 16 * sc), (x + 4 * sc, y + s * 6 * sc)], 'ПТ_оборудование', 35)
    d.c(x, y + s * 10 * sc, 1.6 * sc, 'ПТ_оборудование', 25)                          # колба
    d.l(x - 8 * sc, y + s * 17 * sc, x + 8 * sc, y + s * 17 * sc, 'ПТ_оборудование', 50)  # розетка
    return y + s * 17 * sc

