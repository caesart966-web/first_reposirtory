def volumes():
    """объёмы воды в системах по модели и в обвязке насосной (длины — как в спецификации), м³"""
    V = {}
    for p in M['pipes']:
        dn = p.get('dn')
        if not dn:
            continue
        L = math.dist(p['a'][:2], p['b'][:2]) / 1000 + abs(p['a'][2] - p['b'][2])
        V[p['sys']] = V.get(p['sys'], 0) + math.pi / 4 * (PIPES[dn][1] / 1000) ** 2 * L
    ns = sum(math.pi / 4 * (d / 1000) ** 2 * L for d, L in ((207, 8), (150, 24), (125, 3), (100, 14), (53, 12), (41, 4), (35.9, 5)))
    return {k: round(v, 1) for k, v in V.items()}, round(ns, 1)


