def _letter_head(doc, to_lines, subject):
    par_tbl = doc.add_table(rows=1, cols=2)
    par_tbl.autofit = False
    from docx.shared import Cm, Pt
    left, right = par_tbl.rows[0].cells
    left.width, right.width = Cm(9.0), Cm(9.0)
    left.text = ""
    lp = left.paragraphs[0]
    lp.paragraph_format.space_after = Pt(0)
    r = lp.add_run("Исх. № __________ от «____» __________ 20____ г.\n"
                   "На № __________ от «____» __________ 20____ г.")
    r.font.size = Pt(10)
    r.font.name = "Times New Roman"
    right.text = ""
    rp = right.paragraphs[0]
    rp.paragraph_format.space_after = Pt(0)
    rr = rp.add_run("\n".join(to_lines))
    rr.font.size = Pt(10)
    rr.font.name = "Times New Roman"
    p(doc, "", after=10)
    p(doc, subject, size=11, bold=True, align="l", after=8)


