def save(doc, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    doc.save(path)
    return path


def safe(name):
    bad = '\\/:*?"<>|\n'
    out = "".join("-" if ch in bad else ch for ch in name)
    return out.strip()[:110]


