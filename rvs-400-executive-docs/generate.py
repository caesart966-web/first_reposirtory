    build_certificates_xlsx(xlsx)
    made.append(xlsx)

    # --- организационные документы и письма ---
    from orgdocs import ORG_BUILDERS
    odir = os.path.join(outdir, "05 Приказы и письма")
    for code, name, builder, land in ORG_BUILDERS:
        d = new_doc(landscape=land)
        builder(d)
        made.append(save(d, os.path.join(odir, f"{code} {safe(name)}.docx")))

    # --- журналы ---
    jdir = os.path.join(outdir, "04 Журналы")
    for code, name in JOURNALS:
        land = code != "J01"
        d = new_doc(landscape=True) if land else new_doc(landscape=True)
        JOURNAL_BUILDERS[code](d)
        made.append(save(d, os.path.join(jdir, f"{code} {safe(name)}.docx")))

    # --- по каждому резервуару ---
    for tank_no in (1, 2):
        base = os.path.join(outdir, f"0{tank_no} РВС-400 №{tank_no}")

        sub = os.path.join(base, "1 Приёмка и входной контроль")
        for code, name in OTHER_ACTS:
            if not code.startswith("A"):
                continue
            d = new_doc()
            OTHER_BUILDERS[code](d, tank_no)
            made.append(save(d, os.path.join(sub, f"{code} {safe(name)} (РВС №{tank_no}).docx")))

        sub = os.path.join(base, "2 Акты освидетельствования скрытых работ")
        for i, act in enumerate(AOSR, start=1):
            d = new_doc()
            build_aosr(d, tank_no, act, i)
            made.append(save(d, os.path.join(
                sub, f'АОСР {act["code"]} {safe(act["name"])} (РВС №{tank_no}).docx')))

        sub = os.path.join(base, "3 Контроль качества")
        for code, name in OTHER_ACTS:
            if not code.startswith("B"):
                continue
            d = new_doc(landscape=True)
            OTHER_BUILDERS[code](d, tank_no)
            made.append(save(d, os.path.join(sub, f"{code} {safe(name)} (РВС №{tank_no}).docx")))

        sub = os.path.join(base, "4 Испытания")
        for code, name in OTHER_ACTS:
            if not code.startswith("C"):
                continue
            land = code in ("C05",)
            d = new_doc(landscape=True) if land else new_doc()
            OTHER_BUILDERS[code](d, tank_no)
            made.append(save(d, os.path.join(sub, f"{code} {safe(name)} (РВС №{tank_no}).docx")))

        sub = os.path.join(base, "5 Приёмка резервуара")
        for code, name in OTHER_ACTS:
            if not code.startswith("D"):
                continue
            d = new_doc()
            OTHER_BUILDERS[code](d, tank_no)
            made.append(save(d, os.path.join(sub, f"{code} {safe(name)} (РВС №{tank_no}).docx")))

        # --- сводный файл для печати ---
        # Широкие формы (контроль качества, замеры) печатаются альбомно,
        # поэтому комплект собирается разделами с разной ориентацией.
        LANDSCAPE_CODES = {"B01", "B02", "B03", "B04", "B05", "B06", "C05"}
        d = new_doc()
        first = True
        current_landscape = False
        seq = ([(c, "other") for c, _n in OTHER_ACTS if c.startswith("A")]
               + [(a["code"], "aosr") for a in AOSR]
               + [(c, "other") for c, _n in OTHER_ACTS if c[0] in "BCD"])
        aosr_by_code = {a["code"]: a for a in AOSR}
        for code, kind in seq:
            want_landscape = code in LANDSCAPE_CODES
            if first:
                if want_landscape:
                    # первый раздел уже существует — просто разворачиваем его
                    s0 = d.sections[0]
                    s0.orientation = WD_ORIENT.LANDSCAPE
                    s0.page_width, s0.page_height = Cm(29.7), Cm(21.0)
                    current_landscape = True
                first = False
            elif want_landscape != current_landscape:
                new_section(d, landscape=want_landscape)
                current_landscape = want_landscape
            else:
                page_break(d)
            if kind == "aosr":
                build_aosr(d, tank_no, aosr_by_code[code], 0)
            else:
                OTHER_BUILDERS[code](d, tank_no)
        made.append(save(d, os.path.join(
            outdir, f"КОМПЛЕКТ АКТОВ РВС-400 №{tank_no} (для печати).docx")))

    print(f"Сформировано документов: {len(made)}")
    for m in sorted(made):
        print("  ", os.path.relpath(m, outdir))
    return made


