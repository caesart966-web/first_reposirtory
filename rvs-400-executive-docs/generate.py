def act_header(doc, act_title, number_label="№", small=False):
    """Шапка простого акта (не по форме Приказа № 344)."""
    title(doc, act_title, size=12 if not small else 11)
    p(doc, f"{number_label} ______________", size=11, align="c", after=2)
    p(doc, 'г. Рошаль, Московская область                    '
           '«_____» _______________ 20____ г.', size=10, align="c", after=8)


def object_block(doc, tank_no):
    rows = [
        ("Объект капитального строительства", PROJECT["object_name"]),
        ("Адрес объекта", PROJECT["address"]),
        ("Наименование сооружения", f"Резервуар стальной вертикальный цилиндрический "
                                    f"РВС-400 м³ № {tank_no}"),
        ("Застройщик (технический заказчик)", PROJECT["customer"]),
        ("Лицо, осуществляющее строительство", PROJECT["contractor"]),
        ("Основание для производства работ", PROJECT["contract"]),
        ("Рабочая документация", f'{PROJECT["km"]}; {PROJECT["kmd"]}'),
        ("Проект производства работ", PROJECT["ppr"]),
    ]
    table(doc, ["Наименование", "Значение"], rows, widths=[6.0, 12.0], size=9,
          first_col_align="l")
    p(doc, "", after=8)


def std_signatures(doc, extra=()):
    roles = [
        ("Представитель застройщика (технического заказчика):", None),
        ("Представитель лица, осуществляющего строительство:", None),
        ("Представитель лица, осуществляющего строительство, "
         "по вопросам строительного контроля:", None),
    ]
    roles.extend(extra)
    signature_block(doc, roles)


