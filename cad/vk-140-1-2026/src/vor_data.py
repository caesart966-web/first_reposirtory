SP = {r[1]: r for r in numbered() if r[0] == 'item'}
REDUCER = 10                     # поз. 10 — муфта переходная Ду 50×32 у водомерного узла (добавлена после остальных)


def N(p):
    """Номера ниже записаны по нумерации до вставки поз. 10; перевод в действующую."""
    return p + 1 if p >= REDUCER else p


def q(*pos):
    """Сумма количеств позиций спецификации (с одной единицей измерения)."""
    units = {SP[N(p)][6] for p in pos}
    assert len(units) == 1, (pos, units)
    v = sum(SP[N(p)][7] for p in pos)
    return int(v) if float(v).is_integer() else v


def pieces(*pos):
    """Канализационные трубы, заданные штуками по 1/2/3 м: [(L, шт.)]."""
    out = []
    for p in pos:
        name = SP[N(p)][2]
        L = 1 if 'L = 1000' in name else 2 if 'L = 2000' in name else 3
        out.append((L, SP[N(p)][7]))
    return out


def plen(*pos):
    return sum(L * n for L, n in pieces(*pos))


def pformula(*pos):
    return ' + '.join(f'{n}×{L}' for L, n in pieces(*pos)) + f' = {plen(*pos)}'


def rng(*pos):
    return 'поз. ' + ', '.join(str(N(p)) for p in pos)


