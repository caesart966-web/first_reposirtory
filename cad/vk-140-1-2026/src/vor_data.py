def S(n):
    R.append(('section', n))


def I(name, unit, qty, pos=(), sheets=(), note='', formula='', ref=None, extra=(), xref=''):
    R.append(dict(name=name, unit=unit, qty=qty, pos=tuple(N(p) for p in pos) + tuple(extra), sheets=tuple(sheets), note=note, formula=formula,
                  ref=ref if ref is not None else (rng(*pos) if pos else '—'), xref=xref, sub=False))


def M(*posn, note=''):
    """Материалы (фасонные части) к строке работы выше — по строке на позицию СО, номер «п.k».
    Позиции — в действующей нумерации спецификации."""
    for p in posn:
        r = SP[p]
        name = r[2] + (f', {r[3]}' + (' или эквивалент' if r[8] == E else '') if r[3] else '')
        qty = int(r[7]) if float(r[7]).is_integer() else r[7]
        R.append(dict(name=name, unit=r[6], qty=qty, pos=(p,), sheets=(), note=note, formula='', ref=f'поз. {p}',
                      xref='', sub=True))


