    para(doc, 'к материалам архитектурно-градостроительного решения', size=12,
         align=WD_ALIGN_PARAGRAPH.CENTER, space_after=10)
    t = doc.add_table(rows=0, cols=2)
    for k, v in HEAD:
        c = t.add_row().cells
        para(c[0].paragraphs[0], k, bold=True)
        para(c[1].paragraphs[0], v)
    fix_widths(t, (Cm(6.0), Cm(19.7)))
    para(doc, '', space_after=6)

    tbl = doc.add_table(rows=1, cols=4)
    tbl.style = 'Table Grid'
    tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
    widths = (Cm(1.3), Cm(8.2), Cm(12.2), Cm(4.0))
    for cell, txt, w in zip(tbl.rows[0].cells, ('№', 'Замечание', 'Ответ', 'Где исправлено'), widths):
        cell.width = w
        para(cell.paragraphs[0], txt, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER)
        set_cell_bg(cell, 'E7E6E6')
    for r in ROWS:
        if r[0] == 'group':
            cells = tbl.add_row().cells
            m = cells[0].merge(cells[3])
            para(m.paragraphs[0], r[1], bold=True)
            set_cell_bg(m, 'F2F2F2')
            continue
        cells = tbl.add_row().cells
        for cell, txt, w in zip(cells, r, widths):
            cell.width = w
        para(cells[0].paragraphs[0], r[0], align=WD_ALIGN_PARAGRAPH.CENTER)
        para(cells[1].paragraphs[0], r[1], italic=True)
        first = True
        for chunk in r[2].split('\n'):
            p = cells[2].paragraphs[0] if first else cells[2].add_paragraph()
            para(p, chunk, space_after=3)
            first = False
        para(cells[3].paragraphs[0], r[3])
    fix_widths(tbl, widths)
    for row in tbl.rows:                      # строка таблицы не рвётся между страницами
        tp = row._tr.get_or_add_trPr()
        cs = OxmlElement('w:cantSplit')
        cs.set(qn('w:val'), 'true')
        tp.append(cs)
    # повтор шапки таблицы на каждой странице
    trPr = tbl.rows[0]._tr.get_or_add_trPr()
