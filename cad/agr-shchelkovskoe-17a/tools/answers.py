def set_cell_bg(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), hexcolor)
    tcPr.append(shd)


def para(cell_or_doc, text, size=11, bold=False, align=None, space_after=0, italic=False):
    p = cell_or_doc.add_paragraph() if hasattr(cell_or_doc, 'add_paragraph') else cell_or_doc
    for i, chunk in enumerate(text.split('\n')):
        if i:
            p = cell_or_doc.add_paragraph()
        r = p.add_run(chunk)
        r.font.name = FONT
        r._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)
        r.font.size = Pt(size)
        r.bold = bold
        r.italic = italic
        p.paragraph_format.space_after = Pt(space_after)
        p.paragraph_format.space_before = Pt(0)
        if align:
            p.alignment = align
    return p


def fix_widths(tbl, widths):
    """Ширины столбцов и в сетке таблицы (её читает LibreOffice), и в каждой ячейке (её читает Word)."""
    tbl.autofit = False
    grid = tbl._tbl.tblGrid
    for gc, w in zip(grid.findall(qn('w:gridCol')), widths):
        gc.set(qn('w:w'), str(int(w.twips)))
    for row in tbl.rows:
        for cell, w in zip(row.cells, widths):
            cell.width = w


def main(out):
    doc = Document()
    st = doc.styles['Normal']
    st.font.name = FONT
    st.element.rPr.rFonts.set(qn('w:eastAsia'), FONT)
    st.font.size = Pt(11)
    sec = doc.sections[0]
    sec.orientation = WD_ORIENT.LANDSCAPE
    sec.page_width, sec.page_height = Cm(29.7), Cm(21.0)
    for side in ('left_margin', 'right_margin'):
        setattr(sec, side, Cm(2.0))
    sec.top_margin, sec.bottom_margin = Cm(1.5), Cm(1.5)

