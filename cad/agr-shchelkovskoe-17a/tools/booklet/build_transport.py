    def natural(self, sl, name, x, y, w, h):
        """Картинка в натуральную величину (масштаб чертежа сохраняется) с рамкой."""
        sl.image(os.path.join(self.img, name), x, y, x + w, y + h, mode='contain', fmt='png')
        self.frame(sl, x, y, x + w, y + h)

    def table(self, sl, X, y, head, rows, size=8.5, hh=20, rh=15, align=None, bold_rows=()):
        align = align or ['l'] + ['c'] * (len(X) - 2)
        sl.rect(X[0], y, X[-1], y + hh, fill=PINK, line='#FFFFFF', lw=1.0)
        for i, t in enumerate(head):
            pad = 4 if align[i] == 'l' else 0
            sl.text(X[i] + pad, y, X[i + 1] - X[i] - pad - 2, t, size=size, bold=True, align=align[i], h=hh,
                    anchor='m', y_is_glyph_top=False, spacing=0.95)
        y += hh
        for j, r in enumerate(rows):
            h = rh * (2 if any(len(str(c)) > 46 * max(1.0, (X[i + 1] - X[i]) / 240) for i, c in enumerate(r)) else 1)
            for i, t in enumerate(r):
                sl.rect(X[i], y, X[i + 1], y + h, fill=PINK if j in bold_rows else CELL, line='#FFFFFF', lw=1.0)
                pad = 4 if align[i] == 'l' else 0
                sl.text(X[i] + pad, y, X[i + 1] - X[i] - pad - 2, str(t), size=size, bold=j in bold_rows,
                        align=align[i], h=h, anchor='m', y_is_glyph_top=False, spacing=0.95)
            y += h
        return y

    def legend(self, sl, x, y, items, w=30.0, size=9.0, step=20.0):
        for kind, a, b, t in items:
            if kind == 'line':
                sl.line(x, y + 6, x + w, y + 6, color=a, lw=b)
            elif kind == 'dash':
                sl.line(x, y + 6, x + w, y + 6, color=a, lw=b, dash=DASH.DASH)
            elif kind == 'dot':
                sl.line(x, y + 6, x + w, y + 6, color=a, lw=b, dash=DASH.ROUND_DOT)
            elif kind == 'box':
                sl.rect(x, y + 1, x + w, y + 11, fill=a, line=b, lw=0.6)
            elif kind == 'circle':
                sl.rect(x + w / 2 - 5, y + 1, x + w / 2 + 5, y + 11, fill=a, line=b, lw=0.6, shape=MSO_SHAPE.OVAL)
            elif kind == 'arrow':
                sl.line(x, y + 6, x + w - 6, y + 6, color=a, lw=b)
                sl.tri(x + w - 3, y + 6, 6, a, rot=90)
            sl.text(x + w + 10, y + 0.5, 1145.2 - x - w - 10, t, size=size, font=CG, h=step * 1.6, spacing=0.95)
            y += step * (1.6 if len(t) > 34 else 1.0)
        return y

