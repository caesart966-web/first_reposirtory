    @staticmethod
    def bar(sl, title, x0=45.0, x1=1145.2, y0=123.1, y1=147.3, size=14, extra=None):
        sl.rect(x0 + 3.4, y0, x1, y1, fill=GREY_BAR)
        sl.rect(x0, y0, x0 + 4.3, y1, fill=DARK)
        runs = [(title, {})]
        if extra:
            runs.append(('  ' + extra, {'bold': False}))
        sl.text(x0 + 10.6, y0 + (y1 - y0) / 2 - size * 0.5, x1 - x0 - 16, [runs], size=size, bold=True, color=DARK,
                h=size * 1.4)

    @staticmethod
    def frame(sl, x0, y0, x1, y1, lw=0.25, color=FRAME):
        sl.rect(x0, y0, x1, y1, line=color, lw=lw)

    @staticmethod
    def tag(sl, x, y, label, caption=None, w=16.8, h=19.4):
        sl.rect(x, y, x + w, y + h, fill=0.149)
        sl.text(x, y, w, label, size=10, bold=True, color=1.0, align='c', h=h, anchor='m', y_is_glyph_top=False)
        if caption:
            cw = len(caption) * 8 * 0.64 + 16
            sl.rect(x + w, y, x + w + cw, y + h, fill='#FFFFFF')
            sl.text(x + w + 6, y, cw - 8, caption, size=8, h=h, anchor='m', y_is_glyph_top=False)

    def pic(self, sl, name, x0, y0, x1, y1, mode='cover', focus=(0.5, 0.5), frame=True, src=None, **kw):
        path = os.path.join(src or self.img, name)
        r = sl.image(path, x0, y0, x1, y1, mode=mode, focus=focus, **kw)
        if frame:
            self.frame(sl, x0, y0, x1, y1)
        return r

