"""Задание на пересборку ЦИМ АР в Revit и выгрузку IFC + TRM (АГР-1, Щёлковское ш., 17А, стр. 1).

    python3 make_task_doc.py <ar_model.json> <Задание.docx>
"""
import json
import os
import sys

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
import clean_meta  # noqa: E402


def main(src, out):
    d = json.load(open(src, encoding='utf-8'))
    st = d['site']
    doc = Document()
    sty = doc.styles['Normal']
    sty.font.name = 'Calibri'
    sty.font.size = Pt(10.5)
    h = doc.add_heading('Пересборка ЦИМ АР в Revit и выгрузка IFC с TRM', level=1)
    h.alignment = WD_ALIGN_PARAGRAPH.LEFT
    doc.add_paragraph('Объект: реконструкция нежилого здания под магазин, г. Москва, Щёлковское шоссе, вл. 17А, '
                      'стр. 1 (АГР-1). Файл: НН_К01_С01_АР_АГР.')

    def h2(t):
        doc.add_heading(t, level=2)

    def ul(items):
        for x in items:
            doc.add_paragraph(x, style='List Bullet')

    def ol(items):
        for x in items:
            doc.add_paragraph(x, style='List Number')

    h2('Зачем')
    doc.add_paragraph(
        'Проверка заказчика пишет, что TRM с чертежами связан с другой версией IFC. Виды в TRM и IFC делает '
        'плагин «Якорь IFC» за одну выгрузку из Revit, а исходного файла Revit нет. Поэтому модель АР собирается '
        'в Revit заново по исправленному IFC (все правки 26.11.2026 уже в данных) и выгружается плагином. '
        'После выгрузки IFC не открывать и не править: любая правка снова разорвёт связь с TRM.')
    h2('Что нужно на компьютере')
    ul(['Revit 2026 (исходная модель выгружена из Revit 26.5).',
        'Плагин «Якорь IFC» с входом в учётную запись «СтроимПросто».',
        'pyRevit (бесплатный) — для запуска скрипта сборки.',
        'Папка C:\\АГР17А с файлами пакета (ниже).'])
    h2('Файлы пакета')
    t = doc.add_table(rows=1, cols=2)
    t.style = 'Light Grid Accent 1'
    t.rows[0].cells[0].text, t.rows[0].cells[1].text = 'Файл', 'Что это'
    for a, b in [('build_ar_pyrevit.py', 'скрипт сборки модели в открытом проекте Revit'),
                 ('ar_model.json', 'данные модели: координаты, уровни, оси, 121 элемент, 11 помещений, 2 зоны'),
                 ('RUS_shared_params.txt', 'общие параметры RUS_*, IfcExportAs, IfcExportType, IfcGUID'),
                 ('RusSets_mapping.txt', 'наборы свойств RusSet_* для экспорта IFC (если плагину нужен файл)'),
                 ('Параметры_АР_для_Revit.xlsx', 'все значения таблицами — для проверки глазами')]:
        r = t.add_row().cells
        r[0].text, r[1].text = a, b
    h2('Порядок работы')
    ol(['Создать новый проект Revit из архитектурного шаблона (единицы — мм). Сохранить как '
        'C:\\АГР17А\\НН_К01_С01_АР_АГР.rvt.',
        'Запустить build_ar_pyrevit.py (pyRevit: скрипт из папки; или RevitPythonShell). Скрипт работает одной '
        'транзакцией и пишет отчёт build_report.txt. Ошибки по отдельным элементам не останавливают сборку.',
        'Проверить по отчёту и глазами: 2 уровня, 15 осей, 121 элемент, 11 помещений, 2 зоны площадей, '
        'координаты («проверено по точке» в отчёте), план 1 этажа с марками помещений и лист АР-1.',
        'Если плагин требует свой файл общих параметров ДГП — подключить его; если имена параметров у плагина '
        'другие, значения переносятся тем же скриптом после замены имён.',
        'Выгрузка плагином «Якорь IFC»: IFC4, Reference View 1.2, база координат — общие координаты; имя файла '
        'НН_К01_С01_АР_АГР.ifc; в виды TRM — лист АР-1 «План 1 этажа» (в прежнем TRM был один лист — план 1 '
        'этажа с осями, размерами и площадями помещений).',
        'IFC и папку/архив TRM не открывать в других программах и не править. Передать оба файла на сверку.',
        'Сверка нового IFC с эталоном (compare_ifc.py: правила IFC4, положение каждого элемента в МСК-77, '
        'параметры, помещения, высоты, контуры) и сборка комплекта САГР с новыми IFC АР и TRM; ПС и БиО — '
        'прежние исправленные.',
        'Проверка ЦИМ в кабинете заказчика и новая ссылка на результат — Анастасия.'])
    h2('Ключевые значения')
    rows = [('Общие координаты точки (0,0,0) проекта', 'МСК-77: восток %.3f м, север %.3f м, отметка 0'
             % (st['east_mm'] / 1000, st['north_mm'] / 1000)),
            ('Поворот оси X проекта', '%.4f° против часовой стрелки от востока' % st['x_axis_angle_deg_ccw_from_east']),
            ('Широта / долгота', '%d°%d\'%d.%06d" с. ш., %d°%d\'%d.%06d" в. д.'
             % (tuple(st['ref_latitude']) + tuple(st['ref_longitude'])))]
    for l in d['levels']:
        rows.append(('Уровень ' + l['name'], 'абс. отметка %.3f' % (l['elevation_mm'] / 1000)))
    for s in d['spaces']:
        f = {k: v[1] for p in s['psets'].values() for k, v in p.items() if v is not None}
        rows.append(('Помещение %s' % s['name'] if s['kind'] == 'room' else 'Зона: %s' % f.get('RUS_Name'),
                     '%s — %s %s, %.2f м²' % (f.get('RUS_Name'), f.get('RUS_MSSK_SpaceAndZone_Code'),
                                              f.get('RUS_MSSK_SpaceAndZone_Name'), s['area_m2'])))
    t = doc.add_table(rows=0, cols=2)
    t.style = 'Light Grid Accent 1'
    for a, b in rows:
        r = t.add_row().cells
        r[0].text, r[1].text = a, b
    h2('Что уже исправлено в данных (повторять в Revit не нужно)')
    ul(['Координаты участка (не Бостон), имя уровня по требованиям ДГП (ч. 1, п. 6.7).',
        'Высоты стен и других элементов — по геометрии (было: в высоте длина).',
        'Нет повторных наборов свойств; окна и ограждения — на своих типах.',
        'Коды помещений МССК: торговый зал — ПЗ 14 «Зона обслуживания», пом. 11 — ПЗ 31 13 12 '
        '«Помещение инженерных коммуникаций», приёмка — ПЗ 31 13 07 «Подсобное помещение».',
        'Общая площадь 520,63 м² (4 контура), СПП в ГНС 492,54 м².'])
    h2('Если что-то пойдёт не так')
    ul(['Плагин не выгружает DirectShape или классы выходят не те — стены и перекрытия создать штатными '
        'элементами Revit по осям из таблицы (план Б, ещё 0,5–1 день).',
        '«Общая площадь» в Revit — 4 отдельные площади (одна площадь Revit не может состоять из несвязанных '
        'контуров); если проверка потребует одну — согласовать контур.',
        'Отчёт скрипта build_report.txt смотреть после каждого запуска: ошибки по элементам выводятся в нём.'])
    doc.core_properties.title = 'Задание: пересборка ЦИМ АР в Revit'
    doc.save(out)
    clean_meta.clean(out)
    print(out)


if __name__ == '__main__':
    main(*sys.argv[1:3])
