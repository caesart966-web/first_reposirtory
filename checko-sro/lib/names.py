"""Сокращение названий компаний до читаемого вида."""
import re

# Организационно-правовые формы: полное написание -> аббревиатура.
# Порядок важен: длинные формы проверяются раньше коротких,
# иначе «Закрытое акционерное общество» схлопнется по «акционерное общество».
LEGAL_FORMS = [
    ("общество с ограниченной ответственностью", "ООО"),
    ("публичное акционерное общество", "ПАО"),
    ("непубличное акционерное общество", "НАО"),
    ("закрытое акционерное общество", "ЗАО"),
    ("открытое акционерное общество", "ОАО"),
    ("акционерное общество", "АО"),
    ("автономная некоммерческая организация", "АНО"),
    ("государственное унитарное предприятие", "ГУП"),
    ("муниципальное унитарное предприятие", "МУП"),
    ("федеральное государственное унитарное предприятие", "ФГУП"),
    ("федеральное государственное бюджетное учреждение", "ФГБУ"),
    ("государственное бюджетное учреждение", "ГБУ"),
    ("муниципальное бюджетное учреждение", "МБУ"),
    ("индивидуальный предприниматель", "ИП"),
]

# Устойчивые обороты внутри названия. Сокращаем только однозначные:
# каждый из них общепринят и не путается с другим.
INNER_ABBR = [
    ("научно-производственное объединение", "НПО"),
    ("научно-производственное предприятие", "НПП"),
    ("научно-исследовательский институт", "НИИ"),
    ("научно-технический центр", "НТЦ"),
    ("проектно-конструкторское бюро", "ПКБ"),
    ("конструкторское бюро", "КБ"),
    ("управляющая компания", "УК"),
]


def _normalize_quotes(text):
    """Приводит "..." и “...” к «...» — в отчёте один стиль кавычек."""
    text = text.replace("“", "«").replace("”", "»")
    return re.sub(r'"([^"]*)"', "«\\1»", text)


def _strip_leading_form(name):
    """Отрезает ОПФ в начале названия. Возвращает (аббревиатура, остаток)."""
    lowered = name.lower()
    # Сортировка по убыванию длины: самая подробная форма выигрывает.
    for full, abbr in sorted(LEGAL_FORMS, key=lambda p: -len(p[0])):
        if lowered.startswith(full):
            return abbr, name[len(full):].strip()
    return None, name


def shorten_name(name):
    """«Акционерное общество "Абсолют"» -> «АО «Абсолют»».

    ИП сохраняет полное ФИО: «ИП Афонин Денис Витальевич».
    Название без известной ОПФ (Ассоциация, Союз, Фонд) остаётся как есть.
    """
    if not name:
        return name

    result = _normalize_quotes(" ".join(str(name).split()))
    abbr, rest = _strip_leading_form(result)

    if abbr:
        # Форма могла повториться внутри: «АО «Акционерное общество ...»» не нужно.
        inner_abbr, inner_rest = _strip_leading_form(rest)
        if inner_abbr == abbr:
            rest = inner_rest
        result = f"{abbr} {rest}".strip() if rest else abbr

    for full, short in INNER_ABBR:
        result = re.sub(re.escape(full), short, result, flags=re.IGNORECASE)

    return result


def director_from_ip_name(name):
    """ФИО предпринимателя из названия — в ЕГРИП руководитель и есть сам ИП.

    Экономит запрос к API: ФИО уже лежит в наименовании из реестра НОСТРОЙ.
    """
    if not name:
        return None
    match = re.match(
        r"^\s*(?:индивидуальный предприниматель|ИП)\s+(.+?)\s*$", str(name), re.IGNORECASE
    )
    if not match:
        return None
    fio = " ".join(match.group(1).split())
    # Настоящее ФИО — 2–3 слова кириллицей. Иначе это не ИП-физлицо.
    parts = fio.split()
    if 2 <= len(parts) <= 3 and all(re.fullmatch(r"[А-Яа-яЁё\-]+", p) for p in parts):
        return fio
    return None
