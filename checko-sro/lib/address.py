"""Выбор одного — юридического — адреса из списка, приехавшего из Чеко."""
import re
from collections import Counter

# Код региона в первых двух цифрах ИНН -> как регион пишется в адресе.
# Нужен, чтобы из нескольких адресов выбрать тот, где компания
# зарегистрирована, а не её филиал в другом регионе.
REGION_PATTERNS = {
    "01": r"адыге", "02": r"башкортостан", "03": r"буряти", "04": r"респ\w*\s+алтай",
    "05": r"дагестан", "06": r"ингушети", "07": r"кабардино-балкар", "08": r"калмыки",
    "09": r"карачаево-черкес", "10": r"карели", "11": r"коми", "12": r"марий\s+эл",
    "13": r"мордови", "14": r"саха|якути", "15": r"северная\s+осети", "16": r"татарстан",
    "17": r"тыва", "18": r"удмурт", "19": r"хакаси", "20": r"чеченск", "21": r"чувашск",
    "22": r"алтайский\s+кра", "23": r"краснодарский\s+кра", "24": r"красноярский\s+кра",
    "25": r"приморский\s+кра", "26": r"ставропольский\s+кра", "27": r"хабаровский\s+кра",
    "28": r"амурск", "29": r"архангельск", "30": r"астраханск", "31": r"белгородск",
    "32": r"брянск", "33": r"владимирск", "34": r"волгоградск", "35": r"вологод",
    "36": r"воронежск", "37": r"ивановск", "38": r"иркутск", "39": r"калининградск",
    "40": r"калужск", "41": r"камчатск", "42": r"кемеровск|кузбасс", "43": r"кировск",
    "44": r"костромск", "45": r"курганск", "46": r"курск", "47": r"ленинградск",
    "48": r"липецк", "49": r"магаданск", "50": r"московск\w*\s+обл", "51": r"мурманск",
    "52": r"нижегородск", "53": r"новгородск", "54": r"новосибирск", "55": r"омск",
    "56": r"оренбургск", "57": r"орловск", "58": r"пензенск", "59": r"пермск",
    "60": r"псковск", "61": r"ростовск", "62": r"рязанск", "63": r"самарск",
    "64": r"саратовск", "65": r"сахалинск", "66": r"свердловск", "67": r"смоленск",
    "68": r"тамбовск", "69": r"тверск", "70": r"томск", "71": r"тульск",
    "72": r"тюменск", "73": r"ульяновск", "74": r"челябинск", "75": r"забайкальск",
    "76": r"ярославск", "77": r"москва", "78": r"санкт-петербург", "79": r"еврейск",
    "80": r"донецк", "81": r"луганск", "82": r"крым", "83": r"ненецк",
    "84": r"херсонск", "85": r"запорожск", "86": r"ханты-мансийск|югра",
    "87": r"чукотск", "89": r"ямало-ненецк", "91": r"крым", "92": r"севастополь",
}
# «Московская область» тоже содержит «москва»-подобный корень, поэтому
# для кода 77 регион засчитывается только при явном отсутствии области.
REGION_EXCLUDE = {"77": r"московск\w*\s+обл"}

# Признак современного формата ФИАС — так Чеко отдаёт ЮрАдрес.
FIAS_MARKER = re.compile(r"вн\.\s*тер\.\s*г\.", re.IGNORECASE)
POSTAL_INDEX = re.compile(r"^\s*\d{6}\b")
# Старый формат КЛАДР — тип после названия («Санкт-Петербург г», «Фонтанки наб»).
# Так адреса пишет выгрузка НОСТРОЙ; Чеко всегда отдаёт современный формат,
# поэтому легаси-строка почти всегда оказывается адресом СРО, а не компании.
LEGACY_FORMAT = re.compile(r"[А-Яа-яЁё]\s+(?:г|обл|край|респ|р-н)\s*,", re.IGNORECASE)


def split_addresses(raw):
    """Разбивает слипшуюся ячейку на отдельные адреса."""
    if not raw:
        return []
    return [part.strip() for part in str(raw).split(";") if part.strip()]


def detect_shared_addresses(rows, address_index=4, min_share=0.15):
    """Находит адреса, повторяющиеся у многих компаний, — это адреса СРО.

    Собственный адрес компании уникален; адрес СРО приклеился к сотням
    строк при первом прогоне. Порог доли строк отсекает его автоматически,
    без ручного списка.
    """
    counter = Counter()
    for row in rows:
        for address in set(split_addresses(row[address_index])):
            counter[address] += 1
    threshold = max(2, int(len(rows) * min_share))
    return {address for address, count in counter.items() if count >= threshold}


def region_matches(address, inn):
    """Совпадает ли регион адреса с кодом региона в ИНН."""
    code = str(inn or "")[:2]
    pattern = REGION_PATTERNS.get(code)
    if not pattern:
        return False
    lowered = address.lower()
    exclude = REGION_EXCLUDE.get(code)
    if exclude and re.search(exclude, lowered):
        return False
    return bool(re.search(pattern, lowered))


def score_address(address, inn):
    """Чем выше балл, тем вероятнее, что это юридический адрес."""
    score = 0
    if region_matches(address, inn):
        score += 100
    if FIAS_MARKER.search(address):
        score += 40
    if POSTAL_INDEX.match(address):
        score += 10
    if LEGACY_FORMAT.search(address):
        score -= 60
    # Подробный адрес (с корпусом, литерой, помещением) вероятнее
    # юридический, чем обрывок вида «г. Мурманск».
    score += min(address.count(","), 8)
    return score


def pick_address(raw, inn, shared=frozenset()):
    """Возвращает (адрес, признак_неоднозначности).

    Неоднозначность = два кандидата набрали одинаковый максимум;
    такие строки стоит уточнить в Чеко по полю ЮрАдрес.
    """
    candidates = [a for a in split_addresses(raw) if a not in shared]
    if not candidates:
        return None, False
    if len(candidates) == 1:
        return candidates[0], False

    scored = sorted(((score_address(a, inn), a) for a in candidates), key=lambda p: -p[0])
    ambiguous = scored[0][0] == scored[1][0]
    return scored[0][1], ambiguous
