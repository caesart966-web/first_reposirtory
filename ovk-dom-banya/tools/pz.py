def table(head, rows, caption='', widths=None, left=(1,)):
    cg = ''.join(f'<col style="width:{w}%">' for w in widths) if widths else ''
    th = ''.join(f'<th>{h}</th>' for h in head)
    body = ''
    for r in rows:
        if isinstance(r, str):
            body += f'<tr class="sec"><td colspan="{len(head)}">{r}</td></tr>'
            continue
        cls = ''
        if r and r[0] == '!b':
            cls, r = ' class="b"', r[1:]
        body += f'<tr{cls}>' + ''.join(f'<td class="l">{c}</td>' if i in left else f'<td>{c}</td>'
                                       for i, c in enumerate(r)) + '</tr>'
    cap = f'<caption>{caption}</caption>' if caption else ''
    return f'<table>{cap}<colgroup>{cg}</colgroup><thead><tr>{th}</tr></thead><tbody>{body}</tbody></table>'


