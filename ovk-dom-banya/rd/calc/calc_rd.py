def ufh_room(no, cab):
    r = ROOM[no]
    ti = r['ti']
    tv = TV_GROUP[GROUP[cab]]
    tf_max = r['ufh_tf']
    area = r['area']
    frac = r['ufh_frac']
    A = area * frac                                     # площадь петель (без мебели/сантехники)
    if no in A_DRAWN:                                   # 1 этаж дома: площадь зон петель по чертежу (лист 4)
        A = A_DRAWN[no]
    R = FLOOR[COVER[no]]
    Qn = min(r['Q'], r['ufh'])                          # нагрузка, которую несёт пол (ЭП: ufh — предел)
    # если и при наименьшем шаге с σ = 5 К пол не добирает — снижаем долю пола, остаток — на прибор
    Tmin = min(SPACING[room_kind(no)])
    q_ach = k_h(Tmin, R) * 5 / math.log((tv - ti) / (tv - 5 - ti))
    short = 0
    if Qn / A > q_ach:
        short = round(Qn - q_ach * A)
        Qn = q_ach * A
    q = Qn / A
    under = 'garage' if no in ('2.8', '2.9') else 'ground'
    Ru, tu = DOWN[under]
    Ro = 1 / 10.8 + R + SU / LAM_E
    zone = ZONES[no]
    pos = CAB[cab]['pos']
    lead_one = manh(pos, near_point(pos, zone)) * ROUTE_K + 1.0     # +1 м — опуск/подъём у коллектора
    best = None
    for T in ([T_DRAWN[no]] if no in T_DRAWN else SPACING[room_kind(no)]):
        K = k_h(T, R)
        dth = q / K
        tr = solve_return(tv, ti, dth)
        if tr is None:
            continue
        cand = dict(T=T, K=K, dth=dth, tr=tr, sigma=tv - tr)
        best = cand
        if cand['sigma'] >= SIGMA_MIN - 0.05:
            break
    T, K, sigma, tr = best['T'], best['K'], best['sigma'], best['tr']
    sig_d = min(sigma, SIGMA_MAX)                       # перепад, по которому задаётся расход
    L_coil = A / T
    n = max(1, math.ceil(L_coil / (L_LOOP_MAX - 2 * lead_one)))
    # расход (EN 1264-3): с учётом потерь вниз
    m_tot = A * q / (sig_d * CW) * (1 + Ro / Ru + (ti - tu) / (q * Ru)) * 3600    # кг/ч
    q_down = (Ro * q + ti - tu) / Ru
    while True:
        L_loop = L_coil / n + 2 * lead_one
        m = m_tot / n
        # потери давления петли: трение + повороты «улитки» (90°, ζ = 0,3; прямой участок ≈ полстороны петли)
        side = math.sqrt(A / n)
        n_b = math.ceil(2 * (L_coil / n) / side) + 4
        hyd = pipe_dp(m, UFH_DI * 1000, L_loop, tv - sig_d / 2, K_PEX, zeta=0.3 * n_b)
        if no in N_DRAWN:                               # число петель — как на раскладке (лист 4)
            if n == N_DRAWN[no]:
                break
            n = N_DRAWN[no]
            continue
        if hyd['dp'] <= DP_LOOP_MAX * 1000 or n >= 8:
            break
        n += 1
    tf = t_floor(q, ti)
    wet_or_temp = no in ('1.4', '2.8', '2.9', 'б3', 'б7', 'б4', 'б2', '1.5', '1.6', '1.7', '1.8', '1.2', '1.3', '1.9')
