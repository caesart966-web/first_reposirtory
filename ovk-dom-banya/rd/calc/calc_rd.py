def _interp(xs, ys, x):
    if x <= xs[0]:
        return ys[0]
    for x0, x1, y0, y1 in zip(xs, xs[1:], ys, ys[1:]):
        if x <= x1:
            return y0 + (y1 - y0) * (x - x0) / (x1 - x0)
    return ys[-1]


def _bilin(tab, T, R):
    col = [_interp(_RL, row, R) for row in tab]
    return _interp(_T, col, T)


def k_h(T, R):
    """Эквивалентный коэффициент теплопередачи K_H, Вт/(м²·К): q = K_H · Δθ_H."""
    B = 6.7                                    # труба λ = 0,35, стенка 2 мм — эталон EN 1264-2
    aB = (1 / 10.8 + 0.045 / 1.0) / (1 / 10.8 + 0.045 / LAM_E + R)
    aT = _interp(_RL, _AT, R)
    mT = 1 - T / 0.075
    au = _bilin(_AU, T, R)
    mu = 100 * (0.045 - SU)
    aD = _bilin(_AD, T, R)
    mD = 250 * (UFH_DO - 0.020)
    return B * aB * aT ** mT * au ** mu * aD ** mD


def t_floor(q, ti):
    return ti + (q / 8.92) ** (1 / 1.1)


def solve_return(tv, ti, dth):
    """tr из Δθ_H = (tv - tr) / ln((tv - ti)/(tr - ti)); None, если недостижимо."""
    if dth >= tv - ti - 1e-6:
        return None
    lo, hi = ti + 1e-6, tv - 1e-6
    for _ in range(200):
        mid = (lo + hi) / 2
        d = (tv - mid) / math.log((tv - ti) / (mid - ti))
        if d > dth:
            hi = mid
        else:
            lo = mid
    return (lo + hi) / 2


