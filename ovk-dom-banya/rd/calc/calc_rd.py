def n(x, k=1):
    if isinstance(x, (int,)) or (isinstance(x, float) and k == 0):
        return f'{round(x):,}'.replace(',', ' ')
    return f'{x:.{k}f}'.replace('.', ',')


def tab(head, rows):
    o = ['| ' + ' | '.join(head) + ' |', '|' + '|'.join('---' for _ in head) + '|']
    o += ['| ' + ' | '.join(str(c) for c in r) + ' |' for r in rows]
    return '\n'.join(o)


