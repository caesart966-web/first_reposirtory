def friction(v, d, nu, k):
    """Коэффициент трения: ламинарный 64/Re, иначе Колбрук-Уайт (итерации)."""
    re = v * d / nu
    if re < 2300:
        return 64 / max(re, 1e-9), re
    lam = 0.02
    for _ in range(40):
        lam = (-2 * math.log10(k / (3.7 * d) + 2.51 / (re * math.sqrt(lam)))) ** -2
    return lam, re


def pipe_dp(G_kgh, d_mm, L, t, k, zeta=0.0):
    """Потери давления в трубе, Па. G — кг/ч, d — внутренний, мм, L — м."""
    rho, nu = water(t)
    d = d_mm / 1000
    v = G_kgh / 3600 / rho / (math.pi * d * d / 4)
    lam, re = friction(v, d, nu, k)
    dyn = rho * v * v / 2
    R = lam / d * dyn
    return dict(v=v, R=R, Re=re, dp=R * L + zeta * dyn, dp_fr=R * L, dp_loc=zeta * dyn)


def pick_pipe(G_kgh, t, series, k, vmax, vmin=0.0):
    """Меньший диаметр ряда, при котором скорость не выше vmax."""
    rho, _ = water(t)
    for name, (dn, di) in series.items():
        v = G_kgh / 3600 / rho / (math.pi * (di / 1000) ** 2 / 4)
        if v <= vmax:
            return name, di, v
    name, (dn, di) = list(series.items())[-1]
    return name, di, G_kgh / 3600 / rho / (math.pi * (di / 1000) ** 2 / 4)


