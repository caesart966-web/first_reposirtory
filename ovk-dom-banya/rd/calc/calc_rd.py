def duct_r(L_m3h, d_mm):
    d = d_mm / 1000
    v = L_m3h / 3600 / (math.pi * d * d / 4)
    re = v * d / AIR_NU
    lam = 0.11 * (K_DUCT / d + 68 / re) ** 0.25          # Альтшуль
    dyn = AIR_RHO * v * v / 2
    return v, lam / d * dyn, dyn


def pick_duct(L, vmax):
    for d in DUCTS:
        v, _, _ = duct_r(L, d)
        if v <= vmax:
            return d
    return DUCTS[-1]


