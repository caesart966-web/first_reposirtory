def drop45(x, y, d, z_top):
    """Выпуск 2 этажа к сборному под потолком гаража (Заказчица 27.10.2026: примыкания под 45°): в плане — косым
    тройником 45° по ходу стока (на запад); прибор над сборным — косым тройником 45° в вертикальной плоскости."""
    up = 0.03 if d == 50 else 0.0                   # шелыга Ø50 — в шелыге сборного Ø110
    if abs(y - Y_K1) < 0.1:
        xe = round(x - 0.12, 4)
        ze = z_coll(xe, Y_K1) + up
        return [(x, y, z_top), (x, y, ze + 0.12), (xe, Y_K1, ze)]
    sg = 1 if y < Y_K1 else -1
    L = abs(Y_K1 - y)
    l45 = min(L, PRE45)
    yb = round(Y_K1 - sg * l45, 4)
    xe = round(x - l45, 4)
    ze = z_coll(xe, Y_K1) + up
    zb = ze + 0.03 * l45 * math.sqrt(2)
    zh = zb + 0.03 * abs(yb - y)
    pts = [(x, y, z_top), (x, y, zh)]
    if abs(yb - y) > 1e-6:
        pts.append((x, yb, zb))
    return pts + [(xe, Y_K1, ze)]


