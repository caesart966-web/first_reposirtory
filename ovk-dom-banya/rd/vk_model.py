def cleanouts():
    """Прочистки в грунте (тройник с выводом к люку): [(fit, x, y стояка-люка, помещение)]."""
    return [(f, f.extra['riser'][0], f.extra['riser'][1], f.extra['room']) for f in FITS
            if f.kind == 'revision' and f.name.startswith('Прочистка')]


def cleanout_steps():
    """Шаги по длине сборных К1-1 и К1-б: от начала (стояк прочистки или трап) до прочистки и между прочистками, м;
    последний элемент — от последней прочистки до конца трубы в здании (дальше выпуск НВК)."""
    out = {}
    for pid in ('К1-1', 'К1-б'):
        line = next(p for p in PIPES if p.id == pid)
        acc, marks, segs = 0.0, [], []
        for a, b in zip(line.pts, line.pts[1:]):
            segs.append((a, b, acc))
            acc += math.dist(a[:2], b[:2])
        for f, *_ in cleanouts():
            if f.pipe is not line:
                continue
            for a, b, s0 in segs:
                if point_on_seg((f.pos[0], f.pos[1], 0), (a[0], a[1], 0), (b[0], b[1], 0), 1e-3):
                    marks.append(s0 + math.dist(a[:2], f.pos[:2]))
                    break
        marks.sort()
        pts = [0.0] + marks + [acc]
        out[pid] = [round(b - a, 2) for a, b in zip(pts, pts[1:])]
    return out
