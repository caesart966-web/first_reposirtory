def slope(p):
    """Средний уклон горизонтальных участков трубы (по геометрии модели)."""
    dz = L = 0.0
    for a, b in zip(p.pts, p.pts[1:]):
        h = math.dist(a[:2], b[:2])
        if h > 0.05:
            dz += a[2] - b[2]
            L += h
    return round(dz / L, 3) if L else None


def i_txt(p):
    return f'{slope(p):.3f}'.rstrip('0').replace('.', ',')


def cleanouts():
    """Прочистки на сборных в грунте (тройник 45° с выводом в стену к люку): [(fit, x, y, помещение)]."""
    return [(f, f.extra['riser'][0], f.extra['riser'][1], f.extra['room']) for f in FITS
            if f.kind == 'revision' and f.name.startswith('Прочистка')]


def cleanout_steps():
    """Шаги по длине сборных К1-1 и К1-б между точками прочистки, м. Точки: начало (у К1-1 — колодец КК-1 во
    дворе, у К1-б — трап Д-б1), прочистки на сборном и места присоединения стояков с ревизиями (junction);
    последний элемент — от последней точки до конца трубы в здании (дальше — выпуск НВК)."""
    out = {}
    for pid in ('К1-1', 'К1-б'):
        line = next(p for p in PIPES if p.id == pid)
        acc, marks, segs = 0.0, [], []
        for a, b in zip(line.pts, line.pts[1:]):
            segs.append((a, b, acc))
            acc += math.dist(a[:2], b[:2])
        pts = [(f.pos[0], f.pos[1]) for f, *_ in cleanouts() if f.pipe is line]
        pts += [f.extra['junction'] for f in FITS if f.kind == 'revision' and 'junction' in f.extra]
        for q in pts:
            for a, b, s0 in segs:
                if point_on_seg((q[0], q[1], 0), (a[0], a[1], 0), (b[0], b[1], 0), 1e-3):
                    marks.append(s0 + math.dist(a[:2], q))
                    break
        marks.sort()
        head = YARD_L[1] if pid == 'К1-1' else 0.0        # от КК-1 до ввода в дом
        st = [0.0] + marks + [acc]
        steps = [round(b - a, 2) for a, b in zip(st, st[1:])]
        steps[0] = round(steps[0] + head, 2)
        out[pid] = steps
    return out


