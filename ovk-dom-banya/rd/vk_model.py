def slope(p):
    """Средний уклон горизонтальных участков трубы (по геометрии модели); косые фасонные части (отвод/тройник 45°
    в вертикальной плоскости, dz/h > 0,25) — не уклон и в среднее не входят, если у трубы есть прямые участки."""
    for steep in (0.25, None):
        dz = L = 0.0
        for a, b in zip(p.pts, p.pts[1:]):
            h = math.dist(a[:2], b[:2])
            if h > 0.05 and (steep is None or (a[2] - b[2]) / h <= steep):
                dz += a[2] - b[2]
                L += h
        if L:
            return round(dz / L, 3)
    return None


def i_txt(p):
    return f'{slope(p):.3f}'.rstrip('0').replace('.', ',')


