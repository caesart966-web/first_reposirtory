class Pipe:
    """Труба: pts — точки оси (x, y, z); serves — обозначения приборов, которые питает (В1, Т3) или отводит (К1)
    участок; bld — 'h' дом / 'b' баня; mat — pex, pp, ppn (наружная в грунте), pe (ввод), sml (чугун безраструбный
    SML — водостоки К2)."""

    def __init__(self, pid, sysk, mat, dn, pts, serves=(), name='', bld='h', ins=None, where=''):
        self.id, self.sys, self.mat, self.dn, self.bld = pid, sysk, mat, dn, bld
        self.pts = [tuple(round(float(c), 4) for c in p) for p in pts]
        self.serves = list(serves)
        self.name = name or pid
        self.where = where                      # floor (в полу), ceil (под потолком), wall, ground, riser
        self.quiet = False                      # К1: малошумная труба (размечается после построения модели)
        if mat == 'pex':
            self.od = PEX[dn]
        elif mat in ('pp', 'ppn'):
            self.od = PP[dn]
        elif mat == 'pe':
            self.od = PE_IN[dn]
        elif mat == 'sml':
            self.od = SML[dn]
        else:
            self.od = float(dn) / 1000
        self.ins = ins if ins is not None else (0.013 if sysk in ('Т3', 'Т4') else (0.009 if sysk == 'В1' else 0))

    def label(self):
        if self.mat == 'pex':
            return f'PE-Xa {self.dn}'
        if self.mat in ('pp', 'ppn'):
            return f'Ø{self.dn}'
        if self.mat == 'pe':
            return f'ПЭ {self.dn}'
        if self.mat == 'sml':
            return f'SML DN{self.dn}'
        return str(self.dn)

    def length(self):
        return sum(math.dist(a, b) for a, b in zip(self.pts, self.pts[1:]))

    def r(self):
        return self.od / 2 + self.ins


def pipe(*a, **k):
    p = Pipe(*a, **k)
    PIPES.append(p)
    return p


