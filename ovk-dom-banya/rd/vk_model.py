def summary():
    by = {}
    for p in PIPES:
        k = (p.bld, p.sys, p.mat, p.dn)
        by[k] = by.get(k, 0) + p.length()
    return by


def export():
    os.makedirs(OUT, exist_ok=True)
    data = dict(
        pipes=[dict(id=p.id, sys=p.sys, mat=p.mat, dn=p.dn, od=p.od, pts=p.pts, serves=p.serves, name=p.name,
                    bld=p.bld, where=p.where, quiet=p.quiet, L=round(p.length(), 2)) for p in PIPES],
        fits=[dict(kind=f.kind, pipe=f.pipe.id, pos=f.pos, name=f.name, axis=f.axis, sys=f.sys) for f in FITS],
        equip=[dict(id=e.id, mark=e.mark, kind=e.kind, g=e.g, name=e.name, bld=e.bld, bbox=e.bbox()) for e in EQUIP],
        fixtures={k: dict(typ=f.typ, room=f.room, pos=f.pos, floor=f.floor, bld=f.bld, hot=f.hot, cold=f.cold,
                          k1=f.k1, note=f.note, name=f.a1[0]) for k, f in FIXT.items()},
        assume=ASSUME, leak=[dict(id=a, bld=b, level=c, pos=d, place=e) for a, b, c, d, e in LEAK])
    with open(os.path.join(OUT, 'vk.json'), 'w') as fh:
        json.dump(data, fh, ensure_ascii=False, indent=1)
    return data


