def seg_axis(p, pos):
    for a, b in zip(p.pts, p.pts[1:]):
        if point_on_seg(pos, a, b):
            d = [abs(b[k] - a[k]) for k in range(3)]
            return 'xyz'[d.index(max(d))]
    raise ValueError(f'{p.id}: точка {pos} не на трубе')


def point_on_seg(q, a, b, tol=1e-4):
    ab = [b[k] - a[k] for k in range(3)]
    L2 = sum(c * c for c in ab)
    if L2 < 1e-12:
        return math.dist(q, a) < tol
    t = sum((q[k] - a[k]) * ab[k] for k in range(3)) / L2
    if t < -1e-6 or t > 1 + 1e-6:
        return False
    return math.dist(q, [a[k] + ab[k] * t for k in range(3)]) < tol


def fit(kind, p, pos, name='', side=None, **extra):
    f = Fit(kind, p, pos, name, side, **extra)
    FITS.append(f)
    return f


class Eq:
    """Оборудование/приборы: box (x0,y0,z0,x1,y1,z1) или cyl (cx,cy,r,z0,z1)."""

    def __init__(self, eid, mark, kind, g, name, bld='h', ctx=False, pos=None):
        self.id, self.mark, self.kind, self.g, self.name, self.bld, self.ctx, self.pos = \
            eid, mark, kind, g, name, bld, ctx, pos

    def bbox(self):
        if self.kind == 'box':
            return self.g
        cx, cy, r, z0, z1 = self.g
        return (cx - r, cy - r, z0, cx + r, cy + r, z1)


def eq(*a, **k):
    e = Eq(*a, **k)
    EQUIP.append(e)
    return e


