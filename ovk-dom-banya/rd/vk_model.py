class Eq:
    """Оборудование/приборы: box (x0,y0,z0,x1,y1,z1) или cyl (cx,cy,r,z0,z1)."""

    def __init__(self, eid, mark, kind, g, name, bld='h', ctx=False, pos=None):
        self.id, self.mark, self.kind, self.g, self.name, self.bld, self.ctx, self.pos = \
            eid, mark, kind, g, name, bld, ctx, pos

    def bbox(self):
        if self.kind == 'box':
            return self.g
        cx, cy, r, z0, z1 = self.g
        return (cx - r, cy - r, z0, cx + r, cy + r, z1)


def eq(*a, **k):
    e = Eq(*a, **k)
    EQUIP.append(e)
    return e


