def unit(v):
    L = math.hypot(*v)
    return (v[0] / L, v[1] / L)


def ug_line(pid, d, pts2, z0, i, serves, name, bld='h'):
    """Самотёчная линия в грунте: pts2 — точки в плане, z0 — лоток в начале, i — уклон; ось = лоток + d/2."""
    pts, z = [], z0
    for k, (x, y) in enumerate(pts2):
        if k:
            z -= i * math.dist(pts2[k - 1], (x, y))
        pts.append((x, y, round(z + PP[d] / 2, 4)))
    return pipe(pid, 'К1', 'ppn' if d == 110 else 'pp', d, pts, serves=serves, name=name, where='ground', bld=bld)


def z_on(line, x, y):
    """Лоток линии в точке (x, y) плана, лежащей на ней."""
    for a, b in zip(line.pts, line.pts[1:]):
        if point_on_seg((x, y, 0), (a[0], a[1], 0), (b[0], b[1], 0), 1e-3):
            t = math.dist((a[0], a[1]), (x, y)) / max(1e-9, math.dist((a[0], a[1]), (b[0], b[1])))
            return a[2] + (b[2] - a[2]) * t - line.od / 2
    raise ValueError((line.id, x, y))


def branch(pid, d, pts2, line, serves, name, i=I_BR, bld='h'):
    """Отвод в грунте к линии line: шелыга отвода в точке присоединения — в шелыге линии."""
    zend = z_on(line, *pts2[-1]) + (line.od - PP[d])
    L = sum(math.dist(a, b) for a, b in zip(pts2, pts2[1:]))
    return ug_line(pid, d, pts2, zend + i * L, i, serves, name, bld=bld)


def join45(p, line, seg=None, lead=0.0):
    """Точка присоединения отвода от p к прямому участку line под 45° по ходу стока: проекция p на ось плюс
    смещение |h| вниз по потоку (длина отвода — |h|·√2). lead — прямой участок от p до начала косого хода (м)."""
    best = None
    for a, b in zip(line.pts, line.pts[1:]):
        a2, b2 = a[:2], b[:2]
        u = unit((b2[0] - a2[0], b2[1] - a2[1]))
        v = (p[0] - a2[0], p[1] - a2[1])
        h = u[0] * v[1] - u[1] * v[0]
        s = u[0] * v[0] + u[1] * v[1] + abs(h) + lead
        L = math.dist(a2, b2)
        if -1e-6 <= s <= L + 1e-6 and (best is None or abs(h) < best[0]):
            best = (abs(h), (round(a2[0] + u[0] * s, 4), round(a2[1] + u[1] * s, 4)), u)
    if best is None:
        raise ValueError(f'{line.id}: нет точки присоединения 45° для {p}')
    return best[1]


def at_s(line, s):
    """Точка плана на расстоянии s от начала линии."""
    acc = 0.0
    for a, b in zip(line.pts, line.pts[1:]):
        L = math.dist(a[:2], b[:2])
        if s <= acc + L + 1e-9:
            t = (s - acc) / L
            return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)
        acc += L
    return line.pts[-1][:2]


