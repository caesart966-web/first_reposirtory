def along(pts, d):
    """Точка на ломаной в d м от начала."""
    acc = 0.0
    for a, b in zip(pts, pts[1:]):
        L = math.dist(a, b)
        if L > 1e-9 and d <= acc + L:
            t = (d - acc) / L
            return tuple(round(a[k] + (b[k] - a[k]) * t, 4) for k in range(3))
        acc += L
    return pts[-1]


def feed(pid, sysk, dn, pts, fx, name, where='floor', bld='h', serves=None):
    """Подводка от коллектора к прибору; кран шаровой на выходе — в шкафу, в 0,08 м от коллектора."""
    p = pipe(pid, sysk, 'pex', dn, P(*pts), serves=serves or [fx], name=name, where=where, bld=bld)
    fit('ball', p, along(p.pts, 0.08), f'Кран шаровой на выходе к {fx}')
    return p


