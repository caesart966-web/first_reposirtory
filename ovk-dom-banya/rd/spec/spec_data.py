def device_rows(items):
    """items: [(вид, тип/длина, Q, марки, комната/прим)] → строки, одинаковые позиции объединены."""
    out, seen = [], {}
    for it in items:
        key = it[:3]
        if key in seen:
            seen[key][3].append(it[3])
            continue
        seen[key] = [it[0], it[1], it[2], [it[3]]]
        out.append(key)
    rows = []
    for key in out:
        kind, typ, Q, marks = seen[key]
        n = len(marks)
        if kind == 'rad':
            t, L = typ
            rows.append((f'Радиатор стальной панельный {t}, L={int(round(L * 1000))} мм, нижнее подключение, '
                         f'тепловая мощность при 70/55 °С не менее {Q} Вт', A, '', '', 'шт.', n, ', '.join(marks)))
        elif kind in ('conv', 'convn'):
            L, depth = typ
            fan = 'с вентилятором 12 В' if kind == 'conv' else 'без вентилятора (естественная конвекция)'
            dd = ', глубина не более 150 мм' if depth else ''
            rows.append((f'Конвектор внутрипольный {fan}, L={int(round(L * 1000))} мм{dd}, тепловая мощность '
                         f'при 70/55 °С не менее {Q} Вт', 'КЗТО, модель — по каталогу', '', 'КЗТО', 'шт.', n,
                         ', '.join(marks)))
        else:
            rows.append((f'Полотенцесушитель водяной, мощность не менее {typ} Вт при 75/65/20 °С', A, '', '', 'шт.',
                         n, ', '.join(marks)))
    return rows


