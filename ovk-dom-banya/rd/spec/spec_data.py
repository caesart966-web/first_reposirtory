def ufh_perimeter(names):
    """Периметр зон укладки ТП (контуры на листах, слой ОВ_ТП), м — для демпферной ленты."""
    import ezdxf
    P = 0.0
    for n in names:
        doc = ezdxf.readfile(os.path.join(ROOT, 'out', f'{n}.dxf'))
        for e in doc.modelspace().query('LWPOLYLINE[layer=="ОВ_ТП"]'):
            pts = [tuple(p[:2]) for p in e.get_points()]
            if e.closed:
                pts.append(pts[0])
            P += sum(math.dist(a, b) for a, b in zip(pts, pts[1:])) / 1000
    return P


