def L(*ids):
    return sum(P[i].length() for i in ids)


def ids(sys_=None, dn=None, perf=None, mat=None):
    out = []
    for p in M.PIPES:
        if sys_ and p.sys != sys_:
            continue
        if dn and p.dn != dn:
            continue
        if perf is not None and (('перфорир' in p.mat) != perf):
            continue
        if mat and mat not in p.mat:
            continue
        out.append(p.id)
    return out


def turn(a, b):
    """Угол поворота потока в колодце между последним участком трубы a и первым участком трубы b, град."""
    pa, pb = P[a].pts, P[b].pts
    u = (pa[-1][0] - pa[-2][0], pa[-1][1] - pa[-2][1])
    v = (pb[1][0] - pb[0][0], pb[1][1] - pb[0][1])
    c = (u[0] * v[0] + u[1] * v[1]) / math.hypot(*u) / math.hypot(*v)
    return int(round(math.degrees(math.acos(max(-1.0, min(1.0, c))))))


def ins_len(pid):
    return sum(b - a for a, b in P[pid].ins)


def depth_profile(p, z_bot, step=0.25):
    """Средняя глубина траншеи вдоль трубы (от проектной поверхности до дна), м; длина в плане."""
    Lp = p.length()
    if Lp < 1e-6:
        return 0.0, 0.0
    n = max(2, int(Lp / step))
    s = 0.0
    for k in range(n):
        x, y, z = p.at((k + 0.5) * Lp / n)
        s += M.g_design(x, y) - z_bot(z)
    return s / n, Lp


