def bends(p, min_deg=30.0):
    """Число поворотов трассы в плане круче min_deg (под фитинг; пологие — изгибом трубы)."""
    q = [p.pts[0]]
    for pt in p.pts[1:]:
        if math.dist(pt, q[-1]) > 1e-6:
            q.append(pt)
    n = 0
    for a_, b_, c_ in zip(q, q[1:], q[2:]):
        u, v = (b_[0] - a_[0], b_[1] - a_[1]), (c_[0] - b_[0], c_[1] - b_[1])
        cs = (u[0] * v[0] + u[1] * v[1]) / math.hypot(*u) / math.hypot(*v)
        n += math.degrees(math.acos(max(-1.0, min(1.0, cs)))) > min_deg
    return n


