def f(x, n=2):
    if x is None:
        return '—'
    return f'{x:.{n}f}'.replace('.', ',').replace('-', '−')


def table(head, rows, widths=None):
    cg = ''.join(f'<col style="width:{w}%">' for w in widths) if widths else ''
    h = '<tr>' + ''.join(f'<th>{c}</th>' for c in head) + '</tr>'
    b = ''
    for r in rows:
        b += '<tr>' + ''.join(f'<td class="l">{x[1:]}</td>' if isinstance(x, str) and x.startswith('~')
                              else f'<td>{x}</td>' for x in r) + '</tr>'
    return f'<table class="t"><colgroup>{cg}</colgroup>{h}{b}</table>'


def pdf(name, pages, title):
    import rd_stamp
    old = rd_stamp.BLD
    rd_stamp.BLD = BLD
    html = G.document(pages, title, f'{CODE}.{name.split()[0]}')
    rd_stamp.BLD = old
    hp = os.path.join(OUT, f'{CODE}.{name}.html')
    open(hp, 'w').write(html)
    pp = os.path.join(OUT, f'{CODE}.{name}.pdf')
    env = dict(os.environ, NODE_PATH=subprocess.check_output(['npm', 'root', '-g'], text=True).strip())
    subprocess.check_call(['node', os.path.join(HERE, 'html2pdf.js'), hp, pp], env=env)
    return pp


def depth_rows(ids):
    rows = []
    for pid in ids:
        p = P[pid]
        (x0, y0), (x1, y1) = p.pts[0], p.pts[-1]
        g0, g1 = M.g_design(x0, y0), M.g_design(x1, y1)
        ins = ', '.join(f'{f(a, 1)}–{f(b, 1)}' for a, b in p.ins) or 'не требуется'
        rows.append([pid, f(g0), f(g1), f(p.z[0], 3), f(p.z[-1], 3), f(g0 - p.z[0]), f(g1 - p.z[-1]), ins])
    return rows


