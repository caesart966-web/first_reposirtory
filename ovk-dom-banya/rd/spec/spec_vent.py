def plen(pts):
    return sum(math.dist(a, b) for a, b in zip(pts, pts[1:]))


def k2(p):
    return (round(p[0], 2), round(p[1], 2))


def duct_network():
    """Длины по Ø, отводы, тройники, переходы — по трассам листов 9, 10."""
    L = defaultdict(float)
    legs = defaultdict(list)               # (этаж, x, y) -> [(d, направление)]
    elbows = Counter()
    for floor, net in ((1, v1.NET1), (2, v2.NET2)):
        for sid, kind, pts, d, q in net:
            L[d] += plen(pts)
            for i in range(1, len(pts) - 1):
                elbows[d] += 1
            for end, nxt in ((pts[0], pts[1]), (pts[-1], pts[-2])):
                dx, dy = nxt[0] - end[0], nxt[1] - end[1]
                n = math.hypot(dx, dy) or 1
                legs[(floor,) + k2(end)].append((d, (dx / n, dy / n, 0.0)))
    # вертикальные участки: стояки Ш-1, выброс П1 в Ш-2
    for xy, d in ((v1.RIS_P, 200), (v1.RIS_V, 200), (v1.RIS_P27, 100)):
        L[d] += H_RIS
        legs[(1,) + k2(xy)].append((d, (0, 0, 1)))
        legs[(2,) + k2(xy)].append((d, (0, 0, -1)))
    x_end = v1.NET1[[s[0] for s in v1.NET1].index('Выброс')][2][-1]
    L[250] += H_SH2_X
    legs[(1,) + k2(x_end)].append((250, (0, 0, 1)))
    # потолочные решётки: на конце трассы — отвод вниз, в середине — тройник
    ceil1 = [(g[0], g[1]) for g in v1.GRILLES1 if not g[6]]
    ceil2 = [(3.90, v2.YM), (13.75, 8.25), (18.00, 8.25), (13.35, 10.85), (11.00, 9.80)]
    for floor, pts in ((1, ceil1), (2, ceil2)):
        for xy in pts:
            best = min(legs, key=lambda k: (k[0] != floor, math.dist(k[1:], xy)))
            if best[0] == floor and math.dist(best[1:], xy) < 0.10:
                d = min(d_ for d_, _ in legs[best])
                legs[best].append((d, (0, 0, -1)))
    tees, trans = Counter(), Counter()
    for node, lg in legs.items():
        if len(lg) == 2:
            (d1, u1), (d2, u2) = lg
            dot = sum(a * b for a, b in zip(u1, u2))
            if dot > -0.99:
                elbows[max(d1, d2)] += 1
            if d1 != d2:
                trans[(max(d1, d2), min(d1, d2))] += 1
        elif len(lg) == 3:
            pair = None
            for i in range(3):
                for j in range(i + 1, 3):
                    if sum(a * b for a, b in zip(lg[i][1], lg[j][1])) < -0.99:
                        pair = (i, j)
            if pair:
                br = lg[3 - sum(pair)][0]
                main = [lg[pair[0]][0], lg[pair[1]][0]]
                tees[(max(main), br)] += 1
                if main[0] != main[1]:
                    trans[(max(main), min(main))] += 1
            else:
                ds = sorted(d for d, _ in lg)
                tees[(ds[-1], ds[0])] += 1
                elbows[ds[-1]] += 1
        elif len(lg) > 3:
            raise ValueError(f'узел {node}: {len(lg)} ветвей')
    return L, elbows, tees, trans


def rooms(rs):
    """Помещения без повторов, с числом: «1.10 — 3 шт., 2.2»."""
    c = Counter(rs)
    return ', '.join(f'{r} — {n} шт.' if n > 1 else r for r, n in c.items())


