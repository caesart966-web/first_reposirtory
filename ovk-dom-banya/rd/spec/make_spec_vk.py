def split_bend(ang):
    """Поворот на ang° — стандартными отводами 45°, 30°, 15°: ошибка не больше 7,5°, затем меньше штук, затем больше
    отводов 45° (90° = 2 × 45°, 60° = 45° + 15° — поворот К1-б в бане)."""
    if ang < 7.5:
        return []
    best = None
    for n45 in range(5):
        for n30 in range(3):
            for n15 in range(3):
                s = 45 * n45 + 30 * n30 + 15 * n15
                if s:
                    key = (abs(s - ang) > 7.5, n45 + n30 + n15, -n45, abs(s - ang))
                    if best is None or key < best[0]:
                        best = (key, [45] * n45 + [30] * n30 + [15] * n15)
    return best[1]


def sewer_fittings():
    """К1: отводы 45°/30°/15° — повороты внутри трубы и в стыках двух труб (низ подъёмов от приборов, низ стояков);
    тройники косые — конец трубы на другой трубе К1 (по оси или на стенке трубы, как УМ-б1 на выпуске УН-б1)."""
    grp = pipes(SEWER)
    # ключи: (Ø, малошумная, угол) и (Ø магистрали, Ø отвода, малошумная, вид): вид '' — косой 45°, 'v' — на
    # вертикальной трубе (прямой 87,5°: отвод из пола в вывод прочистки Ст.К1-2), 'x' — косая крестовина 45°
    bends, tees = Counter(), Counter()
    for p in grp:
        for a, b, c in zip(p.pts, p.pts[1:], p.pts[2:]):
            for deg in split_bend(angle(vec(a, b), vec(b, c))):
                bends[(p.dn, p.quiet, deg)] += 1
        for e in (p.pts[0], p.pts[-1]):
            q = on_other(e, p, grp)
            if q is not None and q.id == 'Ст.К1-б':
                continue                                      # низ Ст.К1-б — двухплоскостная крестовина (своя строка)
            if q is not None and not any(math.dist(e, t) < 2e-3 for t in (q.pts[0], q.pts[-1])):
                seg = next((a, b) for a, b in zip(q.pts, q.pts[1:]) if VK.point_on_seg(e, a, b, tol=2e-3))
                tees[(q.dn, p.dn, q.quiet, 'v' if is_vert(*seg) and not q.quiet else '')] += 1
            elif q is None:
                for q in grp:                                 # на стенке трубы большего Ø, вдали от её концов
                    if q is not p and q.dn > p.dn and min(math.dist(e, t) for t in (q.pts[0], q.pts[-1])) > 0.10 \
                            and any(VK.point_on_seg(e, a, b, tol=q.od / 2 + 0.01) for a, b in zip(q.pts, q.pts[1:])):
                        tees[(q.dn, p.dn, q.quiet, '')] += 1
                        break
    ends = [(p, k) for p in grp for k in (0, -1)]
    nodes = []                                                # узлы, где сходятся 3 и более концов труб
    for p, k in ends:
        e = p.pts[k]
        for nd in nodes:
            if math.dist(nd[0], e) < 2e-3:
                nd[1].append(p)
                break
        else:
            nodes.append([e, [p]])
    for e, ps in nodes:                                       # четыре конца в одной точке — косая крестовина
        if len(ps) >= 4:
            dn = sorted(q.dn for q in ps)
            tees[(dn[-1], dn[0], any(q.quiet for q in ps), 'x')] += 1
    for i, (p, kp) in enumerate(ends):                        # стыки ровно двух концов труб — отводы
        e = p.pts[kp]
        near = [(q, kq) for q, kq in ends if q is not p and math.dist(q.pts[kq], e) < 2e-3]
        if len(near) != 1 or ends.index(near[0]) < i or on_other(e, p, [x for x in grp if x is not near[0][0]]):
            continue
        q, kq = near[0]
        away = [vec(x.pts[k], x.pts[1 if k == 0 else -2]) for x, k in ((p, kp), (q, kq))]
        own = q if q.where == 'ground' and p.where != 'ground' else p
        for deg in split_bend(180.0 - angle(*away)):
            bends[(own.dn, own.quiet, deg)] += 1
    return bends, tees


def water_ends():
    """PE-Xa: концы труб. На коллекторах — фитинги «евроконус», у приборов и оборудования — переходники на резьбу
    (водорозетки), на другой трубе — тройники."""
    grp = [p for p in VK.PIPES if p.sys in WATER and p.mat == 'pex']
    coll = Counter()
    free = Counter()
    tee = Counter()
    for p in grp:
        if p.id in COLL_IDS:
            continue
        for e in (p.pts[0], p.pts[-1]):
            q = on_other(e, p, grp)
            at_end = q is not None and any(math.dist(e, t) < 2e-3 for t in (q.pts[0], q.pts[-1]))
            if q is None or (q.id in COLL_IDS and (at_end or q.id == 'КХ')):
                free[p.dn] += 1                       # прибор, оборудование, вход/торец коллектора, выход гребёнки
            elif q.id in COLL_IDS:
                coll[p.dn] += 1                       # выход коллектора ¾" «евроконус»
            elif not at_end:
                tee[(q.dn, p.dn)] += 1
    return coll, free, tee


def floor_turns():
    """Фиксаторы поворота 90°: вертикальные участки PE-Xa, пересекающие чистый пол (1 этаж, баня, 2 этаж)."""
    n = Counter()
    for p in pipes(WATER, ('pex',)):
        for a, b in zip(p.pts, p.pts[1:]):
            if not is_vert(a, b):
                continue
            lo, hi = sorted((a[2], b[2]))
            for fl in ((0.0,) if p.bld == 'b' else (0.0, VK.FL2)):
                if lo < fl - 0.01 and hi > fl + 0.01:
                    n[p.dn] += 1
    return n


def wall_rise():
    """Вертикальные участки PE-Xa над чистым полом (в штрабах, инсталляциях и у шкафов) — длина гофры, м."""
    L = Counter()
    for p in pipes(WATER, ('pex',)):
        if p.where in ('ceil',):
            continue
        for a, b in zip(p.pts, p.pts[1:]):
            if is_vert(a, b):
                lo, hi = sorted((a[2], b[2]))
                fl = VK.FL2 if lo > 3.0 else 0.0
                if hi > fl:
                    L[(p.sys == 'В1', p.dn)] += hi - max(lo, fl)
    return L


def slab_passes():
    """Проходы вертикальных участков сквозь плиты: (тип трубы, размер) -> шт."""
    out = Counter()
    where = defaultdict(set)
    for p in VK.PIPES:
        if p.id in COLL_IDS or p.id == 'Ст.К1-2':
            continue
        for a, b in zip(p.pts, p.pts[1:]):
            if not is_vert(a, b):
                continue
            if p.bld == 'h' and min(math.dist(a[:2], q) for q in FUT) < 0.05:
                continue                                        # подъём ввода и опуск КХ-8 — в футлярах Ø75
            lo, hi = sorted((a[2], b[2]))
            for nm, (z0, z1) in SLABS[p.bld].items():
                if lo < z0 + 1e-3 and hi > z1 - 1e-3:
                    out[(p.mat, p.dn, p.sys)] += 1
                    where[(p.mat, p.dn, p.sys)].add(nm)
    return out, where


def sleeve_for(mat, dn, sysk):
    """Гильза по таблице листа 14 (наружный Ø трубы с изоляцией)."""
    if mat == 'sml':
        return 160
    if mat in ('pp', 'ppn'):
        return {32: 50, 50: 75, 110: 160}[dn]
    od = PEX_D.get(dn, 32) + 2 * (13 if sysk in ('Т3', 'Т4') else 9)
    return 50 if od <= 38 else 75


def supports():
    """Крепления: PE-Xa под потолком и по стенам — хомуты (лист 14), в полу — скобы; К1 — хомуты 10d, стояки 2 м."""
    clamp, staple = Counter(), Counter()
    for p in pipes(WATER, ('pex',)):
        L = p.length()
        if p.where == '':                                     # трасса без признака: участки в пазах пола — скобы
            lf = sum(math.dist(a, b) for a, b in zip(p.pts, p.pts[1:]) if not is_vert(a, b) and
                     abs(a[2] - b[2]) < 1e-6 and (-0.26 < a[2] < -0.14 or VK.FL2 - 0.12 < a[2] < VK.FL2))
            if lf > 0.05:
                staple[p.dn] += math.ceil(lf / 0.5) + 1
            if L - lf > 0.05:
                clamp[('pex', p.dn)] += math.ceil((L - lf) / FIX_STEP[p.dn]) + 1
        elif p.where in ('ceil', 'wall'):
            clamp[('pex', p.dn)] += math.ceil(L / FIX_STEP[p.dn]) + 1
        elif p.where == 'floor':
            staple[p.dn] += math.ceil(L / 0.5) + 1
    for p in pipes(SEWER):
        if p.where == 'ground':
            continue
        horiz = sum(math.dist(a, b) for a, b in zip(p.pts, p.pts[1:]) if not is_vert(a, b))
        vert = p.length() - horiz
        n = (math.ceil(horiz / (10 * p.dn / 1000)) if horiz > 0.05 else 0) + (math.ceil(vert / 2.0) if vert > 0.05 else 0)
        clamp[('pp', p.dn)] += max(1, n)
    return clamp, staple


def lengths():
    L = defaultdict(float)
    for p in VK.PIPES:
        if p.id in COLL_IDS or p.id == 'Ст.К1-2':                 # вывод прочистки — в L_CLEAN
            continue
        if p.mat == 'sml':                                      # водостоки К2 — отдельный раздел (k2_sml)
            L[('sml', p.dn, p.where)] += p.length()
            continue
        if p.sys == 'К2':
            L[('k2', p.dn, True)] += p.length()
            continue
        L[(p.mat, p.dn, 'q' if p.quiet else (p.sys if p.mat == 'pex' else (p.where == 'ground')))] += p.length()
    r = vv_rise()                                   # подъём ввода в футляре — ПЭ 32, не PE-Xa
    L[('pe', '32×3,0', True)] += r
    L[('pex', '32×4,4', 'В1')] -= r
    return L


def k2_sml():
    """Водостоки К2 (SML DN100, лист 15): длины, отводы, соединения и крепления — по линиям «стояк + выпуск»."""
    st = {p.id[len('Ст.К2-'):]: p for p in K2L if p.id.startswith('Ст.К2-')}
    out = {p.id[len('К2-ДК'):]: p for p in K2L if p.id.startswith('К2-ДК')}
    assert len(st) == len(out) == len(VK.K2_STACKS) == len(REVS_K2), (len(st), len(out), len(REVS_K2))
    r = dict(n=len(st), bends=0, turn=[], joints=0, clamps=0, rooms=[], L_ins=0.0,
             L_st=sum(p.length() for p in st.values()), L_out=sum(p.length() for p in out.values()),
             main=sum(1 for *_, rf, _p, _d, _r in VK.K2_STACKS if rf == 'main'))
    for n, xy, rf, path, d, room in VK.K2_STACKS:
        s, o = st[n], out[n]
        turns = len(path) - 1                              # повороты выпуска в плане (ДК-5, ДК-7)
        b = 2 + 2 * turns                                  # низ стояка — 2 × 45°, каждый поворот в плане — 2 × 45°
        pieces = math.ceil((s.pts[0][2] - 1.00) / 3.0) + math.ceil((1.00 - s.pts[-1][2]) / 3.0) + len(path)
        r['joints'] += pieces + 1 + b - 1                  # трубы по 3 м, ревизия +1,000 и отводы — подряд
        r['clamps'] += math.ceil(s.length() / 2.0) + 1     # не реже чем через 2 м и у отводов
        r['bends'] += b
        if turns:
            r['turn'].append(f'ДК-{n}')
        r['rooms'].append(room)
        if room != '1.12':                                 # Ст.К2-8 — в стене террасы 1.12 (не отапливается)
            r['L_ins'] += s.length() + o.length()
    return r


