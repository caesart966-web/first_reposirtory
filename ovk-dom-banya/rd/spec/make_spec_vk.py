def sleeves75():
    """Футляры Ø75: (длина по оси с отводами R, число отводов) для ввода и КХ-8 — по трассам модели."""
    vv, k8 = pid('ВВ'), pid('КХ-8')
    out = {}
    for nm, pts in (('ввод В1', [(vv.pts[0][0] + FUT_OUT,) + vv.pts[0][1:], vv.pts[-1], (VK.X_VV, VK.Y_SW, FUT_TOP)]),
                    ('КХ-8', [(VK.X_AP, VK.Y_AP_DROP, FUT_TOP)] + list(k8.pts[3:-1]) +
                     [(k8.pts[-1][0] + FUT_OUT,) + k8.pts[-1][1:]])):
        L, nb = sum(math.dist(a, b) for a, b in zip(pts, pts[1:])), 0
        for a, b, c in zip(pts, pts[1:], pts[2:]):
            t = math.radians(angle(vec(a, b), vec(b, c)))
            if t > 0.1:
                L -= 2 * FUT_R * math.tan(t / 2) - FUT_R * t        # скругление отводом
                nb += 1
        out[nm] = (L, nb)
    return out


def cab_size(cid):
    """Размер шкафа по модели: ширина × высота, мм (до 10 мм); глубина ниши — 120 мм у всех (ТЗ-1)."""
    b = next(e for e in VK.EQUIP if e.id == cid).bbox()
    dx, dy, dz = (round((b[k + 3] - b[k]) * 100) * 10 for k in range(3))
    return f'≈{max(dx, dy)}×{dz}×120'


def pipes(sys_=None, mats=None):
    return [p for p in VK.PIPES if p.id not in COLL_IDS and (sys_ is None or p.sys in sys_)
            and (mats is None or p.mat in mats)]


def vec(a, b):
    return [b[k] - a[k] for k in range(3)]


def angle(u, v):
    lu, lv = math.sqrt(sum(x * x for x in u)), math.sqrt(sum(x * x for x in v))
    if lu < 1e-6 or lv < 1e-6:
        return 0.0
    c = max(-1.0, min(1.0, sum(u[k] * v[k] for k in range(3)) / lu / lv))
    return math.degrees(math.acos(c))


def is_vert(a, b):
    return abs(a[0] - b[0]) < 1e-6 and abs(a[1] - b[1]) < 1e-6 and abs(a[2] - b[2]) > 1e-6


def on_other(pt, me, group):
    """Точка лежит на другой трубе группы (не в её конце-начале совпадающем с нашим концом — тоже считается)."""
    for q in group:
        if q is me:
            continue
        for a, b in zip(q.pts, q.pts[1:]):
            if VK.point_on_seg(pt, a, b, tol=2e-3):
                return q
    return None


