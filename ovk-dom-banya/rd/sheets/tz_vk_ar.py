def bubble(p, at, n, off=(0.9, 0.9), layer='ТЗ_ВК'):
    """Номер позиции в кружке рядом с точкой, с выноской."""
    r = p.H(2.3) / p.unit
    c = (at[0] + off[0], at[1] + off[1])
    L = math.hypot(off[0], off[1])
    p.pl([at, (c[0] - off[0] / L * r, c[1] - off[1] / L * r)], 'ОВ_выноски')
    p.wipe(c[0] - r, c[1] - r, c[0] + r, c[1] + r)
    p.circle(c[0], c[1], 0, layer, r_paper=2.3)
    p.t(c[0], c[1], str(n), 2.2, 'center', layer)


def sleeves(p, M, numbered=False):
    for i, d in enumerate(M, 1):
        lay = 'ТЗ_ВК_К' if d['sys'].startswith('К') else 'ТЗ_ВК'
        if d['n'] > 1:
            p.rect(d['x0'], d['y0'], d['x1'], d['y1'], lay)
        else:
            p.circle(d['x'], d['y'], 0, lay, r_paper=0.9)
        if numbered:
            p.t(d['x1'] + 0.03 if d['n'] > 1 else d['x'] + 0.07, d['y'] + 0.07, str(i), 1.5, 'bl', 'ТЗ_ВК')


def oblock(p, x, y, layer='ТЗ_ВК_К'):
    """О-блок с отверстием Ø160 (условно — квадрат 0,30 с кружком)."""
    p.rect(x - 0.15, y - 0.15, x + 0.15, y + 0.15, layer)
    p.circle(x, y, 0.08, layer)


def wsl(p, M, n, off=(0.8, 0.8)):
    for d in M:
        for x, y, *_ in d['g']:
            m_vk(p, x, y)
    for c in cluster([(d['x'], d['y']) for d in M], 1.2):
        bubble(p, c[0][:2], n, off=off)


