def bubble(p, at, n, off=(0.9, 0.9), layer='ТЗ_ВК'):
    """Номер позиции в кружке рядом с точкой, с выноской."""
    r = p.H(2.3) / p.unit
    c = (at[0] + off[0], at[1] + off[1])
    L = math.hypot(off[0], off[1])
    p.pl([at, (c[0] - off[0] / L * r, c[1] - off[1] / L * r)], 'ОВ_выноски')
    p.wipe(c[0] - r, c[1] - r, c[0] + r, c[1] + r)
    p.circle(c[0], c[1], 0, layer, r_paper=2.3)
    p.t(c[0], c[1], str(n), 2.2, 'center', layer)


def sleeves(p, L, start=1, numbered=False):
    for i, (x, y, d, s, l) in enumerate(L, start):
        p.circle(x, y, 0, 'ТЗ_ВК_К' if s.startswith('К') else 'ТЗ_ВК', r_paper=0.9)
        if numbered:
            p.t(x + 0.07, y + 0.07, str(i), 1.5, 'bl', 'ТЗ_ВК')


