def _short(l):
    return l[6:].split('×')[0] if l.startswith('PE-Xa ') else l


def _c10(v):
    return int(math.ceil(round(v * 1000) / 10.0) * 10)


def merge(L, wall=False):
    """Гильзы, которые при своём диаметре задевали бы соседние (зазор менее 10 мм), — одним проёмом под пучок.
    Вход: (x, y, Ø, система, труба[, отм. оси]); выход: словари x, y, size, pipes, n, z."""
    n = len(L)
    par = list(range(n))

    def f(i):
        while par[i] != i:
            par[i] = par[par[i]]
            i = par[i]
        return i
    for i in range(n):
        for j in range(i + 1, n):
            a, b = L[i], L[j]
            dz = abs(a[5] - b[5]) if wall else 0.0
            if math.dist(a[:2], b[:2]) < (a[2] + b[2]) / 2000 + 0.01 and dz < 0.15:
                par[f(i)] = f(j)
    groups = {}
    for i in range(n):
        groups.setdefault(f(i), []).append(L[i])
    out = []
    for g in groups.values():
        xs, ys = [t[0] for t in g], [t[1] for t in g]
        zs = [t[5] for t in g] if wall else [0.0]
        if len(g) == 1:
            size = f'Ø{g[0][2]}'
        else:
            dm = max(t[2] for t in g) / 1000
            if wall:
                w = max(max(xs) - min(xs), max(ys) - min(ys)) + dm + 0.04
                h = max(zs) - min(zs) + dm + 0.04
            else:
                w, h = max(xs) - min(xs) + dm + 0.04, max(ys) - min(ys) + dm + 0.04
            size = f'проём {_c10(w)}×{_c10(h)}'
        out.append(dict(x=sum(xs) / len(g), y=sum(ys) / len(g), size=size, n=len(g), g=g, sys=g[0][3],
                        pipes=', '.join(f'{t[3]} {_short(t[4])}' for t in g), z=(min(zs), max(zs)),
                        x0=min(xs) - max(t[2] for t in g) / 2000 - 0.02, x1=max(xs) + max(t[2] for t in g) / 2000 + 0.02,
                        y0=min(ys) - max(t[2] for t in g) / 2000 - 0.02, y1=max(ys) + max(t[2] for t in g) / 2000 + 0.02))
    return sorted(out, key=lambda d: (round(d['x'], 1), d['y']))


