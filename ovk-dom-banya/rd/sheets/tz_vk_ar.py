def sleeve(p):
    if p.mat in ('pp', 'ppn'):
        return {32: 50, 50: 75, 110: 160}[p.dn]
    d = {'16×2,2': 16, '20×2,8': 20, '25×3,5': 25, '32×4,4': 32}[p.dn] + 2 * (13 if p.sys in ('Т3', 'Т4') else 9)
    return 50 if d <= 38 else 75


def passes(bld, z0, z1):
    """Гильзы: вертикальные участки труб, проходящие плиту z0…z1 целиком."""
    out = []
    for p in VK.PIPES:
        if p.bld != bld or p.id in COLL_IDS:
            continue
        for a, b in zip(p.pts, p.pts[1:]):
            if abs(a[0] - b[0]) < 1e-6 and abs(a[1] - b[1]) < 1e-6:
                lo, hi = sorted((a[2], b[2]))
                if lo < z0 + 1e-3 and hi > z1 - 1e-3:
                    out.append((a[0], a[1], sleeve(p), p.sys, p.label()))
    return out


