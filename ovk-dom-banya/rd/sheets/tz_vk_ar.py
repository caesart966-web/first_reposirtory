def cross_y(p, y0):
    """Первое пересечение трассы трубы с линией y = y0: (x, y0, ось)."""
    for a, b in zip(p.pts, p.pts[1:]):
        if (a[1] - y0) * (b[1] - y0) < 0:
            t = (y0 - a[1]) / (b[1] - a[1])
            return (a[0] + (b[0] - a[0]) * t, y0, a[2] + (b[2] - a[2]) * t)
    raise ValueError(f'{p.id}: нет пересечения с y = {y0}')


