def split_rows(data, heights):
    """Делит строки таблицы на два листа так, чтобы каждая часть уместилась между Y_TOP и Y_BOT."""
    room = Y_TOP - Y_BOT - heights[0]
    acc, cut = 0.0, len(data)
    for i, hh in enumerate(heights[1:], 1):
        acc += hh
        if acc > room:
            cut = i
            break
    return cut


