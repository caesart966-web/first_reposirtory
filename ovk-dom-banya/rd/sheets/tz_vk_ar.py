def nlab(M):
    if not M:
        return 'нет'
    k = sum(1 for d in M if d['n'] > 1)
    return f'{len(M) - k} шт.' + (f' и {k} проём' + ('а' if 1 < k < 5 else 'ов' if k >= 5 else '') if k else '')


def cluster(L, d=1.0):
    out = []
    for q in L:
        for c in out:
            if math.dist(c[0][:2], q[:2]) <= d:
                c.append(q)
                break
        else:
            out.append([q])
    return out


def cnt(L):
    from collections import Counter
    c = Counter(t[2] for t in L)
    return ', '.join(f'Ø{k} — {v}' for k, v in sorted(c.items()))


