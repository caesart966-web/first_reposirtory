def wall_passes(bld, key, zlo, zhi, extra=()):
    """Проходы труб сквозь стены: группы пересечений с гранями A-WALL на одном отрезке трубы (≤ 0,45 м между
    гранями). Один проход — одна гильза. Выход из ниши шкафа или штробы на одной грани — канал ниши (в гофре)."""
    from ezdxf.math import Vec2, intersection_line_line_2d
    W = _wall_segs(key, extra)
    out = []
    for p in VK.PIPES:
        if p.bld != bld or p.id in COLL_IDS or p.id in TAP_PIPES or p.sys.startswith('К'):
            continue
        for a, b in zip(p.pts, p.pts[1:]):
            if not (zlo <= a[2] <= zhi and abs(a[2] - b[2]) < 0.05):
                continue
            A, B = Vec2(a[:2]), Vec2(b[:2])
            if (A - B).magnitude < 1e-6:
                continue
            hits = []
            for u, v in W:
                ip = intersection_line_line_2d((A, B), (u, v), virtual=False)
                if ip is not None and not _inside((ip.x, ip.y), SKIP[bld]):
                    hits.append(((ip - A).magnitude, ip))
            hits.sort(key=lambda h: h[0])
            groups = []
            for d, ip in hits:
                if groups and d - groups[-1][-1][0] <= 0.32:              # грани одной стены (толщина ≤ 0,30)
                    groups[-1].append((d, ip))
                elif not groups or d - groups[-1][-1][0] > 1e-3:
                    groups.append([(d, ip)])
            L = (A - B).magnitude
            for g in groups:
                if len(g) == 1:
                    d = g[0][0]
                    if min(d, L - d) < 0.10:                             # конец трубы у грани: подъём в штробе
                        continue                                         # или выход к смесителю
                    if any(_inside(q[:2], [nb]) and a[2] < nb[4] for q in (a, b) for nb in NICHES[bld]):
                        continue                                         # выход из ниши / штробы — канал в гофре
                x = sum(ip.x for _, ip in g) / len(g)
                y = sum(ip.y for _, ip in g) / len(g)
                out.append((round(x, 2), round(y, 2), sleeve(p), p.sys, p.label(), a[2]))
    return sorted(set(out), key=lambda t: (t[0], t[1]))


