def _wall_segs(key, extra=()):
    from ezdxf import recover
    from ezdxf.math import Vec2
    doc, _ = recover.readfile(UNDER[key])
    out = []

    def segs(e):
        t = e.dxftype()
        if t == 'LINE':
            yield e.dxf.start, e.dxf.end
        elif t == 'LWPOLYLINE':
            p = [Vec2(q[0], q[1]) for q in e.get_points()]
            if e.closed:
                p.append(p[0])
            yield from zip(p, p[1:])
        elif t == 'POLYLINE':
            p = [Vec2(v.dxf.location) for v in e.vertices]
            if e.is_closed:
                p.append(p[0])
            yield from zip(p, p[1:])
        elif t == 'INSERT':
            try:
                for v in e.virtual_entities():
                    yield from segs(v)
            except Exception:  # noqa: BLE001
                pass
    for e in doc.modelspace():
        if e.dxf.layer != 'A-WALL':
            continue
        for a, b in segs(e):
            a = Vec2((a[0] - OX) / 1000, (a[1] - OY) / 1000)
            b = Vec2((b[0] - OX) / 1000, (b[1] - OY) / 1000)
            if (a - b).magnitude > 0.05:
                out.append((a, b))
    return out + [(Vec2(a), Vec2(b)) for a, b in extra]


def _inside(q, boxes):
    return any(b[0] - 1e-3 <= q[0] <= b[2] + 1e-3 and b[1] - 1e-3 <= q[1] <= b[3] + 1e-3 for b in boxes)


def _nbox(eid, far):
    """Ниша шкафа на всю толщину стены: bbox шкафа, глубина — до дальней грани стены far."""
    b = E[eid].bbox()
    if abs(b[3] - b[0]) < abs(b[4] - b[1]):                       # ниша в стене вдоль y (глубина по x)
        return (min(b[0], far), b[1], max(b[3], far), b[4])
    return (b[0], min(b[1], far), b[3], max(b[4], far))


