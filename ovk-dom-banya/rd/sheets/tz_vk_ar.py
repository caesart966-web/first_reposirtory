def wall_cross(y0):
    """Трубы под потолком, пересекающие стену гараж/1.6 (линия y0)."""
    out = []
    for p in VK.PIPES:
        if p.bld != 'h' or p.id in COLL_IDS:
            continue
        for a, b in zip(p.pts, p.pts[1:]):
            if (a[1] - y0) * (b[1] - y0) < 0 and abs(a[2] - b[2]) < 1e-6 and a[2] > 2.5:
                t = (y0 - a[1]) / (b[1] - a[1])
                out.append((a[0] + (b[0] - a[0]) * t, y0, sleeve(p), p.sys, p.label()))
    return out


