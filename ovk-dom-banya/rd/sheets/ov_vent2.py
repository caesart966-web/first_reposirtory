"""И05.09.26-ОВ, лист 10. План 2 этажа. Вентиляция и кондиционирование.

python3 sheets/ov_vent2.py  ->  out/ov_vent2.dxf + out/ov_vent2_Лист.pdf
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import ov_vent1 as v1                                                    # noqa: E402
from ov_vent1 import (new_doc, DPlan, RDSheet, add_underlay, insert_underlay, UNDER, SHEET_LIST,  # noqa: E402
                      SHEETS_TOTAL, axes, VS, VE, AC, sec_d, sec_L, SH1, SH2, SH2_CH, SH2_X, SH2_CX, SH2_SQ, RIS_P, RIS_V,
                      RIS_F, RIS_P27, KU2, draw_net, wall_grille, ceil_grille, ku, riser, freon, drain, zone,
                      mask, legend, L_duct, L_grille, L_wgrille, L_ku, L_freon, L_drain, L_riser, L_shaft,
                      L_zone, save_sheet, DUCT_LAYER, LAYERS, vz_riser, VZ_RISER)

SHEET_NO = 10
YM = 7.60          # ось магистрали П в подшивке галереи/холла
YR = 7.36          # ось воздуховодов возврата блоков К

# ---------------------------------------------------------------- сеть 2 этажа
NET2 = [
    ('2эт-зап', 'П', [RIS_P, (12.15, 9.25), (12.15, YM), (11.85, YM)], sec_d(VS, '2эт-зап'), sec_L(VS, '2эт-зап')),
    ('2.5 (ЩП)', 'П', [(11.85, YM), (11.85, 6.58)], sec_d(VS, '2.5 (ЩП)'), sec_L(VS, '2.5 (ЩП)')),
    ('2эт-11.7', 'П', [(11.85, YM), (8.15, YM)], sec_d(VS, '2эт-11.7'), sec_L(VS, '2эт-11.7')),
    ('2.4 (ЩП)', 'П', [(8.15, YM), (8.15, 6.58)], sec_d(VS, '2.4 (ЩП)'), sec_L(VS, '2.4 (ЩП)')),
    ('2эт-7.9', 'П', [(8.15, YM), (3.90, YM)], sec_d(VS, '2эт-7.9'), sec_L(VS, '2эт-7.9')),
    ('2эт-3.9', 'П', [(3.90, YM), (0.45, YM), (0.45, 6.58)], sec_d(VS, '2эт-3.9'), sec_L(VS, '2эт-3.9')),
    ('2.7 (ЩП)', 'П', [RIS_P27, (13.80, 9.88)], sec_d(VS, '2.7 (ЩП)'), sec_L(VS, '2.7 (ЩП)')),
    # вытяжка (по ходу воздуха к стояку)
    ('2-юг-в', 'В', [(18.00, 8.25), (13.75, 8.25)], sec_d(VE, '2-юг-в'), sec_L(VE, '2-юг-в')),
    ('2-юг', 'В', [(13.75, 8.25), (13.35, 8.25), RIS_V], sec_d(VE, '2-юг'), sec_L(VE, '2-юг')),
    ('2.6', 'В', [(13.35, 10.80), (13.35, 10.25)], sec_d(VE, '2.6'), sec_L(VE, '2.6')),
    ('2-сев', 'В', [(13.35, 10.25), RIS_V], sec_d(VE, '2-сев'), sec_L(VE, '2-сев')),
    ('2.1', 'В', [(11.00, 9.80), (11.00, 10.25)], sec_d(VE, '2.1'), sec_L(VE, '2.1')),
    ('2-зап', 'В', [(11.00, 10.25), (13.35, 10.25)], sec_d(VE, '2-зап'), sec_L(VE, '2-зап')),
    ('2-зап-2', 'В', [(9.75, 11.20), (9.90, 11.20), (9.90, 10.25), (11.00, 10.25)], sec_d(VE, '2-зап-2'),
     sec_L(VE, '2-зап-2')),
]

# щелевые решётки в стенах: (имя, центр x, y стены, ЩП/ЩВ, блок)
SLOTS = [('ЩП', 1.00, 'К-4'), ('ЩВ', 3.15, 'К-4'), ('ЩП', 7.60, 'К-5'), ('ЩВ', 5.00, 'К-5'),
         ('ЩП', 11.40, 'К-6'), ('ЩВ', 9.45, 'К-6')]
Y_WALL = 6.30      # ось стены спален со стороны галереи/холла (стена 6.15–6.46)

ZONES2 = [
    ([(12.70, 9.45), (13.90, 9.45), (13.90, 9.05), (15.60, 9.05), (15.60, 12.00), (14.90, 12.00), (14.90, 13.60),
      (12.70, 13.60)], 'П-6', 400, '+7,150', 'К-7, стояки из Ш-1, П Ø160, В Ø200/Ø160, фреон, дренаж'),
    ([(9.50, 6.46), (12.40, 6.46), (12.40, 11.00), (10.30, 11.00), (10.30, 11.40), (9.50, 11.40)], 'П-7', 350,
     '+7,200', 'К-6, П Ø160, В Ø160, фреон, дренаж'),
    ([(0.25, 6.46), (9.50, 6.46), (9.50, 7.90), (0.25, 7.90)], 'П-8', 400, '+7,150',
     'К-4, К-5, П Ø160…Ø100, возврат К, фреон, дренаж'),
    ([(12.70, 6.46), (19.80, 6.46), (19.80, 8.76), (12.70, 8.76)], 'П-9', 250, 'по АР',
     'В Ø160/Ø125 санузлов (низ подшивки — по АР, не ниже глубины 250)'),
]


def build():
    doc = new_doc()
    blk = add_underlay(doc, UNDER['plan2'], 'АР_План_2_этажа')
    insert_underlay(doc.modelspace(), blk)
    p = DPlan(doc, k=100)
    axes(p, y_bub=-2.4, x_bub=-2.4)

    ZPOS = {'П-6': (12.80, 13.30), 'П-7': (9.45, 6.66), 'П-8': (5.40, 7.12), 'П-9': (16.20, 6.62)}
    for pts, lab, dep, low, what in ZONES2:
        zone(p, pts, lab, dep, low, *ZPOS[lab])

    # Ш-1 со стояками, Ш-2 с каналами
    p.shaft(*SH1)
    mask(p, SH1[0] + 0.02, SH1[1] + 0.02, SH1[2] - 0.02, SH1[3] - 0.02)
    p.rect(*SH1, 'ОВ_шахты', lw=35)
    riser(p, RIS_P, 'П', 200)
    riser(p, RIS_V, 'В', 200)
    riser(p, RIS_P27, 'П', 100)
    p.circle(RIS_F[0], RIS_F[1], 0.05, 'ОВ_Фреон')
    mask(p, *SH2)
    p.shaft(*SH2)
    p.rect(SH2_X - 0.20, SH2_SQ[0], SH2_X + 0.20, SH2_SQ[1], 'ОВ_шахты', lw=25)
    for yc, d, n in SH2_CH:
        p.circle(SH2_CX[n], yc, d / 2000.0, 'ОВ_шахты', lw=25)
        if n == 'Дп':
            p.circle(SH2_CX[n], yc, 0.10, 'ОВ_шахты', lw=18)

    draw_net(p, NET2, labels={
        '2эт-зап': (1, 0.5, 1), '2эт-11.7': (1, 0.5, None), '2эт-7.9': (1, 0.6, None), '2эт-3.9': (1, 0.55, 0),
        '2-юг-в': (-1, 0.5, None), '2-юг': (1, 0.42, 1), '2-сев': (-1, 0.78, None), '2-зап': (1, 0.55, None),
        '2-зап-2': (-1, 0.5, 1),
    }, skip_labels=('2.5 (ЩП)', '2.4 (ЩП)', '2.7 (ЩП)', '2.6', '2.1', '2-юг', '2-сев'))
    p.t(13.50, 8.85, 'Ø160', 1.8, 'center', 'ОВ_В', rot=90)

    # решётки
    ceil_grille(p, 3.90, YM, 'П', 30, txt=(0.30, -0.25), name='2.2')
    ceil_grille(p, 13.75, 8.25, 'В', 75, txt=(0.0, -0.40), al='center')
    ceil_grille(p, 18.00, 8.25, 'В', 75, txt=(0.0, -0.40), al='center')
    ceil_grille(p, 13.35, 10.85, 'В', 60, txt=(-0.28, 0.0), al='right')
    ceil_grille(p, 11.00, 9.80, 'В', 90, txt=(0.0, -0.40), al='center')
    wall_grille(p, 9.62, 11.20, 'В', 120, 'left', txt_off=(-0.40, 0.42))
    p.label(4.3, 12.35, 'Решётка в стене, верх 2-го света, низ +6,400', 1.9, at=(9.60, 11.20))

    # блоки К-4…К-6: напорная камера к ЩП, возврат от ЩВ, ЩП/ЩВ в стене со стороны галереи/холла
    for n in ('К-4', 'К-5', 'К-6'):
        ku(p, n, KU2[n])
    for kind, xc, n in SLOTS:
        lay = 'ОВ_П' if kind == 'ЩП' else 'ОВ_Рец'
        p.rect(xc - 0.40, Y_WALL - 0.07, xc + 0.40, Y_WALL + 0.07, lay, fill=LAYERS[lay][0])
        x0, y0, x1, y1 = KU2[n]
        s = p.H(2.6) / p.unit
        if kind == 'ЩП':
            p.rect(xc - 0.40, 6.46, xc + 0.40, y0, 'ОВ_Рец')            # камера блок -> щель
            for xx in (xc - 0.2, xc + 0.2):
                p.arrow(xx, Y_WALL - 0.07, xx, Y_WALL - 0.07 - s, 'ОВ_П', size=1.5)
            p.t(xc, Y_WALL - 0.07 - s - 0.18, 'ЩП 800×150', 1.8, 'center', 'ОВ_П')
        else:
            p.duct([(xc, 6.50), (xc, v1.KU2[n][3] + 0.12), ((x0 + x1) / 2, v1.KU2[n][3] + 0.12)], (250, 150), 'Р')
            for xx in (xc - 0.2, xc + 0.2):
                p.arrow(xx, Y_WALL - 0.07 - s, xx, Y_WALL - 0.07, 'ОВ_Рец', size=1.5)
            p.t(xc, Y_WALL - 0.07 - s - 0.18, 'ЩВ 800×150', 1.8, 'center', 'ОВ_Рец')

    # К-7 (гардеробная 2.6) обслуживает спальню 2.7: ЩП и ЩВ в стене 2.6/2.7
    ku(p, 'К-7', KU2['К-7'])
    p.duct([(14.52, 11.75), (15.55, 11.75)], (250, 150), 'Р')
    p.duct([(15.55, 10.00), (13.80, 10.00), (13.80, 11.75), (13.90, 11.75)], (250, 150), 'Р')
    for (yc, kind) in ((11.75, 'ЩП'), (10.00, 'ЩВ')):
        lay = 'ОВ_П' if kind == 'ЩП' else 'ОВ_Рец'
        p.rect(15.63, yc - 0.40, 15.77, yc + 0.40, lay, fill=LAYERS[lay][0])
        s = p.H(2.6) / p.unit
        for yy in (yc - 0.2, yc + 0.2):
            if kind == 'ЩП':
                p.arrow(15.77, yy, 15.77 + s, yy, 'ОВ_П', size=1.5)
            else:
                p.arrow(15.77 + s, yy, 15.77, yy, 'ОВ_Рец', size=1.5)
        p.t(15.77 + s + 0.12, yc, f'{kind} 800×150', 1.8, 'left', lay)

    # фреон и дренаж
    freon(p, [RIS_F, (13.60, 9.70), (12.30, 9.70), (12.30, 7.78), (1.00, 7.78)])
    freon(p, [(13.60, 9.70), (13.60, 11.55), (13.90, 11.55)])
    for n in ('К-4', 'К-5', 'К-6'):
        x0, y0, x1, y1 = KU2[n]
        freon(p, [((x0 + x1) / 2 + 0.15, 7.78), ((x0 + x1) / 2 + 0.15, y1)])
        drain(p, [((x0 + x1) / 2 - 0.15, y1), ((x0 + x1) / 2 - 0.15, 7.85)])
    drain(p, [(0.85, 7.85), (12.55, 7.85), (12.95, 8.35)])
    drain(p, [(14.25, 11.40), (14.25, 9.30), (14.25, 8.60)])

    # марки и подписи
    p.label(0.4, 9.20, 'К-4, К-5, К-6 — Daikin FXDQ, 2,8 кВт', 1.9, at=(1.00, 7.10))
    for n in ('К-5', 'К-6'):
        x0, y0, x1, y1 = KU2[n]
        p.pl([(1.9, 9.20), ((x0 + x1) / 2, 7.10)], 'ОВ_выноски')
        p.dot((x0 + x1) / 2, 7.10)
    p.label(16.0, 13.05, 'К-7 — Daikin FXDQ, 2,8 кВт (для 2.7)', 1.9, at=(14.21, 11.95))
    p.label(16.35, 9.30, 'Ш-1: стояки П, В Ø200, П Ø100, фреон', 1.8, at=(13.90, 9.30))
    p.label(16.0, 15.85, 'Ш-2: Дг, Дп, выброс П1, В2 (лист 9, задание АР)', 1.8, at=(15.36, 13.30))
    # ВЗ — транзит через шахту над мангалом террасы 1.12 (эскиз Заказчика 19.10.2026)
    vz_riser(p, label=False)
    p.label(10.0, 16.05, 'Ст. ВЗ Ø200 в изоляции', 1.8, at=VZ_RISER, lines='транзит, выброс выше кровли',
            mask=True)
    p.label(4.5, 8.65, 'Дренаж блоков К — в сифон за инсталляцией унитаза 2.9 (ВК)', 1.8, at=(12.95, 8.35))
    p.label(16.2, 9.45 - 0.9, 'Дренаж К-7 — в сифон у ванны 2.9 (ВК)', 1.8, at=(14.25, 8.75))

    def tg(x, y, lines, anchor=None):
        p.tag(x, y, lines, anchor=anchor, h=2.0)

    tg(0.5, 5.4, ['2.3  П 60 (ЩП)', 'К-4'])
    tg(4.55, 5.4, ['2.4  П 60 (ЩП)', 'К-5'])
    tg(8.65, 5.4, ['2.5  П 60 (ЩП)', 'К-6'])
    tg(16.6, 10.95, ['2.7  П 60 (ЩП)', 'К-7'])
    tg(13.1, 12.95, ['2.6  В 60'])
    tg(0.5, 11.0, ['2.1  В 90, верх 2-го света В 120', '2.2  П 30'])
    tg(16.6, 7.55, ['2.8  В 75'])
    tg(12.85, 6.95 + 0.0, ['2.9  В 75'])

    # ---------------------------------------------------------------- лист
    sh = RDSheet(doc, 'Лист', SHEET_LIST[SHEET_NO], SHEET_NO, SHEETS_TOTAL)
    sh.viewport(152, 179, 258, 218, 9.4, 7.4, k=100)
    sh.title(152, 289.5, 'План 2 этажа. Вентиляция и кондиционирование. М 1:100')

    def L_slotS(pp, x, y):
        pp.rect(x + 2, y - 0.7, x + 12, y + 0.7, 'ОВ_П', fill=LAYERS['ОВ_П'][0])

    def L_slotR(pp, x, y):
        pp.rect(x + 2, y - 0.7, x + 12, y + 0.7, 'ОВ_Рец', fill=LAYERS['ОВ_Рец'][0])

    yb = legend(sh, 292, 290, [
        (L_duct('П'), 'Приточный воздуховод П1 (Ø, L — м³/ч)'),
        (L_duct('В'), 'Вытяжной воздуховод к П1'),
        (L_duct('Р'), 'Воздуховод блока К (напорная камера, возврат)'),
        (L_grille('П'), 'Потолочный диффузор (приток П1)'),
        (L_grille('В'), 'Потолочная решётка (вытяжка)'),
        (L_slotS, 'ЩП — щелевая решётка в стене: подача К + свежий воздух П1'),
        (L_slotR, 'ЩВ — щелевая решётка в стене: возврат (рециркуляция) К'),
        (L_wgrille('В'), 'Решётка в стене (вытяжка)'),
        (L_ku, 'Внутренний канальный блок мини-VRV'),
        (L_freon, 'Фреонопроводы (жидкость + газ)'),
        (L_drain, 'Дренаж конденсата'),
        (L_riser('П'), 'Стояк воздуховода в Ш-1'),
        (L_shaft, 'Шахта'),
        (L_zone, 'Зона подшивки потолка'),
    ], w=122)
    rows = [['Зона', 'Глуб., мм', 'Низ', 'Что проходит']]
    for pts, lab, dep, low, what in ZONES2:
        rows.append([lab, str(dep), low, what])
    yt = sh.table(292, yb - 1, [11, 12, 15, 84], rows, row_h=7.4, head_h=5.5, h=1.8,
                  aligns=['center', 'center', 'center', 'left'])
    sh.s.text('Зоны подшивки потолков 2 этажа', 292 + 61, yb + 1.6, h=2.2, align='center')
    sh.notes(292, yt - 4, 122, [
        'Подложка — АР09 (выгрузка из Revit 19.10.2026). Отметки — от ±0,000; пол 2 этажа +4,050, низ плиты '
        'покрытия +7,550. Подшивка — не ниже верха окон; к блокам К и клапанам — люки 600×600.',
        'Приток и вытяжка 2 этажа — от П1 (лист 9) стояками в шахте Ш-1 у южной стены гардеробной 2.6 '
        '(зона, указанная Заказчиком). Магистраль П — через стену Ш-1 в холл 2.1 и по галерее 2.2.',
        'Спальни 2.3–2.5, 2.7 — без подшивки (решение Заказчика): подача кондиционера вместе со свежим '
        'воздухом П1 — щелевой решёткой ЩП, возврат — ЩВ, обе в верхней зоне стены со стороны галереи, холла '
        'и гардеробной (низ решёток не ниже +6,950, над шкафами — с зазором до потолка не менее 300 мм). '
        'Свежий воздух П1 подаётся в напорную камеру ЩП круглый год; из спален воздух уходит перетеканием '
        'под дверью (зазор 15–20 мм — АР) и удаляется вытяжкой санузлов, гардеробной, холла и верха 2-го света.',
        'К-7 (гардеробная 2.6) обслуживает спальню 2.7: ЩП и ЩВ — в стене 2.6/2.7, ЩВ — над дверью; '
        'свежий воздух П1 (стояк Ø100) — в воздуховод возврата К-7.',
        'Блоки К — тонкие канальные Daikin серии FXDQ (типоразмер — по каталогу Daikin или аналог), '
        'обслуживание — снизу через люки. Дренаж — в канализацию через сифоны с сухим затвором (ВК), '
        'уклон не менее 0,01, иначе — помпа.',
        'Пересечения воздуховодов в подшивке П-6 — с обходом по высоте.',
    ], h=1.9)
    return doc


if __name__ == '__main__':
    doc = build()
    print(save_sheet(doc, 'ov_vent2'))
