def grilles_rows():
    """Строки таблицы подбора воздухораспределителей блоков К (лист 10): расходы, живое сечение, шум."""
    V_MAX = 2.0                                       # м/с в живом сечении (rd/calc_rd.py, кондиционирование)
    NOISE = {'2.3': 25, '2.4': 25, '2.5': 25, '2.7': 25}  # спальни и кабинет; остальные — 30 дБА

    def F(L):
        return fmt_num(L / 3600 / V_MAX, 3)
    rows = [['Блок', 'Пом.', 'Подача — воздухораспределитель', 'L, м³/ч', 'Возврат — решётка', 'L, м³/ч',
             'Живое сечение не менее, м² (подача / возврат)', 'Шум, дБА, не более']]
    for n, xs in (('К-1', (1.70, 2.70)), ('К-2', (5.40, 6.40)), ('К-3', (3.40, 4.50))):
        a = AC[n]['air']
        ln = round((xs[1] - xs[0]) * 1000)
        rows.append([n, AC[n]['room'], f'щелевой диффузор длиной {ln} мм в торце подшивки, через КСД', str(a),
                     'решётка-люк 600×600 под блоком', str(a), f'{F(a)} / {F(a)}', '30'])
    for n in ('К-4', 'К-5', 'К-6', 'К-7'):
        ls, lr = slot_L('ЩП', n), slot_L('ЩВ', n)
        fr = sec_L(VS, f"{AC[n]['room']} (ЩП)")
        where = 'в стене' if n == 'К-7' else 'в подшивке'
        sup = f'ЩП 800×150 {where}, через КСД' + (f' ({AC[n]["air"]} блок + {fr} П1)' if n != 'К-7' else '')
        ret = f'ЩВ 800×150 {where}, через КСД' + (f' (+{fr} П1 в возврат)' if n == 'К-7' else '')
        rows.append([n, AC[n]['room'], sup, str(ls), ret, str(lr), f'{F(ls)} / {F(lr)}',
                     str(NOISE.get(AC[n]['room'], 30))])
    return rows


def grilles_table(sh, x, y):
    rows = grilles_rows()
    sh.s.text('Воздухораспределители кондиционирования — данные для подбора', x + 82, y + 2.2, h=2.5,
              align='center')
    yb = sh.table(x, y, [10, 10, 45, 11, 38, 11, 24, 15], rows, row_h=6.0, head_h=8.6, h=1.8,
                  aligns=['center', 'center', 'left', 'center', 'left', 'center', 'center', 'center'])
    sh.s.mtext('Расход блока К — на высокой скорости (типовой для мини-VRV), у выбранного блока сверить по паспорту; '
               'живое сечение — при скорости не более 2,0 м/с: F = L / (3600 · 2,0). Шум решётки при этом расходе — '
               'по каталогу производителя. Расходы П1 — у решёток на листах 9 и 10.', x, yb - 1.3, 164, h=1.8,
               attach=1)
    return yb


