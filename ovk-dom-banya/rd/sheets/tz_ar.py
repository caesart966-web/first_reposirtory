def mm(v):
    return f'{int(round(abs(v) * 1000))}'


def ax(v, axes_):
    """Ближайшая ось: (имя, расстояние в мм)."""
    n, a = min(axes_, key=lambda q: abs(q[1] - v))
    return n, mm(v - a)


def bx(v, what='', bath=False):
    n, d = ax(v, BXX if bath else AXX)
    rel = f'{d} от оси {n}' if d != '0' else f'по оси {n}'
    return f'{what}x={fmt_num(v, 2)} ({rel})' if what else rel


def by(v, what='', bath=False):
    n, d = ax(v, BXY if bath else AXY)
    rel = f'{d} от оси {n}' if d != '0' else f'по оси {n}'
    return f'{what}y={fmt_num(v, 2)} ({rel})' if what else rel


