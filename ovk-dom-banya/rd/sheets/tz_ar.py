def mark(p, iid, pos, at=None, side='R', more=(), txt=None, h=2.2, r=2.3):
    """Позиция: кружок с номером в pos, размер рядом (side R/L/N), выноска к at (и к more)."""
    d = ITEMS[iid]
    R = p.H(r) / p.unit
    x, y = pos
    for q in ([at] if at else []) + list(more):
        dd = math.hypot(q[0] - x, q[1] - y) or 1
        e = (x + (q[0] - x) / dd * R, y + (q[1] - y) / dd * R)
        p.pl([q, e], 'ТЗ_АР_марки', lw=13)
        p.dot(q[0], q[1], 'ТЗ_АР_марки', r=0.35)
    p.wipe(x - R, y - R, x + R, y + R, 'ТЗ_АР_марки')
    p.circle(x, y, R, 'ТЗ_АР_марки', lw=18)
    p.t(x, y, str(d['no']), h, 'center', 'ТЗ_АР_марки')
    s = txt if txt is not None else short(d)
    if s and side != 'N':
        hh = 1.8
        w = p.tw(s, hh) + p.H(0.6) / p.unit
        g = p.H(0.6) / p.unit
        if side == 'R':
            x0 = x + R + g
        else:
            x0 = x - R - g - w
        p.wipe(x0 - g * 0.5, y - p.H(1.3) / p.unit, x0 + w, y + p.H(1.3) / p.unit, 'ТЗ_АР_марки')
        p.t(x0 + g * 0.3, y, s, hh, 'left', 'ТЗ_АР_марки')


def short(d):
    k = d['kind']
    s = d['size']
    if k == 'pit':
        return d['id'] + ' ' + s
    if k == 'ceil':
        return f'{d["id"]} h={s.split()[-1]}'
    if k in ('door', 'win', 'hatch', 'pad', 'roof', 'shaft'):
        return ''
    return s.replace('(h)', 'h')


def anchor(d, i=0):
    """Точка выноски: центр i-го элемента геометрии."""
    kind, v = d['geo'][i]
    if kind in ('wall', 'slab', 'roof', 'fdn', 'niche', 'pit', 'shaft', 'win', 'pad', 'hang'):
        return ((v[0] + v[2]) / 2, (v[1] + v[3]) / 2)
    if kind in ('slabr', 'riser', 'ctxc', 'wallc'):
        return (v[0], v[1])
    if kind == 'box':
        xs = [q[0] for q in v]
        ys = [q[1] for q in v]
        return (sum(xs) / len(xs), sum(ys) / len(ys))
    if kind == 'wallmove':
        n = v[1]
        return ((n[0] + n[2]) / 2, (n[1] + n[3]) / 2)
    if kind in ('floor',):
        return (v[0], v[1])
    if kind in ('sleeve', 'hatch'):
        return v
    if kind in ('gap', 'doorgr'):
        return ((v[0] + v[2]) / 2, (v[1] + v[3]) / 2)
    if kind == 'ceil':
        xs = [q[0] for q in v]
        ys = [q[1] for q in v]
        return (sum(xs) / len(xs), sum(ys) / len(ys))
    return v[0]


