def trough(r, w=0.34, add=0.02):
    """Приямок конвектора по прямоугольнику прибора: длина +20 на торец, ширина w по оси прибора."""
    x0, y0, x1, y1 = r
    if x1 - x0 >= y1 - y0:
        cy = (y0 + y1) / 2
        return (x0 - add, cy - w / 2, x1 + add, cy + w / 2)
    cx = (x0 + x1) / 2
    return (cx - w / 2, y0 - add, cx + w / 2, y1 + add)


def tsize(t):
    L = max(t[2] - t[0], t[3] - t[1])
    W = min(t[2] - t[0], t[3] - t[1])
    return f'{mm(L)}×{mm(W)}×150'


def tbind(t, bath=False):
    """Привязка приямка: торец — от оси слева (снизу), край у стены — от ближайшей оси."""
    x0, y0, x1, y1 = t
    AY, AX_ = (BXY, BXX) if bath else (AXY, AXX)

    def from_low(v, A):
        c = [(n, a) for n, a in A if a <= v + 1e-6]
        n, a = max(c, key=lambda q: q[1]) if c else min(A, key=lambda q: abs(q[1] - v))
        return n, mm(v - a)

    def edge(lo, hi, A, names):
        nl, al = min(A, key=lambda q: abs(q[1] - lo))
        nh, ah = min(A, key=lambda q: abs(q[1] - hi))
        if abs(lo - al) <= abs(hi - ah):
            return f'{names[0]} {mm(lo - al)} от оси {nl}'
        return f'{names[1]} {mm(hi - ah)} от оси {nh}'
    if x1 - x0 >= y1 - y0:
        n, d = from_low(x0, AX_)
        return f'зап. торец {d} от оси {n}; {edge(y0, y1, AY, ("юж. край", "сев. край"))}'
    n, d = from_low(y0, AY)
    return f'юж. торец {d} от оси {n}; {edge(x0, x1, AX_, ("зап. край", "вост. край"))}'


