def finish_ar(doc, name):
    """DXF — с Ø (для AutoCAD); PDF — с копии, где Ø заменён на ⌀ (у ISOCPEUR в matplotlib Ø заливается);
    листы — одним PDF, PNG для проверки — в TC.SCR."""
    import subprocess
    import pymupdf
    from rdbase import no_yo, save
    no_yo(doc)
    path = os.path.join(TC.OUT, name + '.dxf')
    save(doc, path)
    tmp = os.path.join(TC.OUT, '_' + name + '_print.dxf')
    open(tmp, 'wb').write(open(path, 'rb').read().replace('Ø'.encode(), '⌀'.encode()))
    names = sorted((l.name for l in doc.layouts if l.name != 'Model'), key=lambda n: int(n.split()[-1]))
    merged = pymupdf.open()
    for n in names:
        out = os.path.join(TC.OUT, f'_{name}_{n.split()[-1]}.pdf')
        subprocess.run([sys.executable, os.path.join(TC.ROOT, 'render_layout.py'), tmp, out, n], check=True,
                       capture_output=True)
        merged.insert_pdf(pymupdf.open(out))
        os.remove(out)
    os.remove(tmp)
    out_pdf = os.path.join(TC.OUT, name + '.pdf')
    merged.save(out_pdf)
    os.makedirs(TC.SCR, exist_ok=True)
    for k, pg in enumerate(pymupdf.open(out_pdf), 1):
        pg.get_pixmap(dpi=110).save(os.path.join(TC.SCR, f'{name}_{k}.png'))
    return path, out_pdf


