def new_doc():
    doc = _tz_doc()
    for n, (c, lw) in LAY.items():
        if n not in doc.layers:
            doc.layers.add(n, color=c, lineweight=lw)
    return doc


def draw_geo(p, g, faint=False):
    kind, v = g
    L = 'ТЗ_АР'
    if kind == 'wall':
        p.rect(*v, L, fill=5)
    elif kind == 'slab':
        p.rect(*v, L, lw=35)
        p.line(v[0], v[1], v[2], v[3], L)
        p.line(v[0], v[3], v[2], v[1], L)
    elif kind == 'roof':
        p.rect(*v, L, lw=35, ltype='ОВ_ШТРИХ')
        p.line(v[0], v[1], v[2], v[3], L)
        p.line(v[0], v[3], v[2], v[1], L)
    elif kind == 'sleeve':
        x, y = v
        p.circle(x, y, 0, L, r_paper=0.9)
        s = p.H(1.4) / p.unit
        p.line(x - s, y, x + s, y, L, lw=13)
        p.line(x, y - s, x, y + s, L, lw=13)
    elif kind == 'floor':
        x, y, d = v
        p.circle(x, y, d / 2, L)
        s = d / 2 + p.H(1.0) / p.unit
        p.line(x - s, y, x + s, y, L, lw=13)
        p.line(x, y - s, x, y + s, L, lw=13)
    elif kind == 'fdn':
        p.rect(*v, L, lw=35, ltype='ОВ_ШТРИХ')
    elif kind == 'route':
        p.pl(v, 'ТЗ_АР_зоны', ltype='ОВ_ШП', lw=25)
    elif kind == 'niche':
        p.rect(*v, L, hatch=('ANSI31', 25.0, 45, 5), lw=35)
    elif kind == 'pit':
        p.rect(*v, L, hatch=('ANSI37', 20.0, 0, 5), lw=25)
    elif kind == 'shaft':
        p.rect(*v, L, lw=35)
        p.line(v[0], v[1], v[2], v[3], L, lw=13)
        p.line(v[0], v[3], v[2], v[1], L, lw=13)
    elif kind == 'ceil':
        p.poly(v, 'ТЗ_АР_зоны', hatch=('ANSI31', 170.0, 45, 5), ltype='ОВ_ШТРИХ')
    elif kind == 'hatch':
        x, y = v
        p.rect(x - 0.30, y - 0.30, x + 0.30, y + 0.30, L, ltype='ОВ_ШТРИХ', lw=25)
        p.line(x - 0.30, y - 0.30, x + 0.30, y + 0.30, L, lw=13)
    elif kind == 'gap':
        x0, y0, x1, y1 = v
        p.line(x0, y0, x1, y1, L, lw=70)
    elif kind == 'doorgr':
        x0, y0, x1, y1 = v
        p.line(x0, y0, x1, y1, L, lw=100)
    elif kind == 'win':
        p.rect(*v, L, lw=70)
    elif kind == 'pad':
        p.rect(*v, 'ТЗ_АР_площ', hatch=('ANSI37', 30.0, 0, 8), lw=35)
    elif kind == 'wallc':
        x, y, d = v
        p.circle(x, y, 0, L, r_paper=1.5, lw=35)
        p.circle(x, y, d / 2, L, fill=5)
    elif kind == 'slabr':
        x, y, d = v
        r = d / 2
        p.circle(x, y, r, L, lw=35)
        k = r * 0.707
        p.line(x - k, y - k, x + k, y + k, L, lw=18)
        p.line(x - k, y + k, x + k, y - k, L, lw=18)
    elif kind == 'riser':
        x, y, d = v
        p.circle(x, y, d / 2, L, lw=35)
        p.circle(x, y, d / 2 - 0.05, L, lw=18)
    elif kind == 'ctxc':
        x, y, r = v
        p.circle(x, y, r, 'ТЗ_контекст', lw=25)
        p.t(x, y, 'Ø400', 1.4, 'center', 'ТЗ_контекст')
    elif kind == 'box':
        p.poly(v, 'ТЗ_АР_зоны', hatch=('ANSI31', 25.0, 135, 5), ltype='ОВ_ШТРИХ')
    elif kind == 'hang':
        x0, y0, x1, y1 = v
        p.rect(x0, y0, x1, y1, L, lw=35)
        e = max(0.12 * min(x1 - x0, y1 - y0), p.H(1.2) / p.unit)
        for x, y in ((x0 + e, y0 + e), (x1 - e, y0 + e), (x1 - e, y1 - e), (x0 + e, y1 - e)):
            p.circle(x, y, 0, L, fill=5, r_paper=0.7)
    elif kind == 'wallmove':
        old, new = v
        p.rect(*old, L, ltype='ОВ_ШТРИХ', lw=25)
