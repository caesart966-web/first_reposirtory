def sheet2():
    doc = new_doc()
    sh = RDSheet(doc, 'Лист', SHEET_LIST[2], 2, SHEETS_TOTAL)
    s, p = sh.s, sh.p
    s.text('Общие указания (окончание)', 25 + 97.5, 288, h=3.0, align='center')
    body = '\\P'.join(f'{i}. {t}' for i, t in enumerate(NOTES_MORE[3:], 9))
    s.mtext(body, 25, 284, 195, h=2.4, attach=1, spacing=1.0)

    # ---------------- условные обозначения
    x0, y = 230, 284
    s.text('Условные обозначения', x0 + 90, 288, h=3.0, align='center')
    col = {n: c for n, (c, _) in LAYERS.items()}

    def row(draw, txt):
        nonlocal y
        draw(x0, y)
        s.mtext(txt, x0 + 22, y + 1.6, 160, h=2.3, attach=1)
        y -= 7.0 if len(txt) < 70 else 10.0

    def ln(lay, lt=None, mark=None):
        def f(x, yy):
            p.pl([(x, yy), (x + 18, yy)], lay, ltype=lt, lw=35)
            if mark:
                p.t(x + 9, yy + 1.6, mark, 2.0, 'center', lay)
        return f

    def box(lay, fill=None, hatch=None, w=12, h=2.4):
        def f(x, yy):
            p.rect(x + 3, yy - h / 2, x + 3 + w, yy + h / 2, lay, fill=fill, hatch=hatch)
        return f

    def duct(lay):
        def f(x, yy):
            p.pl([(x, yy + 1.2), (x + 18, yy + 1.2)], lay)
            p.pl([(x, yy - 1.2), (x + 18, yy - 1.2)], lay)
        return f

    def grille(lay):
        def f(x, yy):
            p.rect(x + 7, yy - 2, x + 11, yy + 2, lay)
            p.line(x + 7, yy - 2, x + 11, yy + 2, lay)
            p.line(x + 7, yy + 2, x + 11, yy - 2, lay)
        return f

    def shaft(x, yy):
        p.shaft(x + 5, yy - 2, x + 13, yy + 2)

    def riser(x, yy):
        p.riser(x + 6, yy, 'ОВ_Т1', r=1.0)
        p.riser(x + 12, yy, 'ОВ_Т2', r=1.0)

    def zone(x, yy):
        p.poly([(x, yy - 2), (x + 18, yy - 2), (x + 18, yy + 2), (x, yy + 2)], 'ОВ_ТП',
               hatch=('ANSI31', 22.0, 45, 1))

    row(ln('ОВ_Т1', None, 'Т1'), 'Т1 — трубопровод подающий системы отопления (70 °С)')
    row(ln('ОВ_Т2', 'ОВ_ПУНКТ', 'Т2'), 'Т2 — трубопровод обратный системы отопления (на планах — пунктир или '
                                         'штрих синего цвета)')
    row(ln('ОВ_Т11', None, 'Т11'), 'Т11 — подающий теплого пола (от смесительного узла или группы РК)')
    row(ln('ОВ_Т21', 'ОВ_ПУНКТ', 'Т21'), 'Т21 — обратный теплого пола')
    row(zone, 'Зона укладки петли теплого пола (номер петли, шаг, длина — на плане)')
    row(box('ОВ_приборы', hatch=('ANSI31', 3.0, 45, 1)), 'Радиатор стальной панельный (Р), нижнее подключение')
    row(box('ОВ_приборы', fill=1), 'Внутрипольный конвектор: Кв, Кн — с вентилятором 12 В; Кн-1 — без '
                                    'вентилятора')
    row(box('ОВ_приборы', hatch=('ANSI37', 2.0, 0, 1), w=4, h=4), 'Полотенцесушитель водяной (Пс)')
    row(box('ОВ_КШ', fill=2, w=10, h=3), 'Коллекторный шкаф (КШ); двухъярусный — КШ-2, КШ-4')
    row(riser, 'Стояк Т1, Т2 (подъем на 2 этаж)')
    row(duct('ОВ_П'), 'Воздуховод приточный (П1, ЩП) — размер и расход на участке')
    row(duct('ОВ_В'), 'Воздуховод вытяжной')
    row(duct('ОВ_Н'), 'Воздуховод наружного воздуха (воздухозабор П1)')
    row(duct('ОВ_Выброс'), 'Воздуховод выброса')
    row(grille('ОВ_П'), 'Решетка, диффузор: стрелка — направление воздуха, L — расход, м³/ч')
    row(ln('ОВ_Фреон', 'ОВ_ШП'), 'Фреонопроводы (жидкость и газ) мини-VRF')
    row(ln('ОВ_Дренаж', 'ОВ_ШТРИХ'), 'Дренаж конденсата')
    row(shaft, 'Шахта (Ш-1, Ш-2), канал')
    return doc


