    L(20.75, 12.95, 'Ввод газа, +2,200 (лист 7)', GAS[0], 'восточная стена, севернее окна', anchor='left')
    L(20.75, 12.05, 'Окно — легкосбрасываемая', (20.05, 12.10), f'конструкция: остекление ≥{fmt_num(A_GLASS, 1)} м²',
      anchor='left')
    L(20.75, 10.75, 'Приток: решётка в двери', (19.86, 10.15), f'живое сечение ≥{fmt_num(BRV["A_in_free"], 3)} м²',
      anchor='left')
