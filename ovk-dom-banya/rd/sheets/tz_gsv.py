"""И05.09.26-ОВ.ТЗ-4. Задание на газоснабжение (ГСВ): топочная 1.6 (план и развёртка, М 1:50), потребители газа,
требования к помещению, воздуху на горение и дымоудалению. Один лист.

python3 sheets/tz_gsv.py  ->  out/tz_gsv.dxf + out/tz_gsv.pdf
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from tz_common import (new_doc, underlays, plan, viewport, frag_axes, ctx_boiler, lab, row_heights, finish,  # noqa
                       RDSheet, BP, GAS, DPlan, fmt_num, offset_poly, ROOT)

CODE = 'И05.09.26-ОВ.ТЗ-4'
TITLE = 'Задание на газоснабжение (ГСВ)'
RD = json.load(open(os.path.join(ROOT, '..', 'rd', 'rd_calc.json')))
G = RD['gas']
BRV = RD['boiler_room_vent']
QN, ETA = 9.3, 0.95                                   # кВт·ч/м³ (33,5 МДж/м³), КПД — как в расчёте ОВ
P1 = G['P_boilers'] / 2
G1 = P1 / (QN * ETA)
G_SUM = G['gas_m3h']
L_COMB = BRV['L_comb_gas']
A_GLASS = 0.03 * BRV['V']                             # требуемое остекление, м² (0,03 м² на 1 м³ объёма)
RAZ = (80.0, 0.0)                                     # развёртка в модели (м)


def flue(p, pts, d):
    p.pl(offset_poly(pts, d / 2), 'ОВ_дымоход', lw=35)
    p.pl(offset_poly(pts, -d / 2), 'ОВ_дымоход', lw=35)


def draw_plan(doc):
    p = plan(doc, 'frag', 50)
    frag_axes(p)
    ctx_boiler(p)
    for n in ('К1', 'К2'):
        r = BP.EQ[n]
        p.rect(*r, 'ТЗ_ГСВ', hatch=('ANSI31', 50.0, 45, 40), lw=50)
    # шахта Ш-2: каналы (лист 7)
    for name, kind, g in BP.CH:
        if kind == 'sq':
            p.rect(*g, 'ОВ_дымоход')
        else:
            x, y, r = g
            p.circle(x, y, r, 'ОВ_дымоход')
    flue(p, [(15.98, 11.08), (15.98, 12.92), (15.30, 12.92)], 0.13)          # каскадный дымоход Ø125
    # вытяжка из верхней зоны, приток через дверь
    p.rect(15.80, 12.57, 15.86, 12.78, 'ОВ_В', fill=32)
    p.arrow(16.25, 12.675, 15.90, 12.675, 'ОВ_В', size=2.0)
    p.rect(19.82, 9.75, 19.90, 10.25, 'ОВ_Н')
    p.arrow(20.45, 10.00, 19.95, 10.00, 'ОВ_Н', size=2.0)
    # окно — легкосбрасываемая конструкция
    p.line(20.05, BP.WIN_E[0], 20.05, BP.WIN_E[1], 'ТЗ_ГСВ', lw=70)
    # газопровод (условно, лист 7) и ввод
    p.pl(GAS, 'ОВ_Г', lw=50, ltype='ОВ_ШП')
    for y in (11.20, 11.90):
        p.circle(16.05, y, 0, 'ОВ_Г', r_paper=0.9)
    p.circle(GAS[0][0], GAS[0][1], 0, 'ТЗ_ГСВ', fill=40, r_paper=1.4)
    # подписи: слева
    L = lambda x, y, s, at, line2=None, anchor='right': lab(p, x, y, s, at=at, lines=line2, anchor=anchor)
    L(15.55, 14.05, 'Ш-2: выброс П1, вытяжка Ø250,', (15.25, 13.50), 'дымоход Ø125, дымоход ПК Ø280')
    L(15.55, 13.35, 'Каскадный дымоход Ø125 → Ш-2', (15.30, 12.92), 'ось +2,300, уклон 3° к котлам')
    L(15.55, 12.65, 'Вытяжка Ø250 из верхней зоны', (15.83, 12.675), f'{BRV["L_exh"]} м³/ч, канал в Ш-2')
    L(15.55, 11.40, f'К1 Viessmann ≈24–25 кВт', (15.98, 11.78), f'{fmt_num(G1, 2)} м³/ч, низ +1,100')
    L(15.55, 10.60, f'К2 Viessmann ≈24–25 кВт', (15.98, 11.08), f'{fmt_num(G1, 2)} м³/ч, низ +1,100')
    # сверху
    L(15.20, 15.15, 'Газопровод — условно, +2,600; трасса — по проекту ГСВ', (17.20, 13.45), anchor='left')
    L(17.30, 14.15, 'ПК — пеллетный, резерв (газ не нужен)', (16.60, 13.00), anchor='left')
