def legend(p, x, y):
    """Условные обозначения: линии систем и знаки арматуры — те же функции, что на листах."""
    from tm_model import Pipe, Fit
    lines = [('Т1', 'Т1 — трубопровод подающий отопления (котловой контур, группы)'),
             ('Т2', 'Т2 — трубопровод обратный отопления'),
             ('Т11', 'Т11 — трубопровод подающий тёплого пола (Н4)'),
             ('Т21', 'Т21 — трубопровод обратный тёплого пола'),
             ('Т3', 'Т3 — горячая вода от Б1 (ВК)'), ('Т4', 'Т4 — циркуляция ГВС (ВК)'),
             ('В1', 'В1 — холодная вода: подпитка, Б1 (ВК)'), ('Г', 'Г — газопровод (условно, ГСВ)'),
             ('К', 'К — конденсат котлов (ВК)')]
    yy = y
    for sysk, txt in lines:
        lay, lt = PIPE_STYLE[sysk]
        p.pl([(x, yy), (x + 16, yy)], lay, ltype=lt)
        p.t(x + 20, yy, txt, 2.2, 'left', 'ТМ_текст')
        yy -= 6.0
    syms = [('ball', 'Кран шаровой'), ('gas', 'Кран газовый (ГСВ)'), ('check', 'Клапан обратный'),
            ('filter', 'Фильтр сетчатый'), ('reducer', 'Редуктор давления'),
            ('three', 'Клапан трёхходовой термостатический (КТ)'), ('pump', 'Насос циркуляционный'),
            ('dirt', 'Шламоотделитель магнитный (ШО)'), ('safety', 'Группа безопасности (клапан предохранительный)'),
            ('vent', 'Воздухоотводчик автоматический'), ('drain', 'Кран спускной'), ('mano', 'Манометр'),
            ('therm', 'Термометр')]
    for kind, txt in syms:
        pp = Pipe('L', 'Т1' if kind != 'gas' else 'Г', 'steel', 25, [(0, 0, 0), (1, 0, 0)], '')
        side = '+y' if kind in ('vent', 'mano', 'therm', 'safety', 'three') else ('-y' if kind == 'drain' else None)
        fi = Fit(kind, pp, (0.5, 0, 0), '', side)
        V = View('plan', 62.5, (x, yy), (0.0, 0.0))          # 1 м = 16 мм
        lay, lt = PIPE_STYLE[pp.sys]
        p.pl([(x, yy), (x + 16, yy)], lay, ltype=lt)
        sym_fit(p, V, fi)
        p.t(x + 20, yy, txt, 2.2, 'left', 'ТМ_текст')
        yy -= 7.0
    p.circle(x + 8, yy, 0, 'ТМ_Т1', r_paper=1.0)
    p.pl([(x, yy), (x + 7, yy)], 'ТМ_Т1')
    p.t(x + 20, yy, 'Трубопровод, уходящий перпендикулярно плоскости чертежа (стояк)', 2.2, 'left', 'ТМ_текст')
    yy -= 8.0
    level_mark(p, x + 8, yy - 2.0, 3.2, h=2.0)
    p.line(x, yy - 2.0, x + 16, yy - 2.0, 'ТМ_Т1')
    p.t(x + 20, yy, 'Отметка оси трубопровода от чистого пола топочной', 2.2, 'left', 'ТМ_текст')
    return yy


