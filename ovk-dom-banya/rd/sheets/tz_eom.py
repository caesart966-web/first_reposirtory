    m_eom(p, *f1)
    m_eom(p, *f2)
    lab(p, 0.40, 7.10, '39. ВВ-б2: 230 В, ≈25 Вт, IPX4', at=f2)
    lab(p, 10.60, 5.30, '38. ВВ-б1: 230 В, ≈25 Вт, IPX4', at=f1)
