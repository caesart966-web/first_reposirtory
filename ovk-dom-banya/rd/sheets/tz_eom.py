    for q in kv.values():
        m_eom(p, *q)
    lab(p, 0.60, -1.15, '37. Кв-б1…Кв-б3: блоки питания 24 В', at=kv['Кв-б3'], more=(kv['Кв-б1'], kv['Кв-б2']))
