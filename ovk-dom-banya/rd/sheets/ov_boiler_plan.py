class PDPlan(DPlan):
    """Рисование на листе в мм (k=1: H(h)=h), штриховые линии — в масштабе листа."""

    def __init__(self, doc, lay):
        super().__init__(doc, k=1, space=lay, unit=1.0)

    def _attrs(self, layer, color=None, lw=None, ltype=None, ltscale=None):
        a = super()._attrs(layer, color, lw, None)
        if ltype:
            a['linetype'] = ltype
            a['ltscale'] = ltscale or 0.01
        return a


def dim(p, a, b, off, txt=None, h=2.2, layer='ОВ_размеры'):
    """Линейный размер (горизонтальный или вертикальный) между точками a, b (м); off — вынос (м, со знаком)."""
    (xa, ya), (xb, yb) = a, b
    t = p.H(1.0) / p.unit
    if abs(ya - yb) < 1e-9 or abs(xa - xb) > abs(ya - yb):      # горизонтальный
        y = ya + off
        p.line(xa, ya, xa, y + math.copysign(t, off), layer)
        p.line(xb, yb, xb, y + math.copysign(t, off), layer)
        p.line(xa - t, y, xb + t, y, layer)
        for x in (xa, xb):
            p.line(x - t, y - t, x + t, y + t, layer, lw=35)
        val = txt or f'{int(round(abs(xb - xa) * 1000))}'
        p.t((xa + xb) / 2, y + p.H(0.8) / p.unit, val, h, 'bc', layer)
    else:                                                          # вертикальный
        x = xa + off
        p.line(xa, ya, x + math.copysign(t, off), ya, layer)
        p.line(xb, yb, x + math.copysign(t, off), yb, layer)
        p.line(x, ya - t, x, yb + t, layer)
        for y in (ya, yb):
            p.line(x - t, y - t, x + t, y + t, layer, lw=35)
        val = txt or f'{int(round(abs(yb - ya) * 1000))}'
        p.t(x - p.H(0.8) / p.unit, (ya + yb) / 2, val, h, 'bc', layer, rot=90)


def level(p, x, y, txt, h=2.2, layer='ОВ_размеры', right=True):
    """Отметка высоты: треугольник и полка с текстом (развёртка)."""
    s = p.H(1.6) / p.unit
    p.poly([(x, y), (x - s * 0.6, y + s), (x + s * 0.6, y + s)], layer, fill=None)
    p.line(x, y + s, x + (s * 9 if right else -s * 9), y + s, layer)
    p.t(x + (s * 0.8 if right else -s * 0.8), y + s * 1.25, txt, h, 'bl' if right else 'br', layer)


