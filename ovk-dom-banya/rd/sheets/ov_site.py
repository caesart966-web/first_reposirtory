RISE_H = (19.25, 13.60)
RISE_B = (BX + ECO_IN[0], BY + ECO_IN[1])     # с/у бани, западнее пилона АР
Y_TURN = 19.40
ROUTE = [RISE_H, (19.25, Y_TURN), (RISE_B[0], Y_TURN), RISE_B]
DEPTH = 0.80                          # до верха трубы, м
OUT_FACE_H = 15.80                    # наружная грань северной стены хозблока 1.13
OUT_FACE_B = BY - 0.24                # наружная грань южной стены бани

NB = (20.55, 13.10, 21.00, 14.10)     # наружный блок НБ-1 (≈1,0×0,45 м)
PAD = (20.35, 12.60, 21.85, 14.60)    # площадка 1,5×2,0 м


def fillet_len(pts, R=1.0):
    """Длина ломаной со скруглением изломов радиусом R."""
    L = 0.0
    for a, b in zip(pts, pts[1:]):
        L += math.hypot(b[0] - a[0], b[1] - a[1])
    n_bend = len(pts) - 2
    return L - n_bend * (2 * R - math.pi * R / 2)


L_PLAN = fillet_len(ROUTE, 1.0)
L_TOT = L_PLAN + 2 * (DEPTH + 0.18 + 0.25)


