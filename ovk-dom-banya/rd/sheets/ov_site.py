    p.rect(RISE_B[0] - 0.22, PORCH_B[0] - 0.30, RISE_B[0] + 0.22, OUT_FACE_B, 'ОВ_оборуд', lw=35)
    L_plan, L_tot = L_PLAN, L_TOT
    # марки (во дворе между домом и баней; выноски не пересекаются)
    XL = 17.8
    p.label(XL, 23.9, 'Ввод в баню: с/у б3, у КШ-Б1 — узел 1, л. 13', 2.2, 'right', at=RISE_B,
            lines='под плитой крыльца бани — в футляре (согласовать с КР)')
    p.pl([(RISE_B[0] - 0.22, sum(PORCH_B) / 2), (XL, 23.9)], 'ОВ_выноски')
    p.dot(RISE_B[0] - 0.22, sum(PORCH_B) / 2)
    p.label(XL, 21.9, f'Ecoflex Quattro: L≈{fmt_num(L_tot, 1)} м, глубина ≥0,8 м', 2.2, 'right', at=(20.4, Y_TURN))
    p.label(XL, 20.4, 'НБ-1 Daikin мини-VRV ≈22,4 кВт на площадке', 2.2, 'right', at=(20.78, 13.6))
    p.label(XL, 18.8, 'Фреон и кабель — в топочную 1.6 (лист 9)', 2.2, 'right', at=(20.25, 13.35))
    p.label(XL, 17.2, 'Ввод в дом: топочная 1.6 — узел 2, л. 13', 2.2, 'right', at=RISE_H)
    # привязки трассы
    def dim_h(x0, x1, y, txt):
        p.line(x0, y, x1, y, 'ОВ_размеры')
        for x in (x0, x1):
            p.line(x - 0.25, y - 0.25, x + 0.25, y + 0.25, 'ОВ_размеры', lw=35)
        p.t((x0 + x1) / 2, y + 0.3, txt, 2.0, 'bc', 'ОВ_размеры')

    def dim_v(x, y0, y1, txt):
        p.line(x, y0, x, y1, 'ОВ_размеры')
        for y in (y0, y1):
            p.line(x - 0.25, y - 0.25, x + 0.25, y + 0.25, 'ОВ_размеры', lw=35)
        p.t(x - 0.3, (y0 + y1) / 2, txt, 2.0, 'bc', 'ОВ_размеры', rot=90)

    dim_h(19.25, 20.0, 12.4 + 0.0, f'{int(round((20.0 - 19.25) * 1000))}')
    p.line(20.0, 12.2, 20.0, 13.0, 'ОВ_размеры')
    dim_v(6.6, 16.7, BY, f'{int(round((BY - 16.7) * 1000))}')
    # привязка оси 1 бани к оси 1 дома
    p.line(0.0, 17.1, 0.0, BY + 7.9, 'ОВ_размеры', ltype='ОВ_ШП')
    dim_h(0.0, BX, BY + 7.6, f'{int(round(BX * 1000))}')
    dim_h(RISE_B[0], BX + 15.9, BY - 1.0, f'{int(round((BX + 15.9 - RISE_B[0]) * 1000))}')
    dim_v(20.3, OUT_FACE_H, Y_TURN, f'{int(round((Y_TURN - OUT_FACE_H) * 1000))}')

    # НБ-1 и площадка
    p.rect(*PAD, 'ОВ_оборуд', hatch=('ANSI37', 12.0, 0, 8))
    p.rect(*NB, 'ОВ_Фреон', fill=None)
    p.line(NB[0], NB[1], NB[2], NB[3], 'ОВ_Фреон')
    p.line(NB[0], NB[3], NB[2], NB[1], 'ОВ_Фреон')
