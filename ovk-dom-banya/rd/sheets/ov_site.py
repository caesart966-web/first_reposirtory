def bound_x(y, side='right'):
    """x границы участка на высоте y: правая — наибольшее пересечение, левая — наименьшее."""
    xs = []
    for (xa, ya), (xb, yb) in zip(BOUND, BOUND[1:] + BOUND[:1]):
        if ya != yb and min(ya, yb) <= y <= max(ya, yb):
            xs.append(xa + (xb - xa) * (y - ya) / (yb - ya))
    return (max(xs) if side == 'right' else min(xs)) if xs else None


