        f'(лист 9). До границы участка (по ГП01, на уровне блока): от восточной грани площадки — '
        f'≈{fmt_num(bound_x(13.6) - PAD[2], 1)} м, от восточной грани НБ-1 — ≈{fmt_num(bound_x(13.6) - NB[2], 1)} м.',
