        'Траншея: глубина до верха трубы не менее 0,8 м; песчаная подушка 100 мм, засыпка песком 150 мм над '
        'трубой, сигнальная лента — 300 мм над трубой. Под проездом и площадками — футляр.',
        'Наружный блок НБ-1 (Daikin мини-VRV, ≈22,4 кВт; решение Заказчика) — у восточной стены топочной, '
        'севернее входа и окна топочной, на опорной раме 0,3–0,5 м над площадкой ≈1,5×2,0 м; выдув — от стены. '
