    bb = add_underlay(doc, UNDER['bath'], 'АР_Баня_план')
    msp.add_blockref(bb, (BX * 1000 - OX, BY * 1000 - OY), dxfattribs={'layer': 'АР_подложка'})
    for n in ('I-FURN', 'G-IMPT', 'P-SANR-FIXT', 'A-FLOR-PATT', 'M-EQPM', 'A-DETL-GENF', 'A-GENM', 'S-STRS',
              'G-ANNO-SYMB', 'A-ANNO-NOTE', 'A-FLOR'):
        if n in doc.layers:
            doc.layers.get(n).off()
    p = DPlan(doc, k=K)

    # оси: дом — снизу и слева, баня — сверху
    axes(p, ([('1', 0.0), ('5', 20.0)], [('А', 0.0), ('Ж', 16.7)]), y_bub=-3.6, x_bub=-3.0, r=3.0, dims=False)
    axes(p, ([('1', BX), ('4', BX + 15.9)], [('А', BY), ('В', BY + 6.6)]), y_bub=None, x_bub=None,
         top=BY + 8.4, r=3.0, dims=False)
    # граница участка
    p.pl(BOUND, 'ОВ_размеры', closed=True, color=1, lw=35, ltype='ОВ_ШП')
    p.t(bound_x(14.5, 'left') - 0.55, 14.5, 'граница участка', 2.0, 'center', 'ОВ_текст', rot=85)

    # трасса Ecoflex: в грунте — двойной линией, внутри зданий — штрихом
