def pid(i):
    return [pp for pp in VK.PIPES if pp.id == i][0]


def offset_poly(pts, d):
    """Смещение ломаной на d (влево по ходу) с острыми углами."""
    out = []
    n = len(pts)
    for i in range(n):
        if i == 0 or i == n - 1:
            a, b = (pts[0], pts[1]) if i == 0 else (pts[-2], pts[-1])
            L = math.dist(a, b)
            nx, ny = -(b[1] - a[1]) / L, (b[0] - a[0]) / L
            q = a if i == 0 else b
            out.append((q[0] + nx * d, q[1] + ny * d))
        else:
            a, b, c = pts[i - 1], pts[i], pts[i + 1]
            L1, L2 = math.dist(a, b), math.dist(b, c)
            n1 = (-(b[1] - a[1]) / L1, (b[0] - a[0]) / L1)
            n2 = (-(c[1] - b[1]) / L2, (c[0] - b[0]) / L2)
            mx, my = n1[0] + n2[0], n1[1] + n2[1]
            k = d / max(1e-9, (mx * n1[0] + my * n1[1]))
            out.append((b[0] + mx * k, b[1] + my * k))
    return out


def lead(p, x, y, x1, y1, lines, side='right', h=1.8, dot=True):
    """Выноска от (x, y) к (x1, y1); полка от (x1, y1) вправо (side='right') или влево; первая строка — над
    полкой, остальные — под ней."""
    w = max(p.tw(t, h) for t in lines) + 1.6
    xs, xe = (x1, x1 + w) if side == 'right' else (x1 - w, x1)
    tw = max(p.tw(t, h) for t in lines)
    boxes = [(xs + 1.0, y1 + 0.9, xs + 0.8 + tw - 0.2, y1 + 0.7 + h)]           # своя надпись над полкой
    if len(lines) > 1:
        boxes.append((xs + 1.0, y1 - 0.8 - (h * 1.35) * (len(lines) - 2) - h, xs + 0.8 + tw - 0.2, y1 - 1.0))
    if any(_seg_rect((x, y), (x1, y1), b) for b in boxes):
        print('  !! выноска через свою надпись:', lines[0])
    p.pl([(x, y), (x1, y1)], 'ТМ_марки')
    if dot:
        p.circle(x, y, 0, 'ТМ_марки', fill=7, r_paper=0.4)
    p.pl([(xs, y1), (xe, y1)], 'ТМ_марки')
    p.t(xs + 0.8, y1 + 0.7, lines[0], h, 'bl', 'ТМ_марки')
    for i, t in enumerate(lines[1:]):
        p.t(xs + 0.8, y1 - 0.8 - (h * 1.35) * i, t, h, 'tl', 'ТМ_марки')


class D:
    """Деталь в масштабе 1:K: точка (u0, z0) детали (м) встаёт в точку (xr, yr) ячейки (мм)."""

    def __init__(self, p, cell, xr, yr, K, u0, z0):
        cx, cy = CELLS[cell]
        self.p, self.cell, self.x, self.y, self.K, self.u0, self.z0 = p, cell, cx + xr, cy + yr, K, u0, z0

    def P(self, u, z):
        return (self.x + (u - self.u0) * 1000 / self.K, self.y + (z - self.z0) * 1000 / self.K)

    def rect(self, u0, z0, u1, z1, layer='ТМ_стены', hatch=None, outline=True, ltype=None):
        a, b = self.P(u0, z0), self.P(u1, z1)
        pts = [(a[0], a[1]), (b[0], a[1]), (b[0], b[1]), (a[0], b[1])]
        if hatch:
            self.p.poly(pts, 'ТМ_штрих', hatch=hatch, outline=False)
        if outline:
            self.p.pl(pts, layer, closed=True, ltype=ltype)

    def poly(self, pts, layer='ТМ_стены'):
        self.p.pl([self.P(u, z) for u, z in pts], layer, closed=True)

    def line(self, pts, layer, lw=None, ltype=None):
        self.p.pl([self.P(u, z) for u, z in pts], layer, lw=lw, ltype=ltype)

    def pipe(self, pts, od, layer, ins=0.0, axis=True, ltype=None):
        """Труба в масштабе: две линии по наружному диаметру; изоляция — тонким штрихом."""
        for sg in (1, -1):
            self.line(offset_poly(pts, sg * od / 2), layer, ltype=ltype)
            if ins:
                self.line(offset_poly(pts, sg * (od / 2 + ins)), 'ТМ_оборуд_тонк', ltype='ОВ_ШТРИХ')
        if axis:
            self.line(pts, 'ТМ_оси', ltype='ОВ_ШП')

    def circ(self, u, z, r, layer):
        c = self.P(u, z)
        self.p.circle(c[0], c[1], 0, layer, r_paper=r * 1000 / self.K)

    def brk(self, u0, z0, u1, z1):
        """Линия обрыва с изломом посередине (ГОСТ 2.303)."""
        a, b = self.P(u0, z0), self.P(u1, z1)
        L = math.dist(a, b)
        ux, uy = (b[0] - a[0]) / L, (b[1] - a[1]) / L
        nx, ny = -uy, ux
        m = ((a[0] + b[0]) / 2, (a[1] + b[1]) / 2)
        s = 1.6
        pts = [a, (m[0] - ux * s, m[1] - uy * s),
               (m[0] - ux * s * 0.4 + nx * s * 1.4, m[1] - uy * s * 0.4 + ny * s * 1.4),
               (m[0] + ux * s * 0.4 - nx * s * 1.4, m[1] + uy * s * 0.4 - ny * s * 1.4),
               (m[0] + ux * s, m[1] + uy * s), b]
        self.p.pl(pts, 'ТМ_размеры')

    def tag(self, u, z, xr, yr, lines, side='right', dot=True):
        """Выноска от точки детали к полке в точке (xr, yr) ячейки."""
        cx, cy = CELLS[self.cell]
        x, y = self.P(u, z)
        lead(self.p, x, y, cx + xr, cy + yr, lines, side=side, dot=dot)

    def lev(self, u, z, right=True):
        x, y = self.P(u, z)
        level_mark(self.p, x, y, z, right=right, h=1.8)


def title(sh, no, txt, scale):
    cx, cy = CELLS[no]
    sh.s.text(f'Узел {no}. {txt}', cx + CELL_W / 2, cy + CELL_H - 3, h=2.6, align='center')
    if scale:
        sh.s.text(scale, cx + CELL_W / 2, cy + CELL_H - 8, h=2.2, align='center')


def foot(p, no, lines, y=14.0):
    cx, cy = CELLS[no]
    for i, t in enumerate(lines):
        p.t(cx + 4, cy + y - 3.4 * i, t, 1.7, 'bl', 'ТМ_текст')


