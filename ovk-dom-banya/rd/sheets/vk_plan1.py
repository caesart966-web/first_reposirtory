S_X0, S_Y0, S_X1, S_Y1 = 8.40, -1.25, 20.80, 16.55      # окно, м (12,4 × 17,8 м → 248 × 356 мм)


def sewer(doc, sh):
    p = PP(doc, sh.lay)
    K = 50
    w, h = (S_X1 - S_X0) * 1000 / K, (S_Y1 - S_Y0) * 1000 / K
    cx, cy = 36 + w / 2, 30 + h / 2
    V, box = plan_doc(doc, sh, 'plan1', cx, cy, w, h, (S_X0 + S_X1) / 2, (S_Y0 + S_Y1) / 2, K)
    p.rect(*box, 'ТМ_оборуд_тонк')
    axes_marks(p, V, box)
    L = Labels(p, box)
    for r in under_texts(UNDER['plan1'], V, box):
        L.block(r)
    pipes = [pp for pp in VK.PIPES if pp.bld == 'h' and pp.sys in ('К1', 'К1в') and pp.where in ('ground', 'riser')]
    pipes += [pp for pp in VK.PIPES if pp.bld == 'h' and pp.id in ('К1-гараж',)]
    k2 = [pp for pp in VK.PIPES if pp.bld == 'h' and pp.sys == 'К2']
    draw_net(p, V, pipes + k2, box, L=L)
    for f in VK.FITS:
        if f.pipe in pipes and in_box(V.P(f.pos), box):
            vk_fit(p, V, f)
    E = {e.id: e for e in VK.EQUIP}
    for eid in ('ЛГ-1', 'ПУ-1'):
        x_0, y_0, z_0, x_1, y_1, z_1 = E[eid].bbox()
        a, b = V.P((x_0, y_0, 0)), V.P((x_1, y_1, 0))
        p.rect(min(a[0], b[0]), min(a[1], b[1]), max(a[0], b[0]), max(a[1], b[1]), 'ВК_К2')
    for pp in pipes:
        if pp.where == 'ground' and pp.id != 'К1-1':
            a = V.P(pp.pts[0])
            p.circle(a[0], a[1], 0, 'ВК_К1', r_paper=max(0.8, pp.od * V.s / 2))
    fixture_marks(p, L, V, box, 'h', floor=1)
    # подписи участков: Ø, уклон, лотки в начале и в конце
    for pp in sorted(pipes, key=lambda q: -q.length()):
        if pp.sys != 'К1':
            continue
        seg = longest_seg(V, pp, box, horiz=False)
        if not seg:
            continue
        Lm, c, A, B = seg
        if Lm < 6 and pp.where != 'ground':
            continue
        t = f'Ø{pp.dn}, i={VK.i_txt(pp)}' if pp.id != 'К1-Ст1' else f'Ø{pp.dn}, отвод 45° и косой тройник 45°'
        z0 = pp.pts[0][2] - pp.od / 2
        z1 = pp.pts[-1][2] - pp.od / 2
        sub = f'лоток {lev(z0)} → {lev(z1)}' if pp.where == 'ground' else 'под потолком гаража, лист 5'
        nm = {'К1-сиф14': 'К1 от сифона конденсата (1.4)', 'К1-1': 'К1-1 сборный', 'К1-Ст1': 'К1 от Ст.К1-1'}.get(
            pp.id, pp.id)
        for tt in (0.5, 0.3, 0.7, 0.15, 0.85):
            at = (A[0] + (B[0] - A[0]) * tt, A[1] + (B[1] - A[1]) * tt)
            if L.shelf(at, f'{nm}: {t}', 1.6, sub=sub):
                break
        else:
            print('  !! нет места для подписи', pp.id)
    P = {pp.id: pp for pp in VK.PIPES}
    k = P['К1-1']
    rv = [f for f in VK.FITS if f.pipe is k and f.kind == 'revision']
    lab = [
        (P['Ст.К1-1'].pts[-1], 'Ст.К1-1 Ø110 — с 2 этажа, в стене гаража/1.9', 'ревизия +1,000, люк в стене со стороны гаража'),
        (P['К1в-1'].pts[0], 'Ст.К1-1в Ø110 — вытяжная часть', 'в стене по оси Г, через 2.8 и кровлю, +0,35 над ней'),
        (k.pts[0], 'Ввод линии бани (через КК-1, НВК)', f'лоток {lev(k.pts[0][2] - k.od / 2)}'),
        (k.pts[-1], 'Выпуск К1-1 Ø110 → ДК5-018 (НВК)', f'лоток {lev(k.pts[-1][2] - k.od / 2)}, футляр Ø160'),
        (P['К2-1'].pts[-1], 'К2-1 Ø110, i=0,02 — от лотка гаража', 'в ливневую сеть (НВК), футляр Ø160'),
        (((E['ЛГ-1'].g[0] + E['ЛГ-1'].g[3]) / 2, 1.85, 0), 'ЛГ-1 — лоток DN100 с решёткой C250', 'пескоуловитель ПУ-1, выпуск вниз Ø110'),
    ]
    for f in rv:
        if f.extra.get('room'):
            lab.append((f.pos, f'Прочистка: вывод в стену, люк со стороны {f.extra["room"]}', 'лист 14, узел 5'))
    for pt, t, sub in lab:
        if L.shelf(V.P(pt), t, 1.7, sub=sub) is None:
            print('  !! нет места для полки:', t)
    sh.title(cx, box[3] + 13.0, 'План 1 этажа. Канализация К1, выпуск К2 лотка гаража. М 1:50', h=3.5)
    sh.notes(300, 405, 286, NOTES_K, h=1.9, spacing=1.0)
    legend(p, 306, 98, k1=True, k2=True)
    return doc


