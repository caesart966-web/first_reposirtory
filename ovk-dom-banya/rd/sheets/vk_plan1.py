def legend(p, x, y, k1=False, k2=False):
    rows = [('В1', 'ВК_В1', None, 'водопровод холодной воды'), ('Т3', 'ВК_Т3', None, 'горячая вода, подающий трубопровод'),
            ('Т4', 'ВК_Т4', 'ОВ_ШТРИХ', 'горячая вода, циркуляционный трубопровод')]
    if k1:
        rows = [('К1', 'ВК_К1', None, 'бытовая канализация'), ('К1в', 'ВК_К1в', 'ОВ_ШП', 'вытяжная часть стояка')]
    p.t(x, y + 6, 'Условные обозначения', 2.2, 'bl', 'ТМ_текст')
    for i, (c, lay, lt, t) in enumerate(rows):
        yy = y - i * 5.0
        p.pl([(x, yy), (x + 14, yy)], lay, ltype=lt, lw=50)
        p.t(x + 17, yy, f'{c} — {t}', 1.9, 'left', 'ТМ_текст')
    yy = y - len(rows) * 5.0
    p.circle(x + 7, yy, 0, 'ВК_К1' if k1 else 'ВК_В1', r_paper=0.9)
    p.t(x + 17, yy, 'стояк, подъём к прибору', 1.9, 'left', 'ТМ_текст')
    if k1:
        for t, k in (('ревизия на стояке (люк в стене)', 'Р'), ('прочистка на сборном (вывод в стену, люк)', 'П')):
            yy -= 5.0
            if k == 'Р':
                q = [(x + 5.6, yy - 1.4), (x + 8.4, yy - 1.4), (x + 8.4, yy + 1.4), (x + 5.6, yy + 1.4)]
                p.poly(q, 'ТМ_арматура')
            else:
                p.circle(x + 7, yy, 0, 'ТМ_арматура', r_paper=1.4)
            p.t(x + 7, yy, k, 1.6, 'center', 'ТМ_арматура')
            p.t(x + 17, yy, t, 1.9, 'left', 'ТМ_текст')
    if k1 and k2:
        yy -= 5.0
        p.pl([(x, yy), (x + 14, yy)], 'ВК_К2', ltype='ОВ_ШП', lw=50)
        p.t(x + 17, yy, 'К2 — от лотка гаража в ливневую сеть (НВК)', 1.9, 'left', 'ТМ_текст')
    elif not k1:
        yy -= 5.0
        leak_sym(p, (x + 7, yy))
        p.t(x + 17, yy, 'ДП — датчик протечки (защита от протечек)', 1.9, 'left', 'ТМ_текст')
        yy -= 5.0
        p.rect(x + 3, yy - 1.5, x + 11, yy + 1.5, 'ТМ_оборуд')
        p.t(x + 17, yy, 'ШВК — шкаф коллекторный в нише стены (люк)', 1.9, 'left', 'ТМ_текст')


