def column(L, V, items, x_m, y_top, y_bot, h=1.6, gap=1.6):
    """Подписи столбцом на свободном поле (Заказчица 29.10.2026: «выноски на пустые поля»): полки начинаются на x_m,
    идут сверху вниз в порядке точек выносок по y — выноски не пересекаются; строка опускается, пока полка
    не встанет на свободное место без пересечения чужих выносок. items — [(точка модели, текст, подпись)]."""
    p = L.p
    items = sorted(items, key=lambda it: -V.P(it[0])[1])
    xc = V.P((x_m, 0, 0))[0]
    y = V.P((0, y_top, 0))[1]
    ybot = V.P((0, y_bot, 0))[1]
    top = h * 1.25 + 0.9
    for pt, t, sub in items:
        at = V.P(pt)
        bot = top if sub else 0.4
        w = max(p.tw(t, h), p.tw(sub, h) if sub else 0) + 1.6
        while y - bot > ybot:
            r = (xc, y - bot, xc + w, y + top)
            if L.free(r) and L._clean(at, (xc, y), r):
                L.shelf(at, t, h, sub=sub, force=(xc - at[0], y - at[1]))
                break
            y -= 0.5
        else:
            print('  !! нет места в столбце для полки:', t)
            continue
        y -= bot + top + gap


