def sewer(doc, sh):
    p = PP(doc, sh.lay)
    V, box = plan_doc(doc, sh, 'plan1', CX, CY, VW, VH, MX, MY, K)
    p.rect(*box, 'ТМ_оборуд_тонк')
    axes_marks(p, V, box)
    L = Labels(p, box)
    for r in under_texts(UNDER['plan1'], V, box):
        L.block(r)
    pipes = [pp for pp in VK.PIPES if pp.bld == 'h' and pp.sys in ('К1', 'К1в') and pp.where in ('ground', 'riser')]
    pipes += [pp for pp in VK.PIPES if pp.bld == 'h' and pp.id in ('К1-гараж',)]
    draw_net(p, V, pipes, box, L=L)
    for f in VK.FITS:
        if f.pipe in pipes and in_box(V.P(f.pos), box):
            vk_fit(p, V, f)
    # стояки и подъёмы от приборов 1 этажа: кружки в точках начала отводов
    for pp in pipes:
        if pp.where == 'ground' and pp.id != 'К1-1':
            a = V.P(pp.pts[0])
            p.circle(a[0], a[1], 0, 'ВК_К1', r_paper=max(0.8, pp.od * V.s / 2))
    fixture_marks(p, L, V, box, 'h', floor=1)
    # подписи участков: Ø, уклон, лотки в начале и в конце
    for pp in pipes:
        if pp.sys != 'К1':
            continue
        seg = longest_seg(V, pp, box, horiz=False)
        if not seg:
            continue
        Lm, c, A, B = seg
        if Lm < 6:
            continue
        i_ = 0.02 if pp.dn == 110 else 0.03
        t = f'Ø{pp.dn}, i={f1(i_, 2)}'
        z0 = pp.pts[0][2] - pp.od / 2
        z1 = pp.pts[-1][2] - pp.od / 2
        sub = f'лоток {lev(z0)} → {lev(z1)}' if pp.where == 'ground' else 'под потолком гаража, лист 5'
        at = ((A[0] + B[0]) / 2, (A[1] + B[1]) / 2)
        L.shelf(at, f'{pp.id}: {t}', 1.8, sub=sub)
    st = {pp.id: pp for pp in VK.PIPES}['Ст.К1-1']
    L.shelf(V.P(st.pts[0]), 'Ст.К1-1 Ø110 — с 2 этажа', 2.0, sub='ревизия +1,000, люк 300×400')
    vv = {pp.id: pp for pp in VK.PIPES}['К1в-1']
    L.shelf(V.P(vv.pts[0]), 'Ст.К1-1в Ø110 — вытяжная часть', 2.0, sub='сквозь 2.8 и кровлю, +0,35 над ней')
    k = {pp.id: pp for pp in VK.PIPES}['К1-1']
    L.shelf(V.P(k.pts[-1]), 'Выпуск К1-1 Ø110 → НВК', 2.2, sub=f'лоток {lev(k.pts[-1][2] - k.od / 2)} у стены')
    sh.title(CX, box[3] + 15.0, 'План 1 этажа (фрагмент в осях 3–5). Канализация К1. М 1:50', h=3.5)
    sh.notes(284, 283, 128, NOTES_K, h=1.9, spacing=1.0)
    legend(p, 290, 100, k1=True)
    return doc


