def sewer(doc, sh):
    p = PP(doc, sh.lay)
    K = 50
    w, h = (S_X1 - S_X0) * 1000 / K, (S_Y1 - S_Y0) * 1000 / K
    cx, cy = 36 + w / 2, 30 + h / 2
    V, box = plan_doc(doc, sh, 'plan1', cx, cy, w, h, (S_X0 + S_X1) / 2, (S_Y0 + S_Y1) / 2, K)
    p.rect(*box, 'ТМ_оборуд_тонк')
    axes_marks(p, V, box)
    L = Labels(p, box)
    for r in under_texts(UNDER['plan1'], V, box) + under_marks('plan1', V, box):
        L.block(r)
    # отводы 1 этажа в грунте, подъёмы и стояки; в полу 1.4 — отводы Ø50 к Ст.К1-2 (Заказчица 29.10.2026)
    pipes = [pp for pp in VK.PIPES if pp.bld == 'h' and pp.sys in ('К1', 'К1в') and
             (pp.where in ('ground', 'riser') or pp.where == 'floor' and pp.pts[0][2] < 1.0)]
    pipes += [pp for pp in VK.PIPES if pp.bld == 'h' and pp.id in ('К1-гараж',)]
    k2 = [pp for pp in VK.PIPES if pp.bld == 'h' and pp.sys == 'К2']
    draw_net(p, V, pipes + k2, box, L=L)
    for f in VK.FITS:
        if f.pipe in pipes and in_box(V.P(f.pos), box):
            vk_fit(p, V, f)
    E = {e.id: e for e in VK.EQUIP}
    for eid in ('ЛГ-1', 'ПУ-1'):
        x_0, y_0, z_0, x_1, y_1, z_1 = E[eid].bbox()
        a, b = V.P((x_0, y_0, 0)), V.P((x_1, y_1, 0))
        p.rect(min(a[0], b[0]), min(a[1], b[1]), max(a[0], b[0]), max(a[1], b[1]), 'ВК_К2')
        L.block((min(a[0], b[0]) - 0.3, min(a[1], b[1]) - 0.3, max(a[0], b[0]) + 0.3, max(a[1], b[1]) + 0.3))
