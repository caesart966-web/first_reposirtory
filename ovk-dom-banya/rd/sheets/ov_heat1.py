        'таблицы (при 75/65/20 °С, рабочая скорость вентилятора); глубина — по толщине пирога пола, не более 150 мм. '
        'Питание вентиляторов — 24 В постоянного тока, блоки питания — по разделу ЭОМ.',
        'Температура поверхности тёплого пола — по СП 60.13330: не выше 26 °С в 1.10, 1.11, не выше 31 °С в '
        'остальных; недостающее тепло дают Кв. Поэтому ТП 1.10, 1.11 (и 1.8, петля 1.9-3) — от смесительного '
        'узла КШ-2 с подачей 36 °С, КШ-1 и КШ-3 — от РК, 48,5 °С. Раскладка петель — лист 4.',
        'Подводки к конвекторам — PE-Xa 16×2,0 с антидиффузионным слоем в теплоизоляции 6 мм и гофре, '
        'в слое утеплителя под петлями ТП; магистрали — в теплоизоляции 9–13 мм. Соединений в конструкции '
        'пола нет. Магистрали в топочной и тамбуре 1.7 — открыто под потолком на +3,200; из 1.6 в 1.7 — одним '
        'пучком над дверью (лист 7, ТЗ-1).',
        'Кв-8 (вместо Кн-2 по ЭП, решение Заказчика 19.10.2026) — у витража лестницы 1.9, под площадкой: '
        'на 2 этаже под витражом пола нет. Мощность — нагрузка 2.1 плюс недостача тёплого пола 1.9.',
        'Стояки Т1, Т2 Ø25×3,5 на 2 этаж — в углу тамбура 1.7 у стены топочной, в коробе ГКЛ (АР); '
        'проход перекрытия — в гильзах.',
