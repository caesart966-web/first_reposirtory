def dashed(p, pts, layer, dash=0.30, gap=0.12, lw=None):
    """Штриховая линия отдельными отрезками (м)."""
    import math as _m
    for (x0, y0), (x1, y1) in zip(pts[:-1], pts[1:]):
        L = _m.hypot(x1 - x0, y1 - y0)
        ux, uy = (x1 - x0) / L, (y1 - y0) / L
        t = 0.0
        while t < L:
            t1 = min(t + dash, L)
            p.line(x0 + ux * t, y0 + uy * t, x0 + ux * t1, y0 + uy * t1, layer, lw=lw)
            t = t1 + gap


def mask(p, x0, y0, x1, y1):
    """Маскировка (WIPEOUT) под надписью: штриховка и линии под текстом не видны."""
    a, b = p.P(min(x0, x1), min(y0, y1)), p.P(max(x0, x1), max(y0, y1))
    p.m.add_wipeout([a, b], dxfattribs={'layer': 'ОВ_марки'})


def mlabel(p, x, y, s, h=2.5, anchor='left', at=None, lines=None):
    w = p.tw(s, h) + p.H(1.2) / p.unit
    if lines:
        w = max(w, p.tw(lines, h) + p.H(1.2) / p.unit)
    x0 = x if anchor == 'left' else x - w
    top = y + p.H(0.9 + h * 1.25) / p.unit
    bot = y - (p.H(0.9 + h * 1.25) / p.unit if lines else p.H(0.3) / p.unit)
    mask(p, x0, bot, x0 + w, top)
    return p.label(x, y, s, h, anchor, at=at, lines=lines)


def mtag(p, x, y, lines, anchor=None, h=2.0):
    lh = p.H(h * 1.45) / p.unit
    pad = p.H(1.0) / p.unit
    w = max(p.tw(t, h) for t in lines) + 2 * pad
    Hh = lh * len(lines) + pad * 0.6
    mask(p, x, y - Hh, x + w, y)
    return p.tag(x, y, lines, anchor=anchor, h=h)


