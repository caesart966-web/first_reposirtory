def G_of(Q, dt):
    return Q * 3.6 / (CW * dt)


def pick_pipe(G, vmax=0.6):
    for D, s in PEXA:
        di = (D - 2 * s) / 1000
        v = G / 3600 / 985 / (math.pi * di * di / 4)
        if v <= vmax:
            return f'{D}×{fmt_num(s, 1)}', v
    D, s = PEXA[-1]
    di = (D - 2 * s) / 1000
    return f'{D}×{fmt_num(s, 1)}', G / 3600 / 985 / (math.pi * di * di / 4)


def dth_H(tv, ti, sig):
    return sig / math.log((tv - ti) / (tv - sig - ti))


def sigma_for(tv, ti, target):
    """Перепад в петле, при котором логарифмический напор = target (бисекция)."""
    lo, hi = 0.05, tv - ti - 0.05
    for _ in range(80):
        m = (lo + hi) / 2
        if dth_H(tv, ti, m) > target:
            lo = m
        else:
            hi = m
    return (lo + hi) / 2


def tF(q, ti):
    return ti + (q / 8.92) ** (1 / 1.1)


