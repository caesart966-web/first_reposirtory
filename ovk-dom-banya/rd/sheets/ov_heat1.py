    doc = new_doc()
    blk = add_underlay(doc, UNDER['plan1'], 'АР_План_1_этажа')
    insert_underlay(doc.modelspace(), blk)
    p = DPlan(doc, k=100)
    axes(p, y_bub=-2.4, x_bub=-2.4)
    draw_base(p, doc)
    draw_convectors(p)
    draw_mains(p, doc)
    for n, r in kv_routes().items():
        pair(p, r)

