    kvm('Кв-4', 1.10, 12.05, at=(0.46, 12.60))
    kvm('Кв-5', 1.10, 8.40, at=(0.46, 7.45))
    kvm('Кв-6', 0.85, -1.00, at=(2.00, 0.48))
    kvm('Кв-7', 4.20, -1.00, at=(4.00, 0.48))
    mlabel(p, 6.60, 16.25, f'Кв-8  L={int(dev["Кв-8"]["L"] * 1000)}, {round(dev["Кв-8"]["Q"] / 10) * 10:.0f} Вт',
            2.0, at=(10.30, 15.12), lines='(вместо Кн-2 по ЭП, решение Заказчика 19.10.2026)')

    # ---- шкафы, стояки, Р-т — подписи в гараже (на листе 3 он свободен)
    c1, c2, c3 = cabs['КШ-1'], cabs['КШ-2'], cabs['КШ-3']
    mlabel(p, 12.90, 8.25, f'КШ-1: ТП {c1["n_tp"]} вых., 48,5 °С', 1.9, at=(13.05, 9.14))
    mlabel(p, 15.95, 8.25, f'КШ-3: ТП {c3["n_tp"]} вых., 48,5 °С', 1.9, at=(16.22, 9.14))
    mlabel(p, 16.10, 7.60, 'Ст. Т1, Т2 Ø25×3,5 на 2 этаж', 1.9, 'right', at=(15.38, 9.16))
    mlabel(p, 19.30, 6.95, f'Р-т  22/500  L={int(C["rt"]["sel"]["L"] * 1000)}, {C["rt"]["Q"]} Вт', 1.9, 'right',
            at=(18.60, 9.14))
    mlabel(p, 12.20, 12.45, f'КШ-2: 2 яруса ≈{c2["W"]}×1300', 1.9, 'right', at=(13.10, 10.92),
            lines=f'Кв {c2["n_dir"]} вых. + ТП {c2["n_tp"]} вых.')
    # ---- магистрали — подписи над зданием, выноски лесенкой (не пересекают полки)
    rows = [(16.00, 17.85, (17.80, 12.80), f'Т1, Т2 {M["КШ-2"]["pipe"]} → КШ-2 (70/55 °С)'),
            (16.40, 17.30, (18.00, 12.60), f'Т11, Т21 {M["КШ-1"]["pipe"]} → КШ-1 (48,5 °С)'),
            (16.80, 16.75, (18.20, 12.40), 'Т1, Т2 25×3,5 → стояки КШ-4 (70/55 °С)'),
            (17.20, 16.20, (18.40, 12.20), f'Т11, Т21 {M["КШ-3"]["pipe"]} → КШ-3 (48,5 °С)')]
    for x, y, at, txt in rows:
        mlabel(p, x, y, txt, 1.9, at=at)
    mlabel(p, 19.05, 14.62, 'Т1, Т2 → баня, Ecoflex 32×2,9', 1.9, 'right', at=(19.25, 14.95),
            lines='в грунте под 1.13 (лист 14)')

    # ---- ярлыки помещений
    R = C['rooms']

    def tg(no, x, y, extra, anchor=None, h=1.9):
        r = ROOM[no]
        mtag(p, x, y, [f'{no}  +{r["ti"]} °С  {kw(r["Q"])} кВт'] + extra, anchor=anchor, h=h)

    q10 = sum(dev[n]['Q'] for n in ('Кв-1', 'Кв-2', 'Кв-3', 'Кв-4', 'Кв-5'))
    q11 = dev['Кв-6']['Q'] + dev['Кв-7']['Q']
    tg('1.10', 0.85, 7.55, [f'ТП 4 петли — {kw(R["1.10"]["Q_ufh"])} кВт', f'Кв-1–5 — {kw(q10)} кВт'])
    tg('1.11', 0.85, 5.95, [f'ТП 3 петли — {kw(R["1.11"]["Q_ufh"])} кВт', f'Кв-6, 7 — {kw(q11)} кВт'])
    tg('1.2', 7.10, 5.20, ['ТП 1 петля'])
    tg('1.3', 10.00, 2.95, ['ТП 1 петля'], h=1.8)
    tg('1.4', 10.35, 5.95, ['ТП 1 петля'], h=1.8)
    tg('1.9', 9.80, 14.45, [f'ТП 3 петли — {kw(R["1.9"]["Q_ufh"])} кВт', 'Кв-8 — см. выноску'])
    mtag(p, 13.95, 10.30, [f'1.7  +{ROOM["1.7"]["ti"]} °С', f'{kw(ROOM["1.7"]["Q"])} кВт, ТП'], h=1.6)
    tg('1.8', 12.85, 13.45, ['ТП 1 петля'], h=1.8)
    tg('1.6', 12.95, 15.20, ['ТП 3 петли + Р-т', 'котлы Viessmann', '(каскад, лист 7)'], anchor=(17.00, 12.10),
       h=1.8)
    tg('1.5', 13.40, 5.20, ['ТП 2 петли, дежурный', 'режим +10 °С'])

    # ------------------------------------------------ лист
    sh = RDSheet(doc, 'Лист', SHEET_LIST[SHEET_NO].replace('ё', 'е'), SHEET_NO, SHEETS_TOTAL)
    sh.viewport(152, 177, 258, 222, 9.4, 7.2, k=100)
    sh.title(152, 289.5, 'План 1 этажа. Отопление. М 1:100')
    rows = [['Вых.', 'Прибор', 'Пом.', 'Q, Вт', 'Тип, размер', 'G, л/ч', 'Lподв, м', 'Настр., л/мин']]
    for i, n in enumerate(['Кв-1', 'Кв-2', 'Кв-3', 'Кв-4', 'Кв-5', 'Кв-6', 'Кв-7', 'Кв-8'], 1):
        d = dev[n]
        rows.append([f'В{i}', n, d['room'], f'{round(d["Q"] / 10) * 10:.0f}',
                     f'«Бриз В» L={int(round(d["L"] * 1000))}, ≥{round(d["qn"] / 10) * 10:.0f} Вт/м',
                     fmt_num(d['G'], 0), fmt_num(d['lead'], 1), fmt_num(d['lmin'], 2)])
    widths = [9, 13, 10, 11, 40, 12, 13, 15]
    yb = sh.table(290, 286, widths, rows, row_h=5.0, head_h=7, h=1.9,
                  aligns=['center', 'center', 'center', 'center', 'left', 'center', 'center', 'center'])
    sh.s.text('КШ-2, верхний ярус (70/55 °С): подключения конвекторов', 290 + sum(widths) / 2, 289.5, h=2.5,
              align='center')
    rows = [['Контур от РК (топочная)', 'Q, кВт', 'G, кг/ч', 't, °С', 'Труба PE-Xa', 'v, м/с']]
    for m in mains:
        rows.append([m['name'], kw(m['Q']), fmt_num(m['G'], 0), m['temp'], m['pipe'], fmt_num(m['v'], 2)])
