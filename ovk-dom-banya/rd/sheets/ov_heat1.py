def plen(pts):
    return sum(math.hypot(b[0] - a[0], b[1] - a[1]) for a, b in zip(pts, pts[1:]))


def poly_area(pts):
    return abs(sum(x0 * y1 - x1 * y0 for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1]))) / 2


def loop_area(lid):
    if lid in LOOP_POLY:
        return poly_area(LOOP_POLY[lid])
    x0, y0, x1, y1 = LOOP_RECT[lid]
    return (x1 - x0) * (y1 - y0)
