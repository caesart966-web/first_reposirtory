    u0, u = UFH0[no], UFH[no]
    q = min(u0['q'], QLIM[no])
    A = A_DRAWN2[no] if UFH2_BY_DRAWING else u0['A_loops']
    lead = sum(math.dist(a, b) for a, b in zip(LEAD2[no], LEAD2[no][1:])) + RISE
    L = A / (u0['T_mm'] / 1000) + 2 * lead if UFH2_BY_DRAWING else u0['L_loop']
    Q_new = q * A
    deficit = u0['Q_ufh'] - Q_new
    sig = sig_for(TV4, u0['ti'], q / u0['K_H'])
    qd = u0['q_down'] * q / u0['q']
    G = (q + qd) * A * 3.6 / (CW * sig)
    u.update(q=q, A_loops=A, L_loop=L, Q_ufh=round(Q_new), sig=sig, G_loop=G, l_min=G / 60,
             dp_loop=u0['dp_loop'] * (G / u0['G_loop']) ** 1.75 * L / u0['L_loop'],
             t_floor=u0['ti'] + (q / 8.92) ** (1 / 1.1), tv=TV4)
    d = DEV[ps]
    d['Q'] = round(d['Q'] + deficit)
    d['G'] = d['Q'] * 3.6 / (CW * 15)
    d['sel'] = dict(d['sel'], Q=d['Q'], Qn_need=round(d['Q'] / d['sel']['k']))
    d['gvs'] = True                              # с 20.10.2026 — от циркуляции ГВС (раздел ВК), к КШ-4 не подключается


