        'Система двухтрубная лучевая от КШ-4, параметры 70/55 °С. Подводки — PE-Xa 16×2,0 с антидиффузионным '
        'слоем в защитной гофре, в конструкции пола; изгибы не менее 5 Dн, соединений в полу нет.',
        'КШ-4 — встроенный двухъярусный ≈750×1250×150 мм в полосе шкафов у южной стены 2.6 (место указал '
        'Заказчик). Верх — прямой коллектор 1" на 9 выходов с расходомерами и термоклапанами под '
