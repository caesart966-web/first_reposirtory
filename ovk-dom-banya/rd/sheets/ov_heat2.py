def lmtd(tv, tr, ti):
    return (tv - tr) / math.log((tv - ti) / (tr - ti))


DT_N = lmtd(75, 65, 20)
TOWEL_GVS = {}
for no, ps in (('2.8', 'Пс-1'), ('2.9', 'Пс-2')):
    ti = ROOM[no]['ti']
    f = (lmtd(T3, T4, ti) / DT_N) ** 1.25
