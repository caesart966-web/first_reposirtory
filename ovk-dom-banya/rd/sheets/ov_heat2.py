def kw(w):
    return fmt_num(w / 1000, 1)


# ---------------------------------------------------------------- пересчёт ТП санузлов по СП 60 (пол не выше 31 °С)
def dth_H(tv, ti, sig):
    return sig / math.log((tv - ti) / (tv - sig - ti))


def tv_for(dth, ti, sig):
    """Подача, при которой логарифмический напор петли с перепадом sig равен dth (бисекция)."""
    lo, hi = ti + sig + 0.1, 80.0
    for _ in range(80):
        m = (lo + hi) / 2
        if dth_H(m, ti, sig) < dth:
            lo = m
        else:
            hi = m
    return (lo + hi) / 2


def sig_for(tv, ti, dth):
    """Перепад в петле при подаче tv, дающий логарифмический напор dth (бисекция)."""
    lo, hi = 0.1, tv - ti - 0.1
    for _ in range(80):
        m = (lo + hi) / 2
        if dth_H(tv, ti, m) > dth:
            lo = m
        else:
            hi = m
    return (lo + hi) / 2


SIG = 5.0
QLIM = {no: 8.92 * (UFH0[no]['sp60_limit'] - UFH0[no]['ti']) ** 1.1 for no in ('2.8', '2.9')}
TV4 = max(tv_for(min(UFH0[no]['q'], QLIM[no]) / UFH0[no]['K_H'], UFH0[no]['ti'], SIG) for no in ('2.8', '2.9'))
TV4 = math.ceil(TV4 * 2) / 2                     # подача смесительного узла КШ-4, с шагом 0,5 °С
for no, ps in (('2.8', 'Пс-1'), ('2.9', 'Пс-2')):
    u0, u = UFH0[no], UFH[no]
    q = min(u0['q'], QLIM[no])
    Q_new = q * u0['A_loops']
    deficit = u0['Q_ufh'] - Q_new
    sig = sig_for(TV4, u0['ti'], q / u0['K_H'])
    qd = u0['q_down'] * q / u0['q']
    G = (q + qd) * u0['A_loops'] * 3.6 / (CW * sig)
    u.update(q=q, Q_ufh=round(Q_new), sig=sig, G_loop=G, l_min=G / 60,
             dp_loop=u0['dp_loop'] * (G / u0['G_loop']) ** 1.75,
             t_floor=u0['ti'] + (q / 8.92) ** (1 / 1.1), tv=TV4)
    d = DEV[ps]
    d['Q'] = round(d['Q'] + deficit)
    d['G'] = d['Q'] * 3.6 / (CW * 15)
    d['sel'] = dict(d['sel'], Q=d['Q'], Qn_need=round(d['Q'] / d['sel']['k']))


