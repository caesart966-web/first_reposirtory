    conv(16.42, 13.18, 19.17, 13.52)       # Кн-1, 2.7, у окна 3000×3000, без вентилятора
    conv(0.30, 6.75, 0.62, 7.65)           # Кн-3, 2.2, у окна 1000×3000, с вентилятором
    p.rect(19.68, 7.35, 19.78, 7.95, 'ОВ_приборы', hatch=('ANSI37', 2.0, 0, 1))   # Пс-1, 2.8
    p.rect(15.48, 7.30, 15.58, 7.85, 'ОВ_приборы', hatch=('ANSI37', 2.0, 0, 1))   # Пс-2, 2.9

    # ------------------------------------------------ зоны ТП санузлов (нижний ярус КШ-4)
    p.ufh_zone([(16.35, 7.40), (19.60, 7.40), (19.60, 7.95), (17.95, 7.95), (17.95, 8.68), (16.35, 8.68)])
    p.ufh_zone([(12.80, 7.05), (15.40, 7.05), (15.40, 7.90), (13.40, 7.90), (13.40, 8.05), (12.80, 8.05)])

    # ------------------------------------------------ подводки в конструкции пола (лучевые, в гофре)
    west = [  # имя, x выхода, y по тамбуру 2.6, x поворота в холле 2.1, y по галерее 2.2
        ('Р-3', 14.92, 9.85, 10.90, 7.00),
        ('Р-2', 15.00, 9.95, 10.80, 7.10),
        ('Р-1', 15.08, 10.05, 10.70, 7.20),
        ('Кн-3', 15.16, 10.15, 10.60, 7.30),
    ]
    ends = {
        'Р-3': [(9.70, 6.45), (9.70, 1.62), (9.60, 1.62), (9.60, 1.48)],
        'Р-2': [(6.30, 6.45), (6.30, 1.62), (5.70, 1.62), (5.70, 1.48)],
        'Р-1': [(3.15, 6.45), (3.15, 1.62), (3.00, 1.62), (3.00, 1.48)],
        'Кн-3': [(0.80, 7.30), (0.62, 7.30)],
    }
    for n, x0, yv, xh, yg in west:
        e = ends[n]
        pair([(x0, 9.23), (x0, yv), (xh, yv), (xh, yg), (e[0][0], yg)] + e)
    pair([(14.86, 9.23), (14.86, 9.75), (13.45, 9.75), (13.45, 12.75), (12.82, 12.75)])                 # Р-5
    pair([(15.24, 9.23), (15.24, 9.70), (16.70, 9.70), (16.70, 13.05), (16.55, 13.05), (16.55, 13.18)])  # Кн-1
    pair([(15.32, 9.23), (15.32, 9.60), (16.85, 9.60), (16.85, 7.65), (19.68, 7.65)])                  # Пс-1
    pair([(15.25, 9.08), (15.25, 7.60), (15.48, 7.60)])                                                # Пс-2
    pair([(15.40, 9.08), (15.40, 8.95), (17.05, 8.95), (17.05, 8.68)], ('ОВ_Т11', 'ОВ_Т21'))          # ТП 2.8
    pair([(15.10, 9.08), (15.10, 7.90)], ('ОВ_Т11', 'ОВ_Т21'))                                         # ТП 2.9

