# ---------------------------------------------------------------- пересчёт ТП санузлов по СП 60 (пол не выше 31 °С)
def dth_H(tv, ti, sig):
    return sig / math.log((tv - ti) / (tv - sig - ti))


def tv_for(dth, ti, sig):
    """Подача, при которой логарифмический напор петли с перепадом sig равен dth (бисекция)."""
    lo, hi = ti + sig + 0.1, 80.0
    for _ in range(80):
        m = (lo + hi) / 2
        if dth_H(m, ti, sig) < dth:
            lo = m
        else:
            hi = m
    return (lo + hi) / 2


def sig_for(tv, ti, dth):
    """Перепад в петле при подаче tv, дающий логарифмический напор dth (бисекция)."""
    lo, hi = 0.1, tv - ti - 0.1
    for _ in range(80):
        m = (lo + hi) / 2
        if dth_H(tv, ti, m) > dth:
            lo = m
        else:
            hi = m
    return (lo + hi) / 2


