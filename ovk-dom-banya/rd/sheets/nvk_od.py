def lengths():
    """Протяжённость сетей по системам и диаметрам, м (по модели)."""
    L = defaultdict(float)
    for p in data()['pipes']:
        L[(p['sys'], p['dn'], 'перфорир' in p['mat'])] += p['L']
    return L


def wells():
    cnt = defaultdict(int)
    for w in data()['wells']:
        if not w['exist']:
            cnt[w['kind']] += 1
    return cnt


