import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)
sys.path.insert(0, HERE)
from rdbase import (new_doc, DPlan, RDSheet, add_underlay, insert_underlay, UNDER, save_and_pdf,  # noqa: E402
                    fmt_num, SHEET_LIST, SHEETS_TOTAL, axes)
from ov_heat1 import (calc1, LOOP_RECT, KSH, MAIN_ROUTES, pair, draw_base, draw_convectors, kw,  # noqa: E402
                      ROOM, OUT, mask, mlabel, mtag, noyo)

SHEET_NO = 4
TP = ('ОВ_Т11', 'ОВ_Т21')


def routes():
    """Подводки петель (осевые линии пар) — от шкафов, без пересечений, кроме 1.7 и 1.6-2/-3 (через магистраль)."""
    R = {}
    # КШ-1: выход вверх от фасада шкафа, на запад полосами 9.36…9.64, спуск в холле 1.9
    R['1.9-1'] = [(12.84, 9.22), (12.84, 9.36), (12.32, 9.36), (12.32, 8.55)]
    R['1.9-2'] = [(13.12, 9.22), (13.12, 9.64), (12.30, 9.64)]
    R['1.4-1'] = [(12.91, 9.22), (12.91, 9.43), (12.25, 9.43), (12.25, 6.96), (8.30, 6.96), (8.30, 5.25), (10.35, 5.25)]
    R['1.3-1'] = [(12.98, 9.22), (12.98, 9.50), (12.18, 9.50), (12.18, 7.03), (8.20, 7.03), (8.20, 3.15), (10.35, 3.15)]
    R['1.2-1'] = [(13.05, 9.22), (13.05, 9.57), (12.11, 9.57), (12.11, 7.10), (8.10, 7.10), (8.10, 6.00)]
    R['1.7-1'] = [(13.26, 9.22), (13.26, 9.30), (13.90, 9.30)]
    # КШ-2, нижний ярус (36 °С): выход вниз от фасада, на запад полосами 9.78…10.20
    xe = {'1.10-2': 12.95, '1.10-4': 13.02, '1.10-3': 13.09, '1.10-1': 13.16, '1.11-1': 13.23, '1.11-2': 13.30,
          '1.11-3': 13.37}
    lane = {'1.10-2': 10.20, '1.10-4': 10.13, '1.10-3': 10.06, '1.10-1': 9.99, '1.11-1': 9.92, '1.11-2': 9.85,
            '1.11-3': 9.78}
    xv = {'1.10-2': 11.62, '1.10-4': 11.69, '1.10-3': 11.76, '1.10-1': 11.83, '1.11-1': 11.90, '1.11-2': 11.97,
          '1.11-3': 12.04}
    yw = {'1.10-2': 7.59, '1.10-4': 7.52, '1.10-3': 7.45, '1.10-1': 7.38, '1.11-1': 7.31, '1.11-2': 7.24,
          '1.11-3': 7.17}
    tail = {'1.10-2': [(8.65, None)], '1.10-4': [(6.00, None), (6.00, 9.00)],
            '1.10-3': [(4.45, None), (4.45, 10.20)], '1.10-1': [(4.45, None)],
            '1.11-1': [(4.75, None), (4.75, 6.00)], '1.11-2': [(4.85, None), (4.85, 4.40)],
            '1.11-3': [(4.95, None), (4.95, 2.60)]}
    for n in xe:
        R[n] = [(xe[n], 10.85), (xe[n], lane[n]), (xv[n], lane[n]), (xv[n], yw[n])] + \
               [(x, yw[n] if y is None else y) for x, y in tail[n]]
    R['1.9-3'] = [(12.88, 10.85), (12.88, 10.73), (12.15, 10.73), (12.15, 10.85)]
    R['1.8-1'] = [(13.66, 10.92), (14.15, 10.92), (14.15, 11.30)]
    # КШ-3 (топочная): 1.6 — на север и восток, гараж — на юг сквозь основание стены
    R['1.6-1'] = [(16.00, 9.22), (16.00, 9.45)]
    R['1.6-2'] = [(16.12, 9.22), (16.12, 9.36), (17.30, 9.36), (17.30, 9.60)]
    R['1.6-3'] = [(16.24, 9.22), (16.24, 9.29), (18.50, 9.29), (18.50, 9.35)]
    R['1.5-1'] = [(16.05, 9.07), (16.05, 7.90)]
    R['1.5-2'] = [(16.30, 9.07), (16.30, 7.90)]
    return R


LABEL_AT = {  # где подписать петлю: (x, y) центра надписи; None — в центре зоны
    '1.4-1': ('in', 10.92, 5.32),
    '1.7-1': ('in', 14.52, 9.85),
    '1.9-1': (None,), '1.9-2': (None,), '1.9-3': ('in', 11.72, 13.4),
    '1.6-3': ('in', 19.05, 10.25),
    '1.6-1': ('in', 16.88, 11.20),
    '1.6-2': ('in', 17.83, 11.85),
}


def build():
    C = calc1()
    loops = {lp['id']: lp for lp in C['loops']}
    doc = new_doc()
    blk = add_underlay(doc, UNDER['plan1'], 'АР_План_1_этажа')
    insert_underlay(doc.modelspace(), blk)
    p = DPlan(doc, k=100)
    axes(p, y_bub=-2.4, x_bub=-2.4)
    draw_base(p, doc)
    draw_convectors(p, light=True)

    # ---- зоны петель: 48,5 °С — штриховка 45°, 36 °С — 135° (смесительный узел КШ-2)
    for lid, (x0, y0, x1, y1) in LOOP_RECT.items():
        lp = loops[lid]
        ang = 135 if lp['cab'] == 'КШ-2' else 45
        sc = lp['T'] / 10 * 6
        p.poly([(x0, y0), (x1, y0), (x1, y1), (x0, y1)], 'ОВ_ТП', hatch=('ANSI31', sc, ang - 45, 1),
               ltype='ОВ_ШТРИХ')
    # ---- магистрали ТП от РК и подвод к КШ-2
    pair(p, MAIN_ROUTES['КШ-2'], gap=0.08, lw=35)
    pair(p, MAIN_ROUTES['КШ-1'], lays=TP, gap=0.08, lw=35)
    pair(p, MAIN_ROUTES['КШ-3'], lays=TP, gap=0.08, lw=35)
    # ---- подводки петель
    for lid, r in routes().items():
        pair(p, r, lays=TP)
    # ---- надписи петель
    for lid, (x0, y0, x1, y1) in LOOP_RECT.items():
        lp = loops[lid]
        t1, t2 = lid, f'Ш{lp["T"]}, {fmt_num(lp["L"], 0)} м'
        spec = LABEL_AT.get(lid, (None,))
        if spec[0] == 'lead':
            mlabel(p, spec[1], spec[2], t1, 1.9, at=spec[3], lines=t2)
            continue
        if spec[0] == 'in':
            cx, cy = spec[1], spec[2]
        else:
            cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
            if lid in ('1.9-1', '1.9-2'):
                cx = 10.65
            if lid.startswith('1.11'):
                cx = 2.60
        w = max(p.tw(t1, 2.0), p.tw(t2, 2.0)) + 0.12
        mask(p, cx - w / 2, cy - 0.27, cx + w / 2, cy + 0.27)
        p.rect(cx - w / 2, cy - 0.27, cx + w / 2, cy + 0.27, 'ОВ_марки', fill=None)
        p.t(cx, cy + 0.12, t1, 2.0, 'center', 'ОВ_марки')
        p.t(cx, cy - 0.13, t2, 1.8, 'center', 'ОВ_марки')

    # ---- шкафы
    cabs = C['cabs']
    mlabel(p, 12.90, 8.25, f'КШ-1: {cabs["КШ-1"]["n_tp"]} петель, 48,5 °С', 1.9, at=(13.05, 9.14))
    mlabel(p, 13.00, 14.75, f'КШ-2, нижний ярус: {cabs["КШ-2"]["n_tp"]} петель', 1.9, at=(13.05, 10.95),
            lines='смесительный узел, подача 36 °С')
    mlabel(p, 16.55, 8.25, f'КШ-3: {cabs["КШ-3"]["n_tp"]} петель, 48,5 °С', 1.9, at=(16.22, 9.14))

    # ---- ярлыки помещений (кратко)
    def tg(no, x, y, extra, h=1.8, anchor=None):
        r = ROOM[no]
        mtag(p, x, y, [f'{no}  +{r["ti"]} °С  {kw(r["Q"])} кВт'] + extra, h=h, anchor=anchor)

    R = C['rooms']
    tg('1.10', 0.85, 13.05 + 0.0, [f'ТП {kw(R["1.10"]["Q_ufh"])} кВт, пол ≤26 °С'])
    tg('1.11', 0.85, 6.02, [f'ТП {kw(R["1.11"]["Q_ufh"])} кВт, пол ≤26 °С'])

    # ---- лист
    sh = RDSheet(doc, 'Лист', SHEET_LIST[SHEET_NO].replace('ё', 'е'), SHEET_NO, SHEETS_TOTAL)
    sh.viewport(152, 177, 258, 222, 9.4, 7.2, k=100)
    sh.title(152, 289.5, 'План 1 этажа. Раскладка тёплого пола. М 1:100')
    rows = [['Петля', 'КШ, вых.', 'Покр.', 'Шаг', 'A, м²', 'L, м', 'Q, Вт', 'G, л/ч', 'л/мин', 'Δp, кПа',
             'tпов, °С']]
    order = sorted(C['loops'], key=lambda lp: (lp['cab'], lp['out']))
    for lp in order:
        rows.append([lp['id'], f'{lp["cab"]}.{lp["out"]}', lp['cover'], f'{lp["T"]}', fmt_num(lp['A'], 1),
                     fmt_num(lp['L'], 0), f'{lp["Q"]:.0f}', fmt_num(lp['G'], 0), fmt_num(lp['lmin'], 2),
                     fmt_num(lp['dp'], 1), fmt_num(lp['tF'], 1)])
    widths = [13, 14, 12, 9, 10, 9, 10, 10, 11, 12, 13]
    sh.s.text('Петли тёплого пола 1 этажа (PE-Xa 16×2,0)', 290 + sum(widths) / 2, 289.5, h=2.5, align='center')
    yb = sh.table(290, 286, widths, rows, row_h=4.4, head_h=6.5, h=1.8,
                  aligns=['center'] * 11)
    rows = [['Шкаф', 'Подача, °С', 'Петель', 'G, кг/ч', 'Δp петли max, кПа', 'Ширина, мм']]
    for c, lab in (('КШ-1', f'{48.5:.1f}'.replace('.', ',')), ('КШ-2', '36,0'), ('КШ-3', '48,5')):
        d = cabs[c]
        rows.append([c + (' (низ)' if c == 'КШ-2' else ''), lab, f'{d["n_tp"]}', fmt_num(d['G_tp'], 0),
                     fmt_num(d['dp_max'], 1), f'≈{d["W"]}'])
    widths2 = [22, 18, 14, 18, 30, 21]
    yb = sh.table(290, yb - 3.5, widths2, rows, row_h=4.6, head_h=6, h=1.8, aligns=['center'] * 6)
    sh.notes(290, yb - 5, 123, [
        'Трубы — PE-Xa 16×2,0 с антидиффузионным слоем, в стяжке; укладка спиралью («улиткой») с шагом по '
        'таблице; длина петли с подводками — по таблице ±10 %, не более 90 м. Контуры зон — схематично, раскладка '
        'по месту в пределах свободного пола.',
        'ТП не укладывается под кухонной мебелью и островом, сантехприборами, ванной и душевым поддоном, '
        'встроенными шкафами, а также под площадкой и маршем лестницы в 1.9 (кроме петли 1.9-3).',
        'Температура поверхности пола — по СП 60.13330: в 1.10, 1.11 не выше 26 °С, в остальных — не выше '
        '31 °С. Петли 1.10, 1.11, 1.8, 1.9-3 — от смесительного узла КШ-2 (подача 36 °С, насос класса 25-40); '
        'КШ-1, КШ-3 — от РК, подача 48,5 °С.',
        'Пол по грунту (сверху вниз): покрытие, стяжка 100 мм с фиброй, трубы на плёнке/мате с разметкой, '
        'ЭППС 100 (по АР/КР), демпферная лента по периметру. Деформационные швы — по границам петель и в '
        'дверных проёмах; карта стяжки не более 40 м² и не длиннее 8 м.',
        'Транзитные подводки (на плане — от КШ-1 и КШ-2 через холл 1.9) — в слое утеплителя под петлями, '
        'в гофре; пересечение с магистралями — с обходом по высоте.',
        'Перед заливкой стяжки — испытание давлением 0,6 МПа (не менее 1,5 рабочего) 24 ч; стяжка — под '
        'давлением. Первый пуск — после набора прочности стяжки, с плавным подъёмом температуры.',
        'Покрытия пола и толщина стяжки приняты до получения экспликации полов (доска — 1.9, 1.10, 1.11, '
        'плитка — остальные, гараж — бетон). При другом покрытии длины и настройки петель уточнить.',
    ], h=2.0)
    return doc, C


if __name__ == '__main__':
    doc, C = build()
    print(save_and_pdf(doc, os.path.join(OUT, 'ov_ufh1.dxf')))
