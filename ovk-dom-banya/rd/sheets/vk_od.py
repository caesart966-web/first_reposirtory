def fixtures_rows():
    cnt = Counter((fx.typ, fx.bld) for fx in VK.FIXT.values())
    rows = [['Марка', 'Наименование', 'Дом', 'Баня', 'Подводки']]
    for t in FIX_ORDER:
        h, b = cnt.get((t, 'h'), 0), cnt.get((t, 'b'), 0)
        if not (h or b):
            continue
        ex = [fx for fx in VK.FIXT.values() if fx.typ == t][0]
        con = '+'.join([s for s, on in (('В1', ex.typ not in ('Т', 'Т100')), ('Т3', ex.hot), ('К1', ex.k1)) if on])
        rows.append([t if t != 'Т100' else 'Т', FIX_NAMES[t], str(h) if h else '—', str(b) if b else '—', con])
    return rows


