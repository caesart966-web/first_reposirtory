def f2(v):
    return f'{v:.2f}'.replace('.', ',')


def centered(p, cx, cy, K, ext):
    """Det, у которого габарит ext = (umin, umax, zmin, zmax) стоит по центру (cx, cy); и верх габарита, мм."""
    u0, u1, z0, z1 = ext
    d = Det(p, cx, cy, K, (u0 + u1) / 2, (z0 + z1) / 2)
    return d, cy + (z1 - z0) / 2 * 1000 / K


class Det:
    """Деталь 1:K: точка (u0, z0) (м) встаёт в (x, y) мм листа."""

    def __init__(self, p, x, y, K, u0, z0):
        self.p, self.x, self.y, self.K, self.u0, self.z0 = p, x, y, K, u0, z0

    def P(self, u, z):
        return (self.x + (u - self.u0) * 1000 / self.K, self.y + (z - self.z0) * 1000 / self.K)

    def poly(self, pts, layer='ТМ_стены', hatch=None, outline=True, closed=True, ltype=None, lw=None):
        q = [self.P(u, z) for u, z in pts]
        if hatch:
            self.p.poly(q, 'ТМ_штрих', hatch=hatch, outline=False)
        if outline:
            self.p.pl(q, layer, closed=closed, ltype=ltype, lw=lw)

    def rect(self, u0, z0, u1, z1, layer='ТМ_стены', hatch=None, outline=True, ltype=None, lw=None):
        self.poly([(u0, z0), (u1, z0), (u1, z1), (u0, z1)], layer, hatch, outline, ltype=ltype, lw=lw)

    def line(self, pts, layer='ТМ_оборуд_тонк', ltype=None, lw=None):
        self.p.pl([self.P(u, z) for u, z in pts], layer, ltype=ltype, lw=lw)

    def circ(self, u, z, r, layer, fill=None):
        c = self.P(u, z)
        self.p.circle(c[0], c[1], 0, layer, r_paper=r * 1000 / self.K, fill=fill)

    def lev(self, u, z, txt=None, right=True):
        x, y = self.P(u, z)
        p = self.p
        s = 1.2
        p.pl([(x - s, y + s), (x, y), (x + s, y + s)], 'ТМ_размеры')
        p.line(x, y, x, y + 3.5, 'ТМ_размеры')
        t = txt or alev(z)
        w = p.tw(t, 1.9) + 1.0
        x1 = x + w if right else x - w
        p.line(x, y + 3.5, x1, y + 3.5, 'ТМ_размеры')
        p.t(x + 0.5 if right else x - 0.5, y + 4.0, t, 1.9, 'bl' if right else 'br', 'ТМ_размеры')

    def tag(self, u, z, dx, dy, lines, h=1.9, side='right'):
        """Выноска от точки (u, z) к полке в (x + dx, y + dy) мм."""
        p = self.p
        a = self.P(u, z)
        b = (a[0] + dx, a[1] + dy)
        w = max(p.tw(t, h) for t in lines) + 1.4
        x0 = b[0] if side == 'right' else b[0] - w
        p.pl([a, b], 'ТМ_марки')
        p.circle(a[0], a[1], 0, 'ТМ_марки', fill=7, r_paper=0.3)
        p.pl([(x0, b[1]), (x0 + w, b[1])], 'ТМ_марки')
        for i, t in enumerate(lines):
            if i == 0:
                p.t(x0 + 0.7, b[1] + 0.7, t, h, 'bl', 'ТМ_марки')
            else:
                p.t(x0 + 0.7, b[1] - 0.7 - (i - 1) * h * 1.5, t, h, 'tl', 'ТМ_марки')

    def dim_h(self, u0, u1, z, txt=None, off=0.0):
        x0, y = self.P(u0, z)
        x1, _ = self.P(u1, z)
        y += off
        p = self.p
        p.line(x0, y, x1, y, 'ТМ_размеры')
        for x in (x0, x1):
            p.line(x - 0.8, y - 0.8, x + 0.8, y + 0.8, 'ТМ_размеры', lw=35)
            p.line(x, y - 1.2, x, y + 1.2, 'ТМ_размеры')
        p.t((x0 + x1) / 2, y + 0.7, txt or str(int(round(abs(u1 - u0) * 1000))), 1.8, 'bc', 'ТМ_размеры')

    def dim_v(self, z0, z1, u, txt=None, off=0.0):
        x, y0 = self.P(u, z0)
        _, y1 = self.P(u, z1)
        x += off
        p = self.p
        p.line(x, y0, x, y1, 'ТМ_размеры')
        for y in (y0, y1):
            p.line(x - 0.8, y - 0.8, x + 0.8, y + 0.8, 'ТМ_размеры', lw=35)
            p.line(x - 1.2, y, x + 1.2, y, 'ТМ_размеры')
        p.t(x - 0.7, (y0 + y1) / 2, txt or str(int(round(abs(z1 - z0) * 1000))), 1.8, 'bc', 'ТМ_размеры', rot=90)


def title(p, x, y, n, t, scale):
    p.t(x, y, f'Узел {n}. {t}', 2.8, 'center', 'НВК_текст')
    p.t(x, y - 4.2, scale, 2.2, 'center', 'НВК_текст')


def foot(p, x, y, w, lines, h=1.8):
    for i, t in enumerate(lines):
        p.t(x, y - i * h * 1.6, t, h, 'left', 'НВК_текст')


