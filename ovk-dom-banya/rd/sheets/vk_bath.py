def sheet9(doc, sh):
    p = PP(doc, sh.lay)
    import vk_frag
    vk_frag.K = 50
    zr = (-1.5, 4.5)

    def txt(pp):
        if pp.sys == 'К1в':
            return 'Ст.К1-б Ø110 — вытяжная часть над кровлей +0,35'
        z0 = pp.pts[0][2] - pp.od / 2
        z1 = pp.pts[-1][2] - pp.od / 2
        return f'{pp.id}: Ø{pp.dn}, i={VK.i_txt(pp)}, лоток {lev(z0)} → {lev(z1)}'

    def ex(p, L, V, box):
        P_ = {pp.id: pp for pp in VK.PIPES}
        for pid, t in (('К1-б', 'Выпуск К1-б Ø110 → НВК (КК-1)'), ('К1-бв', 'Выпуск К1-бв Ø110 → НВК (КК-1)')):
            k = P_[pid]
            sub = f'лоток {lev(k.pts[-1][2] - k.od / 2)}'
            if pid == 'К1-бв':                     # своя подпись трубы не ставится — уклон и лотки здесь
                sub = f'i={VK.i_txt(k)}, лоток {lev(k.pts[0][2] - k.od / 2)} → {lev(k.pts[-1][2] - k.od / 2)}'
            L.shelf(V.P(k.pts[-1]), t, 2.0, sub=sub)
        um = P_['К1-УМ-б1']                        # в коробе инсталляции — подпись над коробом
        at = V.P((13.30, 0.38, 0.21))                # западный конец горизонтального участка в коробе
        if (L.shelf(at, txt(um), 1.6, strict=True) or L.shelf(at, txt(um), 1.6)) is None:
            print('  !! нет места для полки: К1-УМ-б1')
        L.shelf(V.P((VK.STB[0], VK.STB[1], 0)), 'Ст.К1-б Ø110 — в О-блоках перегородки б2/б3 (250 мм),', 1.9,
                sub=f'внизу — двухплоскостная крестовина {lev(VK.Z_CROSS)}; над кровлей +0,35')
        L.shelf(V.P((VK.BT[0], VK.BT[1], 0)), 'Поворот 60°: отводы 45° + 15°', 1.8)
        # номера помещений подложки — в кружках ≈ Ø0,5 м: кружок целиком занят для полок
        from rdbase import UNDER
        from vk_draw import under_texts
        for r in under_texts(UNDER['bath'], V, box):
            if r[2] - r[0] <= (r[3] - r[1]) * 1.5:
                cx_, cy_, rr = (r[0] + r[2]) / 2, (r[1] + r[3]) / 2, 0.3 * V.s
                L.block((cx_ - rr, cy_ - rr, cx_ + rr, cy_ + rr))
        L.shelf(V.P((VK._GB[0], VK._GB[1], 0)), 'Воронка ГБ Б2', 1.8, sub='верх +0,300',
                cands=[(1.5, -16), (1.5, -20), (-3, -16), (1.5, -12)])
        L.shelf(V.P((VK.CB[0], VK.CB[1], 0)), 'Прочистка — в О-блоках стены б6/б8 (250 мм),', 1.8,
                sub='люк со стороны б6, заглушка +0,200')
        L.shelf(V.P(((VK.BT[0] + VK.B_OUT[0]) / 2 + 0.05, 1.0, 0)), 'Под террасой б1 — утеплитель ЭППС 50 мм', 1.8,
                sub='над трубой, ширина 1,2 м')
    V, box, L = fragment(doc, sh, p, 'bath', 200, 194, -0.45, -1.10, 16.25, 6.90, zr, ('К1', 'К1в'), bld='b',
                         title='', marks_floor=1, extra=ex, text=txt, skip=('Ст.К1-б', 'К1-бв', 'К1-УМ-б1'))
    for pp in VK.PIPES:
        if pp.bld == 'b' and pp.sys == 'К1' and pp.where == 'ground' and pp.id not in ('К1-б', 'К1-бв', 'Ст.К1-б'):
            a = V.P(pp.pts[0])
            p.circle(a[0], a[1], 0, 'ВК_К1', r_paper=max(0.8, pp.od * V.s / 2))
    sh.s.text('Баня. План канализации К1. М 1:50', 200, box[3] + 13, h=3.5, align='center')
    sh.notes(24, 109, 200, NOTES9, h=1.9, spacing=1.0)
    legend(p, 240, 98, k1=True)
    return doc


