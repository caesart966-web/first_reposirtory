def sheet8(doc, sh):
    """План водопровода бани целиком в М 1:25 на А1 — без фрагментов (как листы 3 и 6 дома)."""
    p = PP(doc, sh.lay)
    zr = (-1.3, 2.6)
    sysw = ('В1', 'Т3', 'Т4')

    def txt8(pp):
        tg = target(pp)
        if tg == 'баня':
            tg = 'ШВК-Б2'
        if pp.id in ('В1-ШВК-Б1', 'Т3-ШВК-Б1'):
            return f'{pp.sys} {SHORT.get(pp.dn, pp.dn)}: ШВК-Б2 → ШВК-Б1'
        if pp.id == 'Т4-баня':
            return 'Т4 20: ШВК-Б1 → Пс-б1.1, Пс-б1.2, Пс-б2 → Н9 → Б2'
        if pp.id == 'Т3-Б2':
            return 'Т3 20: Б2 → ШВК-Б2'
        if tg.startswith(pp.sys + ' '):
            tg = tg[len(pp.sys) + 1:]
        w0 = tg.split(' ')[0] if tg else ''
        if w0.isalpha() and len(w0) > 3 and w0[0].isupper() and not w0.isupper():
            tg = tg[0].lower() + tg[1:]
        return f'{pp.sys} {SHORT.get(pp.dn, pp.dn)} → {tg}'

    def ex(p, L, V, box):
        for pt, t, sub in (((15.10, 0.40, 0), 'В1 из санитарной трубы Ecoflex Quattro 32×4,4',
                            'от КХ-3 дома (лист 7); в бане — 25×3,5 к ШВК-Б2'),
                           ((14.35, 1.77, 0.6), 'ШВК-Б2 (В1, Т3) — ниша в перегородке б3/б4,',
                            'нажимной люк под плитку со стороны б3 (лист 13)'),
                           ((5.55, 3.80, 0.6), 'ШВК-Б1 (В1, Т3) — в коробе на перегородке б6/б7',
                            'у двери в помывочную, люк со стороны б6 (лист 13)'),
                           ((15.04, 2.00, 0), 'Б2 200 л (ОВ), ГБ 6 бар, РБ-Б2 12 л', 'в выгородке'),
                           ((12.85, 1.62, 0.25), 'Пс-б1.1', None), ((13.70, 1.62, 0.25), 'Пс-б1.2', None),
                           ((15.60, 2.80, 0.25), 'Пс-б2', None),
                           ((15.45, 2.80, 0.45), 'Н9, клапан обратный', 'на Т4, +0,450'),
                           ((VK.X_PK3, VK.Y_PK3, 0.44), 'ПК-3 — кран незамерзающий 1/2" × 3/4",',
                            'шток 350 мм через стену (лист 14, узел 9)'),
                           ((5.30, 3.58, -0.2), 'В1, Т3 к Д-б1, СПА, В-б1 — в полу,', 'сквозь перегородку б6/б7 в гильзах')):
            L.shelf(V.P(pt), t, 1.9, sub=sub)
    V, box, L = fragment(doc, sh, p, 'bath', 370, 405, -0.45, -0.85, 16.25, 6.90, zr, sysw, bld='b', k=25,
                         title='Баня. План водопровода В1, Т3, Т4. М 1:25', title_h=4.0, marks_floor=1,
                         eqs=('ШВК-Б1', 'ШВК-Б2', 'Б2', 'РБ-Б2', 'КЗП-2'), extra=ex,
                         skip=('ШВК-Б1В', 'ШВК-Б1Т', 'ШВК-Б2В', 'ШВК-Б2Т'), leak=1, text=txt8)
    sh.notes(24, 232, 600, NOTES8, h=2.0, spacing=1.0)
    legend(p, 660, 222)
    return doc


