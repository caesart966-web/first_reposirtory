def sheet9(doc, sh):
    p = PP(doc, sh.lay)
    import vk_frag
    vk_frag.K = 50
    zr = (-1.5, 4.5)

    def txt(pp):
        if pp.sys == 'К1в':
            return 'Ст.К1-б Ø110 — вытяжная часть над кровлей +0,35'
        z0 = pp.pts[0][2] - pp.od / 2
        z1 = pp.pts[-1][2] - pp.od / 2
        return f'{pp.id}: Ø{pp.dn}, i={VK.i_txt(pp)}, лоток {lev(z0)} → {lev(z1)}'

    def ex(p, L, V, box):
        k = {pp.id: pp for pp in VK.PIPES}['К1-б']
        L.shelf(V.P(k.pts[-1]), 'Выпуск К1-б Ø110 → НВК', 2.0, sub=f'лоток {lev(k.pts[-1][2] - k.od / 2)}')
        for pp in VK.PIPES:
            if pp.bld == 'b' and pp.sys == 'К1в':
                L.shelf(V.P(pp.pts[0]), 'Ст.К1-б Ø110 — вытяжная часть', 1.9, sub='сквозь кровлю бани, +0,35 над ней')
    V, box, L = fragment(doc, sh, p, 'bath', 200, 194, -0.45, -1.10, 16.25, 6.90, zr, ('К1', 'К1в'), bld='b',
                         title='', marks_floor=1, extra=ex, text=txt)
    for pp in VK.PIPES:
        if pp.bld == 'b' and pp.sys == 'К1' and pp.where == 'ground' and pp.id != 'К1-б':
            a = V.P(pp.pts[0])
            p.circle(a[0], a[1], 0, 'ВК_К1', r_paper=max(0.8, pp.od * V.s / 2))
    sh.s.text('Баня. План канализации К1. М 1:50', 200, box[3] + 13, h=3.5, align='center')
    sh.notes(24, 109, 200, NOTES9, h=1.9, spacing=1.0)
    legend(p, 240, 98, k1=True)
    return doc


