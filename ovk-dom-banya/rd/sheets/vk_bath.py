def sheet8(doc, sh):
    p = PP(doc, sh.lay)
    zr = (-1.3, 2.6)
    sysw = ('В1', 'Т3', 'Т4')
    import vk_frag
    vk_frag.K = 50

    def ex(p, L, V, box):
        for pt, t, sub in (((15.10, 0.40, 0), 'В1 из санитарной трубы Ecoflex Quattro 32×4,4',
                            'от КХ-3 дома (лист 7); в бане — 25×3,5 к ШВК-Б'),
                           ((13.26, 2.00, 0), 'ШВК-Б (В1, Т3) — лист 13', 'накладной, на перегородке б3/б4'),
                           ((12.00, 2.88, 0), 'В1, Т3 к приборам б6, б7 — в полу', 'сквозь стену б2/б6 в гильзах'),
                           ((15.04, 2.00, 0), 'Б2 200 л (ОВ), ГБ 6 бар, РБ-Б2 12 л', 'в выгородке'),):
            L.shelf(V.P(pt), t, 1.9, sub=sub)
    V, box, L = fragment(doc, sh, p, 'bath', 205, 316, -0.45, -0.85, 16.25, 6.90, zr, sysw, bld='b',
                         title='', marks_floor=1, eqs=(), extra=ex, label=False, leak=1)
    sh.s.text('Баня. План водопровода В1, Т3, Т4. М 1:50', 205, box[3] + 15, h=3.5, align='center')
    vk_frag.K = 25

    def ex2(p, L, V, box):
        for pt, t, sub in (((12.85, 1.62, 0), 'Пс-б1.1', None), ((13.70, 1.62, 0), 'Пс-б1.2', None),
                           ((15.60, 2.80, 0), 'Пс-б2', None), ((15.45, 2.80, 0), 'Н9, клапан обратный', 'на Т4, +0,450')):
            L.shelf(V.P(pt), t, 1.8, sub=sub)
    def txt8(pp):
        tg = target(pp)
        if tg == 'баня':
            tg = 'ШВК-Б'
        if tg.startswith(pp.sys + ' '):
            tg = tg[len(pp.sys) + 1:]
        w0 = tg.split(' ')[0] if tg else ''
        if w0.isalpha() and len(w0) > 3 and w0[0].isupper() and not w0.isupper():
            tg = tg[0].lower() + tg[1:]
        return f'{pp.sys} {SHORT.get(pp.dn, pp.dn)} → {tg}'
    fragment(doc, sh, p, 'bath', 105, 100, 12.35, -0.65, 16.05, 3.40, zr, sysw, bld='b',
             title='Фрагмент: с/у б3, раздевалка б4, ШВК-Б, Б2. М 1:25', marks_floor=1,
             eqs=('ШВК-Б', 'Б2', 'РБ-Б2', 'КЗП-2'), extra=ex2, skip=('ШВК-БВ', 'ШВК-БТ'), leak=1, text=txt8)
    sh.notes(200, 196, 190, NOTES8, h=1.9, spacing=1.0)
    legend(p, 410, 190)
    return doc


