def shelf_clean(L, V, at, text, h, sub=None, pipes=(), r_max=70.0, prefer=None, pad=0.6):
    """Полка на свободном поле, выноска которой не пересекает ни трубы pipes (на листе), ни чужие выноски и полки
    (Заказчица 29–30.10.2026: «выноски на пустые поля, чтобы хорошо читались»). Места — сетка смещений по
    возрастанию длины выноски; prefer — сначала заданные смещения; pad — зазор до занятых мест. Нет места — None."""
    p = L.p
    segs = []
    for pp in pipes:
        q = [V.P(pt) for pt in pp.pts]
        segs += [(a, b) for a, b in zip(q, q[1:]) if abs(a[0] - b[0]) + abs(a[1] - b[1]) > 1e-6]
    w = max(p.tw(text, h), p.tw(sub, h) if sub else 0) + 1.6
    top = h * 1.25 + 0.9
    bot = top if sub else 0.4
    grid = sorted({(dx, dy) for dx in range(-int(r_max), int(r_max) + 1, 2) for dy in range(-40, 41, 2)
                   if abs(dx) >= 3 and dx * dx + dy * dy <= r_max * r_max},
                  key=lambda c: c[0] * c[0] + 2.0 * c[1] * c[1])
    for dx, dy in list(prefer or []) + grid:
        x0 = at[0] + dx if dx >= 0 else at[0] + dx - w
        r = (x0, at[1] + dy - bot, x0 + w, at[1] + dy + top)
        e = (x0 if dx >= 0 else x0 + w, at[1] + dy)
        if not (L.free(r, pad) and L._clean(at, e, r)):
            continue
        if any(_seg_x(at, e, a, b) for a, b in segs):
            continue
        rr = (r[0] - 0.4, r[1] - 0.4, r[2] + 0.4, r[3] + 0.4)
        if any(_seg_rect(a, b, rr) for a, b in segs):          # текст полки — не на трубе
            continue
        return L.shelf(at, text, h, sub=sub, force=(dx, dy))
    return None

def unhide(L, V, key, area=None):
    """Надписи подложки на выключенных слоях (отметки и марки осей Revit) на листе не видны — снимаем их с занятых
    мест; area — только те, что задевают этот прямоугольник листа."""
    from ezdxf import recover, bbox
    from underlay import OX, OY
    from rdbase import UNDER
    hid = []
    for e in recover.readfile(UNDER[key])[0].modelspace().query('TEXT MTEXT'):
        if e.dxf.layer in ('S-GRID-IDEN', 'A-ANNO-DIMS', 'G-ANNO-DIMS'):
            b = bbox.extents([e], fast=True)
            if b.has_data:
                a = V.P(((b.extmin.x - OX) / 1000, (b.extmin.y - OY) / 1000, 0))
                c = V.P(((b.extmax.x - OX) / 1000, (b.extmax.y - OY) / 1000, 0))
                hid.append((min(a[0], c[0]) - 1, min(a[1], c[1]) - 1, max(a[0], c[0]) + 1, max(a[1], c[1]) + 1))

    def gone(r):
        if area is not None and not (r[0] < area[2] and r[2] > area[0] and r[1] < area[3] and r[3] > area[1]):
            return False
        return any(h[0] <= (r[0] + r[2]) / 2 <= h[2] and h[1] <= (r[1] + r[3]) / 2 <= h[3] for h in hid)
    L.busy[:] = [r for r in L.busy if not gone(r)]


