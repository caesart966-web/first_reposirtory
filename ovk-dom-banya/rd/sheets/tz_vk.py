def legend(sh, x, y):
    s = sh.s
    s.text('Условные обозначения', x + 45, y, h=3.0, align='center')
    y -= 8
    sh.p.rect(x + 3, y - 1.05, x + 5.1, y + 1.05, 'ТЗ_ВК', fill=5)
    s.text('подключение к водопроводу (В1, Т3, Т4, вода СПА)', x + 10, y, h=2.2)
    y -= 6
    sh.p.rect(x + 3, y - 1.05, x + 5.1, y + 1.05, 'ТЗ_ВК_К', fill=30)
    s.text('выпуск в канализацию (конденсат, трап, сбросы)', x + 10, y, h=2.2)
    y -= 6
    sh.p.line(x + 1, y, x + 7, y, 'ТЗ_ВК_К', ltype='ОВ_ПУНКТ')
    s.text('дренаж конденсата, сбросы (ОВ) — для увязки', x + 10, y, h=2.2)
    y -= 6
    sh.p.rect(x + 1, y - 1.5, x + 7, y + 1.5, 'ТЗ_контекст')
    s.text('оборудование ОВ (по листам РД ОВ) — для ориентации', x + 10, y, h=2.2)
    return y - 4


