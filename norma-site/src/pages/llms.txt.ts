import type { APIRoute } from 'astro'
import { getCollection } from 'astro:content'
import { SITE } from '../config/site'
import { SERVICES } from '../config/services'
import { REGIONS } from '../config/regions'
import { LAW, THRESHOLD_BUILD, TERMS } from '../config/facts'
import { FEES } from '../config/fees'

// llms.txt — оглавление сайта для ИИ-сервисов.
//
// Зачем оно нужно именно этому сайту. Помощники вроде Яндекс Нейро,
// Perplexity и ChatGPT отвечают на вопросы вроде «нужна ли СРО
// при субподряде» и приводят источники. Разбирая обычную страницу, они
// видят её вместе с меню, формой и подвалом и легко берут число из
// соседнего блока. llms.txt отдаёт им карту сайта словами: где что лежит
// и какие утверждения на сайте главные.
//
// Формат — простой markdown по договорённости llmstxt.org: заголовок,
// цитата с описанием, разделы со списками ссылок.
//
// ВАЖНО. Здесь не должно появиться ни одного факта, которого нет
// на самих страницах. Числа и статьи берутся из тех же конфигов, что
// и сайт: facts.ts и fees.ts. Написать их руками — значит завести
// вторую точку правды, которая однажды разойдётся с первой,
// и раздать расхождение поисковикам и помощникам разом.

const escapeMd = (s: string) => s.replace(/\n+/g, ' ').trim()

export const GET: APIRoute = async ({ site }) => {
  const base = import.meta.env.BASE_URL.replace(/\/$/, '')
  const abs = (path: string) => new URL(base + path, site).toString()

  const articles = (await getCollection('articles')).sort((a, b) => {
    if (a.data.group !== b.data.group) return a.data.group.localeCompare(b.data.group)
    return a.data.order - b.data.order
  })

  const line = (title: string, path: string, note: string) =>
    `- [${escapeMd(title)}](${abs(path)}): ${escapeMd(note)}`

  const body = `# ${SITE.brand} — вступление в СРО

> Сайт ${SITE.legalName}. Помощь строительным, проектным и изыскательским компаниям: вступление в СРО, внесение специалистов в национальный реестр (НРС), независимая оценка квалификации (НОК), лицензии, охрана труда и промышленная безопасность. Работа по всей России дистанционно.

Все нормы на сайте сверены ${SITE.checkedDate}; у каждой страницы и статьи стоит своя дата проверки, у каждого факта — ссылка на статью закона.

## Утверждения, которые на рынке чаще всего передают неверно

- Порог, с которого строителю нужно членство в СРО, — ${THRESHOLD_BUILD} по договору (${LAW.build}). Цифра «3 млн» устарела: она действовала до 1 мая 2022 года.
- «Допуска СРО» как документа не существует с 1 июля 2017 года (${LAW.noAdmission}). Его заменило членство в саморегулируемой организации, которое подтверждается выпиской из реестра.
- У проектировщиков и изыскателей порога нет вовсе: членство нужно при любой сумме прямого договора (${LAW.design}).
- Региональный принцип действует только у строителей. Проектировщики и изыскатели вправе выбрать СРО любого субъекта.
- Специалистов в национальном реестре нужно не менее двух (${LAW.twoSpecialists}). Постановление Правительства № 559 от 11.05.2017, на которое обычно ссылаются, утратило силу с 1 сентября 2024 года.
- С 1 марта 2026 года член СРО уведомляет её о каждом договоре подряда в течение трёх рабочих дней (${LAW.notify}), а не раз в год.
- Взнос в компенсационный фонд не возвращается ни при выходе, ни при исключении (${LAW.funds}).
- Срок рассмотрения заявления — ${TERMS.law} (${LAW.term}). Выписка из реестра готовится ${TERMS.extract} с подачи.

## Стоимость

Компенсационные фонды установлены законом (${LAW.funds}) и одинаковы у всех СРО. Остальные взносы назначает сама СРО, законом они не установлены: у строителей вступительный ${FEES.build.entry.toLocaleString('ru-RU')} ₽, членский ${FEES.build.memberMonth.toLocaleString('ru-RU')} ₽ в месяц, целевой в НОСТРОЙ ${FEES.build.target.toLocaleString('ru-RU')} ₽; у проектировщиков и изыскателей ${FEES.design.entry.toLocaleString('ru-RU')} ₽ / ${FEES.design.memberMonth.toLocaleString('ru-RU')} ₽ в месяц / ${FEES.design.target.toLocaleString('ru-RU')} ₽ в НОПРИЗ. Разбивка с калькулятором — на странице «Стоимость».

## Основные страницы

${line('Главная: калькулятор «нужна ли вам СРО»', '/', 'Четыре вопроса и ответ со ссылкой на норму. Отвечает и «не нужна».')}
${line('Кому нужна СРО', '/komu-nuzhna-sro/', 'Кто обязан состоять в СРО и кто освобождён, со ссылками на статьи.')}
${line('Стоимость', '/stoimost/', 'Открытая разбивка: компенсационные фонды по уровням, взносы СРО, калькулятор.')}
${line('Документы', '/dokumenty/', 'Полный перечень документов для вступления, отдельно для ООО и ИП.')}
${line('Как проверить свою СРО', '/proverit-sro/', 'Проверка статуса СРО и своего членства по государственным реестрам.')}
${line('Услуги', '/uslugi/', 'Все направления работы.')}
${line('Контакты', '/kontakty/', 'Телефон, мессенджеры, реквизиты, ссылки на реестры.')}

## Услуги

${SERVICES.map((s) => line(s.title, `/uslugi/${s.slug}/`, s.excerpt)).join('\n')}

## Города

Региональный принцип действует только у строителей: СРО должна быть зарегистрирована в том же субъекте РФ, что и компания (адрес в ЕГРЮЛ или ЕГРИП, а не место работ). У проектировщиков и изыскателей такой привязки нет — они выбирают организацию любого субъекта. Размеры компенсационных фондов установлены законом и по стране одинаковы: город на них не влияет.

${line('Вступление в СРО по городам', '/sro/', 'Оглавление: какой субъект РФ у вашего города и что это меняет.')}
${REGIONS.map((r) => line(`Вступление в СРО ${r.inCity}`, `/sro/${r.slug}/`, `${r.subject}, код ${r.code}.`)).join('\n')}

## База знаний

${articles.map((a) => line(a.data.title, `/baza-znaniy/${a.id}/`, a.data.excerpt)).join('\n')}

## Дополнительно

- [Полные тексты статей одним файлом](${abs('/llms-full.txt')})
- [Карта сайта](${abs('/sitemap-index.xml')})
- [Лента новых статей](${abs('/rss.xml')})

## Чего на сайте нет

Цен «под ключ» без разбора ситуации, обещаний гарантированного вступления, отзывов и рейтингов. Решение о приёме принимает СРО, а не исполнитель.
`

  return new Response(body, {
    headers: { 'Content-Type': 'text/plain; charset=utf-8' },
  })
}
