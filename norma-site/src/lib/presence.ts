// Что сейчас быстрее — позвонить или написать.
//
// Режим круглосуточный, поэтому строка не говорит «открыто / закрыто»:
// такой индикатор всегда горел бы зелёным и читался бы наклейкой
// «мы всегда онлайн», которой никто не верит. Она говорит то, что
// действительно меняется за сутки: днём быстрее дозвониться, ночью —
// написать.
//
// Время московское, независимо от часового пояса посетителя: клиенту
// из Иркутска важно, который час у того, кому он звонит.
//
// Одна функция на два места — строку «Сейчас на связи» на «Контактах»
// и строку под кнопками первого экрана (с 06.10.2026). Фразы у них
// разной длины, а решение одно: если бы каждое место считало часы
// по-своему, первый экран и контакты однажды сказали бы разное.

export interface Presence {
  /** on — день, звоните или пишите; night — ночь, быстрее написать. */
  state: 'on' | 'night'
  /** Для «Контактов»: там под строку отдана целая полоса. */
  long: string
  /** Для первого экрана: строка под именем, рядом с фотографией. */
  short: string
}

export function presence(now: Date = new Date()): Presence {
  const parts = Object.fromEntries(
    new Intl.DateTimeFormat('en-US', {
      timeZone: 'Europe/Moscow',
      weekday: 'short',
      hour: 'numeric',
      hour12: false,
    })
      .formatToParts(now)
      .map((p) => [p.type, p.value]),
  )
  // hour12: false в полночь отдаёт «24» — приводим к нулю.
  const hour = Number(parts.hour) % 24
  const weekend = parts.weekday === 'Sat' || parts.weekday === 'Sun'

  if (hour < 8 || hour >= 22) {
    return {
      state: 'night',
      long: 'Ночь в Москве — быстрее всего написать в мессенджер',
      short: 'Ночь в Москве — быстрее написать',
    }
  }
  if (weekend) {
    return {
      state: 'on',
      long: 'Выходной, но на связи — звоните или пишите',
      short: 'Выходной, но на связи',
    }
  }
  return { state: 'on', long: 'Сейчас на связи, отвечу сразу', short: 'Сейчас на связи' }
}
