//
// Зачем отдельная страница. Алиса, ChatGPT, Google и другие помощники
// отвечают на вопрос и ставят ссылку на страницу, где ответ сказан прямо:
// вопрос — заголовком, ответ — первой фразой, рядом норма и дата. Разборы
