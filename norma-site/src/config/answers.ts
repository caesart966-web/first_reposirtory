//    что сайт уже говорит в разборе, на который ведёт `more`; числа —
//    из facts.ts и fees.ts, нормы — из LAW.
// 2. `short` — одна фраза, сам ответ: «Да», «Нет», число. Её помощник
//    и процитирует, поэтому без вводных слов и без оговорок, которые
//    меняют смысл: оговорка, если она есть, — в `detail`.
// 3. `quote` — дословный текст нормы, только если его прочитал робот
//    «НОРМА: прочитать текст закона» (дата и сайты — в SVERKA.md). Пересказ
//    в кавычках сюда не ставится.
// 4. Якорь (id) — латиницей и не меняется: на него ведут ссылки снаружи.
// 5. Дата у ответа — дата сверки разбора из `more` (берётся на странице
//    из коллекции статей), а не сегодняшняя.

