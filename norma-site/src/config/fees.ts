// ВЗНОСЫ КОНКРЕТНЫХ СРО — единая точка правды для сумм, которые не устанавливает закон.
//
// ГЛАВНОЕ ОТЛИЧИЕ ОТ facts.ts. Там лежат компенсационные фонды: их размеры
// установлены статьёй 55.16 ГрК РФ, одинаковы у всех СРО страны и рядом
// с ними на сайте стоит чип со статьёй. Здесь — вступительный взнос,
// членские, целевой взнос в национальное объединение и страхование. Закон
// их не устанавливает: каждая СРО определяет их своими внутренними
// документами, и у соседней СРО они будут другими.
//
// Отсюда правило, которое нельзя нарушать: рядом с этими суммами НЕ должно
// появиться чипа со статьёй закона. Чип на сайте означает «так написано
// в законе», и поставить его здесь значило бы выдать коммерческие условия
// за норму. Ровно за это сайт критикует конкурентов.
//
// Суммы ниже — условия тех СРО, с которыми работает заказчик. Он назвал их
// сам; проверить их по открытым источникам нельзя, потому что внутренние
// документы СРО не сведены ни в один реестр. Поэтому на сайте они всюду
// подписаны как условия конкретных СРО, а не как «цены рынка».
//
// Целевой взнос у проектировщиков и изыскателей заказчик сначала назвал
// с оговоркой «вроде» (8 000 ₽), потом уточнил и подтвердил: в НОПРИЗ
// это 10 000 ₽ — столько же, сколько строителям в НОСТРОЙ. Проверить сумму
// по открытым источникам всё равно нельзя: размер целевого взноса
// устанавливает сама СРО, и в реестрах его нет.

export type FeeSet = {
  /** Вступительный взнос — разовый, при приёме в члены. */
  entry: number
  /**
   * Членский взнос за ОДИН МЕСЯЦ.
   *
   * Раньше здесь лежало поле memberFirstYear — членский взнос за весь первый
   * год, 5 000 ₽. Заказчик уточнил: 5 000 ₽ стоит месяц. Разница в двенадцать
   * раз, и она была видна на первом экране, в итоге на главной и в разбивке
   * на «Стоимости» — сайт называл цену в двенадцать раз меньше настоящей.
   * Поэтому поле переименовано, а не просто переписано числом: старое имя
   * само подсказывало неверный смысл тому, кто будет править суммы потом.
   */
  memberMonth: number
  /** Целевой взнос в национальное объединение (НОСТРОЙ или НОПРИЗ). */
  target: number
  /** Требуется ли страхование гражданской ответственности в первый год. */
  insuranceFirstYear: boolean
  /** Куда идёт целевой взнос. */
  union: string
}

export const FEES: Record<'build' | 'design', FeeSet> = {
  build: {
    entry: 0,
    memberMonth: 5000,
    target: 10000,
    insuranceFirstYear: false,
    union: 'НОСТРОЙ',
  },
  design: {
    entry: 0,
    memberMonth: 5000,
    target: 10000,
    insuranceFirstYear: false,
    union: 'НОПРИЗ',
  },
}

/**
 * Меняются ли эти взносы от уровня ответственности.
 *
 * Компенсационный фонд — да, и его размеры лежат в facts.ts (FUNDS): они
 * прописаны в законе по уровням. Вступительный, членский и целевой взносы
 * здесь одинаковы для всех уровней — так их назвал заказчик. Если у СРО
 * они окажутся разными по уровням, эту структуру нужно будет развернуть
 * в таблицу по образцу FUNDS, а не подписывать «примерно».
 */
export const FEES_VARY_BY_LEVEL = false

/**
 * Периоды оплаты членских взносов — для калькулятора на «Стоимости».
 * Взнос помесячный, поэтому период умножается на месячную ставку;
 * никаких скидок за длинный период нет, и придумывать их нельзя.
 */
export const MEMBER_PERIODS = [
  { months: 1, label: '1 месяц' },
  { months: 3, label: '3 месяца' },
  { months: 6, label: '6 месяцев' },
  { months: 12, label: '12 месяцев' },
] as const

/** Членские взносы за N месяцев. */
export const memberFor = (kind: 'build' | 'design', months: number) =>
  FEES[kind].memberMonth * months

/** Членские взносы за год — то, что раньше ошибочно лежало в memberFirstYear. */
export const memberYear = (kind: 'build' | 'design') => memberFor(kind, 12)

/** Форматирование сумм: 100000 → «100 000 ₽», 0 → «0 ₽». Неразрывный пробел. */
export const money = (n: number) => `${n.toLocaleString('ru-RU').replace(/\s/g, ' ')} ₽`

/**
 * Оговорка, обязательная везде, где показаны эти суммы. Отделяет условия
 * конкретных СРО от норм закона.
 */
export const FEES_NOTE =
  'Это условия саморегулируемых организаций, с которыми я работаю, а не нормы закона: вступительный, членский и целевой взносы каждая СРО устанавливает своими документами. У другой СРО суммы будут другими.'
