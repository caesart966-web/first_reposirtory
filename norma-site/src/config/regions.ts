// Зачем они вообще. Запрос «вступить в СРО в Москве» — это другой запрос,
// чем «вступить в СРО». Отвечать на него общей страницей нечем: поисковик
// ищет соответствие городу, а его на сайте не было ни одного.
//
// ГЛАВНАЯ ОПАСНОСТЬ ЗДЕСЬ — ДОРВЕИ. Двадцать одинаковых страниц, где
// подменено только название города, Яндекс и Google распознают и наказывают
// весь сайт целиком. Поэтому у каждого города здесь записано то, чего нет
// у других: субъект РФ и его код, соседний субъект, с которым этот город
// путают, и в чём именно ошибка. Это не украшение текста — это единственное,
// что отличает такую страницу от дорвея. Добавляете город — пишите ему
// СВОЙ разбор, а не переставляйте слова из соседнего.
// Стережёт scripts/test-regions.mjs: он меряет, сколько текста на странице
// не встречается ни на одной другой, и падает, если мало.
//
// ЧЕГО ЗДЕСЬ БЫТЬ НЕ ДОЛЖНО. Числа, которых я не знаю: сколько СРО в регионе,
// сколько там стоит вступление, за сколько дней принимают. Правило сайта
// то же, что везде: отсутствие факта дешевле факта, за который нельзя
// ответить. Всё, что здесь написано, — это география субъектов РФ
// и следствия из регионального принципа.

export type Region = {
  /** Часть адреса: /sro/moskva/ */
  slug: string
  /** Именительный падеж: «Москва» */
  city: string
  /** Предложный с предлогом: «в Москве» */
  inCity: string
  /** Родительный: «Москвы» — для оборота «компании из Москвы» */
  ofCity: string
  /** Субъект РФ полностью: «город Москва», «Ростовская область» */
  subject: string
  /** Предложный субъекта: «в городе Москве», «в Ростовской области» */
  inSubject: string
  /** Код субъекта в реестрах и на автомобильных номерах. */
  code: string
  /** Разговорные названия — чтобы страница находилась и по ним. */
  aliases: string[]
  /** Разбор ошибки, которую делают именно в этом городе. */
  trap: string
  /** Что ещё полезно знать про этот субъект. */
  around: string
  /**
   * Соседние субъекты, которые путают с этим. Не «все граничащие» —
   * только те, где путаница реально случается: одинаковые названия,
   * сплошная застройка через границу, общее разговорное имя региона.
   */
  neighbours: { name: string; code: string }[]
  /**
   * Своя фотография в тёмной шапке. Файл кладётся в public/img/,
   * здесь пишется только имя — например 'moskva.webp'.
   * Пусто — шапка остаётся ровно тёмной, и это нормально.
   *
   * ВАЖНО: поставили фотографию — прогоните node scripts/test-hero-photo.mjs.
   * Он снимает настоящие пиксели под каждой строкой и требует контраста 4.5:1;
   * светлое небо или белая стена в кадре делают заголовок нечитаемым,
   * а по стилям этого не видно — там ровный тёмный фон.
   */
  photo?: string
  /** Точка кадра, которая должна остаться в поле зрения: '70% 40%'. */
  photoPos?: string
}

