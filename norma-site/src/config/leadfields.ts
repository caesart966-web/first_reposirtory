//
// Виды работ спрашивают в двух местах: в калькуляторе «Нужна ли вам СРО»
// и в форме заявки. Списки обязаны совпадать — иначе калькулятор ответит
// «снос», а в форме такого варианта не окажется, и подстановка тихо
// промахнётся. Раньше форма вообще спрашивала свободной строкой
// «Город и вид работ», и приходило «строю дома» и «перезвоните»:
// заявки были несравнимы между собой, а первый ответ всегда начинался
// с уточняющего вопроса.
//
// ИДЕНТИФИКАТОРЫ ЗДЕСЬ — ТЕ ЖЕ, ЧТО В Calculator.astro (build / design /
// survey / demolition). Переименуете — подстановка из калькулятора
// перестанет работать, и заметить это без проверки нельзя: форма просто
// останется пустой. Стережёт scripts/test-form.mjs.

export type WorkKind = { id: string; label: string }

export const WORK_KINDS: readonly WorkKind[] = [
  { id: 'build', label: 'Строительство, реконструкция, капремонт' },
  { id: 'design', label: 'Проектирование' },
  { id: 'survey', label: 'Инженерные изыскания' },
  { id: 'demolition', label: 'Снос объектов' },
  { id: 'unknown', label: 'Пока не знаю' },
] as const

/** Подпись вида работ по идентификатору — для письма и для подстановки. */
export const workKindLabel = (id: string) =>
  WORK_KINDS.find((k) => k.id === id)?.label ?? ''

/** Подписи ответа про специалистов НРС — для письма. */
export const NRS_LABEL: Record<string, string> = {
  yes: 'нужна помощь, своих нет или не проходят',
  no: 'не нужна, специалисты уже в реестре',
  idk: 'не знает, нужно разобраться',
}

/**
 * Ключ, через который калькуляторы передают расчёт в форму заявки.
 *
 * sessionStorage, а не адресная строка: расчёт — это несколько строк
 * текста, и тащить их через URL значит получить ссылку на пол-экрана,
 * которую посетитель увидит и, чего доброго, куда-нибудь отправит.
 * И не localStorage: расчёт живёт один заход, а не вечно.
 */
export const CALC_KEY = 'norma-calc'

/**
 * Сколько расчёт считается свежим, миллисекунды.
 *
 * Полчаса. Человек, вернувшийся на сайт назавтра, не должен получить
 * в заявку вчерашний расчёт, о котором он уже забыл, — а именно так
 * выглядела бы «заботливая» подстановка без срока.
 */
export const CALC_TTL = 30 * 60 * 1000
