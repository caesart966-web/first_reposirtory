// ГЛАВНОЕ ПРАВИЛО, соблюдать при любых правках.
//
// Это НЕ нормы закона, а условия конкретных СРО, с которыми работает
// заказчик. Закон таких льгот не устанавливает и устанавливать не может:
// он задаёт минимальные размеры компенсационных фондов и требования
// к членству, а вступительный взнос, членские взносы и страхование —
// это внутренние документы каждой СРО.
//
// Поэтому нигде рядом с этими пунктами НЕ должно появиться чипа со статьёй
// закона: чип на сайте означает «это написано в законе», и поставить его
// здесь значило бы выдать коммерческие условия за норму. Ровно за это
// сайт критикует конкурентов на странице «Как проверить СРО».
//
// По той же причине у блока есть строка о том, что набор условий зависит
// от подобранной СРО. Убирать её нельзя.
//
// ВТОРОЕ ПРАВИЛО. Условия здесь и суммы в src/config/fees.ts обязаны
// сходиться. Один раз они разошлись: карточка обещала «вступительный взнос
// 0 ₽» и «первый год без членских взносов», а в разбивке стоимости у тех же
// проектировщиков был вступительный 8 000 ₽ и членский 5 000 ₽. Посетитель,
// сравнивший первый экран со страницей стоимости, поймал бы сайт на
// неправде — и именно этим сайт бьёт конкурентов. Меняете суммы в fees.ts —
// перечитайте эти пять пунктов.

export type OfferPoint = {
  /**
   * Строка карточки на первом экране — как в прайсе: подпись слева,
   * значение справа. Раньше была одна строка («Мои услуги — 0 ₽»);
   * разведены 28.09.2026, когда карточка стала тарифом по образцу сайта
   * СРО «СОМ», который прислал заказчик: суммы, стоящие одной колонкой
   * у правого края, сравниваются взглядом, а не чтением.
   */
  label: string
  value: string
  /** Значение — льгота (0 ₽, «не нужно»): набирается зелёным. */
  good?: boolean
  /** Полная формулировка — для блока предложения. */
  full: string
  /** Пояснение под ней. */
  note: string
}

/** «Мои услуги — 0 ₽» — одной строкой, для ролика и текстов. */
export const offerLine = (p: OfferPoint) => `${p.label} — ${p.value}`

