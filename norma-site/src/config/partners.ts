/**
 * Что список партнёров означает для компаний ИМЕННО этого города.
 *
 * Смысл пишется руками для каждого города: вывод из регионального принципа
 * у Москвы, Петербурга и Ростова разный, общей формулировкой его не закрыть.
 * А вот КТО в списке — имена и счёт — берётся из PARTNERS. До 01.10.2026
 * пояснения были целиком текстом, и московское говорило «строительная СРО
 * в списке такая одна: АСО «МСК»» уже после того, как под ним встал РОСТ,
 * а проектным называло один ЯРД рядом с карточкой ИТП. Добавили партнёра —
 * пояснение пересчиталось само; пропал целый вид — сборка падает и просит
 * переписать смысл, потому что «есть куда вступать любому профилю»
 * без организаций этого вида стало бы неправдой.
 */
const NUM_F = ['', 'одна', 'две', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять', 'десять']
const ofKind = (slug: string, kind: 'build' | 'design' | 'survey') =>
  PARTNERS.filter((p) => p.citySlug === slug && p.reg && partnerKind(p.reg) === kind).map((p) => p.short)
const joinRu = (xs: readonly string[]) => (xs.length < 2 ? xs.join('') : `${xs.slice(0, -1).join(', ')} и ${xs[xs.length - 1]}`)
const count = (n: number, forms: readonly [string, string, string]) => {
  const form = n % 10 === 1 && n % 100 !== 11 ? forms[0] : n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 12 || n % 100 > 14) ? forms[1] : forms[2]
  return `${NUM_F[n] ?? n} ${form}`
}
const need = (slug: string, kind: 'build' | 'design' | 'survey') => {
  const xs = ofKind(slug, kind)
  if (!xs.length) throw new Error(`PARTNERS_NOTE: у города ${slug} не осталось партнёров вида ${kind} — перепишите пояснение, оно на них опирается`)
  return xs
}

