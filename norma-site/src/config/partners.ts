// СРО, С КОТОРЫМИ РАБОТАЕТ ЗАКАЗЧИК, — единая точка правды для партнёров.
//
// Данные пришли из коммерческого предложения заказчика (КП «Сопровождение
// вступления в СРО»), то есть от него самого. Регистрационные номера при этом
// проверяемые: каждый из них есть в государственном реестре саморегулируемых
// организаций, и посетитель может открыть реестр и убедиться. Это и есть
// причина, по которой список вообще можно ставить на сайт: у названий здесь
// нет ничего, что нельзя было бы сверить за минуту.
//
// ЧТО ИЗ КП СЮДА НЕ ПОПАЛО И ПОЧЕМУ.
//
// 1. Колонка «Взнос в КФ: от 50 000 / от 100 000 ₽». Это НЕ условие СРО,
//    а установленный законом минимальный размер компенсационного фонда
//    возмещения вреда первого уровня: ст. 55.16 ГрК РФ, 100 000 ₽
//    у строителей и 50 000 ₽ у проектировщиков и изыскателей. Суммы
//    совпадают с FUNDS в facts.ts до рубля. Показывать закон в карточке
//    партнёра значило бы выдать норму за его условие — ровно наоборот
//    к тому, за что сайт критикует конкурентов. Фонды показываются
//    отдельно и со статьёй.
//
// 2. Оценочные формулировки: «одна из старейших и уважаемых», «солидное»,
//    «динамично развивающаяся». Проверить их нельзя, а сайт держится
//    на том, что проверить можно всё. Вместо них — дата внесения в реестр
//    и специализация. Заодно ушло внутреннее противоречие КП: «одна
//    из старейших» стояло рядом с «основана в 2019 году».
//
// 3. «Входит в структуры НОСТРОЙ» у строительной СРО. Это не отличие:
//    членство в национальном объединении обязательно для ВСЕХ СРО своего
//    вида. Как признак выбора это ввело бы в заблуждение.
//
// 4. Целевой взнос 8 000 ₽. Заказчик подтвердил: в НОСТРОЙ и в НОПРИЗ
//    это 10 000 ₽, в КП ошибка. Сумма и так лежит в fees.ts (FEES.*.target),
//    и здесь она не дублируется — иначе завелась бы вторая точка правды.
//
// ДАТА НЕ ХРАНИТСЯ ОТДЕЛЬНО. Последние восемь цифр регистрационного номера —
// это дата внесения СРО в государственный реестр: СРО-С-308-08092022 — 8
// сентября 2022 года. Она вычисляется из номера функцией regDate(), поэтому
// разойтись с ним не может. Во всех семи номерах год совпал с годом,
// названным в КП, — это и была проверка, что номера прочитаны верно.

import type { FeeSet } from './fees'

export type Partner = {
  /** Полное название — как в государственном реестре. */
  name: string
  /** Короткое имя для заголовка карточки. */
  short: string
  /**
   * Регистрационный номер в государственном реестре СРО.
   * Из него же берутся вид организации (С / П / И) и дата внесения.
   *
   * ПУСТАЯ СТРОКА = номер ещё не подтверждён, и такая организация
   * на сайт НЕ выводится (partnersOf её отфильтровывает). Весь раздел
   * держится на том, что каждую строку можно открыть в государственном
   * реестре; карточка без номера — это «работаем с надёжными СРО»,
   * то есть ровно то, что здесь считается пустым словом. Запись при этом
   * не выбрасывается: она ждёт номера на виду, и npm run facts о ней
   * напоминает, — иначе её просто забудут.
   */
  reg: string
  /** Город регистрации — по нему карточка попадает на страницу города. */
  citySlug: string
  /** Чем эта СРО отличается от соседней. Только проверяемые факты. */
  note: string
  /**
   * Условия, которыми эта СРО отличается от общего предложения (fees.ts).
   * Пусто — значит условия те же, что на первом экране сайта.
   * Здесь лежат ТОЛЬКО отличия: так страница не сможет разойтись
   * с предложением молча, она обязана назвать разницу вслух.
   */
  fees?: Partial<Pick<FeeSet, 'entry' | 'memberMonth' | 'target'>>
  /** Если формулировка про страхование отличается от общей. */
  insurance?: string
  /**
   * Логотип для ленты на главной — ключ в src/config/partner-logos.json
   * (файлы и размеры собирает scripts/prepare-partner-logos.py из того,
   * что прислал заказчик). Нет логотипа — в ленте организации нет,
   * а карточка на «Партнёрах» и странице города остаётся.
   */
  logo?: string
}

/** Вид СРО по регистрационному номеру: СРО-С-… / СРО-П-… / СРО-И-… */
export const partnerKind = (reg: string): 'build' | 'design' | 'survey' => {
  const letter = reg.split('-')[1]
  return letter === 'С' ? 'build' : letter === 'П' ? 'design' : 'survey'
}

/** Взносы берутся у строителей из FEES.build, у остальных — из FEES.design. */
export const partnerFeeKind = (reg: string): 'build' | 'design' =>
  partnerKind(reg) === 'build' ? 'build' : 'design'

const KIND_WORD = {
  build: 'строительное',
  design: 'проектное',
  survey: 'изыскательское',
} as const

/** «строительное» / «проектное» / «изыскательское». */
export const partnerKindWord = (reg: string) => KIND_WORD[partnerKind(reg)]

const MONTHS = [
  'января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
  'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря',
]

/**
 * Дата внесения в государственный реестр — из последних восьми цифр номера.
 * СРО-С-308-08092022 → «8 сентября 2022 года».
 */
export const regDate = (reg: string) => {
  const tail = reg.slice(-8)
  const day = Number(tail.slice(0, 2))
  const month = Number(tail.slice(2, 4))
  const year = tail.slice(4)
  return `${day} ${MONTHS[month - 1]} ${year} года`
}

