    c.line(r * mm, -1.6 * mm, r * mm, 1.6 * mm)
    c.line(1.1 * mm, 0.9 * mm, 2.9 * mm, 2.2 * mm); c.line(1.1 * mm, -0.9 * mm, 2.9 * mm, -2.2 * mm)
    c.restoreState()
