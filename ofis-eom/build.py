    c.saveState(); c.translate(x * mm, y * mm); c.rotate(ang); col(rgb); fil(rgb); lw(0.45)
    r = 1.5
    p = c.beginPath(); p.moveTo(0, -r * mm); p.arcTo(-r * mm, -r * mm, r * mm, r * mm, -90, 180); p.close()
