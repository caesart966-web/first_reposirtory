def breaker(x, ytop, ybot, rcd=False):
    """Условное изображение аппарата на вертикальной линии."""
    lw(0.5); col(BLACK)
    ym = (ytop + ybot) / 2
    line(x, ytop, x, ym + 4); line(x, ym - 4, x, ybot)
    line(x, ym - 4, x - 3.2, ym + 3.6)                       # подвижный контакт
    line(x - 1.1, ym + 2.9, x + 1.1, ym + 5.1); line(x - 1.1, ym + 5.1, x + 1.1, ym + 2.9)   # крестик
    if rcd:
        c.ellipse((x - 2.6) * mm, (ym - 9.6) * mm, (x + 2.6) * mm, (ym - 6.4) * mm)
        c.setDash([0.8 * mm, 0.6 * mm]); line(x - 1.7, ym, x - 5.5, ym); line(x - 5.5, ym, x - 5.5, ym - 8); line(x - 5.5, ym - 8, x - 2.6, ym - 8); c.setDash()

