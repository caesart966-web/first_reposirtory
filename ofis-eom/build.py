# ---------- примитивы (всё в миллиметрах листа) ----------
def lw(w): c.setLineWidth(w * mm)
def col(rgb): c.setStrokeColorRGB(*rgb)
def fil(rgb): c.setFillColorRGB(*rgb)
def line(x1, y1, x2, y2): c.line(x1 * mm, y1 * mm, x2 * mm, y2 * mm)
def rect(x, y, w, h, fill=0, stroke=1): c.rect(x * mm, y * mm, w * mm, h * mm, fill=fill, stroke=stroke)
def circ(x, y, r, fill=0, stroke=1): c.circle(x * mm, y * mm, r * mm, fill=fill, stroke=stroke)
def poly(pts, close=False, fill=0, stroke=1):
    p = c.beginPath(); p.moveTo(pts[0][0] * mm, pts[0][1] * mm)
    for x, y in pts[1:]: p.lineTo(x * mm, y * mm)
    if close: p.close()
    c.drawPath(p, fill=fill, stroke=stroke)
def tw(s, size, font='R'): return pdfmetrics.stringWidth(s, font, size) / mm
def text(x, y, s, size=9, font='R', anchor='l', rgb=BLACK, rot=0):
    c.saveState(); fil(rgb); c.setFont(font, size)
    c.translate(x * mm, y * mm)
    if rot: c.rotate(rot)
    {'l': c.drawString, 'c': c.drawCentredString, 'r': c.drawRightString}[anchor](0, 0, s)
    c.restoreState()
def fit(x, y, s, wmax, size=9, font='R', anchor='c', rgb=BLACK):
    while tw(s, size, font) > wmax and size > 4.5: size -= 0.25
    assert tw(s, size, font) <= wmax + 0.01, 'не помещается: ' + s
    text(x, y, s, size, font, anchor, rgb)
def wrap(s, wmax, size, font='R'):
    out, cur = [], ''
    for word in s.split(' '):
        t = (cur + ' ' + word).strip()
        if tw(t, size, font) <= wmax: cur = t
        else: out.append(cur); cur = word
    out.append(cur); return out
def para(x, y, s, wmax, size=9, lead=4.2, font='R', indent=0):
    """Абзац с переносом строк; возвращает y под абзацем."""
    for i, ln in enumerate(wrap(s, wmax - indent, size, font)):
        text(x + (indent if i else 0), y, ln, size, font); y -= lead
    return y
def table(x, ytop, widths, rows, rh, size=8, head=1, aligns=None, headh=None, bold_last=False):
    """Таблица: первая строка — шапка. Возвращает y низа."""
    y = ytop
    for ri, row in enumerate(rows):
        h = (headh or rh) if ri < head else rh
        xx = x
        for ci, cell in enumerate(row):
            w = widths[ci]
            lw(0.5 if ri < head else 0.25); col(BLACK); rect(xx, y - h, w, h)
            al = 'c' if ri < head else (aligns[ci] if aligns else 'l')
            f = 'B' if (ri < head or (bold_last and ri == len(rows) - 1)) else 'R'
            lines = str(cell).split('\n')
            ly = y - h / 2 + (len(lines) - 1) * size * 0.19 - size * 0.125
            for ln in lines:
                if al == 'c': fit(xx + w / 2, ly, ln, w - 1.6, size, f, 'c')
                elif al == 'r': fit(xx + w - 1.2, ly, ln, w - 1.6, size, f, 'r')
                else: fit(xx + 1.2, ly, ln, w - 1.6, size, f, 'l')
                ly -= size * 0.38
            xx += w
        y -= h
    lw(0.5); rect(x, y, sum(widths), ytop - y)
    return y

