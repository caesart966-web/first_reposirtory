def totals(pan):
    G = lambda g: GR[(pan, g)]
    p_l = G(1)['p'] + G(2)['p'] + G(8)['p'] + G(9)['p']; p_s = sum(G(g)['p'] for g in (3, 4, 5, 6)); p_ac = G(7)['p']
    pu = p_l + p_s + p_ac
    pr_s = KS_SOCK * p_s
    pr = p_l + pr_s + p_ac
    q = p_l * math.tan(math.acos(0.95)) + pr_s * math.tan(math.acos(0.9)) + p_ac * math.tan(math.acos(0.85))
    sfull = math.hypot(pr, q); cosf = pr / sfull
    ir = sfull / (math.sqrt(3) * 0.4)
    ph = {f: sum(GR[(pan, g)]['p'] for g in range(1, 10) if GR[(pan, g)]['ph'] == f) for f in ('L1', 'L2', 'L3')}
    return dict(pu=pu, pr=pr, ir=ir, cos=cosf, ph=ph, p_l=p_l, p_s=p_s, pr_s=pr_s, p_ac=p_ac, s=sfull, iph=G(7)['i'])
