// Фирменный водяной знак: архивная гравюра «Themis» позади всего контента.
// Зафиксирован во вьюпорте, контент проезжает поверх. Вне потока, не ловит
// клики, скрыт от скринридеров.
//
// Почему mix-blend-multiply: у гравюры прямоугольная белая подложка, вырезать
// её из растра нечем. При multiply белое становится прозрачным само, остаётся
// только штрих.
//
// Два разных кадра, и это не случайность.
//
// Телефон и планшет: фигура целиком. Высота меньше 100vh, картинка центрована
// по вертикали. Ширина кадра равна 0.586 высоты, поэтому при 58vh и 76vh она
// не упирается в боковые края даже на самом узком телефоне.
//
// Десктоп (от lg): фигура крупная, верх зафиксирован под шапкой, подол уходит
// за нижний край — «вся фигура в кадре» и «фигура во всю высоту экрана» при
// пропорции 1:1.7 несовместимы, и здесь выбран масштаб. Срезается около 30%
// кадра снизу на любой высоте экрана: и высота картинки, и срез считаются от
// vh, поэтому доля держится стабильно.
//
// Маски тоже две. Общая держит фигуру целиком и гасит только края. Десктопная
// сдвинута вверх и сжата по вертикали так, чтобы штрих сходил на нет ДО нижней
// границы экрана: на срезе остаётся 0–7% альфы. Иначе подол обрывался бы
// горизонтальной линейкой во всю ширину окна.
//
// Классы масок записаны литералами: Tailwind сканирует исходники строками,
// до интерполяции ${...} он не доходит и правило просто не сгенерируется.
//
// Прозрачность задана в index.css (.themis-backdrop img) — там же зафиксирован
// потолок по ТЗ (не выше 0.06) и более деликатное значение для телефона.
export function ThemisBackdrop() {
  return (
    <div
      className="themis-backdrop pointer-events-none fixed inset-0 z-0 select-none overflow-hidden"
      aria-hidden="true"
    >
      <img
        src="./img/themis.webp"
        alt=""
        width={938}
        height={1600}
        loading="lazy"
        decoding="async"
        className="
          absolute w-auto max-w-none
          h-[58vh] sm:h-[76vh] lg:h-[130vh]
          top-[calc(50%+32px)] -translate-y-1/2 lg:top-[72px] lg:translate-y-0
          left-1/2 -translate-x-1/2 sm:left-auto sm:translate-x-0
          sm:right-0 lg:right-[3%] xl:right-[8%]
          mix-blend-multiply
          [mask-image:radial-gradient(78%_64%_at_50%_44%,#000_0%,#000_60%,transparent_100%)]
          [-webkit-mask-image:radial-gradient(78%_64%_at_50%_44%,#000_0%,#000_60%,transparent_100%)]
          lg:[mask-image:radial-gradient(80%_38%_at_50%_30%,#000_0%,#000_62%,transparent_100%)]
          lg:[-webkit-mask-image:radial-gradient(80%_38%_at_50%_30%,#000_0%,#000_62%,transparent_100%)]
        "
      />
    </div>
  )
}
