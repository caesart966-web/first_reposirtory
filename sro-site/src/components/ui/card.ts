// Отклик карточки на наведение. Уровня два, и разница между ними не
// декоративная: подъём — это обещание клика.
//
// Карточка, которая приподнимается под курсором, читается как кнопка. Если
// нажать на неё нельзя, обещание ложное, и посетитель тыкает в пустоту. Поэтому
// подъём есть только там, где карточка действительно кликается целиком —
// виды СРО, плитки мессенджеров. Услуги и форматы работы это просто описания,
// им остаётся подсветка без подъёма.
//
// Общее у обоих: рамка набирает цвет, тень уходит с card на card-hover (обе
// заданы в tailwind.config.js). Держим в одном месте, потому что сеток на
// странице четыре, и раньше каждая отзывалась по-своему.
//
// transition-all, а не transition-colors: анимировать нужно и тень тоже.
// При prefers-reduced-motion переходы гасит глобальное правило в index.css.
const base = 'transition-all duration-200 hover:border-accent-400 hover:shadow-card-hover'

/** Карточка кликается целиком. Подъём на 2px — маленький намеренно: в ряду
 *  их три-четыре, и заметный прыжок превращает наведение в аттракцион. */
export const cardHover = `${base} hover:-translate-y-0.5`

/** Карточка только читается. Подсветка есть, обещания клика — нет. */
export const cardHoverStatic = base
