import { useEffect } from 'react'

// Переход на страницу с якорем: '/?sro=construction#quiz' со страницы вида
// СРО, ссылка на раздел из письма или мессенджера.
//
// Браузер прыгает к якорю сразу после разбора HTML — а разметку рисует React,
// и в этот момент нужного элемента ещё нет. Прыжок молча не срабатывает, и
// человек оказывается наверху главной, хотя нажимал «Оставить заявку».
// Поймано проверкой T7 после того, как карточки видов стали вести на
// отдельные страницы.
//
// Прокрутка мгновенная, а не плавная: это открытие страницы, а не переход
// внутри неё. Плавная прокрутка через всю страницу читалась бы как сбой.
export function useHashScroll() {
  useEffect(() => {
    const id = window.location.hash.slice(1)
    if (!id) return
    // Ждём кадр: к следующему у секций уже есть высота, и попадаем точно.
    const frame = requestAnimationFrame(() => {
      document.getElementById(id)?.scrollIntoView({ behavior: 'auto', block: 'start' })
    })
    return () => cancelAnimationFrame(frame)
  }, [])
}
