// Неразрывный пробел после коротких предлогов и союзов: «в СРО», «по задаче».
// Без него узкая колонка оставляет предлог висеть в конце строки
// («Вступление в / СРО») — в русском наборе это ошибка вёрстки.
//
// Слева — просмотр назад, а не захват: у стоящих подряд коротких слов
// («и в СРО») захват съедал пробел первого, и второе оставалось без склейки.
const SHORT = /(?<=^|[\s(«])(в|во|с|со|к|ко|о|об|у|и|а|по|до|на|от|за|из|не)\s+/gi

// Тире не начинает строку: пробел перед ним тоже неразрывный
// («специалист — от первого звонка» переносилось как «специалист /
// — от первого звонка», 01.10.2026).
export function nbsp(text: string): string {
  return text.replace(SHORT, '$1 ').replace(/ +—/g, ' —')
}
