// Дата словами: «15 октября 2026». Свой список месяцев, а не Intl: страница
// собирается и при сборке (entry-server.tsx), и в браузере, и формат
// не должен зависеть от того, какие локали есть у машины.
const MONTHS = [
  'января',
  'февраля',
  'марта',
  'апреля',
  'мая',
  'июня',
  'июля',
  'августа',
  'сентября',
  'октября',
  'ноября',
  'декабря',
]

/** '2026-10-15' → '15 октября 2026'. */
export function formatDate(iso: string): string {
  const [year, month, day] = iso.split('-').map(Number)
  return `${day} ${MONTHS[month - 1]} ${year}`
}
