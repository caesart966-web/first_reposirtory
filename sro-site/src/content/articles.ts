/** Свежие первыми: по дате выхода, при равной — по дате сверки. */
export const ARTICLES_SORTED: Article[] = [...ARTICLES].sort(
  (a, b) => b.published.localeCompare(a.published) || b.checked.localeCompare(a.checked),
)

export const articleBySlug = (slug: string) => ARTICLES.find((a) => a.slug === slug)

/** «Статьи по теме» для страницы вида СРО или услуги: свежие первыми,
 *  не больше трёх — дальше список перестаёт читаться как «по теме». */
export const articlesFor = (place: string) => ARTICLES_SORTED.filter((a) => a.on.includes(place)).slice(0, 3)

/** Нормы статьи по порядку появления, без повторов: столбец справа. */
export function articleLaws(article: Article): string[] {
  const out: string[] = []
  const add = (law?: string) => {
    if (law && !out.includes(law)) out.push(law)
  }
  for (const section of article.sections) {
    for (const block of section.blocks) {
      if (block.kind === 'p' || block.kind === 'note') add(block.law)
      else for (const item of block.items) add(item.law)
    }
  }
  return out
}

/** Время чтения в минутах: 180 слов в минуту, не меньше двух. */
export function readingMinutes(article: Article): number {
  const texts: string[] = [article.answer]
  for (const section of article.sections) {
    texts.push(section.title)
    for (const block of section.blocks) {
      if (block.kind === 'p') texts.push(block.text)
      else if (block.kind === 'note') texts.push(block.title, block.text)
      else if (block.kind === 'list') texts.push(...block.items.map((i) => i.text))
      else texts.push(...block.items.flatMap((i) => [i.label, i.text]))
    }
  }
  const words = texts.join(' ').split(/\s+/).filter(Boolean).length
  return Math.max(2, Math.round(words / 180))
}
