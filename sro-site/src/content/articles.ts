// Статьи (раздел /stati/, с 15.10.2026, просьба заказчика: «раздел статьи,
// обновлять раз в неделю»).
//
// Зачем. У сайта одиннадцать страниц, и все отвечают на один вопрос — как
// вступить в СРО. Люди же ищут частные вопросы: «нужна ли СРО на договор
// 8 млн», «как проверить СРО», «в СРО какого региона вступать». Каждая статья —
// ответ на один такой вопрос и вход на сайт из поиска.
//
// Правила те же, что у всего сайта:
// - только проверенные нормы, у каждого утверждения о законе — статья
//   (law у абзаца, пункта или строки); чего не удалось сверить, в статье нет;
// - цен, сроков и обещаний, которых не называл заказчик, нет;
// - тексты без примет нейросети (README, «Тексты без примет нейросети»):
//   без заголовков через двоеточие, фраз-анонсов, «нередко/обычно»,
//   приёма «не X, а Y»; речь специалиста компании от первого лица;
// - пишется как говорит живой специалист: полными простыми фразами, без
//   служебных строк («нормы сверены…», «статья не заменяет консультацию»)
//   и без рубленых формул (16.10.2026, заказчик: «человечнее, понятно»);
// - checked — дата, когда нормы статьи сверены. Её двигает человек,
//   сверивший статью целиком, а не правка запятой.
//
// Файл без импортов значений: его читает и сборщик страниц
// (scripts/build-articles.mjs, Node сам снимает типы). Импорт типа
// стирается и Node не мешает.
//
// Как добавить статью: дописать объект в ARTICLES и выполнить
// `npm run articles` — появятся stati/<slug>/index.html, микроразметка,
// карта сайта. Подробно — README, «Статьи».
import type { IMAGES } from './images'

export type ArticleBlock =
  /** Абзац. law — норма сноской под ним. */
  | { kind: 'p'; text: string; law?: string }
  /** Перечень. ordered — только там, где есть порядок (шаги). */
  | { kind: 'list'; items: { text: string; law?: string }[]; ordered?: boolean }
  /** «Ситуация — ответ»: подпись слева, суть справа. */
  | { kind: 'rows'; items: { label: string; text: string; law?: string }[] }
  /** Оговорка с латунной чертой. */
  | { kind: 'note'; title: string; text: string; law?: string }

export type ArticleSection = { title: string; blocks: ArticleBlock[] }

export type Article = {
  /** Папка страницы: stati/<slug>/. Латиницей, через дефис. */
  slug: string
  /** Заголовок страницы (h1). */
  title: string
  /** <title> до « — ООО «БИЗНЕС-ГРУПП»», если он должен отличаться от h1. */
  seoTitle?: string
  /** meta description: что человек узнает, 140–200 знаков. */
  description: string
  /** Строка под заголовком в шапке. */
  lead: string
  /** Подсказка в списках статей: одна строка о сути. */
  hint: string
  /** Когда статья вышла, ГГГГ-ММ-ДД. */
  published: string
  /** Когда нормы статьи сверены, ГГГГ-ММ-ДД. */
  checked: string
  /** Кадр в шапке — из IMAGES. */
  image: keyof typeof IMAGES
  /** Короткий ответ в начале статьи: две-три фразы. */
  answer: string
  sections: ArticleSection[]
  /** Услуги по теме (slug из services.ts) — внизу статьи. */
  related: string[]
  /** Где ставить ссылку на статью в «Статьях по теме» (16.10.2026): slug
   *  страниц видов СРО (construction, design, survey из sroDetails.ts)
   *  и услуг (из services.ts). Неизвестный адрес роняет сборку
   *  (checkArticlePlaces в entry-server.tsx). */
  on: string[]
}

