// С чем человек пишет — начало сообщения в WhatsApp и тема письма
// (22.10.2026, разбор удобства, пункт 2).
//
// Нажал «Проверить мои документы» — в WhatsApp уже набрано «Здравствуйте!
// Хочу проверить документы для вступления в СРО.», в письме та же тема.
// Человеку не нужно формулировать первую фразу, а специалист сразу видит,
// о чём речь и что человек пришёл с сайта. Текст — только начало: его
// можно дописать или стереть до отправки. Telegram и MAX готового текста
// не принимают (content/contacts.ts, messengerHref), там открывается
// пустой диалог.
//
// Тема берётся с кнопки (data-topic у ссылки на #contacts, ключ из TOPICS),
// а у кнопок без своей темы — со страницы: вид СРО, услуга, статья
// (typeTopic, serviceTopic, articleTopic). Та же тема страницы стоит
// у WhatsApp в нижней панели телефона и в разделе «Связаться».
export type Topic = {
  /** Начало сообщения в WhatsApp. */
  text: string
  /** Тема письма. */
  subject: string
}

