export type TopicKey = keyof typeof TOPICS

export const isTopicKey = (key: string | undefined): key is TopicKey =>
  key !== undefined && Object.prototype.hasOwnProperty.call(TOPICS, key)

// Тема страницы вида СРО: title — «СРО строителей».
export const typeTopic = (title: string): Topic => ({
  text: `Здравствуйте! Интересует вступление в ${title}.`,
  subject: `Вступление в ${title}`,
})

// Тема страницы услуги: short — название из меню, «Подготовка документов».
export const serviceTopic = (short: string): Topic => ({
  text: `Здравствуйте! Интересует услуга «${short}».`,
  subject: short,
})

// Тема статьи: человек пишет, дочитав её.
export const articleTopic = (title: string): Topic => ({
  text: `Здравствуйте! Пишу по статье «${title}».`,
  subject: `По статье «${title}»`,
})

// Письмо с темой. Тема в адресе mailto кодируется как в адресе страницы.
export const mailHref = (email: string, topic: Topic) =>
  `mailto:${email}?subject=${encodeURIComponent(topic.subject)}`
