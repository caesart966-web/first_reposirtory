// Содержимое страниц видов СРО.
//
// ПРАВИЛО: ни одной цифры «на глаз». Каждая величина — из закона, и рядом
// с ней стоит статья, по которой её можно проверить. Ничего про цены,
// сроки нашей работы и «за 1 день» здесь нет и быть не может: таких данных
// заказчик не давал, а придумывать их нельзя.
//
// Суммы взносов — это МИНИМУМЫ по закону. Конкретная СРО не вправе взять
// меньше, но своими документами может установить больше; об этом на странице
// сказано прямо, иначе таблица читается как окончательный счёт.
