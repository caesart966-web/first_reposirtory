export type SroDetail = {
  /** Значение ?sro= на главной и data-sro в html страницы. */
  slug: string
  /** Папка страницы. Отдельно от slug: в адресе нужен читаемый по-русски
   *  путь, а в параметре — короткий ключ, по которому страница находит себя. */
  path: string
  /** Ответ квиза — тот же, что у карточки на главной. */
  answer: string
  /** Заголовок вкладки и h1. */
  title: string
  /** Короткая строка под заголовком. */
  lead: string
  /** Описание для поисковика. */
  description: string
  card: { title: string; text: string; image: PageImage }
  /** Кому членство обязательно. */
  who: { text: string; law: string }[]
  /** Что входит в область деятельности. */
  scope: string[]
  funds: {
    harm: { rows: FundRow[]; law: string }
    contract: { rows: FundRow[]; law: string }
  }
  /** Действует ли региональный принцип: только у строителей. */
  regional: boolean
}

