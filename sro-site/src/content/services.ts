// Страницы услуг: семь отдельных адресов под /uslugi/.
//
// Зачем страницы, а не якоря. Посетитель, который «клацает всё подряд»,
// нажав на карточку услуги, должен попасть на страницу с понятным заголовком,
// а не прыгнуть по той же странице вниз. Плюс поиск: «специалисты НРС», «НОК»,
// «документы для СРО» — отдельные запросы, и отдельные страницы по ним
// находятся лучше, чем секции одной длинной.
//
// Почему семь, а не восемь по числу карточек: «Подбор СРО» и «Проверка СРО»
// — одна тема, это одна страница. Страница из трёх абзацев вредит: человек
// заходит, видит пустоту и уходит.
//
// Правило то же, что на всём сайте: факты — только те, что уже есть на сайте
// или в законе, с чипом статьи. Цифр, сроков и цен, которых заказчик не
// называл, здесь нет.
import { IMAGES, type PageImage } from './images'
import { DOCS_SPECIALISTS, LAW, type DocItem } from './sroDetails'

// Формы разделов (28–29.09.2026). Длинные абзацы заменены формами, которые
// читаются глазами, а не подряд, — заказчик просил «красиво расположить
// информацию, как у Apple, но не как у нейросети»:
// rows      — таблица «что — как», как характеристики в спецификации;
// statement — одна главная фраза крупно (норма закона), под ней пояснение;
// cards     — пункты сеткой; ordered — этапы с номерами; aside — оговорка;
// scale     — шкала по нарастающей (меры воздействия);
// actions   — «Что делаю я» списком дел, у вступления — рядом «От вас».
export type ServiceBlock =
  | { kind: 'rows'; title: string; intro?: string; items: { label: string; text: string; law?: string }[]; law?: string }
  | { kind: 'statement'; title: string; quote: string; text?: string; law?: string }
  // ordered — пункты идут по порядку (этапы работы): тогда у них номера.
  // У перечней без порядка номеров нет — правило всего сайта.
  | {
      kind: 'cards'
      title: string
      intro?: string
      ordered?: boolean
      items: { title: string; text: string; law?: string }[]
      aside?: { text: string; law?: string }
    }
  | { kind: 'scale'; title: string; intro?: string; items: string[]; note?: string; law?: string }
  | { kind: 'actions'; title: string; mine: string[]; yours?: string[] }
  | { kind: 'list'; title: string; intro?: string; items: DocItem[] }
  | { kind: 'note'; title: string; paragraphs: string[]; law?: string }
  | { kind: 'steps'; title: string; intro: string }
  | { kind: 'types'; title: string; intro?: string }
  | { kind: 'docs'; title: string; intro: string }

export type ServicePage = {
  /** Ключ: data-service в html страницы и ?help= для квиза. */
  slug: string
  /** Папка страницы относительно корня сайта. */
  path: string
  /** Заголовок карточки в «Услугах» и пункта меню. */
  short: string
  title: string
  lead: string
  /** Подсказка под пунктом меню и подпись карточки. */
  hint: string
  description: string
  icon: 'building' | 'search' | 'file' | 'user' | 'graduation' | 'list' | 'handshake'
  /** Вариант ответа «Какая помощь нужна?», который квиз подставит сам. */
  help?: string
  blocks: ServiceBlock[]
  /** Кадр в шапке — только если у услуги есть предмет, который можно снять. */
  image?: PageImage
  /** Услуги по теме — ссылки внизу страницы, перед «Связаться». Чтобы
      страница не кончалась тупиком: дочитав, человек видит, куда дальше. */
  related: string[]
}

