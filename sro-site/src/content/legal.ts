// Тексты документов о персональных данных: политика и согласие.
//
// Почему они здесь, а не внутри компонента: один и тот же текст показывается
// в двух местах — в окне, которое открывается из формы заявки, и на отдельной
// странице /politika-konfidencialnosti/ с постоянным адресом. Второй экземпляр
// текста рано или поздно разошёлся бы с первым, а расхождение двух редакций
// одного документа на одном сайте — ровно то, что ищут при проверке.
//
// Что в тексте можно писать: только то, что на сайте действительно
// происходит. Здесь нет ни слова про счётчики посещаемости, про cookie, про
// рекламные рассылки и про платёжные системы — ничего этого на сайте нет,
// а обещанное в политике, но не выполняемое хуже, чем не обещанное вовсе.
// Появится счётчик — сюда придётся дописать абзац.
//
// Юридическая оговорка, та же, что в README: тексты составлены по
// требованиям 152-ФЗ, но юрист их не вычитывал.

export type LegalDocId = 'privacy' | 'consent'

/** Абзац или маркированный список внутри раздела. */
