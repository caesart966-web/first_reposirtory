#!/usr/bin/env python3
"""Стопка кодексов для блока «Смежные юридические задачи».

Зачем заменять весы. Они там стояли третьими на странице: те же весы — знаком
в шапке и гравюрой Фемиды фоном.

Почему рисуем. Фотостоки из этой среды недоступны, а из того, что есть в
репозитории, юридическую тему не иллюстрирует ничего, кроме тех же весов.

Что важно в геометрии. Первая попытка дала коробки, а не книги, потому что
книга узнаётся не объёмом, а КАНТОМ: жёсткая обложка выступает за блок
страниц с трёх сторон. Здесь обложка и блок страниц рисуются отдельно, блок
уже обложки на COVER_LIP с каждой стороны, и штрихи страниц идут только по
переднему срезу — не заходя ни на корешок, ни на кант.

Вид выбран почти фронтальный, с малым подъёмом: чем сильнее перспектива, тем
очевиднее, что это построение, а не рисунок.
"""

from pathlib import Path

# Холст подогнан по самому объекту: при квадратном боксе стопка висела в
# нижней трети, а сверху оставалась пустота, и объект читался съехавшим.
W, H = 560, 330
INK = '#202F93'   # accent-800
COVER_LIP = 7     # насколько обложка выступает за блок страниц
RISE = 15         # подъём дальнего края: лёгкий взгляд сверху

# Снизу вверх: ширина обложки, высота корешка, сдвиг, наклон.
BOOKS = [
    dict(w=440, h=54, dx=0, tilt=0.0),
    dict(w=400, h=44, dx=30, tilt=-1.4),
    dict(w=424, h=50, dx=6, tilt=1.1),
    dict(w=372, h=40, dx=48, tilt=-0.7),
]

parts: list[str] = []
add = parts.append


def n(v: float) -> str:
    return f'{v:.1f}'.rstrip('0').rstrip('.')


y = H - 26
cx = W / 2

for i, b in enumerate(BOOKS):
    w, h, dx, tilt = b['w'], b['h'], b['dx'], b['tilt']
    x = cx - w / 2 + dx - 22
    top = y - h
    add(f'<g transform="rotate({tilt} {n(cx)} {n(y)})">')

    # Верхняя плоскость обложки: лёгкий подъём дальнего края.
    add(f'<path d="M{n(x)} {n(top)} L{n(x + w)} {n(top)} '
        f'L{n(x + w - 10)} {n(top - RISE)} L{n(x + 10)} {n(top - RISE)} Z"/>')

    # Обложка: передняя грань со скруглением у корешка.
    add(f'<path d="M{n(x)} {n(top)} L{n(x)} {n(y - 5)} Q{n(x)} {n(y)} {n(x + 5)} {n(y)} '
        f'L{n(x + w - 5)} {n(y)} Q{n(x + w)} {n(y)} {n(x + w)} {n(y - 5)} L{n(x + w)} {n(top)}"/>')

    # Блок страниц: уже обложки на кант с трёх сторон — по этому и читается книга.
    bx, bw = x + COVER_LIP, w - 2 * COVER_LIP
    bt, bb = top + COVER_LIP * 0.6, y - COVER_LIP * 0.6
    add(f'<rect x="{n(bx)}" y="{n(bt)}" width="{n(bw)}" height="{n(bb - bt)}" opacity="0.9"/>')

    # Страницы: редкие штрихи по переднему срезу, с отступом от краёв блока.
    add('<g stroke-width="0.9" opacity="0.45">')
    px = bx + 14
    while px < bx + bw - 14:
        add(f'<line x1="{n(px)}" y1="{n(bt + 4)}" x2="{n(px)}" y2="{n(bb - 4)}"/>')
        px += 9
    add('</g>')

    # Тиснение: одна рамка по центру корешка. Двух линий по краям больше нет —
    # вместе со штрихами страниц они давали решётку.
    add(f'<rect x="{n(x + w * 0.36)}" y="{n(top + h * 0.28)}" width="{n(w * 0.28)}" '
        f'height="{n(h * 0.44)}" rx="2" opacity="0.7"/>')

    add('</g>')
    y = top - RISE - 2

svg = (
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" fill="none" '
    f'stroke="{INK}" stroke-width="2.2" stroke-linejoin="round" stroke-linecap="round">'
    + ''.join(parts)
    + '</svg>'
)
out = Path('public/img/lawbooks.svg')
out.write_text(svg, encoding='utf-8')
print(f'{out}: {len(svg) / 1024:.1f} КБ')
