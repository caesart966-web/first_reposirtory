# Силуэт России для сайта: не картография, а узнаваемый контур.
# Проекция линейная по долготе и широте — для декоративной карты этого
# достаточно, а искажения на глаз читаются как привычная «плоская» карта.
W, H = 1000, 520
LON0, LON1 = 19.0, 191.0
LAT0, LAT1 = 78.5, 41.0

def P(lon, lat):
    x = (lon - LON0) / (LON1 - LON0) * W
    y = (LAT0 - lat) / (LAT0 - LAT1) * H
    return round(x, 1), round(y, 1)

