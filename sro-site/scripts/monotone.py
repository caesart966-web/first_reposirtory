"""Тёплый монохром — общая обработка всех фотографий сайта (с 26.09.2026).

Кадры присланы из разных мест и в разном свете: кран на лиловом закате,
папки с коричневыми корешками, серая статуя, бирюзовое небо изыскателей.
Вместе они читались пятью разными сайтами. Монохром сводит их в одну серию,
как отпечатки одной плёнки: яркость пикселя переводится в градиент палитры —
тени в графит разделов (accent-950), света в бумагу страницы (neutral-50).
Цвет исходника значения больше не имеет, важны только свет и тень.

У каждого кадра свои уровни (black, white, gamma): чёрная и белая точки
растягивают яркость, гамма меньше единицы высветляет. Кран на первом экране
сделан «светлым ключом» — небо уходит в бумагу, и кадр растворяется в листе
без серой полосы на стыке.

Только Pillow: яркость — Image.convert с весами Rec. 709, градиент —
таблица на 256 значений через Image.point.
"""
from PIL import Image

# Точки градиента: доля яркости → цвет. Между точками — линейно.
STOPS = (
    (0.0, (28, 24, 21)),  # accent-950 — графит тёмных разделов
    (0.45, (118, 105, 92)),  # тёплый серо-коричневый
    (0.78, (205, 194, 179)),  # песок
    (1.0, (251, 249, 245)),  # neutral-50 — бумага страницы
)
REC709 = (0.2126, 0.7152, 0.0722, 0)


def _ramp(x: float) -> tuple[int, int, int]:
    for (x0, c0), (x1, c1) in zip(STOPS, STOPS[1:]):
        if x <= x1:
            t = (x - x0) / (x1 - x0)
            return tuple(round(a + (b - a) * t) for a, b in zip(c0, c1))  # type: ignore[return-value]
    return STOPS[-1][1]


def monotone(img: Image.Image, black: float = 0.02, white: float = 0.95, gamma: float = 1.0) -> Image.Image:
    """Кадр в тёплом монохроме. black/white — доли яркости, растягиваемые до 0 и 1."""
    luma = img.convert("RGB").convert("L", REC709)
    table = []
    for v in range(256):
        x = min(1.0, max(0.0, (v / 255 - black) / (white - black))) ** gamma
        table.append(_ramp(x))
    channels = [luma.point([c[i] for c in table]) for i in range(3)]
    return Image.merge("RGB", channels)
